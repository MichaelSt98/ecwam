      IF(L_IFROMIJ.OR.L_KFROMIJ.OR.L_JFROMIJ)THEN
         !... copy only selected members
         IF(L_IFROMIJ)THEN
             CALL SELF%F_IFROMIJ%SYNC_HOST_RDWR(QUEUE=QUEUE)
         ENDIF
         IF(L_KFROMIJ)THEN
             CALL SELF%F_KFROMIJ%SYNC_HOST_RDWR(QUEUE=QUEUE)
         ENDIF
         IF(L_JFROMIJ)THEN
             CALL SELF%F_JFROMIJ%SYNC_HOST_RDWR(QUEUE=QUEUE)
         ENDIF
      ELSE
         !... copy entire struct
         CALL SELF%F_IFROMIJ%SYNC_HOST_RDWR(QUEUE=QUEUE)
         CALL SELF%F_KFROMIJ%SYNC_HOST_RDWR(QUEUE=QUEUE)
         CALL SELF%F_JFROMIJ%SYNC_HOST_RDWR(QUEUE=QUEUE)
      ENDIF

   END SUBROUTINE WVGRIDLOC_SYNC_HOST_RDWR

   SUBROUTINE WVGRIDLOC_DELETE_DEVICE_DATA(SELF)
      TYPE(WVGRIDLOC) :: SELF

      CALL SELF%F_IFROMIJ%DELETE_DEVICE_DATA()
      CALL SELF%F_KFROMIJ%DELETE_DEVICE_DATA()
      CALL SELF%F_JFROMIJ%DELETE_DEVICE_DATA()

   END SUBROUTINE WVGRIDLOC_DELETE_DEVICE_DATA

