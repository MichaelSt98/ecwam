   SUBROUTINE WVGRIDLOC_ALLOC(SELF, UBOUNDS, LBOUNDS)
      TYPE(WVGRIDLOC) :: SELF
      INTEGER(KIND=JWIM), INTENT(IN) :: UBOUNDS(2)
      INTEGER(KIND=JWIM), INTENT(IN), OPTIONAL :: LBOUNDS(2)
      INTEGER(KIND=JWIM) :: LLBOUNDS(2)

      LLBOUNDS(:) = 1
      IF(PRESENT(LBOUNDS)) LLBOUNDS = LBOUNDS

      CALL FIELD_NEW(SELF%F_IFROMIJ, LBOUNDS=LLBOUNDS, UBOUNDS=UBOUNDS, PERSISTENT=.TRUE.)
      CALL SELF%F_IFROMIJ%GET_HOST_DATA_RDWR(SELF%IFROMIJ)
      SELF%IFROMIJ(:,:) = 0_JWIM
      CALL FIELD_NEW(SELF%F_KFROMIJ, LBOUNDS=LLBOUNDS, UBOUNDS=UBOUNDS, PERSISTENT=.TRUE.)
      CALL SELF%F_KFROMIJ%GET_HOST_DATA_RDWR(SELF%KFROMIJ)
      SELF%KFROMIJ(:,:) = 0_JWIM
      CALL FIELD_NEW(SELF%F_JFROMIJ, LBOUNDS=LLBOUNDS, UBOUNDS=UBOUNDS, PERSISTENT=.TRUE.)
      CALL SELF%F_JFROMIJ%GET_HOST_DATA_RDWR(SELF%JFROMIJ)
      SELF%JFROMIJ(:,:) = 0_JWIM

      SELF%LALLOC = .TRUE.
#ifdef OMPGPU
      !$omp target enter data map(to:SELF)
#else
      !$acc enter data copyin(SELF)
#endif

   END SUBROUTINE WVGRIDLOC_ALLOC

   SUBROUTINE WVGRIDLOC_DEALLOC(SELF)
      TYPE(WVGRIDLOC) :: SELF

      NULLIFY(SELF%IFROMIJ)
#ifdef OMPGPU
      !$omp target exit data map(release:SELF%IFROMIJ)
#else
      !$acc exit data detach(SELF%IFROMIJ)
#endif
      CALL FIELD_DELETE(SELF%F_IFROMIJ)
      NULLIFY(SELF%F_IFROMIJ)
      NULLIFY(SELF%KFROMIJ)
#ifdef OMPGPU
      !$omp target exit data map(release:SELF%KFROMIJ)
#else
      !$acc exit data detach(SELF%KFROMIJ)
#endif
      CALL FIELD_DELETE(SELF%F_KFROMIJ)
      NULLIFY(SELF%F_KFROMIJ)
      NULLIFY(SELF%JFROMIJ)
#ifdef OMPGPU
      !$omp target exit data map(release:SELF%JFROMIJ)
#else
      !$acc exit data detach(SELF%JFROMIJ)
#endif
      CALL FIELD_DELETE(SELF%F_JFROMIJ)
      NULLIFY(SELF%F_JFROMIJ)

      SELF%LALLOC = .FALSE.
#ifdef OMPGPU
      !$omp target exit data map(delete:SELF)
#else
      !$acc exit data delete(SELF)
#endif

   END SUBROUTINE WVGRIDLOC_DEALLOC

