         IF(L_NEMOCICOVER)THEN
             CALL SELF%F_NEMOCICOVER%SYNC_DEVICE_RDWR(QUEUE=QUEUE)
         ENDIF
         IF(L_NEMOCITHICK)THEN
             CALL SELF%F_NEMOCITHICK%SYNC_DEVICE_RDWR(QUEUE=QUEUE)
         ENDIF
         IF(L_NEMOUCUR)THEN
             CALL SELF%F_NEMOUCUR%SYNC_DEVICE_RDWR(QUEUE=QUEUE)
