#ifdef OMPGPU
      !$omp target exit data map(release:SELF%NEMOUCUR)
#else
      !$acc exit data detach(SELF%NEMOUCUR)
#endif
      CALL FIELD_DELETE(SELF%F_NEMOUCUR)
      NULLIFY(SELF%F_NEMOUCUR)
      NULLIFY(SELF%NEMOVCUR)
#ifdef OMPGPU
      !$omp target exit data map(release:SELF%NEMOVCUR)
#else
      !$acc exit data detach(SELF%NEMOVCUR)
#endif
      CALL FIELD_DELETE(SELF%F_NEMOVCUR)
      NULLIFY(SELF%F_NEMOVCUR)
