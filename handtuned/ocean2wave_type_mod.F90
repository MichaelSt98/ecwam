   SUBROUTINE OCEAN2WAVE_ALLOC(SELF, UBOUNDS, LBOUNDS)
      TYPE(OCEAN2WAVE) :: SELF
      INTEGER(KIND=JWIM), INTENT(IN) :: UBOUNDS(2)
      INTEGER(KIND=JWIM), INTENT(IN), OPTIONAL :: LBOUNDS(2)
      INTEGER(KIND=JWIM) :: LLBOUNDS(2)

      LLBOUNDS(:) = 1
      IF(PRESENT(LBOUNDS)) LLBOUNDS = LBOUNDS

      CALL FIELD_NEW(SELF%F_NEMOCICOVER, LBOUNDS=LLBOUNDS, UBOUNDS=UBOUNDS, PERSISTENT=.TRUE.)
      CALL SELF%F_NEMOCICOVER%GET_HOST_DATA_RDWR(SELF%NEMOCICOVER)
      SELF%NEMOCICOVER(:,:) = 0_JWRO
      CALL FIELD_NEW(SELF%F_NEMOCITHICK, LBOUNDS=LLBOUNDS, UBOUNDS=UBOUNDS, PERSISTENT=.TRUE.)
      CALL SELF%F_NEMOCITHICK%GET_HOST_DATA_RDWR(SELF%NEMOCITHICK)
      SELF%NEMOCITHICK(:,:) = 0_JWRO
      CALL FIELD_NEW(SELF%F_NEMOUCUR, LBOUNDS=LLBOUNDS, UBOUNDS=UBOUNDS, PERSISTENT=.TRUE.)
      CALL SELF%F_NEMOUCUR%GET_HOST_DATA_RDWR(SELF%NEMOUCUR)
      SELF%NEMOUCUR(:,:) = 0_JWRO
      CALL FIELD_NEW(SELF%F_NEMOVCUR, LBOUNDS=LLBOUNDS, UBOUNDS=UBOUNDS, PERSISTENT=.TRUE.)
      CALL SELF%F_NEMOVCUR%GET_HOST_DATA_RDWR(SELF%NEMOVCUR)
      SELF%NEMOVCUR(:,:) = 0_JWRO
      CALL FIELD_NEW(SELF%F_NEMOCIIBR, LBOUNDS=LLBOUNDS, UBOUNDS=UBOUNDS, PERSISTENT=.TRUE.)
      CALL SELF%F_NEMOCIIBR%GET_HOST_DATA_RDWR(SELF%NEMOCIIBR)
      SELF%NEMOCIIBR(:,:) = 0_JWRO

      SELF%LALLOC = .TRUE.
#ifdef OMPGPU
      !$omp target enter data map(to:SELF)
#else
      !$acc enter data copyin(SELF)
#endif

   END SUBROUTINE OCEAN2WAVE_ALLOC

   SUBROUTINE OCEAN2WAVE_DEALLOC(SELF)
      TYPE(OCEAN2WAVE) :: SELF

      NULLIFY(SELF%NEMOCICOVER)
#ifdef OMPGPU
      !$omp target exit data map(release:SELF%NEMOCICOVER)
#else
