MODULE SEPWISW_LOKI_MOD
  CONTAINS
  SUBROUTINE SEPWISW_LOKI (KIJS, KIJL, MIJ, FL1, XLLWS, CINV, UFRIC, WDWAVE, COSWDIF, ESWELL, FSWELL, THSWELL, P1SWELL, P2SWELL,  &
  & SPRDSWELL, ESEA, FSEA, THWISEA, P1SEA, P2SEA, SPRDSEA, EMTRAIN, THTRAIN, PMTRAIN, IJ, XINVWVAGE, DIRCOEF, SWM, F1,  &
  & SEP3TR_NPEAK, SEP3TR_FRINVMIJ, SEP3TR_NFRP, SEP3TR_NTHP, SEP3TR_SUMENE, SEP3TR_ETT, SEP3TR_ENMAX, SEP3TR_FLNOISE,  &
  & SEP3TR_EUNASNG, SEP3TR_FUNASNG, SEP3TR_THUNASNG, SEP3TR_SPRD, SEP3TR_DIR, SEP3TR_PER, SEP3TR_ENE, SEP3TR_FL, SEP3TR_FLLOW,  &
  & SEP3TR_SUNASGN, SEP3TR_LLCOSDIFF, FNDPRT_KLOC, FNDPRT_W2, FNDPRT_W1, FNDPRT_SPEC, FNDPRT_LLW3, PARMEAN_F1D, PARMEAN_TEMP,  &
  & PARMEAN_SI, PARMEAN_CI, PARMEAN_EM, PARMEAN_FM, PARMEAN_THQ, WDIRSPREAD_F1D)

    ! ----------------------------------------------------------------------

    !**** *SEPWISW* - COMPUTES THE SWELL ENERGY, THE MEAN SWELL DIRECTION,
    !****             THE MEAN SWELL FREQUENCY AND THE MEAN WINDSEA DIR.

    !     P.LIONELLO     FEBRUARY 87

    !     L.ZAMBRESKY    NOVEMBER 87   GKSS/ECMWF   OPTIMIZED SUB.
    !     J. BIDLOT      FEBRARY 1996       ECMWF   MESSAGE PASSING
    !     J. BIDLOT      MAY     1999       ECMWF   ADD HIGH FREQUENCY TAIL
    !     J. BIDLOT      APRIL   2000       ECMWF   ADD  EXTRA PARAMETERS
    !     J. BIDLOT      DECEMBER2003       ECMWF   MOVE ALL ALLOCATION TO
    !                                               *OUTBS*
    !                                               TO MAKE IT CALLABLE IN AN
    !                                               OPENMP LOOP.
    !     J. BIDLOT     JUNE 2013           ECMWF    ADD PARTITIONING SCHEME

    !*    PURPOSE.
    !     --------

    !       TO SEPARATE THE SWELL FROM THE WIND INTERACTING SEA

    !**   INTERFACE.
    !     ----------

    !       *CALL* SEPWISW (KIJS, KIJL, MIJ, FL1, XLLWS,
    !    &                  UFRIC, WSWAVE, WDWAVE, COSWDIF,
    !    &                  ESWELL   ,FSWELL   ,THSWELL  ,
    !    &                  P1SWELL  ,P2SWELL  ,SPRDSWELL,
    !    &                  ESEA     ,FSEA     ,THWISEA  ,
    !    &                  P1SEA    ,P2SEA    ,SPRDSEA  ,
    !    &                  EMTRAIN  ,THTRAIN  ,PMTRAIN)
    !          *KIJS*   - INDEX OF FIRST GRIDPOINT
    !          *KIJL*   - INDEX OF LAST GRIDPOINT
    !          *MIJ*    - LAST FREQUENCY INDEX OF THE PROGNOSTIC RANGE.
    !          *FL1*    - BLOCK OF SPECTRA
    !          *XLLWS*  - WINDSEA MASK FROM INPUT SOURCE TERM
    !          *UFRIC*  - NEW FRICTION VELOCITY IN M/S.
    !          *WSWAVE* - LATESt WIND SPEED.
    !          *WDWAVE* - LATEST WIND DIRECTION.
    !          *COSWDIF*- COSINE (WDWAVE - WAVES DIRECTIONS)
    !          *        - SWELL and WINDSEA PARAMETERS.

    !     METHOD.
    !     -------

    !       THE WAVES WHICH DO NOT INTERACT WITH THE WIND ARE
    !       CONSIDERED SWELL.
    !       IF LLPARTITION THEN A SPECTRAl PARTITIONING SCHEME WILL BE USED
    !       TO SPLIT THE SWELL SPECTRUM INTO ITS TWO MAIN COMPONENTS.

    !     EXTERNALS.
    !     ----------

    !       NONE.

    ! ----------------------------------------------------------------------

    USE WDIRSPREAD_LOKI_MOD, ONLY: WDIRSPREAD_LOKI
    USE STHQ_LOKI_MOD, ONLY: STHQ_LOKI
    USE SEP3TR_LOKI_MOD, ONLY: SEP3TR_LOKI
    USE MWP2_LOKI_MOD, ONLY: MWP2_LOKI
    USE MWP1_LOKI_MOD, ONLY: MWP1_LOKI
    USE FEMEAN_LOKI_MOD, ONLY: FEMEAN_LOKI
    USE PARKIND_WAVE, ONLY: JWIM, JWRB, JWRU

    USE YOWCOUT, ONLY: NTRAIN, LLPARTITION
    USE YOWFRED, ONLY: FR, TH, FRIC, OLDWSFC, ZPIFR
    USE YOWPCONS, ONLY: G, EPSMIN, NPMAX
    USE YOWMAP, ONLY: LCLDOMAIN
    USE YOWPARAM, ONLY: NANG, NFRE

    USE YOMHOOK, ONLY: LHOOK, JPHOOK

    ! -----------------------------------------------------------------------

    IMPLICIT NONE
    INTEGER(KIND=JWIM), INTENT(IN) :: KIJS, KIJL
    INTEGER(KIND=JWIM), INTENT(IN), DIMENSION(KIJL) :: MIJ
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL, NANG, NFRE) :: FL1
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL, NANG, NFRE) :: XLLWS
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL, NFRE) :: CINV
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL) :: UFRIC, WDWAVE
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL, NANG) :: COSWDIF
    REAL(KIND=JWRB), INTENT(OUT), DIMENSION(KIJL) :: ESWELL, FSWELL, THSWELL, P1SWELL, P2SWELL, SPRDSWELL
    REAL(KIND=JWRB), INTENT(OUT), DIMENSION(KIJL) :: ESEA, FSEA, THWISEA, P1SEA, P2SEA, SPRDSEA
    REAL(KIND=JWRB), INTENT(OUT), DIMENSION(KIJL, NTRAIN) :: EMTRAIN, THTRAIN, PMTRAIN


    INTEGER(KIND=JWIM) :: K, M, NT
    INTEGER(KIND=JWIM), INTENT(IN) :: IJ

    REAL(KIND=JWRB) :: COEF
    REAL(KIND=JWRB) :: CHECKTA
    REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
    REAL(KIND=JWRB) :: R
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL, NFRE) :: XINVWVAGE
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL, NANG) :: DIRCOEF
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL, NANG, NFRE) :: SWM
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL, NANG, NFRE) :: F1

    LOGICAL :: LLPEAKF
!$acc routine seq
    INTEGER(KIND=JWIM), INTENT(INOUT) :: SEP3TR_NPEAK(KIJL)
    INTEGER(KIND=JWIM), INTENT(INOUT) :: SEP3TR_FRINVMIJ(KIJL)
    INTEGER(KIND=JWIM), INTENT(INOUT) :: SEP3TR_NFRP(KIJL, NPMAX)
    INTEGER(KIND=JWIM), INTENT(INOUT) :: SEP3TR_NTHP(KIJL, NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_SUMENE(KIJL)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_ETT(KIJL)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_ENMAX(KIJL)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_FLNOISE(KIJL)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_EUNASNG(KIJL)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_FUNASNG(KIJL)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_THUNASNG(KIJL)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_SPRD(KIJL, NANG)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_DIR(KIJL, 0:NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_PER(KIJL, 0:NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_ENE(KIJL, 0:NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_FL(KIJL, NANG, NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_FLLOW(KIJL, NANG, NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: SEP3TR_SUNASGN(KIJL, NANG, NFRE)
    LOGICAL, INTENT(INOUT) :: SEP3TR_LLCOSDIFF(KIJL, NANG)
    INTEGER(KIND=JWIM), INTENT(INOUT) :: FNDPRT_KLOC(3*NANG)
    REAL(KIND=JWRB), INTENT(INOUT) :: FNDPRT_W2(NANG, NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: FNDPRT_W1(KIJL, NANG, NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: FNDPRT_SPEC(NANG, NFRE, MERGE(NPMAX, 1, LLPARTITION), KIJL)
    LOGICAL, INTENT(INOUT) :: FNDPRT_LLW3(KIJL, NANG, NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_F1D(NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_TEMP(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_SI(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_CI(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_EM(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_FM(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_THQ(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: WDIRSPREAD_F1D(KIJL, NFRE)
!$acc data present( MIJ, FL1, XLLWS, CINV, UFRIC, WDWAVE, COSWDIF, ESWELL, FSWELL, THSWELL, P1SWELL, P2SWELL, SPRDSWELL, ESEA,  &
!$acc & FSEA, THWISEA, P1SEA, P2SEA, SPRDSEA, EMTRAIN, THTRAIN, PMTRAIN, XINVWVAGE, DIRCOEF, SWM, F1, SEP3TR_NPEAK,  &
!$acc & SEP3TR_FRINVMIJ, SEP3TR_NFRP, SEP3TR_NTHP, SEP3TR_SUMENE, SEP3TR_ETT, SEP3TR_ENMAX, SEP3TR_FLNOISE, SEP3TR_EUNASNG,  &
!$acc & SEP3TR_FUNASNG, SEP3TR_THUNASNG, SEP3TR_SPRD, SEP3TR_DIR, SEP3TR_PER, SEP3TR_ENE, SEP3TR_FL, SEP3TR_FLLOW,  &
!$acc & SEP3TR_SUNASGN, SEP3TR_LLCOSDIFF, FNDPRT_KLOC, FNDPRT_W2, FNDPRT_W1, FNDPRT_SPEC, FNDPRT_LLW3, PARMEAN_F1D,  &
!$acc & PARMEAN_TEMP, PARMEAN_SI, PARMEAN_CI, PARMEAN_EM, PARMEAN_FM, PARMEAN_THQ, WDIRSPREAD_F1D )

    ! ----------------------------------------------------------------------


    !*    1. THE SWELL DISTRIBUTION IS COMPUTED.
    !        -----------------------------------

    COEF = OLDWSFC*FRIC

!$acc loop seq
    DO M=1,NFRE
      XINVWVAGE(IJ, M) = UFRIC(IJ)*CINV(IJ, M)
    END DO

!$acc loop seq
    DO K=1,NANG
      DIRCOEF(IJ, K) = COEF*COSWDIF(IJ, K)
    END DO

!$acc loop seq
    DO M=1,NFRE
!$acc loop seq
      DO K=1,NANG
        IF (XLLWS(IJ, K, M) /= 0.0_JWRB) THEN
          ! this is windsea
          SWM(IJ, K, M) = 0.0_JWRB
        ELSE
          CHECKTA = XINVWVAGE(IJ, M)*DIRCOEF(IJ, K)
          IF (CHECKTA >= 1.0_JWRB) THEN
            ! this is extra windsea
            SWM(IJ, K, M) = 0.0_JWRB
          ELSE
            ! this is swell
            SWM(IJ, K, M) = 1.0_JWRB
          END IF
        END IF
      END DO
    END DO

    IF (.not.LCLDOMAIN) THEN
      !     CHECK THAT TOTAL SWELL MEAN FREQUENCY IS LOWER THAN WINDSEA ONE
      !     OTHERWISE RESET WIND SECTOR TO WINDSEA

      !     SWELL:
!$acc loop seq
      DO M=1,NFRE
!$acc loop seq
        DO K=1,NANG
          F1(IJ, K, M) = FL1(IJ, K, M)*SWM(IJ, K, M)
        END DO
      END DO
      CALL FEMEAN_LOKI(KIJS, KIJL, F1, ESWELL, FSWELL, IJ=IJ)

      !     WINDSEA:
!$acc loop seq
      DO M=1,NFRE
!$acc loop seq
        DO K=1,NANG
          F1(IJ, K, M) = MAX(FL1(IJ, K, M) - F1(IJ, K, M), 0.0_JWRB)
        END DO
      END DO
      CALL FEMEAN_LOKI(KIJS, KIJL, F1, ESEA, FSEA, IJ=IJ)

      !     CHECK:
      IF (FSWELL(IJ) > 0.96_JWRB*FSEA(IJ)) THEN
        R = 1.0_JWRB
      ELSE
        R = 0.0_JWRB
      END IF
!$acc loop seq
      DO K=1,NANG
        ! add factor to extend windsea area
        DIRCOEF(IJ, K) = R*COEF*SIGN(1.0_JWRB, 0.4_JWRB + COSWDIF(IJ, K))
      END DO
!$acc loop seq
      DO M=1,NFRE
!$acc loop seq
        DO K=1,NANG
          CHECKTA = XINVWVAGE(IJ, M)*DIRCOEF(IJ, K)
          IF (CHECKTA >= 1.0_JWRB) THEN
            ! this is additional windsea
            SWM(IJ, K, M) = 0.0_JWRB
          END IF
        END DO
      END DO

      !     ADJUST THE LOW FREQUENCY BOUNDARY OF THE WINDSEAS AREA
      !     TO TOPOLOGICALLY CONNECT IT TO THE WINDSEA
!$acc loop seq
      DO K=1,NANG
!$acc loop seq
        DO M=NFRE,2,-1
          IF (SWM(IJ, K, M) == 1.0_JWRB .and. SWM(IJ, K, -1 + M) == 1.0_JWRB) THEN
            EXIT
          ELSE IF (SWM(IJ, K, M) == 0.0_JWRB .and. SWM(IJ, K, -1 + M) == 1.0_JWRB) THEN
            IF (FL1(IJ, K, M) >= FL1(IJ, K, -1 + M)) SWM(IJ, K, M - 1) = 0.0_JWRB
          END IF
        END DO
      END DO

    END IF
    ! CLDOMAIN

    !     SWELL SPECTRUM
!$acc loop seq
    DO M=1,NFRE
!$acc loop seq
      DO K=1,NANG
        F1(IJ, K, M) = MAX(FL1(IJ, K, M), EPSMIN)*SWM(IJ, K, M)
      END DO
    END DO

    !*    2.1 COMPUTATION OF THE PARTITIONED SWELL OUTPUT PARAMETERS
    !         ------------------------------------------------------

    IF (LLPARTITION) THEN
      CALL FEMEAN_LOKI(KIJS, KIJL, F1, ESWELL, FSWELL, IJ=IJ)
      CALL STHQ_LOKI(KIJS, KIJL, F1, THSWELL, IJ=IJ)
      CALL SEP3TR_LOKI(KIJS, KIJL, FL1, MIJ, WDWAVE, COSWDIF, ESWELL, FSWELL, THSWELL, FSEA, F1, SWM, EMTRAIN, THTRAIN, PMTRAIN,  &
      & IJ=IJ, NPEAK=SEP3TR_NPEAK, FRINVMIJ=SEP3TR_FRINVMIJ, NFRP=SEP3TR_NFRP, NTHP=SEP3TR_NTHP, SUMENE=SEP3TR_SUMENE,  &
      & ETT=SEP3TR_ETT, ENMAX=SEP3TR_ENMAX, FLNOISE=SEP3TR_FLNOISE, EUNASNG=SEP3TR_EUNASNG, FUNASNG=SEP3TR_FUNASNG,  &
      & THUNASNG=SEP3TR_THUNASNG, SPRD=SEP3TR_SPRD, DIR=SEP3TR_DIR, PER=SEP3TR_PER, ENE=SEP3TR_ENE, FL=SEP3TR_FL,  &
      & FLLOW=SEP3TR_FLLOW, SUNASGN=SEP3TR_SUNASGN, LLCOSDIFF=SEP3TR_LLCOSDIFF, FNDPRT_KLOC=FNDPRT_KLOC, FNDPRT_W2=FNDPRT_W2,  &
      & FNDPRT_W1=FNDPRT_W1, FNDPRT_SPEC=FNDPRT_SPEC, FNDPRT_LLW3=FNDPRT_LLW3, PARMEAN_F1D=PARMEAN_F1D,  &
      & PARMEAN_TEMP=PARMEAN_TEMP, PARMEAN_SI=PARMEAN_SI, PARMEAN_CI=PARMEAN_CI, PARMEAN_EM=PARMEAN_EM, PARMEAN_FM=PARMEAN_FM,  &
      & PARMEAN_THQ=PARMEAN_THQ)
    ELSE
!$acc loop seq
      DO NT=1,NTRAIN
        EMTRAIN(IJ, NT) = 0.0_JWRB
        THTRAIN(IJ, NT) = 0.0_JWRB
        PMTRAIN(IJ, NT) = 0.0_JWRB
      END DO
    END IF

    !*    2.2 COMPUTATION OF TOTAL SWELL OUTPUT PARAMETERS
    !         --------------------------------------------

    CALL FEMEAN_LOKI(KIJS, KIJL, F1, ESWELL, FSWELL, IJ=IJ)

    CALL STHQ_LOKI(KIJS, KIJL, F1, THSWELL, IJ=IJ)

    CALL MWP1_LOKI(KIJS, KIJL, F1, P1SWELL, IJ=IJ)

    CALL MWP2_LOKI(KIJS, KIJL, F1, P2SWELL, IJ=IJ)

    LLPEAKF = .true.
    CALL WDIRSPREAD_LOKI(KIJS, KIJL, F1, ESWELL, LLPEAKF, SPRDSWELL, IJ=IJ, F1D=WDIRSPREAD_F1D)


    !*    3. COMPUTATION OF WIND SEA OUTPUT PARAMETERS
    !        -----------------------------------------

!$acc loop seq
    DO M=1,NFRE
!$acc loop seq
      DO K=1,NANG
        !! add a small amount of noise in the wind direction
        IF (COSWDIF(IJ, K) > 0.8_JWRB .and. M >= NFRE / 2) THEN
          F1(IJ, K, M) = MAX(FL1(IJ, K, M) - F1(IJ, K, M) + EPSMIN*COSWDIF(IJ, K)**4, 0.0_JWRB)
        ELSE
          F1(IJ, K, M) = MAX(FL1(IJ, K, M) - F1(IJ, K, M), 0.0_JWRB)
        END IF
      END DO
    END DO

    CALL FEMEAN_LOKI(KIJS, KIJL, F1, ESEA, FSEA, IJ=IJ)

    CALL STHQ_LOKI(KIJS, KIJL, F1, THWISEA, IJ=IJ)
    !     if there isn't any windsea energy, set the windsea mean direction
    !     to the wind direction.
    IF (ESEA(IJ) <= 1.0E-9_JWRB) THEN
      THWISEA(IJ) = WDWAVE(IJ)
    END IF

    CALL MWP1_LOKI(KIJS, KIJL, F1, P1SEA, IJ=IJ)

    CALL MWP2_LOKI(KIJS, KIJL, F1, P2SEA, IJ=IJ)

    LLPEAKF = .true.
    CALL WDIRSPREAD_LOKI(KIJS, KIJL, F1, ESEA, LLPEAKF, SPRDSEA, IJ=IJ, F1D=WDIRSPREAD_F1D)



!$acc end data
  END SUBROUTINE SEPWISW_LOKI
END MODULE SEPWISW_LOKI_MOD
