MODULE SEP3TR_LOKI_MOD
  CONTAINS
  SUBROUTINE SEP3TR_LOKI (KIJS, KIJL, FL1, MIJ, WDWAVE, COSWDIF, ESWELL, FSWELL, THSWELL, FSEA, FLSW, SWM, EMTRAIN, THTRAIN,  &
  & PMTRAIN, IJ, NPEAK, FRINVMIJ, NFRP, NTHP, SUMENE, ETT, ENMAX, FLNOISE, EUNASNG, FUNASNG, THUNASNG, SPRD, DIR, PER, ENE, FL,  &
  & FLLOW, SUNASGN, LLCOSDIFF, FNDPRT_KLOC, FNDPRT_W2, FNDPRT_W1, FNDPRT_SPEC, FNDPRT_LLW3, PARMEAN_F1D, PARMEAN_TEMP,  &
  & PARMEAN_SI, PARMEAN_CI, PARMEAN_EM, PARMEAN_FM, PARMEAN_THQ)

    ! ----------------------------------------------------------------------

    !**** *SEP3TR* -  COMPUTE ENERGY, DIRECTION AND PERIOD FOR THE 3 WAVE
    !****             TRAINS: SWELL1, SWELL2, SWELL3

    !     D.PETTENUZZO     MAY 2012
    !     JEAN BIDLOT      JUNE 2013  SIMPLIFIED BY REMOVING THE WIND SEA PART
    !                                 AND ONLY PARTITIONED THE SWELL SPECTRUM
    !                                 AND ONLY LOOKING IN THE PROGNOSTIC RANGE


    !*    PURPOSE.
    !     --------

    !     CREATED TO TEST WAVE SWELL SPECTRA PARTITIONING INTO 3 WAVE TRAINS

    !**   INTERFACE.
    !     ----------

    !       *CALL* *SEP3TR (KIJS, KIJL, FL1, MIJ, WSWAVE, WDWAVE, COSWDIF,
    !                       ESWELL, FSWELL, THSWELL, FSEA,
    !                       FLSW, SWM,
    !                       EMTRAIN  ,THTRAIN  ,PMTRAIN)
    !          *KIJS*   - INDEX OF FIRST GRIDPOINT
    !          *KIJL*   - INDEX OF LAST GRIDPOINT
    !          *FL1*    - BLOCK OF FULL SPECTRA
    !          *MIJ*    - LAST FREQUENCY INDEX OF THE PROGNOSTIC RANGE.
    !          *WSWAVE* - LATESt WIND SPEED.
    !          *WDWAVE* - LATEST WIND DIRECTION.
    !          *COSWDIF*- COSINE (WDWAVE - WAVES DIRECTIONS)
    !          *ESWELL* - TOTAL SWELL ENERGY
    !          *FSWELL* - TOTAL SWELL MEAN FREQUENCY
    !          *THSWELL*- TOTAL SWELL MEAN DIRECTION
    !          *FSEA*   - WINDSEA MEAN FREQUENCY
    !          *FLSW*   - SWELL SPECTRA
    !          *SWM*    - ORIGINAL SWELL MASK
    !                     IT MIGHT NEED TO BE ADJUSTED
    !                     THIS IS POSSIBLE BECAUSE WE SUPPLY SWELL SPECTRA
    !                     IN WHICH THE WIND SEA HAS BEEN REMOVED. SOME OF
    !                     THE ENERGY LEAKING OUT FROM THE WINDSEA SPECTRUM
    !                     MIGHT NOT BE PARTITIONED.
    !          *EMTRAIN*- PARTITIONED ENERGY
    !          *THTRAIN*- PARTITIONED MEAN DIRECTION
    !          *PMTRAIN*- PARTITIONED MEAN PERIOD

    !     METHOD.
    !     -------

    !       HANSON AND PHILLIPS 2001

    ! ----------------------------------------------------------------------
    USE STHQ_LOKI_MOD, ONLY: STHQ_LOKI
    USE SEMEAN_LOKI_MOD, ONLY: SEMEAN_LOKI
    USE FEMEAN_LOKI_MOD, ONLY: FEMEAN_LOKI
    USE FNDPRT_LOKI_MOD, ONLY: FNDPRT_LOKI
    USE PARKIND_WAVE, ONLY: JWIM, JWRB, JWRU

    USE YOWCOUT, ONLY: NTRAIN, LLPARTITION
    USE YOWFRED, ONLY: FR, DFIM, C, TH, COSTH, SINTH, FRIC
    USE YOWICE, ONLY: FLMIN
    USE YOWPARAM, ONLY: NANG, NFRE
    USE YOWPCONS, ONLY: ZPI, G, EPSMIN, NPMAX

    USE YOMHOOK, ONLY: LHOOK, JPHOOK

    ! ----------------------------------------------------------------------

    IMPLICIT NONE
    INTEGER(KIND=JWIM), INTENT(IN) :: KIJS, KIJL
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL, NANG, NFRE) :: FL1
    INTEGER(KIND=JWIM), INTENT(IN), DIMENSION(KIJL) :: MIJ
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL) :: WDWAVE
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL, NANG) :: COSWDIF
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL) :: ESWELL, FSWELL, THSWELL
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL) :: FSEA
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL, NANG, NFRE) :: FLSW, SWM
    REAL(KIND=JWRB), INTENT(OUT), DIMENSION(KIJL, NTRAIN) :: EMTRAIN, THTRAIN, PMTRAIN


    INTEGER(KIND=JWIM) :: NPMAX_LOC
    INTEGER(KIND=JWIM) :: M, K, IP
    INTEGER(KIND=JWIM), INTENT(IN) :: IJ
    INTEGER(KIND=JWIM) :: ISORT, I, IPLOC
    INTEGER(KIND=JWIM) :: IFL, IFH, ITHL, ITHH
    INTEGER(KIND=JWIM) :: KM, KP
    INTEGER(KIND=JWIM), INTENT(INOUT), DIMENSION(KIJL) :: NPEAK
    INTEGER(KIND=JWIM) :: NPK
    INTEGER(KIND=JWIM) :: NPKNA
    INTEGER(KIND=JWIM), INTENT(INOUT), DIMENSION(KIJL) :: FRINVMIJ
    INTEGER(KIND=JWIM) :: MMIN, MMAX
    INTEGER(KIND=JWIM) :: IPNOW
    INTEGER(KIND=JWIM), DIMENSION(NTRAIN) :: IENERGY
    INTEGER(KIND=JWIM), INTENT(INOUT), DIMENSION(KIJL, NPMAX) :: NFRP
    INTEGER(KIND=JWIM), INTENT(INOUT), DIMENSION(KIJL, NPMAX) :: NTHP

    ! relative value above max swell value that is considered above noise level
    REAL(KIND=JWRB), PARAMETER :: XNOISELEVEL = 0.005_JWRB
    ! minimum Hs (m) value to keep a partition HSMIN=HSMIN_INTER+HSMIN_SLOPE*PERIOD
    REAL(KIND=JWRB), PARAMETER :: HSMIN_INTER = 0.05_JWRB
    REAL(KIND=JWRB), PARAMETER :: HSMIN_SLOPE = -0.0017_JWRB
    REAL(KIND=JWRB) :: THRS
    REAL(KIND=JWRB) :: HSMIN

    REAL(KIND=JWRB) :: DELDW
    REAL(KIND=JWRB) :: COSDIR, FRLIMIT
    REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
    REAL(KIND=JWRB) :: FLLOWEST
    REAL(KIND=JWRB) :: ENEX
    REAL(KIND=JWRB) :: SUMETRAIN
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL) :: SUMENE
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL) :: ETT
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL) :: ENMAX
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL) :: FLNOISE
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL) :: EUNASNG
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL) :: FUNASNG
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL) :: THUNASNG
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL, NANG) :: SPRD
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL, 0:NPMAX) :: DIR
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL, 0:NPMAX) :: PER
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL, 0:NPMAX) :: ENE
    REAL(KIND=JWRB), DIMENSION(NTRAIN) :: TEMPDIR, TEMPPER, TEMPENE
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL, NANG, NFRE) :: FL
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL, NANG, NFRE) :: FLLOW
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL, NANG, NFRE) :: SUNASGN

    LOGICAL :: LLEPSMIN
    LOGICAL :: LLADDPART
    LOGICAL, DIMENSION(NTRAIN) :: LPWSECTOR
    LOGICAL, INTENT(INOUT), DIMENSION(KIJL, NANG) :: LLCOSDIFF
!$acc routine seq
    INTEGER(KIND=JWIM), INTENT(INOUT) :: FNDPRT_KLOC(3*NANG)
    REAL(KIND=JWRB), INTENT(INOUT) :: FNDPRT_W2(NANG, NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: FNDPRT_W1(KIJL, NANG, NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: FNDPRT_SPEC(NANG, NFRE, MERGE(NPMAX, 1, LLPARTITION), KIJL)
    LOGICAL, INTENT(INOUT) :: FNDPRT_LLW3(KIJL, NANG, NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_F1D(NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_TEMP(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_SI(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_CI(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_EM(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_FM(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_THQ(NPMAX)
!$acc data present( FL1, MIJ, WDWAVE, COSWDIF, ESWELL, FSWELL, THSWELL, FSEA, FLSW, SWM, EMTRAIN, THTRAIN, PMTRAIN, NPEAK,  &
!$acc & FRINVMIJ, NFRP, NTHP, SUMENE, ETT, ENMAX, FLNOISE, EUNASNG, FUNASNG, THUNASNG, SPRD, DIR, PER, ENE, FL, FLLOW, SUNASGN,  &
!$acc & LLCOSDIFF, FNDPRT_KLOC, FNDPRT_W2, FNDPRT_W1, FNDPRT_SPEC, FNDPRT_LLW3, PARMEAN_F1D, PARMEAN_TEMP, PARMEAN_SI,  &
!$acc & PARMEAN_CI, PARMEAN_EM, PARMEAN_FM, PARMEAN_THQ )

    ! ----------------------------------------------------------------------

    !*    LOOP THROUGH THE GRID POINTS
    !     ----------------------------


    FRINVMIJ(IJ) = 1.0_JWRB / FR(MIJ(IJ))

    ENMAX(IJ) = 0.0_JWRB
    !     SMOOTH INPUT SPECTRA (in direction only)
!$acc loop seq
    DO M=1,NFRE
!$acc loop seq
      DO K=1,NANG
        KM = K - 1
        IF (KM < 1) KM = NANG
        KP = K + 1
        IF (KP > NANG) KP = 1
        !           RE-IMPOSE THE WINDSEA MASK
        IF (FLSW(IJ, K, M) <= 0.0_JWRB) THEN
          FL(IJ, K, M) = 0.0_JWRB
        ELSE
          FL(IJ, K, M) = 0.10_JWRB*(FLSW(IJ, KM, M) + FLSW(IJ, KP, M)) + 0.80_JWRB*FLSW(IJ, K, M)
          ENMAX(IJ) = MAX(ENMAX(IJ), FL(IJ, K, M))
        END IF
      END DO
    END DO

    FLNOISE(IJ) = XNOISELEVEL*ENMAX(IJ)

!$acc loop seq
    DO ISORT=1,NTRAIN
      EMTRAIN(IJ, ISORT) = 0.0_JWRB
      PMTRAIN(IJ, ISORT) = 0.0_JWRB
      IF (ESWELL(IJ) > 0.0_JWRB) THEN
        THTRAIN(IJ, ISORT) = THSWELL(IJ)
      ELSE
        THTRAIN(IJ, ISORT) = WDWAVE(IJ)
      END IF
    END DO

    NPEAK(IJ) = 0

    !*    1. DETERMINATES MAXIMA POSITIONS AND NUMBER
    !        ----------------------------------------

!$acc loop seq
    DO K=1,NANG
      LLCOSDIFF(IJ, K) = COSWDIF(IJ, K) < -0.4_JWRB
      SPRD(IJ, K) = MAX(0.0_JWRB, COSWDIF(IJ, K))**2
    END DO

!$acc loop seq
    DO M=1,NFRE
!$acc loop seq
      DO K=1,NANG
        FLLOW(IJ, K, M) = FLMIN
      END DO
    END DO


!$acc loop seq
    OUT: DO M=2,MIJ(IJ) - 1
      IFL = MAX(1, M - 1)
      IFH = MIN(NFRE, M + 1)
!$acc loop seq
      DO K=1,NANG

        FLLOWEST = MAX(FLLOW(IJ, K, M), FLNOISE(IJ))

        IF (FL(IJ, K, M) > FLLOWEST) THEN
          ITHL = 1 + MOD(NANG + K - 2, NANG)
          ITHH = 1 + MOD(K, NANG)
          IF (FL(IJ, ITHL, M) > 0.0_JWRB .and. FL(IJ, ITHH, M) > 0.0_JWRB .and. FL(IJ, K, IFL) > 0.0_JWRB .and. FL(IJ, K, IFH) >  &
          & 0.0_JWRB .and. FL(IJ, ITHL, IFL) > 0.0_JWRB .and. FL(IJ, ITHL, IFH) > 0.0_JWRB .and. FL(IJ, ITHH, IFL) > 0.0_JWRB  &
          & .and. FL(IJ, ITHH, IFH) > 0.0_JWRB) THEN


            IF (FL(IJ, K, M) >= FL(IJ, K, IFL) .and. FL(IJ, K, M) >= FL(IJ, K, IFH) .and. FL(IJ, K, M) >= FL(IJ, ITHL, IFL) .and. &
            &  FL(IJ, K, M) >= FL(IJ, ITHL, M) .and. FL(IJ, K, M) >= FL(IJ, ITHL, IFH) .and. FL(IJ, K, M) >= FL(IJ, ITHH, IFL)  &
            & .and. FL(IJ, K, M) >= FL(IJ, ITHH, M) .and. FL(IJ, K, M) >= FL(IJ, ITHH, IFH)) THEN
              NPEAK(IJ) = NPEAK(IJ) + 1
              IF (NPEAK(IJ) > NPMAX) EXIT OUT
              NFRP(IJ, NPEAK(IJ)) = M
              NTHP(IJ, NPEAK(IJ)) = K
            END IF
          END IF
        END IF

      END DO

    END DO OUT

    NPEAK(IJ) = MIN(NPEAK(IJ), NPMAX)

    !*    2. GENERATE MASK FOR EACH PARTITION AND COMPUTE STATISTICS
    !        -------------------------------------------------------

    CALL FNDPRT_LOKI(KIJS, KIJL, NPMAX, NPEAK, MIJ, NTHP, NFRP, FLLOW, LLCOSDIFF, FLNOISE, FL, SWM, SUNASGN, ENE, DIR, PER,  &
    & IJ=IJ, KLOC=FNDPRT_KLOC, W2=FNDPRT_W2, W1=FNDPRT_W1, SPEC=FNDPRT_SPEC, LLW3=FNDPRT_LLW3, PARMEAN_F1D=PARMEAN_F1D,  &
    & PARMEAN_TEMP=PARMEAN_TEMP, PARMEAN_SI=PARMEAN_SI, PARMEAN_CI=PARMEAN_CI, PARMEAN_EM=PARMEAN_EM, PARMEAN_FM=PARMEAN_FM,  &
    & PARMEAN_THQ=PARMEAN_THQ)

    ! UPDATE SWELL SPECTRUM ??????
!$acc loop seq
    DO M=1,NFRE
!$acc loop seq
      DO K=1,NANG
        FLSW(IJ, K, M) = MAX(FL1(IJ, K, M), EPSMIN)*SWM(IJ, K, M)
      END DO
    END DO

    !     TOTAL ENERGY IN THE UPDATED SWELL SPECTRA
    LLEPSMIN = .false.
    CALL SEMEAN_LOKI(FLSW, KIJS, KIJL, ETT, LLEPSMIN, IJ=IJ)

    !     TOTAL ENERGY IN THE PARTITIONS
    SUMENE(IJ) = 0.0_JWRB
!$acc loop seq
    DO IP=1,NPEAK(IJ)
      SUMENE(IJ) = SUMENE(IJ) + ENE(IJ, IP)
    END DO


    !     PARTITION OF THE UNASSIGNED SWELL SPECTRA
    CALL FEMEAN_LOKI(KIJS, KIJL, SUNASGN, EUNASNG, FUNASNG, IJ=IJ)
    LLEPSMIN = .false.
    CALL SEMEAN_LOKI(SUNASGN, KIJS, KIJL, EUNASNG, LLEPSMIN, IJ=IJ)
    CALL STHQ_LOKI(KIJS, KIJL, SUNASGN, THUNASNG, IJ=IJ)

    IF (EUNASNG(IJ) > SUMENE(IJ)) THEN
      NPKNA = NTRAIN
    ELSE
      NPKNA = NTRAIN - 1
    END IF

    !     IF LESS THAN NPKNA PARTITIONS, CREATE A NEW PARTITION WITH THE UNASSIGNED SWELL SPECTRUM
    IF (NPEAK(IJ) < NPKNA .and. EUNASNG(IJ) > 0.0_JWRB) THEN
      NPEAK(IJ) = NPEAK(IJ) + 1
      ENE(IJ, NPEAK(IJ)) = EUNASNG(IJ)
      DIR(IJ, NPEAK(IJ)) = THUNASNG(IJ)
      PER(IJ, NPEAK(IJ)) = 1.0_JWRB / FUNASNG(IJ)
    END IF

    !     REMOVE PARTITION WITH Hs < HSMIN
    !     MEAN PERIOD > 1/FR(MIJ)
    NPK = NPEAK(IJ)
!$acc loop seq
    DO IP=1,NPEAK(IJ)
      HSMIN = HSMIN_INTER + HSMIN_SLOPE*PER(IJ, IP)
      THRS = 0.0625_JWRB*HSMIN**2
      IF (ENE(IJ, IP) < THRS .or. PER(IJ, IP) < FRINVMIJ(IJ)) THEN
        ENE(IJ, IP) = 0.0_JWRB
        DIR(IJ, IP) = 0.0_JWRB
        PER(IJ, IP) = 0.0_JWRB
        NPK = NPK - 1
      END IF
    END DO

    !     IF NO SWELL PARTITION BUT TOTAL SWELL EXIST THEN
    !     ASSIGN FIRST PARTITION TO TOTAL SWELL
    !     IF IT HAS SWELL CHARACTERSITICS
    IF (NPK <= 0 .and. ESWELL(IJ) > 0.0_JWRB) THEN
      IF (FSWELL(IJ) < FSEA(IJ)) THEN
        NPEAK(IJ) = 1
        ENE(IJ, 1) = ESWELL(IJ)
        DIR(IJ, 1) = THSWELL(IJ)
        PER(IJ, 1) = 1.0_JWRB / FSWELL(IJ)
      END IF
    END IF

    !*    5. SORT PARTITIONS ACCORDING TO ENERGY AND ASSIGN THE FIRST NTRAIN TRAINS
    !        WE ONLY NEED THE FIRST NTRAIN TO BE SORTED
    !        -----------------------------------------------------------------

    NPMAX_LOC = MAXVAL(NPEAK(:))

!$acc loop seq
    DO ISORT=1,NTRAIN
      IPNOW = 0
      ENMAX(IJ) = 0.0_JWRB

!$acc loop seq
      DO IP=1,NPMAX_LOC
        IF (ENE(IJ, IP) > ENMAX(IJ)) THEN
          IPNOW = IP
          ENMAX(IJ) = ENE(IJ, IP)
        END IF
      END DO

      EMTRAIN(IJ, ISORT) = ENE(IJ, IPNOW)
      THTRAIN(IJ, ISORT) = DIR(IJ, IPNOW)
      PMTRAIN(IJ, ISORT) = PER(IJ, IPNOW)
      ENE(IJ, IPNOW) = 0.0_JWRB
      IENERGY(ISORT) = MIN(IPNOW, 1)
    END DO


    !*    6. PRESERVE TOTAL ENERGY
    !        ---------------------

    !     6.1 Distribute extra energy proportionally to swell trains if more systems than NPKNA

    SUMETRAIN = MAX(EMTRAIN(IJ, 1), EPSMIN)
!$acc loop seq
    DO ISORT=2,NTRAIN
      SUMETRAIN = SUMETRAIN + EMTRAIN(IJ, ISORT)
    END DO

    IF (NPEAK(IJ) >= NPKNA) THEN
      ENEX = MAX((ETT(IJ) - SUMETRAIN), 0.0_JWRB) / SUMETRAIN
    ELSE
      ENEX = 0.0_JWRB
    END IF

!$acc loop seq
    DO ISORT=1,NTRAIN
      EMTRAIN(IJ, ISORT) = EMTRAIN(IJ, ISORT) + ENEX*EMTRAIN(IJ, ISORT)
    END DO

    !     RE-ORDER SWELL SYSTEM ACCORDING TO TOTAL ENERGY

!$acc loop seq
    DO ISORT=1,NTRAIN
      TEMPENE(ISORT) = EMTRAIN(IJ, ISORT)
      TEMPDIR(ISORT) = THTRAIN(IJ, ISORT)
      TEMPPER(ISORT) = PMTRAIN(IJ, ISORT)
    END DO

!$acc loop seq
    DO ISORT=1,NTRAIN
      IPNOW = 0
      ENMAX(IJ) = 0.0_JWRB

!$acc loop seq
      DO IP=1,NTRAIN
        IF (TEMPENE(IP) > ENMAX(IJ)) THEN
          IPNOW = IP
          ENMAX(IJ) = TEMPENE(IP)
        END IF
      END DO

      IPLOC = MAX(IPNOW, 1)
      EMTRAIN(IJ, ISORT) = TEMPENE(IPLOC)
      THTRAIN(IJ, ISORT) = TEMPDIR(IPLOC)
      PMTRAIN(IJ, ISORT) = TEMPPER(IPLOC)
      TEMPENE(IPLOC) = 0.0_JWRB
    END DO

    !     PREPARE OUTPUT

!$acc loop seq
    DO ISORT=1,NTRAIN
      IF (IENERGY(ISORT) == 0) THEN
        EMTRAIN(IJ, ISORT) = 0.0_JWRB
        THTRAIN(IJ, ISORT) = WDWAVE(IJ)
        PMTRAIN(IJ, ISORT) = 0.0_JWRB
      END IF
    END DO



!$acc end data
  END SUBROUTINE SEP3TR_LOKI
END MODULE SEP3TR_LOKI_MOD
