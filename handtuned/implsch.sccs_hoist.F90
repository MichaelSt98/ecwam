!$acc routine seq
    REAL(KIND=JWRB), INTENT(INOUT) :: SNONLIN_ENH(KIJL, MLSTHG)
!$acc data present( FL1, WAVNUM, CGROUP, CINV, XK2CG, STOKFAC, EMAXDPT, DEPTH, IOBND, IODP, IBRMEM, AIRD, WDWAVE, CICOVER,  &
!$acc & WSWAVE, WSTAR, USTRA, VSTRA, UFRIC, TAUW, TAUWDIR, Z0M, Z0B, CHRNCK, CITHICK, NEMOUSTOKES, NEMOVSTOKES, NEMOSTRN,  &
!$acc & NPHIEPS, NTAUOC, NSWH, NMWP, NEMOTAUX, NEMOTAUY, NEMOTAUICX, NEMOTAUICY, NEMOWSWAVE, NEMOPHIF, WSEMEAN, WSFMEAN,  &
!$acc & USTOKES, VSTOKES, STRNMS, TAUXD, TAUYD, TAUOCXD, TAUOCYD, TAUOC, TAUICX, TAUICY, PHIOCD, PHIEPS, PHIAW, MIJ, XLLWS,  &
!$acc & DELFL, EMEAN, FMEAN, FMEANWS, F1MEAN, AKMEAN, XKMEAN, PHIWA, FLM, COSWDIF, SINWDIF2, TEMP, RHOWGDFTH, FLD, SL, SPOS,  &
!$acc & SSOURCE, SLICE, ALPFAC, TEMPA, TEMPX, TEMP2, WD, FLWD, FD, GAM0, DSTAB, COSLP, FACSAT, FACWTRB, SDISSIP_TEMP1, BTH0, C_,  &
!$acc & C_C, DSIP, TRPZ_DSIP, BTH, SDISSIP_TEMP2, D, SCUMUL, RENEWALFREQ, WCUMUL, ALP, XK2, SDICE3_ALP, SNONLIN_ENH )

    ! ----------------------------------------------------------------------



    !*    1. INITIALISATION.
    !        ---------------

    DELT = IDELT
    DELTM = 1.0_JWRB / DELT
    DELT5 = XIMP*DELT

    LCFLX = LWFLUX .or. LWFLUXOUT .or. LWNEMOCOU


    RAORW = MAX(AIRD(IJ), 1.0_JWRB)*ROWATERM1

    ALPFAC(IJ) = ZALPFACX      ! <1=some reduction, 1=no reduction to attenuation

!$acc loop seq
    DO K=1,NANG
      COSWDIF(IJ, K) = COS(TH(K) - WDWAVE(IJ))
      SINWDIF2(IJ, K) = SIN(TH(K) - WDWAVE(IJ))**2
    END DO

    IF (LWNEMOCOUWRS .and. .not.(LCIWA1 .or. LCIWA2 .or. LCIWA3)) THEN
!$acc loop seq
      DO M=1,NFRE
!$acc loop seq
        DO K=1,NANG
          SLICE(IJ, K, M) = 0.0_JWRB
        END DO
      END DO
    END IF

    ! ----------------------------------------------------------------------

    !*    2. COMPUTATION OF IMPLICIT INTEGRATION.
    !        ------------------------------------

    !         INTEGRATION IS DONE FROM CDATE UNTIL CDTPRO FOR A BLOCK
    !         OF LATITUDES BETWEEN PROPAGATION CALLS.


    !     REDUCE WAVE ENERGY IF LARGER THAN DEPTH LIMITED WAVE HEIGHT
    IF (LBIWBK) THEN
      ! [Loki] inlined child subroutine: SDEPTHLIM
      ! =========================================

      ! ----------------------------------------------------------------------


      LLEPSMIN = .true.
      ! [Loki] inlined child subroutine: SEMEAN
      ! =========================================

      ! ----------------------------------------------------------------------


      !*    1. INITIALISE ENERGY ARRAY.
      !        ------------------------

      IF (LLEPSMIN) THEN
        EM = EPSMIN
      ELSE
        EM = 0.0_JWRB
      END IF

      ! ----------------------------------------------------------------------

      !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTION.
      !        -----------------------------------------

!$acc loop seq
      DO SEMEAN_M=1,NFRE
        SEMEAN_K = 1
        SDEPTHLIM_TEMP = FL1(IJ, SEMEAN_K, SEMEAN_M)
!$acc loop seq
        DO SEMEAN_K=2,NANG
          SDEPTHLIM_TEMP = SDEPTHLIM_TEMP + FL1(IJ, SEMEAN_K, SEMEAN_M)
        END DO
        EM = EM + DFIM(SEMEAN_M)*SDEPTHLIM_TEMP
      END DO

      ! ----------------------------------------------------------------------

      !*    3. ADD TAIL ENERGY.
      !        ----------------

      DELT25 = WETAIL*FR(NFRE)*DELTH
      EM = EM + DELT25*SDEPTHLIM_TEMP


      ! =========================================

      EM = MIN(EMAXDPT(IJ) / EM, 1.0_JWRB)

!$acc loop seq
      DO SDEPTHLIM_M=1,NFRE
!$acc loop seq
        DO SDEPTHLIM_K=1,NANG
          FL1(IJ, SDEPTHLIM_K, SDEPTHLIM_M) = MAX(FL1(IJ, SDEPTHLIM_K, SDEPTHLIM_M)*EM, EPSMIN)
        END DO
      END DO


      ! =========================================
    END IF

    !*    2.2 COMPUTE MEAN PARAMETERS.
    !        ------------------------

    ! [Loki] inlined child subroutine: FKMEAN
    ! =========================================

    ! ----------------------------------------------------------------------



    !*    1. INITIALISE MEAN FREQUENCY ARRAY AND TAIL FACTOR.
    !        ------------------------------------------------

    EMEAN(IJ) = EPSMIN
    FMEAN(IJ) = EPSMIN
    F1MEAN(IJ) = EPSMIN
    AKMEAN(IJ) = EPSMIN
    XKMEAN(IJ) = EPSMIN

    FKMEAN_DELT25 = WETAIL*FR(NFRE)*DELTH
    COEFM1 = FRTAIL*DELTH
    COEF1 = WP1TAIL*DELTH*FR(NFRE)**2
    COEFA = COEFM1*SQRT(G) / ZPI
    COEFX = COEF1*(ZPI / SQRT(G))

    !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTIONS.
    !        ------------------------------------------

    !*    2.2 SHALLOW WATER INTEGRATION.
    !         --------------------------

!$acc loop seq
    DO FKMEAN_M=1,NFRE
      SQRTK = SQRT(WAVNUM(IJ, FKMEAN_M))
      TEMPA(IJ) = DFIM(FKMEAN_M) / SQRTK
      TEMPX(IJ) = SQRTK*DFIM(FKMEAN_M)
      FKMEAN_K = 1
      TEMP2(IJ) = FL1(IJ, FKMEAN_K, FKMEAN_M)
!$acc loop seq
      DO FKMEAN_K=2,NANG
        TEMP2(IJ) = TEMP2(IJ) + FL1(IJ, FKMEAN_K, FKMEAN_M)
      END DO
      EMEAN(IJ) = EMEAN(IJ) + DFIM(FKMEAN_M)*TEMP2(IJ)
      FMEAN(IJ) = FMEAN(IJ) + DFIMOFR(FKMEAN_M)*TEMP2(IJ)
      F1MEAN(IJ) = F1MEAN(IJ) + DFIMFR(FKMEAN_M)*TEMP2(IJ)
      AKMEAN(IJ) = AKMEAN(IJ) + TEMPA(IJ)*TEMP2(IJ)
      XKMEAN(IJ) = XKMEAN(IJ) + TEMPX(IJ)*TEMP2(IJ)
    END DO

    !*      ADD TAIL CORRECTION TO MEAN FREQUENCY AND
    !*      NORMALIZE WITH TOTAL ENERGY.
    EMEAN(IJ) = EMEAN(IJ) + FKMEAN_DELT25*TEMP2(IJ)
    FMEAN(IJ) = FMEAN(IJ) + COEFM1*TEMP2(IJ)
    FMEAN(IJ) = EMEAN(IJ) / FMEAN(IJ)
    F1MEAN(IJ) = F1MEAN(IJ) + COEF1*TEMP2(IJ)
    F1MEAN(IJ) = F1MEAN(IJ) / EMEAN(IJ)
    AKMEAN(IJ) = AKMEAN(IJ) + COEFA*TEMP2(IJ)
    AKMEAN(IJ) = (EMEAN(IJ) / AKMEAN(IJ))**2
    XKMEAN(IJ) = XKMEAN(IJ) + COEFX*TEMP2(IJ)
    XKMEAN(IJ) = (XKMEAN(IJ) / EMEAN(IJ))**2


    ! =========================================

!$acc loop seq
    DO K=1,NANG
      ! still allow noise in full sea ice cover, but only ten percent
      FLM(IJ, K) = (1._JWRB - 0.9_JWRB*MIN(CICOVER(IJ), 0.99_JWRB))*FLMIN*MAX(0.0_JWRB, COSWDIF(IJ, K))**2
    END DO

    ! ----------------------------------------------------------------------

    !*    2.3 COMPUTATION OF SOURCE FUNCTIONS.
    !         --------------------------------

    !*    2.3.1 ITERATIVELY UPDATE STRESS AND COMPUTE WIND INPUT TERMS.
    !           -------------------------------------------------------

    LUPDTUS = .true.
    NCALL = 2
!$acc loop seq
    DO ICALL=1,NCALL
      ! [Loki] inlined child subroutine: SINFLX
      ! =========================================

      ! ----------------------------------------------------------------------


      ! UPDATE UFRIC AND Z0M
      IF (ICALL == 1) THEN
        IUSFG = 0
        IF (LWCOU) THEN
          ICODE_WND = ICODE_CPL
        ELSE
          ICODE_WND = ICODE
        END IF
      ELSE
        IUSFG = 1
        ICODE_WND = 3
      END IF

      IF (LLNORMAGAM .and. LLCAPCHNK) THEN
        RNFAC = 1.0_JWRB + DTHRN_A*(1.0_JWRB + TANH(WSWAVE(IJ) - DTHRN_U))
      ELSE
        RNFAC = 1.0_JWRB
      END IF


      IF (LUPDTUS) THEN
        ! increase noise level in the tail
        IF (ICALL == 1) THEN
!$acc loop seq
          DO SINFLX_K=1,NANG
            FL1(IJ, SINFLX_K, NFRE) = MAX(FL1(IJ, SINFLX_K, NFRE), FLM(IJ, SINFLX_K))
          END DO

          IF (LLGCBZ0) THEN
            ! [Loki] inlined child subroutine: HALPHAP
            ! =========================================

            ! ----------------------------------------------------------------------


            ZLNFRNFRE = LOG(FR(NFRE))

            ! Find spectrum in wind direction
!$acc loop seq
            DO HALPHAP_K=1,NANG
              WD(IJ, HALPHAP_K) = 0.5_JWRB + 0.5_JWRB*SIGN(1.0_JWRB, COSWDIF(IJ, HALPHAP_K))
            END DO

!$acc loop seq
            DO SINFLX_M=1,NFRE
!$acc loop seq
              DO HALPHAP_K=1,NANG
                FLWD(IJ, HALPHAP_K, SINFLX_M) = FL1(IJ, HALPHAP_K, SINFLX_M)*WD(IJ, HALPHAP_K)
              END DO
            END DO

            ! [Loki] inlined child subroutine: MEANSQS_LF
            ! =========================================

            ! ----------------------------------------------------------------------

            !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTIONS.
            !        ------------------------------------------

            KFRE = MIN(NFRE, NFRE)

            XMSS = 0.0_JWRB

            !*    2.2 SHALLOW WATER INTEGRATION.
            !         --------------------------

!$acc loop seq
            DO MEANSQS_LF_M=1,KFRE
              TEMP1 = DFIM(MEANSQS_LF_M)*WAVNUM(IJ, MEANSQS_LF_M)**2
              SINFLX_TEMP2 = 0.0_JWRB
!$acc loop seq
              DO MEANSQS_LF_K=1,NANG
                SINFLX_TEMP2 = SINFLX_TEMP2 + FLWD(IJ, MEANSQS_LF_K, MEANSQS_LF_M)
              END DO
              XMSS = XMSS + TEMP1*SINFLX_TEMP2
            END DO


            ! =========================================

            ! [Loki] inlined child subroutine: FEMEAN
            ! =========================================

            ! ----------------------------------------------------------------------


            !*    1. INITIALISE MEAN FREQUENCY ARRAY AND TAIL FACTOR.
            !        ------------------------------------------------

            SINFLX_EM = 0.0_JWRB
            FM = 0.0_JWRB

            SINFLX_DELT25 = WETAIL*FR(NFRE)*DELTH
            DELT2 = FRTAIL*DELTH

            !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTIONS.
            !        ------------------------------------------

!$acc loop seq
            DO FEMEAN_M=1,NFRE
              FEMEAN_K = 1
              FEMEAN_TEMP2 = MAX(FLWD(IJ, FEMEAN_K, FEMEAN_M), EPSMIN)
!$acc loop seq
              DO FEMEAN_K=2,NANG
                FEMEAN_TEMP2 = FEMEAN_TEMP2 + MAX(FLWD(IJ, FEMEAN_K, FEMEAN_M), EPSMIN)
              END DO
              SINFLX_EM = SINFLX_EM + FEMEAN_TEMP2*DFIM(FEMEAN_M)
              FM = FM + DFIMOFR(FEMEAN_M)*FEMEAN_TEMP2
            END DO


            !*    3. ADD TAIL CORRECTION TO MEAN FREQUENCY AND
            !*       NORMALIZE WITH TOTAL ENERGY.
            !        ------------------------------------------

            SINFLX_EM = SINFLX_EM + SINFLX_DELT25*FEMEAN_TEMP2
            FM = FM + DELT2*FEMEAN_TEMP2
            FM = SINFLX_EM / FM
            FM = MAX(FM, FR(1))


            ! =========================================

            IF (SINFLX_EM > 0.0_JWRB .and. FM < FR(-2 + NFRE)) THEN
              ALPHAP = XMSS / (ZLNFRNFRE - LOG(FM))
              IF (ALPHAP > ALPHAPMAX) THEN
                ! some odd cases, revert to tail value
                F1D = 0.0_JWRB
!$acc loop seq
                DO HALPHAP_K=1,NANG
                  F1D = F1D + FLWD(IJ, HALPHAP_K, NFRE)*DELTH
                END DO
                ALPHAP = ZPI4GM2*FR5(NFRE)*F1D
              END IF
            ELSE
              F1D = 0.0_JWRB
!$acc loop seq
              DO HALPHAP_K=1,NANG
                F1D = F1D + FLWD(IJ, HALPHAP_K, NFRE)*DELTH
              END DO
              ALPHAP = ZPI4GM2*FR5(NFRE)*F1D
            END IF

            !     1/2 ALPHAP:
            HALP = 0.5_JWRB*MIN(ALPHAP, ALPHAPMAX)


            ! =========================================
          ELSE
            HALP = 0.0_JWRB
          END IF

        END IF

        ! [Loki] inlined child subroutine: AIRSEA
        ! =========================================

        ! ----------------------------------------------------------------------

        !*    2. DETERMINE TOTAL STRESS (if needed)
        !        ----------------------------------

        IF (ICODE_WND == 3) THEN

          ! [Loki] inlined child subroutine: TAUT_Z0
          ! =========================================

          ! ----------------------------------------------------------------------


          XLOGXL = LOG(XNLEV)
          US2TOTAUW = 1.0_JWRB + EPS1

          RNUEFF = 0.04_JWRB*RNU
          RNUKAPPAM1 = RNUEFF / XKAPPA

          PCE_GC = 0.001_JWRB*IUSFG + (1 - IUSFG)*0.005_JWRB

          !     ONLY take the contribution of TAUW that is in the wind direction
          COSDIFF = COS(WDWAVE(IJ) - TAUWDIR(IJ))
          TAUWACT = MAX(TAUW(IJ)*COSDIFF, EPSMIN)
          LLCOSDIFF = COSDIFF > 0.9_JWRB

          !  USING THE CG MODEL:
          IF (LLGCBZ0) THEN

            IF (LLCAPCHNK) THEN
              CHARNOCK_MIN = CHNKMIN_LOKI(WSWAVE(IJ))
              ALPHAOG = CHARNOCK_MIN*GM1
            ELSE
              ALPHAOG = 0.0_JWRB
            END IF

            USMAX = MAX(-0.21339_JWRB + 0.093698_JWRB*WSWAVE(IJ) - 0.0020944_JWRB*WSWAVE(IJ)**2 + 5.5091E-5_JWRB*WSWAVE(IJ)**3,  &
            & 0.03_JWRB)
            TAUWEFF = MIN(TAUWACT*US2TOTAUW, USMAX**2)


            IF (IUSFG == 0) THEN
              ALPHAGM1 = ALPHA*GM1
              IF (WSWAVE(IJ) < 1.0_JWRB) THEN
                CDFG = 0.002_JWRB
              ELSE IF (LLCOSDIFF) THEN
                X = MIN(TAUWACT / MAX(UFRIC(IJ), EPSUS)**2, PMAX)
                ZCHAR = MIN(ALPHAGM1*UFRIC(IJ)**2 / SQRT(1.0_JWRB - X), 0.05_JWRB*EXP(-0.05_JWRB*(WSWAVE(IJ) - 35._JWRB)))
                ZCHAR = MIN(ZCHAR, ALPHAMAX)
                CDFG = ACDLIN + BCDLIN*SQRT(ZCHAR)*WSWAVE(IJ)
              ELSE
                CDFG = CDM(WSWAVE(IJ))
              END IF
              UFRIC(IJ) = WSWAVE(IJ)*SQRT(CDFG)
            END IF

            W1 = 0.85_JWRB - 0.05_JWRB*(TANH(10.0_JWRB*(WSWAVE(IJ) - 5.0_JWRB)) + 1.0_JWRB)

            XKUTOP = XKAPPA*WSWAVE(IJ)

            USTOLD = UFRIC(IJ)
            TAUOLD = USTOLD**2

!$acc loop seq
            DO ITER=1,NITER
              !         Z0 IS DERIVED FROM THE NEUTRAL LOG PROFILE: UTOP = (USTAR/XKAPPA)*LOG((XNLEV+Z0)/Z0)
              Z0M(IJ) = MAX(XNLEV / (EXP(MIN(XKUTOP / USTOLD, 50.0_JWRB)) - 1.0_JWRB), Z0MIN)
              ! Viscous kinematic stress nu_air * dU/dz at z=0 of the neutral log profile reduced by factor 25 (0.04)
              TAUV = RNUKAPPAM1*USTOLD / Z0M(IJ)

              ANG_GC = ANG_GC_A + ANG_GC_B*TANH(ANG_GC_C*TAUOLD)

              TAUUNR = STRESS_GC_LOKI(ANG_GC, UFRIC(IJ), Z0M(IJ), Z0MIN, HALP, RNFAC)

              !         TOTAL kinematic STRESS:
              TAUNEW = TAUWEFF + TAUV + TAUUNR
              USTNEW = SQRT(TAUNEW)
              UFRIC(IJ) = W1*USTOLD + (1.0_JWRB - W1)*USTNEW

              !         CONVERGENCE ?
              DEL = UFRIC(IJ) - USTOLD
              IF (ABS(DEL) < PCE_GC*UFRIC(IJ)) EXIT
              TAUOLD = UFRIC(IJ)**2
              USTOLD = UFRIC(IJ)
            END DO

            X = TAUWEFF / TAUOLD

            ! protection just in case there is no convergence
            IF (ITER > NITER .and. X >= PMAX) THEN
              CDFG = CDM(WSWAVE(IJ))
              UFRIC(IJ) = WSWAVE(IJ)*SQRT(CDFG)
              Z0MINRST = UFRIC(IJ)**2*ALPHA*GM1
              Z0M(IJ) = MAX(XNLEV / (EXP(XKUTOP / UFRIC(IJ)) - 1.0_JWRB), Z0MINRST)
              Z0B(IJ) = Z0MINRST
            ELSE
              Z0M(IJ) = MAX(XNLEV / (EXP(XKUTOP / UFRIC(IJ)) - 1.0_JWRB), Z0MIN)
              Z0B(IJ) = Z0M(IJ)*SQRT(TAUUNR / TAUOLD)
            END IF

            !       Refine solution

            IF (X < PMAX) THEN

              USNRF = UFRIC(IJ)
              Z0NRF = Z0M(IJ)
              Z0BNRF = Z0B(IJ)

              USTOLD = UFRIC(IJ)
              TAUOLD = MAX(USTOLD**2, TAUWEFF)

              ALPOG = MAX(MIN(Z0B(IJ) / TAUOLD, ALPHAMAX), ALPHAOG)

!$acc loop seq
              DO ITER=1,NITER
                X = MIN(TAUWEFF / TAUOLD, PMAX)
                USTM1 = 1.0_JWRB / MAX(USTOLD, EPSUS)
                Z0VIS = RNUM*USTM1
                HZ0VISO1MX = 0.5_JWRB*Z0VIS / (1.0_JWRB - X)
                Z0B(IJ) = ALPOG*TAUOLD
                Z0M(IJ) = HZ0VISO1MX + SQRT(HZ0VISO1MX**2 + Z0B(IJ)**2 / (1.0_JWRB - X))

                XOLOGZ0 = 1.0_JWRB / LOG(XNLEV / Z0M(IJ) + 1.0_JWRB)
                F = USTOLD - XKUTOP*XOLOGZ0
                ZZ = 2.0_JWRB*USTM1*(3.0_JWRB*Z0B(IJ)**2 + 0.5_JWRB*Z0VIS*Z0M(IJ) - Z0M(IJ)**2) / (2.0_JWRB*Z0M(IJ)**2*(1.0_JWRB  &
                & - X) - Z0VIS*Z0M(IJ))

                DELF = 1.0_JWRB - XKUTOP*XOLOGZ0**2*ZZ

                IF (DELF /= 0.0_JWRB) UFRIC(IJ) = USTOLD - F / DELF
                !           CONVERGENCE ?
                TAUNEW = MAX(UFRIC(IJ)**2, TAUWEFF)
                UFRIC(IJ) = SQRT(TAUNEW)
                DEL = TAUNEW - TAUOLD
                IF (ABS(DEL) < PCE_GC*TAUOLD) EXIT
                TAUOLD = TAUNEW
                USTOLD = UFRIC(IJ)

              END DO
              ! protection just in case there is no convergence
              IF (ITER > NITER) THEN
                UFRIC(IJ) = USNRF
                Z0M(IJ) = Z0NRF
                Z0B(IJ) = Z0BNRF
                USTM1 = 1.0_JWRB / MAX(UFRIC(IJ), EPSUS)
                Z0VIS = RNUM*USTM1
                CHRNCK(IJ) = MAX(G*(Z0M(IJ) - Z0VIS)*USTM1**2, ALPHAMIN)

              ELSE
                CHRNCK(IJ) = MAX(G*(Z0B(IJ) / SQRT(1.0_JWRB - X)) / MAX(UFRIC(IJ), EPSUS)**2, ALPHAMIN)
              END IF

            ELSE
              USTM1 = 1.0_JWRB / MAX(UFRIC(IJ), EPSUS)
              Z0VIS = RNUM*USTM1
              CHRNCK(IJ) = MAX(G*(Z0M(IJ) - Z0VIS)*USTM1**2, ALPHAMIN)
            END IF



          ELSE

            TAUWEFF = TAUWACT*US2TOTAUW

            IF (LLCAPCHNK) THEN
              CHARNOCK_MIN = CHNKMIN_LOKI(WSWAVE(IJ))
              XMIN = 0.15_JWRB*(ALPHA - CHARNOCK_MIN)
              ALPHAOG = CHARNOCK_MIN*GM1
            ELSE
              XMIN = 0.0_JWRB
              ALPHAOG = ALPHA*GM1
            END IF

            XKUTOP = XKAPPA*WSWAVE(IJ)

            USTOLD = (1 - IUSFG)*WSWAVE(IJ)*SQRT(MIN(ACD + BCD*WSWAVE(IJ), CDMAX)) + IUSFG*UFRIC(IJ)
            TAUOLD = MAX(USTOLD**2, TAUWEFF)
            UFRIC(IJ) = SQRT(TAUOLD)
            USTM1 = 1.0_JWRB / MAX(UFRIC(IJ), EPSUS)

!$acc loop seq
            DO ITER=1,NITER
              X = MAX(TAUWACT / TAUOLD, XMIN)
              Z0CH = ALPHAOG*TAUOLD / SQRT(1.0_JWRB - X)
              Z0VIS = RNUM*USTM1
              Z0TOT = Z0CH + Z0VIS

              XOLOGZ0 = 1.0_JWRB / (XLOGXL - LOG(Z0TOT))
              F = UFRIC(IJ) - XKUTOP*XOLOGZ0
              ZZ = USTM1*(Z0CH*(2.0_JWRB - TWOXMP1*X) / (1.0_JWRB - X) - Z0VIS) / Z0TOT
              DELF = 1.0_JWRB - XKUTOP*XOLOGZ0**2*ZZ

              IF (DELF /= 0.0_JWRB) UFRIC(IJ) = UFRIC(IJ) - F / DELF
              TAUNEW = MAX(UFRIC(IJ)**2, TAUWEFF)
              UFRIC(IJ) = SQRT(TAUNEW)
              IF (TAUNEW == TAUOLD) EXIT
              USTM1 = 1.0_JWRB / MAX(UFRIC(IJ), EPSUS)
              TAUOLD = TAUNEW
            END DO

            Z0M(IJ) = Z0CH
            Z0B(IJ) = ALPHAOG*TAUOLD
            CHRNCK(IJ) = MAX(G*Z0M(IJ)*USTM1**2, ALPHAMIN)


          END IF


          ! =========================================

        ELSE IF (ICODE_WND == 1 .or. ICODE_WND == 2) THEN

          ! [Loki] Removed content of pragma-marked region!
        END IF


        ! =========================================

      END IF

      ! COMPUTE WIND INPUT
      !!  FLD AND SL ARE INITIALISED IN SINPUT
      IF (ICALL < NCALL) THEN
        NGST = 1
        LLPHIWA = .false.
        LLSNEG = .false.
      ELSE
        NGST = 2
        LLPHIWA = .true.
        LLSNEG = .true.
      END IF

      ! [Loki] inlined child subroutine: SINPUT
      ! =========================================
      ! ----------------------------------------------------------------------


      SELECT CASE (IPHYS)
      CASE (0)
        ! [Loki] Removed content of pragma-marked region!
      CASE (1)
        ! [Loki] inlined child subroutine: SINPUT_ARD
        ! =========================================
        ! ----------------------------------------------------------------------


        AVG_GST = 1.0_JWRB / NGST
        CONST1 = BETAMAXOXKAPPA2
        CONSTN = DELTH / (XKAPPA*ZPI)

        ABS_TAUWSHELTER = ABS(TAUWSHELTER)
        IF (ABS_TAUWSHELTER == 0.0_JWRB) THEN
          LTAUWSHELTER = .false.
        ELSE
          LTAUWSHELTER = .true.
        END IF


        !     ESTIMATE THE STANDARD DEVIATION OF GUSTINESS.
        IF (NGST > 1) THEN
          ! [Loki] inlined child subroutine: WSIGSTAR
          ! =========================================


          ! ----------------------------------------------------------------------


          IF (LLGCBZ0 .or. LLNORMAGAM) THEN
            ZN = RNUM

            U10M1 = 1.0_JWRB / MAX(WSWAVE(IJ), WSPMIN)
            ! CHARNOCK:
            WSIGSTAR_Z0VIS = ZN / MAX(UFRIC(IJ), EPSUS)
            SINPUT_ZCHAR = G*(Z0M(IJ) - WSIGSTAR_Z0VIS) / MAX(UFRIC(IJ)**2, EPSUS)
            SINPUT_ZCHAR = MAX(MIN(SINPUT_ZCHAR, ALPHAMAX), ALPHAMIN)

            BCD_LOC = BCDLIN*SQRT(SINPUT_ZCHAR)
            C_D = ACDLIN + BCD_LOC*WSWAVE(IJ)
            DC_DDU = BCD_LOC
            SIG_CONV = 1.0_JWRB + 0.5_JWRB*WSWAVE(IJ) / C_D*DC_DDU
            SIG_N = MIN(SIG_NMAX, SIG_CONV*U10M1*(BG_GUST*UFRIC(IJ)**3 + 0.5_JWRB*XKAPPA*WSTAR(IJ)**3)**ONETHIRD)

          ELSE
            ZN = 0.0_JWRB


            !!! for consistency I have kept the old method, even though the new method above could be used,
            !!! but until LLGCBZ0 or LLNORMAGAM is the default, keep the old scheme whe it is not...
            !
            !       IN THE FOLLOWING U10 IS ESTIMATED ASSUMING EVERYTHING IS
            !       BASED ON U*
            !
            SINPUT_XKAPPAD = 1.0_JWRB / XKAPPA
            U10 = UFRIC(IJ)*SINPUT_XKAPPAD*(LOG(10.0_JWRB) - LOG(Z0M(IJ)))
            U10 = MAX(U10, WSPMIN)
            U10M1 = 1.0_JWRB / U10
            C2U10P1 = C2*U10**P1
            U10P2 = U10**P2
            C_D = (C1 + C2U10P1)*U10P2
            DC_DDU = (P2*C1 + (P1 + P2)*C2U10P1)*U10P2*U10M1
            SIG_CONV = 1.0_JWRB + 0.5_JWRB*U10 / C_D*DC_DDU
            SIG_N = MIN(SIG_NMAX, SIG_CONV*U10M1*(BG_GUST*UFRIC(IJ)**3 + 0.5_JWRB*XKAPPA*WSTAR(IJ)**3)**ONETHIRD)

          END IF


          ! =========================================
        END IF


        IF (LLNORMAGAM) THEN
          CSTRNFAC = CONSTN*RNFAC / RAORW
        END IF
        ! ----------------------------------------------------------------------

        IF (LLSNEG) THEN
          !!!!  only for the negative sinput
          NU_AIR = RNU
          FACM1_NU_AIR = 4.0_JWRB / NU_AIR

          FAC_NU_AIR = RNUM

          FU = ABS(SWELLF3)
          FUD = SWELLF2
          DELABM1 = REAL(IAB) / (ABMAX - ABMIN)


          !       computation of Uorb and Aorb
          UORBT = EPSMIN
          AORB = EPSMIN

!$acc loop seq
          DO SINPUT_M=1,NFRE
            SIG = ZPIFR(SINPUT_M)
            SIG2 = SIG**2
            DFIM_SIG2 = DFIM(SINPUT_M)*SIG2

            SINPUT_K = 1
            SINFLX_TEMP = FL1(IJ, SINPUT_K, SINPUT_M)
!$acc loop seq
            DO SINPUT_K=2,NANG
              SINFLX_TEMP = SINFLX_TEMP + FL1(IJ, SINPUT_K, SINPUT_M)
            END DO

            UORBT = UORBT + DFIM_SIG2*SINFLX_TEMP
            AORB = AORB + DFIM(SINPUT_M)*SINFLX_TEMP
          END DO

          UORBT = 2.0_JWRB*SQRT(UORBT)            ! this is the significant orbital amplitude
          AORB = 2.0_JWRB*SQRT(AORB)            ! this 1/2 Hs
          RE = FACM1_NU_AIR*UORBT*AORB            ! this is the Reynolds number
          SINPUT_Z0VIS = FAC_NU_AIR / MAX(UFRIC(IJ), 0.0001_JWRB)
          Z0TUB = Z0RAT*MIN(Z0TUBMAX, Z0M(IJ))
          Z0NOZ = MAX(SINPUT_Z0VIS, Z0TUB)
          ZORB = AORB / Z0NOZ

          !         compute fww
          SINPUT_XI = (LOG10(MAX(ZORB, 3.0_JWRB)) - ABMIN)*DELABM1
          IND = MIN(IAB - 1, INT(SINPUT_XI))
          SINPUT_DELI1 = MIN(1.0_JWRB, SINPUT_XI - REAL(IND, kind=JWRB))
          SINPUT_DELI2 = 1.0_JWRB - SINPUT_DELI1
          FWW = SWELLFT(IND)*SINPUT_DELI2 + SWELLFT(IND + 1)*SINPUT_DELI1
          SINPUT_TEMP2 = FWW*UORBT

          !       Define the critical Reynolds number
          IF (SWELLF6 == 1.0_JWRB) THEN
            RE_C = SWELLF4
          ELSE
            HFTSWELLF6 = 1.0_JWRB - SWELLF6
            RE_C = SWELLF4*(2.0_JWRB / AORB)**HFTSWELLF6
          END IF

          !       Swell damping weight between viscous and turbulent boundary layer
          IF (SWELLF7 > 0.0_JWRB) THEN
            SMOOTH = 0.5_JWRB*TANH((RE - RE_C)*SWELLF7M1)
            PTURB = 0.5_JWRB + SMOOTH
            PVISC = 0.5_JWRB - SMOOTH
          ELSE
            IF (RE <= RE_C) THEN
              PTURB = 0.0_JWRB
              PVISC = 0.5_JWRB
            ELSE
              PTURB = 0.5_JWRB
              PVISC = 0.0_JWRB
            END IF
          END IF

          AIRD_PVISC = PVISC*RAORW

        END IF



        ! Initialisation

        IF (NGST == 1) THEN
          USTP(1) = UFRIC(IJ)
        ELSE IF (NGST == 2) THEN
          USTP(1) = UFRIC(IJ)*(1.0_JWRB + SIG_N)
          USTP(2) = UFRIC(IJ)*(1.0_JWRB - SIG_N)
        END IF

        !... Expressing the IGST loop in this way enables the compiler to
        !... unroll it whilst still retaining correctness for the case
        !... where NGST == 1. This is an important optimisation for GPUs.
!$acc loop seq
        DO IGST=1,2
          IF (IGST <= NGST) THEN
            USTPM1(IGST) = 1.0_JWRB / MAX(USTP(IGST), EPSUS)
          END IF
        END DO

        IF (LTAUWSHELTER) THEN
!$acc loop seq
          DO IGST=1,2
            IF (IGST <= NGST) THEN
              XSTRESS(IGST) = 0.0_JWRB
              YSTRESS(IGST) = 0.0_JWRB
              USG2 = USTP(IGST)**2
              TAUX(IGST) = USG2*SIN(WDWAVE(IJ))
              TAUY(IGST) = USG2*COS(WDWAVE(IJ))
            END IF
          END DO

          ROGOROAIR = G / RAORW

        ELSE
!$acc loop seq
          DO SINPUT_K=1,NANG
            COSLP(IJ, SINPUT_K) = COSWDIF(IJ, SINPUT_K)
          END DO
        END IF


        !*    2. MAIN LOOP OVER FREQUENCIES.
        !        ---------------------------

        IF (.not.LLNORMAGAM) THEN
          GAMNORMA(1) = 1.0_JWRB
          GAMNORMA(2) = 1.0_JWRB
        END IF

        IF (.not.LLSNEG) THEN
!$acc loop seq
          DO SINPUT_K=1,NANG
            DSTAB(IJ, SINPUT_K, 1) = 0.0_JWRB
            DSTAB(IJ, SINPUT_K, 2) = 0.0_JWRB
          END DO
        END IF

!$acc loop seq
        DO SINPUT_M=1,NFRE
          SIG = ZPIFR(SINPUT_M)
          SIG2 = SIG**2
          SINPUT_CONST = SIG*CONST1

          IF (LLSNEG) THEN
            COEF = -SWELLF*16._JWRB*SIG2 / G
            COEF5 = -SWELLF5*2._JWRB*SQRT(2._JWRB*NU_AIR*SIG)
          END IF

          IF (LTAUWSHELTER) THEN
!$acc loop seq
            DO IGST=1,2
              IF (IGST <= NGST) THEN
                TAUPX = TAUX(IGST) - ABS_TAUWSHELTER*XSTRESS(IGST)
                TAUPY = TAUY(IGST) - ABS_TAUWSHELTER*YSTRESS(IGST)
                USDIRP(IGST) = ATAN2(TAUPX, TAUPY)
                USTP(IGST) = (TAUPX**2 + TAUPY**2)**0.25_JWRB
                USTPM1(IGST) = 1.0_JWRB / MAX(USTP(IGST), EPSUS)
              END IF
            END DO

            CONSTF = ROGOROAIR*CINV(IJ, SINPUT_M)*DFIM(SINPUT_M)
          END IF


          !*      PRECALCULATE FREQUENCY DEPENDENCE.
          !       ----------------------------------

!$acc loop seq
          DO IGST=1,2
            IF (IGST <= NGST) THEN
              UCN(IGST) = USTP(IGST)*CINV(IJ, SINPUT_M)
              UCNZALPD(IGST) = XKAPPA / (UCN(IGST) + ZALP)
            END IF
          END DO
          ZCN = LOG(WAVNUM(IJ, SINPUT_M)*Z0M(IJ))
          CNSN = SINPUT_CONST*RAORW

          !*    2.1 LOOP OVER DIRECTIONS.
          !         ---------------------

!$acc loop seq
          DO SINPUT_K=1,NANG
            XLLWS(IJ, SINPUT_K, SINPUT_M) = 0.0_JWRB
          END DO

          IF (LLNORMAGAM) THEN
            XNGAMCONST = CSTRNFAC*XK2CG(IJ, SINPUT_M)
          END IF

          IF (LLSNEG) THEN
            !       SWELL DAMPING:
            DSTAB1 = COEF5*AIRD_PVISC*WAVNUM(IJ, SINPUT_M)
            SINPUT_TEMP1 = COEF*RAORW
          END IF

!$acc loop seq
          DO IGST=1,2
            IF (IGST <= NGST) THEN
!$acc loop seq
              DO SINPUT_K=1,NANG
                IF (LTAUWSHELTER) THEN
                  COSLP(IJ, SINPUT_K) = COS(TH(SINPUT_K) - USDIRP(IGST))
                END IF
                GAM0(IJ, SINPUT_K, IGST) = 0.0_JWRB
                IF (COSLP(IJ, SINPUT_K) > 0.01_JWRB) THEN
                  SINPUT_X = COSLP(IJ, SINPUT_K)*UCN(IGST)
                  ZLOG = ZCN + UCNZALPD(IGST) / COSLP(IJ, SINPUT_K)
                  IF (ZLOG < 0.0_JWRB) THEN
                    ZLOG2X = ZLOG*ZLOG*SINPUT_X
                    GAM0(IJ, SINPUT_K, IGST) = EXP(ZLOG)*ZLOG2X*ZLOG2X*CNSN
                    XLLWS(IJ, SINPUT_K, SINPUT_M) = 1.0_JWRB
                  END IF
                END IF
              END DO

              IF (LLNORMAGAM) THEN

                SUMF = 0.0_JWRB
                SUMFSIN2 = 0.0_JWRB
!$acc loop seq
                DO SINPUT_K=1,NANG
                  SUMF = SUMF + GAM0(IJ, SINPUT_K, IGST)*FL1(IJ, SINPUT_K, SINPUT_M)
                  SUMFSIN2 = SUMFSIN2 + GAM0(IJ, SINPUT_K, IGST)*FL1(IJ, SINPUT_K, SINPUT_M)*SINWDIF2(IJ, SINPUT_K)
                END DO

                ZNZ = XNGAMCONST*USTPM1(IGST)
                GAMNORMA(IGST) = (1.0_JWRB + ZNZ*SUMFSIN2) / (1.0_JWRB + ZNZ*SUMF)

              END IF

              IF (LLSNEG) THEN
!$acc loop seq
                DO SINPUT_K=1,NANG
                  DSTAB2 = SINPUT_TEMP1*(SINPUT_TEMP2 + (FU + FUD*COSLP(IJ, SINPUT_K))*USTP(IGST))
                  DSTAB(IJ, SINPUT_K, IGST) = DSTAB1 + PTURB*DSTAB2
                END DO
              END IF
            END IF
          END DO


          !*    2.2 UPDATE THE SHELTERING STRESS (in any),
          !         AND THEN ADDING INPUT SOURCE TERM TO NET SOURCE FUNCTION.
          !         ---------------------------------------------------------

!$acc loop seq
          DO SINPUT_K=1,NANG

!$acc loop seq
            DO IGST=1,2
              IF (IGST <= NGST) THEN
                ! SLP: only the positive contributions
                SLP = GAM0(IJ, SINPUT_K, IGST)*GAMNORMA(IGST)
                FLP = SLP + DSTAB(IJ, SINPUT_K, IGST)

                SLP = SLP*FL1(IJ, SINPUT_K, SINPUT_M)

                IF (LTAUWSHELTER) THEN
                  CONST11 = CONSTF*SINTH(SINPUT_K)
                  CONST22 = CONSTF*COSTH(SINPUT_K)
                  XSTRESS(IGST) = XSTRESS(IGST) + SLP*CONST11
                  YSTRESS(IGST) = YSTRESS(IGST) + SLP*CONST22
                END IF

                IF (IGST == 1) THEN
                  SLP_AVG = SLP
                  FLP_AVG = FLP
                ELSE
                  SLP_AVG = SLP_AVG + SLP
                  FLP_AVG = FLP_AVG + FLP
                END IF
              END IF
            END DO

            SPOS(IJ, SINPUT_K, SINPUT_M) = AVG_GST*SLP_AVG

            FLD(IJ, SINPUT_K, SINPUT_M) = AVG_GST*FLP_AVG
            SL(IJ, SINPUT_K, SINPUT_M) = FLD(IJ, SINPUT_K, SINPUT_M)*FL1(IJ, SINPUT_K, SINPUT_M)

          END DO

        END DO
        ! END LOOP OVER FREQUENCIES


        ! =========================================
      END SELECT


      ! =========================================


      ! MEAN FREQUENCY CHARACTERISTIC FOR WIND SEA
      ! [Loki] inlined child subroutine: FEMEANWS
      ! =========================================

      ! ----------------------------------------------------------------------


      !*    1. INITIALISE MEAN FREQUENCY ARRAY AND TAIL FACTOR.
      !        ------------------------------------------------

      EM_LOC = EPSMIN
      FMEANWS(IJ) = EPSMIN

      FEMEANWS_DELT25 = WETAIL*FR(NFRE)*DELTH
      FEMEANWS_DELT2 = FRTAIL*DELTH


      !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTIONS.
      !        ------------------------------------------

!$acc loop seq
      DO FEMEANWS_M=1,NFRE
        FEMEANWS_TEMP2 = 0.0_JWRB
!$acc loop seq
        DO FEMEANWS_K=1,NANG
          FEMEANWS_TEMP2 = FEMEANWS_TEMP2 + XLLWS(IJ, FEMEANWS_K, FEMEANWS_M)*FL1(IJ, FEMEANWS_K, FEMEANWS_M)
        END DO
        EM_LOC = EM_LOC + DFIM(FEMEANWS_M)*FEMEANWS_TEMP2
        FMEANWS(IJ) = FMEANWS(IJ) + DFIMOFR(FEMEANWS_M)*FEMEANWS_TEMP2
      END DO

      !*    3. ADD TAIL CORRECTION TO MEAN FREQUENCY AND
      !*       NORMALIZE WITH TOTAL ENERGY.
      !        ------------------------------------------

      EM_LOC = EM_LOC + FEMEANWS_DELT25*FEMEANWS_TEMP2
      FMEANWS(IJ) = FMEANWS(IJ) + FEMEANWS_DELT2*FEMEANWS_TEMP2
      FMEANWS(IJ) = EM_LOC / FMEANWS(IJ)



      ! =========================================

      ! COMPUTE LAST FREQUENCY INDEX OF PROGNOSTIC PART OF SPECTRUM.
      ! [Loki] inlined child subroutine: FRCUTINDEX
      ! =========================================

      ! ----------------------------------------------------------------------


      !*    COMPUTE LAST FREQUENCY INDEX OF PROGNOSTIC PART OF SPECTRUM.
      !*    FREQUENCIES LE MAX(TAILFACTOR*MAX(FMNWS,FM),TAILFACTOR_PM*FPM),
      !*    WHERE FPM IS THE PIERSON-MOSKOWITZ FREQUENCY BASED ON FRICTION
      !*    VELOCITY. (FPM=G/(FRIC*ZPI*USTAR))
      !     ------------------------------------------------------------

      FPMH = TAILFACTOR / FR(1)
      FPPM = TAILFACTOR_PM*G / (FRIC*ZPIFR(1))

      IF (CICOVER(IJ) <= CITHRSH_TAIL) THEN
        FM2 = MAX(FMEANWS(IJ), FMEAN(IJ))*FPMH
        FPM = FPPM / MAX(UFRIC(IJ), EPSMIN)
        FPM4 = MAX(FM2, FPM)
        MIJ(IJ) = NINT(LOG10(FPM4)*FLOGSPRDM1) + 1
        MIJ(IJ) = MIN(MAX(1, MIJ(IJ)), NFRE)
      ELSE
        MIJ(IJ) = NFRE
      END IF

      !     SET RHOWGDFTH
!$acc loop seq
      DO FRCUTINDEX_M=1,MIJ(IJ)
        RHOWGDFTH(IJ, FRCUTINDEX_M) = RHOWG_DFIM(FRCUTINDEX_M)
      END DO
      IF (MIJ(IJ) /= NFRE) RHOWGDFTH(IJ, MIJ(IJ)) = 0.5_JWRB*RHOWGDFTH(IJ, MIJ(IJ))
!$acc loop seq
      DO FRCUTINDEX_M=MIJ(IJ) + 1,NFRE
        RHOWGDFTH(IJ, FRCUTINDEX_M) = 0.0_JWRB
      END DO


      ! =========================================

      ! UPDATE TAUW
      ! [Loki] inlined child subroutine: STRESSO
      ! =========================================

      ! ----------------------------------------------------------------------


      PHIWA(IJ) = 0.0_JWRB
      STRESSO_XSTRESS = 0.0_JWRB
      STRESSO_YSTRESS = 0.0_JWRB

      !*    CONTRIBUTION TO THE WAVE STRESS FROM THE NEGATIVE PART OF THE WIND INPUT
      !     ------------------------------------------------------------------------

      IF (LLPHIWA) THEN
        !     full energy flux due to negative Sinput (SL-SPOS)
        !     we assume that above NFRE, the contibutions can be neglected
!$acc loop seq
        DO STRESSO_M=1,NFRE
!$acc loop seq
          DO STRESSO_K=1,NANG
            PHIWA(IJ) = PHIWA(IJ) + (SL(IJ, STRESSO_K, STRESSO_M) - SPOS(IJ, STRESSO_K, STRESSO_M))*RHOWG_DFIM(STRESSO_M)
          END DO
        END DO
      END IF

      !*    CALCULATE LOW-FREQUENCY CONTRIBUTION TO STRESS AND ENERGY FLUX (positive sinput).
      !     ---------------------------------------------------------------------------------
!$acc loop seq
      DO STRESSO_M=1,NFRE
        !     THE INTEGRATION ONLY UP TO FR=MIJ SINCE RHOWGDFTH=0 FOR FR>MIJ
        STRESSO_K = 1
        SUMX = SPOS(IJ, STRESSO_K, STRESSO_M)*SINTH(STRESSO_K)
        SUMY = SPOS(IJ, STRESSO_K, STRESSO_M)*COSTH(STRESSO_K)
        SUMT = SPOS(IJ, STRESSO_K, STRESSO_M)
!$acc loop seq
        DO STRESSO_K=2,NANG
          SUMX = SUMX + SPOS(IJ, STRESSO_K, STRESSO_M)*SINTH(STRESSO_K)
          SUMY = SUMY + SPOS(IJ, STRESSO_K, STRESSO_M)*COSTH(STRESSO_K)
          SUMT = SUMT + SPOS(IJ, STRESSO_K, STRESSO_M)
        END DO
        CMRHOWGDFTH = RHOWGDFTH(IJ, STRESSO_M)*CINV(IJ, STRESSO_M)
        STRESSO_XSTRESS = STRESSO_XSTRESS + CMRHOWGDFTH*SUMX
        STRESSO_YSTRESS = STRESSO_YSTRESS + CMRHOWGDFTH*SUMY

        IF (LLPHIWA) THEN
          PHIWA(IJ) = PHIWA(IJ) + RHOWGDFTH(IJ, STRESSO_M)*SUMT
        END IF
      END DO

      !     TAUW is the kinematic wave stress !
      STRESSO_XSTRESS = STRESSO_XSTRESS / MAX(AIRD(IJ), 1.0_JWRB)
      STRESSO_YSTRESS = STRESSO_YSTRESS / MAX(AIRD(IJ), 1.0_JWRB)


      !*    CALCULATE HIGH-FREQUENCY CONTRIBUTION TO STRESS and energy flux (positive sinput).
      !     ----------------------------------------------------------------------------------

      IF (IPHYS == 0 .or. TAUWSHELTER == 0.0_JWRB) THEN
        STRESSO_LTAUWSHELTER = .false.
        STRESSO_USDIRP = WDWAVE(IJ)
        UST = UFRIC(IJ)
      ELSE
        STRESSO_LTAUWSHELTER = .true.
        STRESSO_TAUX = UFRIC(IJ)**2*SIN(WDWAVE(IJ))
        STRESSO_TAUY = UFRIC(IJ)**2*COS(WDWAVE(IJ))
        STRESSO_TAUPX = STRESSO_TAUX - TAUWSHELTER*STRESSO_XSTRESS
        STRESSO_TAUPY = STRESSO_TAUY - TAUWSHELTER*STRESSO_YSTRESS
        STRESSO_USDIRP = ATAN2(STRESSO_TAUPX, STRESSO_TAUPY)
        UST = (STRESSO_TAUPX**2 + STRESSO_TAUPY**2)**0.25_JWRB
      END IF

      ! [Loki] inlined child subroutine: TAU_PHI_HF
      ! =========================================


      ! ----------------------------------------------------------------------


      IF (LLGCBZ0) THEN
        ! [Loki] inlined child subroutine: OMEGAGC
        ! =========================================
        ! ----------------------------------------------------------------------


        NS = NS_GC_LOKI(UFRIC(IJ))
        XKS = XK_GC(NS)
        OMS = OMEGA_GC(NS)


        ! =========================================
      END IF

      !     See INIT_X0TAUHF
      X0G = X0TAUHF*G

      IF (LLPHIWA) USTPH = UST

      !*    COMPUTE THE INTEGRALS
      !     ---------------------

      XLOGGZ0 = LOG(G*Z0M(IJ))
      OMEGACC = MAX(ZPIFR(MIJ(IJ)), X0G / UST)
      SQRTZ0OG = SQRT(Z0M(IJ)*GM1)
      SQRTGZ0 = 1.0_JWRB / SQRTZ0OG
      YC = OMEGACC*SQRTZ0OG
      ZINF = LOG(YC)

      CONSTTAU = ZPI4GM2*FR5(MIJ(IJ))

      TAU_PHI_HF_K = 1
      TAU_PHI_HF_COSW = MAX(COSWDIF(IJ, TAU_PHI_HF_K), 0.0_JWRB)
      TAU_PHI_HF_FCOSW2 = FL1(IJ, TAU_PHI_HF_K, MIJ(IJ))*TAU_PHI_HF_COSW**2
      F1DCOS3 = TAU_PHI_HF_FCOSW2*TAU_PHI_HF_COSW
      F1DCOS2 = TAU_PHI_HF_FCOSW2
      F1DSIN2 = FL1(IJ, TAU_PHI_HF_K, MIJ(IJ))*SINWDIF2(IJ, TAU_PHI_HF_K)
      STRESSO_F1D = FL1(IJ, TAU_PHI_HF_K, MIJ(IJ))
!$acc loop seq
      DO TAU_PHI_HF_K=2,NANG
        TAU_PHI_HF_COSW = MAX(COSWDIF(IJ, TAU_PHI_HF_K), 0.0_JWRB)
        TAU_PHI_HF_FCOSW2 = FL1(IJ, TAU_PHI_HF_K, MIJ(IJ))*TAU_PHI_HF_COSW**2
        F1DCOS3 = F1DCOS3 + TAU_PHI_HF_FCOSW2*TAU_PHI_HF_COSW
        F1DCOS2 = F1DCOS2 + TAU_PHI_HF_FCOSW2
        F1DSIN2 = F1DSIN2 + FL1(IJ, TAU_PHI_HF_K, MIJ(IJ))*SINWDIF2(IJ, TAU_PHI_HF_K)
        STRESSO_F1D = STRESSO_F1D + FL1(IJ, TAU_PHI_HF_K, MIJ(IJ))
      END DO
      F1DCOS3 = DELTH*F1DCOS3
      F1DCOS2 = DELTH*F1DCOS2
      F1DSIN2 = DELTH*F1DSIN2
      STRESSO_F1D = DELTH*STRESSO_F1D

      IF (LLNORMAGAM) THEN
        CONFG = GAMNCONST*FR5(MIJ(IJ))*RNFAC*SQRTGZ0
        STRESSO_CONST1 = CONFG*F1DSIN2
        CONST2 = CONFG*STRESSO_F1D
      ELSE
        STRESSO_CONST1 = 0.0_JWRB
        CONST2 = 0.0_JWRB
      END IF


      !     TAUHF :
      IF (LLGCBZ0) THEN
        ZSUP = MIN(LOG(OMS*SQRTZ0OG), ZSUPMAX)
      ELSE
        ZSUP = ZSUPMAX
      END IF

      TAUL = UST**2
      DELZ = MAX((ZSUP - ZINF) / REAL(JTOT_TAUHF - 1, kind=JWRB), 0.0_JWRB)
      TAUHF = 0.0_JWRB

      ! Intergrals are integrated following a change of variable : Z=LOG(Y)
      IF (STRESSO_LTAUWSHELTER) THEN
!$acc loop seq
        DO TAU_PHI_HF_J=1,JTOT_TAUHF
          Y = EXP(ZINF + REAL(TAU_PHI_HF_J - 1, kind=JWRB)*DELZ)
          OMEGA = Y*SQRTGZ0
          CM1 = OMEGA*GM1
          ZX = UST*CM1 + ZALP
          ZARG = XKAPPA / ZX
          STRESSO_ZLOG = XLOGGZ0 + 2.0_JWRB*LOG(CM1) + ZARG
          STRESSO_ZLOG = MIN(STRESSO_ZLOG, 0.0_JWRB)
          ZBETA = STRESSO_ZLOG**4*EXP(STRESSO_ZLOG)
          STRESSO_ZNZ = ZBETA*UST*Y
          STRESSO_GAMNORMA = (1.0_JWRB + STRESSO_CONST1*STRESSO_ZNZ) / (1.0_JWRB + CONST2*STRESSO_ZNZ)
          FNC2 = F1DCOS3*CONSTTAU*ZBETA*TAUL*WTAUHF(TAU_PHI_HF_J)*DELZ*STRESSO_GAMNORMA
          TAUL = MAX(TAUL - TAUWSHELTER*FNC2, 0.0_JWRB)

          UST = SQRT(TAUL)
          TAUHF = TAUHF + FNC2
        END DO
      ELSE
!$acc loop seq
        DO TAU_PHI_HF_J=1,JTOT_TAUHF
          Y = EXP(ZINF + REAL(TAU_PHI_HF_J - 1, kind=JWRB)*DELZ)
          OMEGA = Y*SQRTGZ0
          CM1 = OMEGA*GM1
          ZX = UST*CM1 + ZALP
          ZARG = XKAPPA / ZX
          STRESSO_ZLOG = XLOGGZ0 + 2.0_JWRB*LOG(CM1) + ZARG
          STRESSO_ZLOG = MIN(STRESSO_ZLOG, 0.0_JWRB)
          ZBETA = STRESSO_ZLOG**4*EXP(STRESSO_ZLOG)
          FNC2 = ZBETA*WTAUHF(TAU_PHI_HF_J)
          STRESSO_ZNZ = ZBETA*UST*Y
          STRESSO_GAMNORMA = (1.0_JWRB + STRESSO_CONST1*STRESSO_ZNZ) / (1.0_JWRB + CONST2*STRESSO_ZNZ)
          TAUHF = TAUHF + FNC2*STRESSO_GAMNORMA
        END DO
        TAUHF = F1DCOS3*CONSTTAU*TAUL*TAUHF*DELZ
      END IF


      PHIHF = 0.0_JWRB
      IF (LLPHIWA) THEN
        !       PHIHF:
        !       We are neglecting the gravity-capillary contribution
        !       Recompute DELZ over the full interval
        TAUL = USTPH**2
        ZSUP = ZSUPMAX
        DELZ = MAX((ZSUP - ZINF) / REAL(JTOT_TAUHF - 1, kind=JWRB), 0.0_JWRB)

        CONSTPHI = AIRD(IJ)*ZPI4GM1*FR5(MIJ(IJ))

        ! Intergrals are integrated following a change of variable : Z=LOG(Y)
        IF (STRESSO_LTAUWSHELTER) THEN
!$acc loop seq
          DO TAU_PHI_HF_J=1,JTOT_TAUHF
            Y = EXP(ZINF + REAL(TAU_PHI_HF_J - 1, kind=JWRB)*DELZ)
            OMEGA = Y*SQRTGZ0
            CM1 = OMEGA*GM1
            ZX = USTPH*CM1 + ZALP
            ZARG = XKAPPA / ZX
            STRESSO_ZLOG = XLOGGZ0 + 2.0_JWRB*LOG(CM1) + ZARG
            STRESSO_ZLOG = MIN(STRESSO_ZLOG, 0.0_JWRB)
            ZBETA = STRESSO_ZLOG**4*EXP(STRESSO_ZLOG)
            STRESSO_ZNZ = ZBETA*UST*Y
            STRESSO_GAMNORMA = (1.0_JWRB + STRESSO_CONST1*STRESSO_ZNZ) / (1.0_JWRB + CONST2*STRESSO_ZNZ)
            FNC2 = ZBETA*TAUL*WTAUHF(TAU_PHI_HF_J)*DELZ*STRESSO_GAMNORMA
            TAUL = MAX(TAUL - TAUWSHELTER*F1DCOS3*CONSTTAU*FNC2, 0.0_JWRB)
            USTPH = SQRT(TAUL)
            PHIHF = PHIHF + FNC2 / Y
          END DO
          PHIHF = F1DCOS2*CONSTPHI*SQRTZ0OG*PHIHF
        ELSE
!$acc loop seq
          DO TAU_PHI_HF_J=1,JTOT_TAUHF
            Y = EXP(ZINF + REAL(TAU_PHI_HF_J - 1, kind=JWRB)*DELZ)
            OMEGA = Y*SQRTGZ0
            CM1 = OMEGA*GM1
            ZX = USTPH*CM1 + ZALP
            ZARG = XKAPPA / ZX
            STRESSO_ZLOG = XLOGGZ0 + 2.0_JWRB*LOG(CM1) + ZARG
            STRESSO_ZLOG = MIN(STRESSO_ZLOG, 0.0_JWRB)
            ZBETA = STRESSO_ZLOG**4*EXP(STRESSO_ZLOG)
            STRESSO_ZNZ = ZBETA*UST*Y
            STRESSO_GAMNORMA = (1.0_JWRB + STRESSO_CONST1*STRESSO_ZNZ) / (1.0_JWRB + CONST2*STRESSO_ZNZ)
            FNC2 = ZBETA*WTAUHF(TAU_PHI_HF_J)*STRESSO_GAMNORMA
            PHIHF = PHIHF + FNC2 / Y
          END DO
          PHIHF = F1DCOS2*CONSTPHI*SQRTZ0OG*TAUL*PHIHF*DELZ
        END IF
      END IF


      ! =========================================

      STRESSO_XSTRESS = STRESSO_XSTRESS + TAUHF*SIN(STRESSO_USDIRP)
      STRESSO_YSTRESS = STRESSO_YSTRESS + TAUHF*COS(STRESSO_USDIRP)
      TAUW(IJ) = SQRT(STRESSO_XSTRESS**2 + STRESSO_YSTRESS**2)
      TAUW(IJ) = MAX(TAUW(IJ), 0.0_JWRB)
      TAUWDIR(IJ) = ATAN2(STRESSO_XSTRESS, STRESSO_YSTRESS)

      IF (.not.LLGCBZ0) THEN
        TAUTOUS2 = 1.0_JWRB / (1.0_JWRB + EPS1)
        TAUW(IJ) = MIN(TAUW(IJ), UFRIC(IJ)**2*TAUTOUS2)
      END IF

      IF (LLPHIWA) THEN
        PHIWA(IJ) = PHIWA(IJ) + PHIHF
      END IF


      ! =========================================

      ! ----------------------------------------------------------------------


      ! =========================================

    END DO

    !     2.3.3 ADD THE OTHER SOURCE TERMS.
    !           ---------------------------

    ! [Loki] inlined child subroutine: SDISSIP
    ! =========================================

    ! ----------------------------------------------------------------------


    SELECT CASE (IPHYS)
    CASE (0)
      ! [Loki] Removed content of pragma-marked region!
    CASE (1)
      ! [Loki] inlined child subroutine: SDISSIP_ARD
      ! =========================================

      ! ----------------------------------------------------------------------


      ! INITIALISATION

      EPSR = SQRT(SDSBR)

      TPIINV = 1.0_JWRB / ZPI
      TPIINVH = 0.5_JWRB*TPIINV


      TMP03 = 1.0_JWRB / (SDSBR*MICHE)

      SSDSC6M1 = 1._JWRB - SSDSC6

!$acc loop seq
      DO SDISSIP_M=1,NFRE
        saturation_factor = WAVNUM(IJ, SDISSIP_M)*TPIINV*XK2CG(IJ, SDISSIP_M)
        FACSAT(IJ, SDISSIP_M) = saturation_factor

        ! Accumulate the directional sector locally, retaining the arrays
        ! needed by the subsequent cumulative dissipation calculation.
        maximum_saturation = 0.0_JWRB
!$acc loop seq
        DO SDISSIP_K=1,NANG
          sector_energy = 0.0_JWRB
          ! integrates in directional sector
!$acc loop seq
          DO K2=1,NSDSNTH*2 + 1
            KK = INDICESSAT(SDISSIP_K, K2)
            sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, K2)*FL1(IJ, KK, SDISSIP_M)
          END DO
          saturation_value = sector_energy*saturation_factor
          BTH(IJ, SDISSIP_K, SDISSIP_M) = saturation_value
          maximum_saturation = MAX(maximum_saturation, saturation_value)
        END DO
        BTH0(IJ, SDISSIP_M) = maximum_saturation

        ! SATURATION TERM
        SSDSC2_SIG = SSDSC2*ZPIFR(SDISSIP_M)
        ZCOEF = SSDSC2_SIG*SSDSC6
        ZCOEFM1 = SSDSC2_SIG*SSDSC6M1
!$acc loop seq
        DO SDISSIP_K=1,NANG
          D(IJ, SDISSIP_K, SDISSIP_M) = ZCOEF*MAX(0._JWRB, maximum_saturation*TMP03 - SSDSC4)**IPSAT + ZCOEFM1*MAX(0._JWRB,  &
          & BTH(IJ, SDISSIP_K, SDISSIP_M)*TMP03 - SSDSC4)**IPSAT
        END DO
      END DO


      ! CUMULATIVE TERM
      IF (SSDSC3 /= 0.0_JWRB) THEN

        NANGD = NANG / 2
        XLOGDFRTH = LOG(FRATIO)*DELTH
        !       l(k,th)=1/(2*pi²)= the breaking crest density
        BRLAMBDA = BRKPBCOEF / (2.0_JWRB*ZPI**2)
        TMP02 = SSDSC3*BRLAMBDA

        !       NDIKCUMUL is the  integer difference in frequency bands
        !       between the "large breakers" and short "wiped-out waves"
        !!! wrong !!???        NDIKCUMUL = NINT(SSDSBRF1/(FRATIO-1.))
        NDIKCUMUL = NINT(-LOG(SSDSBRF1) / LOG(FRATIO))

!$acc loop seq
        DO SDISSIP_M=1,NFRE
          C_(IJ, SDISSIP_M) = ZPIFR(SDISSIP_M) / WAVNUM(IJ, SDISSIP_M)
          C_C(IJ, SDISSIP_M) = C_(IJ, SDISSIP_M)**2
          DSIP(IJ, SDISSIP_M) = TMP02*ZPIFR(SDISSIP_M)*XLOGDFRTH / CGROUP(IJ, SDISSIP_M)            !  coef*dtheta*dk = coef*dtheta*dsigma/cg
        END DO

!$acc loop seq
        DO M2=1,NFRE - NDIKCUMUL
          IF (BTH0(IJ, M2) > SDSBR) THEN
            SDISSIP_TEMP1(IJ, M2) = 1.0_JWRB
          ELSE
            SDISSIP_TEMP1(IJ, M2) = 0.0_JWRB
          END IF
        END DO
!$acc loop seq
        DO M2=1,NFRE - NDIKCUMUL
!$acc loop seq
          DO K2=1,NANG
            SCUMUL(IJ, K2, M2) = SDISSIP_TEMP1(IJ, M2)*MAX(SQRT(BTH(IJ, K2, M2)) - EPSR, 0.0_JWRB)**2
          END DO
        END DO

!$acc loop seq
        DO SDISSIP_M=NDIKCUMUL + 1,NFRE
!$acc loop seq
          DO SDISSIP_K=1,NANG
            RENEWALFREQ(IJ, SDISSIP_K, SDISSIP_M) = 0.0_JWRB
          END DO
        END DO


!$acc loop seq
        DO SDISSIP_M=NDIKCUMUL + 1,NFRE

          IF (SDISSIP_M - NDIKCUMUL >= 3) THEN
            TRPZ_DSIP(IJ, 1) = 0.5_JWRB*DSIP(IJ, 1)
!$acc loop seq
            DO M2=2,SDISSIP_M - NDIKCUMUL - 1
              TRPZ_DSIP(IJ, M2) = DSIP(IJ, M2)
            END DO
            TRPZ_DSIP(IJ, SDISSIP_M - NDIKCUMUL) = 0.5_JWRB*DSIP(IJ, SDISSIP_M - NDIKCUMUL)
          ELSE
!$acc loop seq
            DO M2=1,SDISSIP_M - NDIKCUMUL
              TRPZ_DSIP(IJ, M2) = DSIP(IJ, M2)
            END DO
          END IF

!$acc loop seq
          DO M2=1,SDISSIP_M - NDIKCUMUL
!$acc loop seq
            DO KK=0,NANGD
              WCUMUL(IJ, KK, M2) = SQRT(ABS(C_C(IJ, SDISSIP_M) + C_C(IJ, M2) - 2.0_JWRB*C_(IJ, SDISSIP_M)*C_(IJ, M2)*COS(KK*DELTH &
              & )))*TRPZ_DSIP(IJ, M2)
            END DO
          END DO

!$acc loop seq
          DO SDISSIP_K=1,NANG
            ! Correction of saturation level for shallow-water kinematics
            ! Cumulative effect based on lambda   (breaking probability is
            ! the expected rate of sweeping by larger breaking waves)

!$acc loop seq
            DO K2=1,NANG
            END DO

!$acc loop seq
            DO M2=1,SDISSIP_M - NDIKCUMUL
!$acc loop seq
              DO K2=1,NANG
                KK = ABS(K2 - SDISSIP_K)
                IF (KK > NANGD) KK = KK - NANGD
                ! Integrates over frequencies M2 and directions K2 to
                ! Integration is performed from M2=1 to a frequency lower than M: IK-NDIKCUMUL
                RENEWALFREQ(IJ, SDISSIP_K, SDISSIP_M) =  &
                & RENEWALFREQ(IJ, SDISSIP_K, SDISSIP_M) + WCUMUL(IJ, KK, M2)*SCUMUL(IJ, K2, M2)
              END DO
            END DO
          END DO
        END DO

!$acc loop seq
        DO SDISSIP_M=NDIKCUMUL + 1,NFRE
!$acc loop seq
          DO SDISSIP_K=1,NANG
            D(IJ, SDISSIP_K, SDISSIP_M) = D(IJ, SDISSIP_K, SDISSIP_M) + RENEWALFREQ(IJ, SDISSIP_K, SDISSIP_M)
          END DO
        END DO
      END IF


      !     WAVE-TURBULENCE INTERACTION TERM
      IF (SSDSC5 /= 0.0_JWRB) THEN
        TMP01 = 2._JWRB*SSDSC5 / G
        FACTURB = TMP01*RAORW*UFRIC(IJ)*UFRIC(IJ)
!$acc loop seq
        DO SDISSIP_M=1,NFRE
          FACWTRB(IJ, SDISSIP_M) = ZPIFR(SDISSIP_M)*WAVNUM(IJ, SDISSIP_M)*FACTURB
!$acc loop seq
          DO SDISSIP_K=1,NANG
            D(IJ, SDISSIP_K, SDISSIP_M) = D(IJ, SDISSIP_K, SDISSIP_M) - FACWTRB(IJ, SDISSIP_M)*COSWDIF(IJ, SDISSIP_K)
          END DO
        END DO
      END IF


      ! ADD ALL CONTRIBUTIONS TO SOURCE TERM
!$acc loop seq
      DO SDISSIP_M=1,NFRE
!$acc loop seq
        DO SDISSIP_K=1,NANG
          SL(IJ, SDISSIP_K, SDISSIP_M) = SL(IJ, SDISSIP_K, SDISSIP_M) + D(IJ, SDISSIP_K, SDISSIP_M)*FL1(IJ, SDISSIP_K, SDISSIP_M)
          FLD(IJ, SDISSIP_K, SDISSIP_M) = FLD(IJ, SDISSIP_K, SDISSIP_M) + D(IJ, SDISSIP_K, SDISSIP_M)
        END DO
      END DO


      ! =========================================
    END SELECT


    ! =========================================

    !     Save source term contributions relevant for the calculation of ocean fluxes
    IF (LCFLX .and. .not.LWVFLX_SNL) THEN
!$acc loop seq
      DO M=1,NFRE
!$acc loop seq
        DO K=1,NANG
          SSOURCE(IJ, K, M) = SL(IJ, K, M)
        END DO
      END DO
    END IF

    CALL SNONLIN_LOKI(KIJS, KIJL, FL1, FLD, SL, WAVNUM, DEPTH, AKMEAN, IJ=IJ, ENH=SNONLIN_ENH)

    IF (LCFLX .and. LWVFLX_SNL) THEN
      !     Save source term contributions relevant for the calculation of ocean fluxes
      !!!!!!  SL must only contain contributions contributed to fluxes into the oceans
      !       MODULATE SL BY IMPLICIT FACTOR
!$acc loop seq
      DO M=1,NFRE
!$acc loop seq
        DO K=1,NANG
          GTEMP1 = MAX((1.0_JWRB - DELT5*FLD(IJ, K, M)), 1.0_JWRB)
          SSOURCE(IJ, K, M) = SL(IJ, K, M) / GTEMP1
        END DO
      END DO
    END IF


    ! [Loki] inlined child subroutine: SDIWBK
    ! =========================================

    ! ----------------------------------------------------------------------


    !*    1. ADDING DISSIPATION AND ITS FUNCTIONAL DERIVATIVE TO NET SOURCE
    !*       FUNCTION AND NET SOURCE FUNCTION DERIVATIVE.
    !        --------------------------------------------------------------

    IF (LBIWBK) THEN
      !       (FOLLOWING BATTJES-JANSSEN AND BEJI)
      IF (DEPTH(IJ) < DEPTHTRS) THEN
        ALPH = 2.0_JWRB*EMAXDPT(IJ) / EMEAN(IJ)
        SDIWBK_ARG = MIN(ALPH, 50.0_JWRB)
        Q_OLD = EXP(-SDIWBK_ARG)
        !            USE NEWTON-RAPHSON METHOD
!$acc loop seq
        DO IC=1,15
          EXPQ = EXP(-SDIWBK_ARG*(1.0_JWRB - Q_OLD))
          Q = Q_OLD - (EXPQ - Q_OLD) / (SDIWBK_ARG*EXPQ - 1.0_JWRB)
          REL_ERR = ABS(Q - Q_OLD) / Q_OLD
          IF (REL_ERR < 0.00001_JWRB) EXIT
          Q_OLD = Q
        END DO
        Q = MIN(Q, 1.0_JWRB)
        SDS = COEF_B_J*ALPH*Q*F1MEAN(IJ)
      END IF

!$acc loop seq
      DO SDIWBK_M=1,NFRE_RED
!$acc loop seq
        DO SDIWBK_K=1,NANG
          IF (DEPTH(IJ) < DEPTHTRS) THEN
            SL(IJ, SDIWBK_K, SDIWBK_M) = SL(IJ, SDIWBK_K, SDIWBK_M) - SDS*FL1(IJ, SDIWBK_K, SDIWBK_M)
            FLD(IJ, SDIWBK_K, SDIWBK_M) = FLD(IJ, SDIWBK_K, SDIWBK_M) - SDS
          END IF
        END DO
      END DO

    END IF


    ! =========================================

    IF (LICERUN) THEN

      !        Use linear scaling of ALL proceeding source terms under sea ice (this is a complete unknown)
      IF (LCISCAL) THEN
!$acc loop seq
        DO M=1,NFRE
!$acc loop seq
          DO K=1,NANG
            BETA = 1._JWRB - CICOVER(IJ)
            SL(IJ, K, M) = BETA*SL(IJ, K, M)
            FLD(IJ, K, M) = BETA*FLD(IJ, K, M)
          END DO
        END DO
      END IF

      !        Coupling of waves and sea ice (type 1): wave-induced sea ice break up + reduced attenuation
      IF (LWNEMOCOUIBR) THEN
        ! [Loki] inlined child subroutine: ICEBREAK_MODIFY_ATTENUATION
        ! =========================================

        ! ----------------------------------------------------------------------


        ZALPFACXINV = 1.0_JWRB / ZALPFACX          ! FACTOR TO DECREASE ATTENUATION BY WHEN ICE IS BROKEN


        ! USE IBRMEM TO CHANGE ATTENUATION FACTOR ALPFAC
        ! OTHERWISE ALPFAC KEEPS VALUE SET IN IMPLSCH

        IF (IBRMEM(IJ) <= ZIBRW_THRSH) THEN
          ALPFAC(IJ) = ZALPFACXINV
        END IF



        ! =========================================
      END IF

      !        Attenuation of waves in ice
      IF (LCIWA1 .or. LCIWA2 .or. LCIWA3) THEN
        ! [Loki] inlined child subroutine: SDICE
        ! =========================================


        ! ----------------------------------------------------------------------


        !     Attenuation of waves in ice (type 1): scattering
        IF (LCIWA1) THEN
          ! [Loki] inlined child subroutine: SDICE1
          ! =========================================


          ! ----------------------------------------------------------------------


          SDICE_DELT = IDELT
          SDICE_DELTM = 1.0_JWRB / SDICE_DELT
          SDICE_DELT5 = XIMP*SDICE_DELT

          !     following  Dumont et al. (2011), eqn (13):
          ! sea ice fragility
          CIFRGL = 0.955_JWRB
          ! sea ice foes minimum size (m)
          CIDMIN = 20.0_JWRB
          ! sea ice fragmentation number (>2)
          CIFRGMT = 2.0_JWRB

          A = 200.0_JWRB
          C = 300.0_JWRB
          !     the maximum number of fragmentation step is set
          !     for the limit value for sea ice = 0 (CIDMAX=A)
          !     to insure that CIDMEAN will be increasing with increasing sea ice cover
          MAXICM = INT(LOG(A / CIDMIN) / LOG(CIFRGMT))
          IF (CITHICK(IJ) > 0.0_JWRB) THEN
            ! sea ice foes maxmimum size (m)
            !!!       testing making it function of sea ice cover
            CIDMAX = A + C*CICOVER(IJ)
            ICM = MIN(INT(LOG(CIDMAX / CIDMIN) / LOG(CIFRGMT)), MAXICM)
            SN = 0.0_JWRB
            SD = 0.0_JWRB
!$acc loop seq
            DO SDICE_I=0,ICM
              SDICE_X = (CIFRGMT**2*CIFRGL)**SDICE_I
              SN = SN + SDICE_X*CIDMAX / CIFRGMT**SDICE_I
              SD = SD + SDICE_X
            END DO
            CIDMEAN = SN / SD
            DINV = 1.0_JWRB / CIDMEAN
          ELSE
            DINV = CIDMIN
          END IF


!$acc loop seq
          DO SDICE_M=1,NFRE
            TW = 1.0_JWRB / FR(SDICE_M)
            IT = FLOOR((TW - TICMIN) / DTIC + 1)
            IT = MAX(1, MIN(IT, NICT))
            IT1 = IT + 1
            IT1 = MAX(1, MIN(IT1, NICT))
            WT1 = MAX(MIN(1.0_JWRB, (TW - (TICMIN + (IT - 1)*DTIC)) / DTIC), 0.0_JWRB)
            WT = 1.0_JWRB - WT1
            IF (CITHICK(IJ) > 0.0_JWRB) THEN
              IH = FLOOR((CITHICK(IJ) - HICMIN) / DHIC + 1)
              IH = MAX(1, MIN(IH, NICH))
              IH1 = IH + 1
              IH1 = MAX(1, MIN(IH1, NICH))
              WH1 = MAX(MIN(1._JWRB, (CITHICK(IJ) - (HICMIN + (IH - 1)*DHIC)) / DHIC), 0.0_JWRB)
              WH = 1.0_JWRB - WH1
              CIDEAC_INT = WT*(WH*CIDEAC(IT, IH) + WH1*CIDEAC(IT, IH1)) + WT1*(WH*CIDEAC(IT1, IH) + WH1*CIDEAC(IT1, IH1))
              ALP(IJ, SDICE_M) = EXP(CIDEAC_INT)*DINV*ZALPFACB                ! CICV accounted for below

            ELSE
              ALP(IJ, SDICE_M) = 0.0_JWRB
            END IF
          END DO

!$acc loop seq
          DO SDICE_M=1,NFRE
!$acc loop seq
            DO SDICE_K=1,NANG

              !              apply the source term
              FLDICE = -ALP(IJ, SDICE_M)*CGROUP(IJ, SDICE_M)
              SLICE(IJ, SDICE_K, SDICE_M) = FL1(IJ, SDICE_K, SDICE_M)*FLDICE
              SL(IJ, SDICE_K, SDICE_M) = SL(IJ, SDICE_K, SDICE_M) + CICOVER(IJ)*SLICE(IJ, SDICE_K, SDICE_M)
              FLD(IJ, SDICE_K, SDICE_M) = FLD(IJ, SDICE_K, SDICE_M) + CICOVER(IJ)*FLDICE

              !              to be used for wave radiative stress calculation
              SDICE_GTEMP1 = MAX((1.0_JWRB - SDICE_DELT5*FLDICE), 1.0_JWRB)
              SLICE(IJ, SDICE_K, SDICE_M) = SLICE(IJ, SDICE_K, SDICE_M) / SDICE_GTEMP1

            END DO
          END DO


          ! =========================================
        END IF

        !     Attenuation of waves in ice (type 2): bottom friction
        IF (LCIWA2) THEN
          ! [Loki] inlined child subroutine: SDICE2
          ! =========================================


          ! ----------------------------------------------------------------------


          SDICE2_DELT = IDELT
          SDICE2_DELTM = 1.0_JWRB / SDICE2_DELT
          SDICE2_DELT5 = XIMP*SDICE2_DELT

!$acc loop seq
          DO SDICE2_M=1,NFRE
!$acc loop seq
            DO SDICE2_K=1,NANG

              EWH = 4.0_JWRB*SQRT(MAX(EPSMIN, FL1(IJ, SDICE2_K, SDICE2_M)*DFIM(SDICE2_M)))
              XK2(SDICE2_M) = WAVNUM(IJ, SDICE2_M)**2
              SDICE2_ALP = CDICWA*XK2(SDICE2_M)*EWH*ZALPFACB

              !              apply the source term
              SDICE2_FLDICE = -SDICE2_ALP*CGROUP(IJ, SDICE2_M)
              SLICE(IJ, SDICE2_K, SDICE2_M) = FL1(IJ, SDICE2_K, SDICE2_M)*SDICE2_FLDICE
              SL(IJ, SDICE2_K, SDICE2_M) = SL(IJ, SDICE2_K, SDICE2_M) + CICOVER(IJ)*SLICE(IJ, SDICE2_K, SDICE2_M)
              FLD(IJ, SDICE2_K, SDICE2_M) = FLD(IJ, SDICE2_K, SDICE2_M) + CICOVER(IJ)*SDICE2_FLDICE

              !              to be used for wave radiative stress calculation
              SDICE2_GTEMP1 = MAX((1.0_JWRB - SDICE2_DELT5*SDICE2_FLDICE), 1.0_JWRB)
              SLICE(IJ, SDICE2_K, SDICE2_M) = SLICE(IJ, SDICE2_K, SDICE2_M) / SDICE2_GTEMP1

            END DO
          END DO


          ! =========================================
        END IF

        !     Attenuation of waves in ice (type 3): viscous friction
        IF (LCIWA3) THEN
          ! [Loki] inlined child subroutine: SDICE3
          ! =========================================


          ! ----------------------------------------------------------------------


          SDICE3_DELT = IDELT
          SDICE3_DELTM = 1.0_JWRB / SDICE3_DELT
          SDICE3_DELT5 = XIMP*SDICE3_DELT

          IMODEL = 2
          HICEMAX = 4.0_JWRB
          HICEMIN = 0.1_JWRB

          SELECT CASE (IMODEL)
          CASE (1)
            !          Best fit w Tempelfjorde obs from Lotfi Aouf
            CDICE = 0.0656_JWRB

!$acc loop seq
            DO SDICE3_M=1,NFRE
              SDICE3_ALP(IJ, SDICE3_M) = (CDICE*CITHICK(IJ)*WAVNUM(IJ, SDICE3_M)**2)*ALPFAC(IJ)
            END DO

          CASE (2)
            !          Jie Yu, W. Erik Rogers, David W. Wang 2022
            CDICE = 0.1274_JWRB*(ZPI / SQRT(G))**4.5_JWRB

!$acc loop seq
            DO SDICE3_M=1,NFRE
              SDICE3_ALP(IJ, SDICE3_M) = (2._JWRB*CDICE*(CITHICK(IJ)**1.25_JWRB)*(FR(SDICE3_M)**4.5_JWRB))*ALPFAC(IJ)*ZALPFACB
            END DO

          END SELECT

!$acc loop seq
          DO SDICE3_M=1,NFRE
!$acc loop seq
            DO SDICE3_K=1,NANG

              !              calculate source term increments
              SDICE3_FLDICE = -SDICE3_ALP(IJ, SDICE3_M)*CGROUP(IJ, SDICE3_M)
              SLICE(IJ, SDICE3_K, SDICE3_M) = FL1(IJ, SDICE3_K, SDICE3_M)*SDICE3_FLDICE

              !              apply the source term (old way to ensure bit-identicality)
              SDICE_TEMP = -CICOVER(IJ)*SDICE3_ALP(IJ, SDICE3_M)*CGROUP(IJ, SDICE3_M)
              SL(IJ, SDICE3_K, SDICE3_M) = SL(IJ, SDICE3_K, SDICE3_M) + FL1(IJ, SDICE3_K, SDICE3_M)*SDICE_TEMP
              FLD(IJ, SDICE3_K, SDICE3_M) = FLD(IJ, SDICE3_K, SDICE3_M) + SDICE_TEMP

              !              apply the source term (new way)
              !                SL(IJ,K,M)     =  SL(IJ,K,M)  + CICV(IJ)*SLICE(IJ,K,M)
              !                FLD(IJ,K,M)    =  FLD(IJ,K,M) + CICV(IJ)*FLDICE
              !
              !              to be used for wave radiative stress calculation
              SDICE3_GTEMP1 = MAX((1.0_JWRB - SDICE3_DELT5*SDICE3_FLDICE), 1.0_JWRB)
              SLICE(IJ, SDICE3_K, SDICE3_M) = SLICE(IJ, SDICE3_K, SDICE3_M) / SDICE3_GTEMP1

            END DO
          END DO


          ! =========================================
        END IF


        ! =========================================
      END IF

    END IF

    ! [Loki] inlined child subroutine: SBOTTOM
    ! =========================================

    ! ----------------------------------------------------------------------


    SBOTTOM_CONST = -2.0_JWRB*0.038_JWRB*GM1
!$acc loop seq
    DO SBOTTOM_M=1,NFRE_RED
      IF (DEPTH(IJ) < BATHYMAX) THEN
        SBOTTOM_ARG = 2.0_JWRB*DEPTH(IJ)*WAVNUM(IJ, SBOTTOM_M)
        SBOTTOM_ARG = MIN(SBOTTOM_ARG, 50.0_JWRB)
        SBO = SBOTTOM_CONST*WAVNUM(IJ, SBOTTOM_M) / SINH(SBOTTOM_ARG)
      ELSE
        SBO = 0.0_JWRB
      END IF

!$acc loop seq
      DO SBOTTOM_K=1,NANG
        SL(IJ, SBOTTOM_K, SBOTTOM_M) = SL(IJ, SBOTTOM_K, SBOTTOM_M) + SBO*FL1(IJ, SBOTTOM_K, SBOTTOM_M)
        FLD(IJ, SBOTTOM_K, SBOTTOM_M) = FLD(IJ, SBOTTOM_K, SBOTTOM_M) + SBO
      END DO
    END DO


    ! =========================================

    ! ----------------------------------------------------------------------

    !*    2.4 COMPUTATION OF NEW SPECTRA.
    !         ---------------------------

    !     INCREASE OF SPECTRUM IN A TIME STEP IS LIMITED TO A FINITE
    !     FRACTION OF A TYPICAL F**(-4) EQUILIBRIUM SPECTRUM.

!$acc loop seq
    DO M=1,NFRE
      DELFL(M) = COFRM4(M)*DELT
    END DO
    USFM = UFRIC(IJ)*MAX(FMEANWS(IJ), FMEAN(IJ))

!$acc loop seq
    DO M=1,NFRE
      TEMP(IJ, M) = USFM*DELFL(M)
    END DO

    IF (LLUNSTR) THEN
!$acc loop seq
      DO K=1,NANG
!$acc loop seq
        DO M=1,NFRE
          GTEMP1 = MAX((1.0_JWRB - DELT5*FLD(IJ, K, M)), 1.0_JWRB)
          GTEMP2 = DELT*SL(IJ, K, M) / GTEMP1
          FLHAB = ABS(GTEMP2)
          FLHAB = MIN(FLHAB, TEMP(IJ, M))
          FL1(IJ, K, M) = FL1(IJ, K, M) + IOBND(IJ)*SIGN(FLHAB, GTEMP2)
          FL1(IJ, K, M) = MAX(IODP(IJ)*FL1(IJ, K, M), FLM(IJ, K))
          SSOURCE(IJ, K, M) = SSOURCE(IJ, K, M) + DELTM*MIN(FLMAX(M) - FL1(IJ, K, M), 0.0_JWRB)
          FL1(IJ, K, M) = MIN(FL1(IJ, K, M), FLMAX(M))
        END DO
      END DO
    ELSE
!$acc loop seq
      DO K=1,NANG
!$acc loop seq
        DO M=1,NFRE
          GTEMP1 = MAX((1.0_JWRB - DELT5*FLD(IJ, K, M)), 1.0_JWRB)
          GTEMP2 = DELT*SL(IJ, K, M) / GTEMP1
          FLHAB = ABS(GTEMP2)
          FLHAB = MIN(FLHAB, TEMP(IJ, M))
          FL1(IJ, K, M) = FL1(IJ, K, M) + SIGN(FLHAB, GTEMP2)
          FL1(IJ, K, M) = MAX(FL1(IJ, K, M), FLM(IJ, K))
          SSOURCE(IJ, K, M) = SSOURCE(IJ, K, M) + DELTM*MIN(FLMAX(M) - FL1(IJ, K, M), 0.0_JWRB)
          FL1(IJ, K, M) = MIN(FL1(IJ, K, M), FLMAX(M))
        END DO
      END DO
    END IF

    IF (LCFLX) THEN
      ! [Loki] inlined child subroutine: WNFLUXES
      ! =========================================

      ! ----------------------------------------------------------------------


      EPSUS3 = EPSUS*SQRT(EPSUS)
      EPSMIN1000 = EPSMIN*1000.0_JWRB

      IF (LCIWA1 .or. LCIWA2 .or. LCIWA3) THEN
        ZCITHRS = 0._JWRB
        CITHRSH_INV = 50._JWRB
        ZMAXEXP = 20._JWRB
      ELSE
        ZCITHRS = CIBLOCK
        CITHRSH_INV = 1._JWRB / MAX(CITHRSH, 0.01_JWRB)
        ZMAXEXP = 10._JWRB
      END IF

      EFD_FAC = 4.0_JWRB*EGRCRV / G**2
      FFD_FAC = (EGRCRV / AFCRV)**(1.0_JWRB / BFCRV)*G

      !*    DETERMINE NORMALIZED FLUXES FROM AIR TO WAVE AND FROM WAVE TO OCEAN.
      !     -------------------------------------------------------------------

      !     ENERGY FLUX from SSURF
      !     MOMENTUM FLUX FROM SSURF and SLICE
      PHILF = 0.0_JWRB
      WNFLUXES_XSTRESS = 0.0_JWRB
      WNFLUXES_YSTRESS = 0.0_JWRB
      XSTRESSICE = 0.0_JWRB
      YSTRESSICE = 0.0_JWRB
      SUMXICE = 0.0_JWRB
      SUMYICE = 0.0_JWRB

      IF (LWNEMOCOUWRS) THEN
        !     THE INTEGRATION UP TO FR(NFRE)
!$acc loop seq
        DO WNFLUXES_M=1,NFRE
          WNFLUXES_K = 1
          !         NOTE THAT EVERYTHING HERE IS ALWAYS NEGATIVE DUE TO SLICE BEING NEGATIVE
          SUMXICE = SINTH(WNFLUXES_K)*MIN(SLICE(IJ, WNFLUXES_K, WNFLUXES_M), -EPSMIN1000)
          SUMYICE = COSTH(WNFLUXES_K)*MIN(SLICE(IJ, WNFLUXES_K, WNFLUXES_M), -EPSMIN1000)
!$acc loop seq
          DO WNFLUXES_K=2,NANG
            SUMXICE = SUMXICE + SINTH(WNFLUXES_K)*MIN(SLICE(IJ, WNFLUXES_K, WNFLUXES_M), -EPSMIN1000)
            SUMYICE = SUMYICE + COSTH(WNFLUXES_K)*MIN(SLICE(IJ, WNFLUXES_K, WNFLUXES_M), -EPSMIN1000)
          END DO
          XSTRESSICE = XSTRESSICE + ZALPWRS*SUMXICE*CINV(IJ, WNFLUXES_M)*RHOWG_DFIM(WNFLUXES_M)
          YSTRESSICE = YSTRESSICE + ZALPWRS*SUMYICE*CINV(IJ, WNFLUXES_M)*RHOWG_DFIM(WNFLUXES_M)
        END DO
      END IF

!$acc loop seq
      DO WNFLUXES_M=1,NFRE
        WNFLUXES_K = 1
        WNFLUXES_SUMT = SSOURCE(IJ, WNFLUXES_K, WNFLUXES_M)
        WNFLUXES_SUMX = SINTH(WNFLUXES_K)*SSOURCE(IJ, WNFLUXES_K, WNFLUXES_M)
        WNFLUXES_SUMY = COSTH(WNFLUXES_K)*SSOURCE(IJ, WNFLUXES_K, WNFLUXES_M)
!$acc loop seq
        DO WNFLUXES_K=2,NANG
          WNFLUXES_SUMT = WNFLUXES_SUMT + SSOURCE(IJ, WNFLUXES_K, WNFLUXES_M)
          WNFLUXES_SUMX = WNFLUXES_SUMX + SINTH(WNFLUXES_K)*SSOURCE(IJ, WNFLUXES_K, WNFLUXES_M)
          WNFLUXES_SUMY = WNFLUXES_SUMY + COSTH(WNFLUXES_K)*SSOURCE(IJ, WNFLUXES_K, WNFLUXES_M)
        END DO
        PHILF = PHILF + WNFLUXES_SUMT*RHOWGDFTH(IJ, WNFLUXES_M)
        WNFLUXES_CMRHOWGDFTH = CINV(IJ, WNFLUXES_M)*RHOWGDFTH(IJ, WNFLUXES_M)
        WNFLUXES_XSTRESS = WNFLUXES_XSTRESS + WNFLUXES_SUMX*WNFLUXES_CMRHOWGDFTH
        WNFLUXES_YSTRESS = WNFLUXES_YSTRESS + WNFLUXES_SUMY*WNFLUXES_CMRHOWGDFTH
      END DO

      IF (LICERUN .and. LWAMRSETCI) THEN
        IF (CICOVER(IJ) > ZCITHRS) THEN
          OOVAL = EXP(-MIN((CICOVER(IJ)*CITHRSH_INV)**4, ZMAXEXP))

          !           ADJUST USTAR FOR THE PRESENCE OF SEA ICE
          U10P = MAX(WSWAVE(IJ), EPSU10)
          CD_BULK = MIN((WNFLUXES_C1 + WNFLUXES_C2*U10P**WNFLUXES_P1)*U10P**WNFLUXES_P2, CDMAX_LOC)
          CD_WAVE = (UFRIC(IJ) / U10P)**2
          CD_ICE = OOVAL*CD_WAVE + (1.0_JWRB - OOVAL)*CD_BULK
          USTAR = MAX(SQRT(CD_ICE)*U10P, EPSUS)

          ! EM_OC and F1_OC with fully developed model ENERGY
          ! The significant wave height derived from EM_OC will be used
          ! by NEMO as a scaling factor as if it was open ocean
          EFD = MIN(EFD_FAC*USTAR**4, EFD_MAX)
          EM_OC = MAX(OOVAL*EMEAN(IJ) + (1.0_JWRB - OOVAL)*EFD, EFD_MIN)
          FFD = FFD_FAC / USTAR
          F1_OC = OOVAL*F1MEAN(IJ) + (1.0_JWRB - OOVAL)*FFD
          F1_OC = MIN(MAX(F1_OC, FR(2)), FR(NFRE))
        ELSE
          OOVAL = 1.0_JWRB
          USTAR = UFRIC(IJ)
          EM_OC = EMEAN(IJ)
          F1_OC = F1MEAN(IJ)
        END IF
      ELSE
        OOVAL = 1.0_JWRB
        USTAR = UFRIC(IJ)
        EM_OC = EMEAN(IJ)
        F1_OC = F1MEAN(IJ)
      END IF

      TAU = AIRD(IJ)*MAX(USTAR**2, EPSUS)
      TAUXD(IJ) = TAU*SIN(WDWAVE(IJ))
      TAUYD(IJ) = TAU*COS(WDWAVE(IJ))

      TAUOCXD(IJ) = TAUXD(IJ) - OOVAL*WNFLUXES_XSTRESS
      TAUOCYD(IJ) = TAUYD(IJ) - OOVAL*WNFLUXES_YSTRESS
      TAUO = SQRT(TAUOCXD(IJ)**2 + TAUOCYD(IJ)**2)
      TAUOC(IJ) = MIN(MAX(TAUO / TAU, TAUOCMIN), TAUOCMAX)

      IF (LWNEMOCOUWRS) THEN
        ! FLIP COMPONENTS TO APPLY POSITIVE STRESS TO SEA ICE
        TAUICX(IJ) = -XSTRESSICE
        TAUICY(IJ) = -YSTRESSICE
      ELSE IF (.not.LWNEMOCOUWRS) THEN
        TAUICX(IJ) = 0.0_JWRB
        TAUICY(IJ) = 0.0_JWRB
      END IF

      IF (LWCOUAST) THEN
        !       USE THE SURFACE STRESSES AS PROVIDED BY THE ATMOSPHERE AND
        !       ONLY RESCALE THEM WITH TAUOC
        IF (USTRA(IJ) /= 0.0_JWRB .or. VSTRA(IJ) /= 0.0_JWRB) THEN
          TAUXD(IJ) = USTRA(IJ)
          TAUOCXD(IJ) = USTRA(IJ)*TAUOC(IJ)
          TAUYD(IJ) = VSTRA(IJ)
          TAUOCYD(IJ) = VSTRA(IJ)*TAUOC(IJ)
        END IF
      END IF


      XN = AIRD(IJ)*MAX(USTAR**3, EPSUS3)
      PHIOCD(IJ) = OOVAL*(PHILF - PHIWA(IJ)) + (1.0_JWRB - OOVAL)*PHIOC_ICE*XN

      PHIEPS(IJ) = PHIOCD(IJ) / XN
      PHIEPS(IJ) = MIN(MAX(PHIEPS(IJ), PHIEPSMIN), PHIEPSMAX)

      PHIOCD(IJ) = PHIEPS(IJ)*XN

      PHIAW(IJ) = PHIWA(IJ) / XN
      PHIAW(IJ) = OOVAL*PHIWA(IJ) / XN + (1.0_JWRB - OOVAL)*PHIAW_ICE

      IF (LWNEMOCOU) THEN
        NPHIEPS(IJ) = PHIEPS(IJ)
        NTAUOC(IJ) = TAUOC(IJ)
        IF (EM_OC /= 0.0_JWRB) THEN
          NSWH(IJ) = 4.0_JWRO*SQRT(EM_OC)
        ELSE
          NSWH(IJ) = 0.0_JWRO
        END IF
        IF (F1_OC /= 0.0_JWRB) THEN
          NMWP(IJ) = 1.0_JWRO / F1_OC
        ELSE
          NMWP(IJ) = 0.0_JWRO
        END IF

        IF (LWNEMOTAUOC) THEN
          NEMOTAUX(IJ) = NEMOTAUX(IJ) + TAUOCXD(IJ)
          NEMOTAUY(IJ) = NEMOTAUY(IJ) + TAUOCYD(IJ)
        ELSE
          NEMOTAUX(IJ) = NEMOTAUX(IJ) + TAUXD(IJ)
          NEMOTAUY(IJ) = NEMOTAUY(IJ) + TAUYD(IJ)
        END IF
        NEMOWSWAVE(IJ) = NEMOWSWAVE(IJ) + WSWAVE(IJ)
        NEMOPHIF(IJ) = NEMOPHIF(IJ) + PHIOCD(IJ)
        NEMOTAUICX(IJ) = NEMOTAUICX(IJ) + TAUICX(IJ)
        NEMOTAUICY(IJ) = NEMOTAUICY(IJ) + TAUICY(IJ)
      END IF

      ! ----------------------------------------------------------------------

      ! =========================================
    END IF
    ! ----------------------------------------------------------------------

    !*    2.5 REPLACE DIAGNOSTIC PART OF SPECTRA BY A F**(-5) TAIL.
    !         -----------------------------------------------------

    ! [Loki] inlined child subroutine: FKMEAN
    ! =========================================

    ! ----------------------------------------------------------------------



    !*    1. INITIALISE MEAN FREQUENCY ARRAY AND TAIL FACTOR.
    !        ------------------------------------------------

    EMEAN(IJ) = EPSMIN
    FMEAN(IJ) = EPSMIN
    F1MEAN(IJ) = EPSMIN
    AKMEAN(IJ) = EPSMIN
    XKMEAN(IJ) = EPSMIN

    FKMEAN_DELT25 = WETAIL*FR(NFRE)*DELTH
    COEFM1 = FRTAIL*DELTH
    COEF1 = WP1TAIL*DELTH*FR(NFRE)**2
    COEFA = COEFM1*SQRT(G) / ZPI
    COEFX = COEF1*(ZPI / SQRT(G))

    !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTIONS.
    !        ------------------------------------------

    !*    2.2 SHALLOW WATER INTEGRATION.
    !         --------------------------

!$acc loop seq
    DO FKMEAN_M=1,NFRE
      SQRTK = SQRT(WAVNUM(IJ, FKMEAN_M))
      TEMPA(IJ) = DFIM(FKMEAN_M) / SQRTK
      TEMPX(IJ) = SQRTK*DFIM(FKMEAN_M)
      FKMEAN_K = 1
      TEMP2(IJ) = FL1(IJ, FKMEAN_K, FKMEAN_M)
!$acc loop seq
      DO FKMEAN_K=2,NANG
        TEMP2(IJ) = TEMP2(IJ) + FL1(IJ, FKMEAN_K, FKMEAN_M)
      END DO
      EMEAN(IJ) = EMEAN(IJ) + DFIM(FKMEAN_M)*TEMP2(IJ)
      FMEAN(IJ) = FMEAN(IJ) + DFIMOFR(FKMEAN_M)*TEMP2(IJ)
      F1MEAN(IJ) = F1MEAN(IJ) + DFIMFR(FKMEAN_M)*TEMP2(IJ)
      AKMEAN(IJ) = AKMEAN(IJ) + TEMPA(IJ)*TEMP2(IJ)
      XKMEAN(IJ) = XKMEAN(IJ) + TEMPX(IJ)*TEMP2(IJ)
    END DO

    !*      ADD TAIL CORRECTION TO MEAN FREQUENCY AND
    !*      NORMALIZE WITH TOTAL ENERGY.
    EMEAN(IJ) = EMEAN(IJ) + FKMEAN_DELT25*TEMP2(IJ)
    FMEAN(IJ) = FMEAN(IJ) + COEFM1*TEMP2(IJ)
    FMEAN(IJ) = EMEAN(IJ) / FMEAN(IJ)
    F1MEAN(IJ) = F1MEAN(IJ) + COEF1*TEMP2(IJ)
    F1MEAN(IJ) = F1MEAN(IJ) / EMEAN(IJ)
    AKMEAN(IJ) = AKMEAN(IJ) + COEFA*TEMP2(IJ)
    AKMEAN(IJ) = (EMEAN(IJ) / AKMEAN(IJ))**2
    XKMEAN(IJ) = XKMEAN(IJ) + COEFX*TEMP2(IJ)
    XKMEAN(IJ) = (XKMEAN(IJ) / EMEAN(IJ))**2


    ! =========================================

    !     MEAN FREQUENCY CHARACTERISTIC FOR WIND SEA
    ! [Loki] inlined child subroutine: FEMEANWS
    ! =========================================

    ! ----------------------------------------------------------------------


    !*    1. INITIALISE MEAN FREQUENCY ARRAY AND TAIL FACTOR.
    !        ------------------------------------------------

    FEMEANWS_EM_LOC = EPSMIN
    FMEANWS(IJ) = EPSMIN

    FEMEANWS_FEMEANWS_DELT25 = WETAIL*FR(NFRE)*DELTH
    FEMEANWS_FEMEANWS_DELT2 = FRTAIL*DELTH


    !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTIONS.
    !        ------------------------------------------

!$acc loop seq
    DO FEMEANWS_FEMEANWS_M=1,NFRE
      FEMEANWS_FEMEANWS_TEMP2 = 0.0_JWRB
!$acc loop seq
      DO FEMEANWS_FEMEANWS_K=1,NANG
        FEMEANWS_FEMEANWS_TEMP2 = FEMEANWS_FEMEANWS_TEMP2 + XLLWS(IJ, FEMEANWS_FEMEANWS_K, FEMEANWS_FEMEANWS_M)*FL1(IJ,  &
        & FEMEANWS_FEMEANWS_K, FEMEANWS_FEMEANWS_M)
      END DO
      FEMEANWS_EM_LOC = FEMEANWS_EM_LOC + DFIM(FEMEANWS_FEMEANWS_M)*FEMEANWS_FEMEANWS_TEMP2
      FMEANWS(IJ) = FMEANWS(IJ) + DFIMOFR(FEMEANWS_FEMEANWS_M)*FEMEANWS_FEMEANWS_TEMP2
    END DO

    !*    3. ADD TAIL CORRECTION TO MEAN FREQUENCY AND
    !*       NORMALIZE WITH TOTAL ENERGY.
    !        ------------------------------------------

    FEMEANWS_EM_LOC = FEMEANWS_EM_LOC + FEMEANWS_FEMEANWS_DELT25*FEMEANWS_FEMEANWS_TEMP2
    FMEANWS(IJ) = FMEANWS(IJ) + FEMEANWS_FEMEANWS_DELT2*FEMEANWS_FEMEANWS_TEMP2
    FMEANWS(IJ) = FEMEANWS_EM_LOC / FMEANWS(IJ)

    EMEANWS = FEMEANWS_EM_LOC


    ! =========================================

    ! [Loki] inlined child subroutine: IMPHFTAIL
    ! =========================================

    ! ----------------------------------------------------------------------


    !*    DIAGNOSTIC TAIL.
    !     ----------------

    IMPHFTAIL_TEMP1 = 1.0_JWRB / XK2CG(IJ, MIJ(IJ)) / WAVNUM(IJ, MIJ(IJ))

!$acc loop seq
    DO IMPHFTAIL_M=MIJ(IJ) + 1,NFRE
      IMPHFTAIL_TEMP2 = 1.0_JWRB / XK2CG(IJ, IMPHFTAIL_M) / WAVNUM(IJ, IMPHFTAIL_M)
      IMPHFTAIL_TEMP2 = IMPHFTAIL_TEMP2 / IMPHFTAIL_TEMP1

      !*    MERGE TAIL INTO SPECTRA.
      !     ------------------------
!$acc loop seq
      DO IMPHFTAIL_K=1,NANG
        TFAC = FL1(IJ, IMPHFTAIL_K, MIJ(IJ))
        FL1(IJ, IMPHFTAIL_K, IMPHFTAIL_M) = MAX(IMPHFTAIL_TEMP2*TFAC, FLM(IJ, IMPHFTAIL_K))
      END DO
    END DO

    ! ----------------------------------------------------------------------


    ! =========================================


    !     UPDATE WINDSEA VARIANCE AND MEAN FREQUENCY IF PASSED TO ATMOSPHERE
    !     ------------------------------------------------------------------
    IF (LWFLUX) THEN
      IF (EMEANWS < WSEMEAN_MIN) THEN
        WSEMEAN(IJ) = WSEMEAN_MIN
        WSFMEAN(IJ) = 2._JWRB*FR(NFRE)
      ELSE
        WSEMEAN(IJ) = EMEANWS
        WSFMEAN(IJ) = FMEANWS(IJ)
      END IF
    END IF


    !*    2.6 SET FL1 ON ICE POINTS TO ZERO
    !         -----------------------------

    IF (LICERUN .and. LMASKICE) THEN
      ! [Loki] inlined child subroutine: SETICE
      ! =========================================
      ! ----------------------------------------------------------------------


      !*    1. SET SPECTRA TO NOISE LEVEL OVER ICE POINTS.
      !     ----------------------------------------------

      IF (CICOVER(IJ) > CITHRSH) THEN
        CIREDUC = MAX(EPSMIN, (1.0_JWRB - CICOVER(IJ)))
        ICEFREE = 0.0_JWRB
      ELSE
        CIREDUC = 0.0_JWRB
        ICEFREE = 1.0_JWRB
      END IF

      SETICE_TEMP = CIREDUC*FLMIN
!$acc loop seq
      DO SETICE_M=1,NFRE
!$acc loop seq
        DO SETICE_K=1,NANG
          FL1(IJ, SETICE_K, SETICE_M) = FL1(IJ, SETICE_K, SETICE_M)*ICEFREE + SETICE_TEMP*MAX(0.0_JWRB, COSWDIF(IJ, SETICE_K))**2
        END DO
      END DO


      ! =========================================
    END IF


    !*    2.7 SURFACE STOKES DRIFT AND STRAIN IN SEA ICE
    !         ------------------------------------------

    ! [Loki] inlined child subroutine: STOKESTRN
    ! =========================================

    ! ----------------------------------------------------------------------


    ! [Loki] inlined child subroutine: STOKESDRIFT
    ! =========================================

    ! ----------------------------------------------------------------------



    !***  1. DETERMINE STOKE DRIFT VECTOR.
    !     --------------------------------

    STOKESTRN_CONST = 2.0_JWRB*DELTH*ZPI**3 / G*FR(NFRE_ODD)**4

    !***  1.1 PERFORM INTEGRATION.
    !     ------------------------

    USTOKES(IJ) = 0.0_JWRB
    VSTOKES(IJ) = 0.0_JWRB

!$acc loop seq
    DO STOKESTRN_M=1,NFRE_ODD
      STFAC = STOKFAC(IJ, STOKESTRN_M)*DFIM_SIM(STOKESTRN_M)
!$acc loop seq
      DO STOKESTRN_K=1,NANG
        FAC3 = STFAC*FL1(IJ, STOKESTRN_K, STOKESTRN_M)
        USTOKES(IJ) = USTOKES(IJ) + FAC3*SINTH(STOKESTRN_K)
        VSTOKES(IJ) = VSTOKES(IJ) + FAC3*COSTH(STOKESTRN_K)
      END DO
    END DO

    !***  1.2 ADD CONTRIBUTION OF UNRESOLVED WAVES.
    !     -----------------------------------------

!$acc loop seq
    DO STOKESTRN_K=1,NANG
      FAC1 = STOKESTRN_CONST*SINTH(STOKESTRN_K)
      FAC2 = STOKESTRN_CONST*COSTH(STOKESTRN_K)
      USTOKES(IJ) = USTOKES(IJ) + FAC1*FL1(IJ, STOKESTRN_K, NFRE_ODD)
      VSTOKES(IJ) = VSTOKES(IJ) + FAC2*FL1(IJ, STOKESTRN_K, NFRE_ODD)
    END DO


    !***  1.3 Sea Ice exception
    !     ---------------------
    IF (LICERUN .and. LWAMRSETCI) THEN
      IF (CICOVER(IJ) > CITHRSH) THEN
        USTOKES(IJ) = 0.016_JWRB*WSWAVE(IJ)*SIN(WDWAVE(IJ))*(1.0_JWRB - CICOVER(IJ))
        VSTOKES(IJ) = 0.016_JWRB*WSWAVE(IJ)*COS(WDWAVE(IJ))*(1.0_JWRB - CICOVER(IJ))
      END IF
    END IF

    !***  1.4 Protection
    !     --------------

    USTOKES(IJ) = MIN(MAX(USTOKES(IJ), -STMAX), STMAX)
    VSTOKES(IJ) = MIN(MAX(VSTOKES(IJ), -STMAX), STMAX)


    ! =========================================

    ! [Loki] Removed content of pragma-marked region!


    IF (LWNEMOCOU .and. (LWNEMOCOUSEND .and. LWCOU .or. .not.LWCOU)) THEN
      IF (LWNEMOCOUSTK) THEN
        NEMOUSTOKES(IJ) = USTOKES(IJ)
        NEMOVSTOKES(IJ) = VSTOKES(IJ)
      ELSE
        NEMOUSTOKES(IJ) = 0.0_JWRO
        NEMOVSTOKES(IJ) = 0.0_JWRO
      END IF

      IF (LWNEMOCOUSTRN) NEMOSTRN(IJ) = STRNMS(IJ)
    END IF


    ! ----------------------------------------------------------------------

    ! =========================================

    ! ----------------------------------------------------------------------



!$acc end data
  END SUBROUTINE IMPLSCH_LOKI
END MODULE IMPLSCH_LOKI_MOD
