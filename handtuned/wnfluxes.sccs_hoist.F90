MODULE WNFLUXES_LOKI_MOD
  CONTAINS
  SUBROUTINE WNFLUXES_LOKI (KIJS, KIJL, RHOWGDFTH, CINV, SSURF, SLICE, CICOVER, PHIWA, EM, F1, WSWAVE, WDWAVE, USTRA, VSTRA,  &
  & UFRIC, AIRD, NPHIEPS, NTAUOC, NSWH, NMWP, NEMOTAUX, NEMOTAUY, NEMOTAUICX, NEMOTAUICY, NEMOWSWAVE, NEMOPHIF, TAUXD, TAUYD,  &
  & TAUOCXD, TAUOCYD, TAUOC, TAUICX, TAUICY, PHIOCD, PHIEPS, PHIAW, LNUPD, IJ)

    ! ----------------------------------------------------------------------

    !**** *WNFLUXES* - WAVE FLUXES CALCULATION

    !*    PURPOSE.
    !     --------

    !**   INTERFACE.
    !     ----------

    !       *CALL* *WNFLUXES* (KIJS, KIJL,
    !    &                     MIJ, RHOWGDFTH,
    !    &                     CINV,
    !    &                     SSURF, CICOVER,
    !    &                     PHIWA,
    !    &                     EM, F1, WSWAVE, WDWAVE,
    !    &                     UFRIC, AIRD, INTFLDS, WAM2NEMO,
    !    &                     LNUPD)
    !          *KIJS*    - INDEX OF FIRST GRIDPOINT.
    !          *KIJL*    - INDEX OF LAST GRIDPOINT.
    !          *MIJ*    - LAST FREQUENCY INDEX OF THE PROGNOSTIC RANGE
    !         *RHOWGDFTH    - WATER DENSITY * G * DF * DTHETA
    !                         FOR TRAPEZOIDAL INTEGRATION BETWEEN FR(1) and FR(MIJ)
    !                         !!!!!!!!  RHOWGDFTH=0 FOR FR > FR(MIJ)
    !          *CINV*   - INVERSE PHASE SPEED.
    !          *SSURF*  - CONTRIBUTION OF ALL SOURCE TERMS ACTING ON
    !                     THE SURFACE MOMENTUM AND ENERGY FLUXES.
    !          *CICOVER*- SEA ICE COVER.
    !          *PHIWA*  - ENERGY FLUX FROM WIND INTO WAVES INTEGRATED
    !                     OVER THE FULL FREQUENCY RANGE.
    !          *EM*     - MEAN WAVE VARIANCE.
    !          *F1*     - MEAN WAVE FREQUENCY BASED ON f*F INTEGRATION.
    !          *WSWAVE* - WIND SPEED IN M/S.
    !          *WDWAVE* - WIND DIRECTION IN RADIANS IN OCEANOGRAPHIC CONVENTION
    !          *UFRIC*  - FRICTION VELOCITY IN M/S.
    !          *AIRD*   - AIR DENSITY IN KG/M3.
    !          *INTFLDS*-  INTEGRATED/DERIVED PARAMETERS
    !          WAM2NEMO*- WAVE FIELDS PASSED TO NEMO
    !          *LNUPD*  - UPDATE NEMO FIELDS.

    ! ----------------------------------------------------------------------

    USE PARKIND_WAVE, ONLY: JWIM, JWRB, JWRU, JWRO
    USE YOWDRVTYPE, ONLY: FORCING_FIELDS, INTGT_PARAM_FIELDS, WAVE2OCEAN

    USE YOWALTAS, ONLY: EGRCRV, AFCRV, BFCRV
    USE YOWCOUP, ONLY: LWCOUAST, LWNEMOCOU, LWNEMOTAUOC, LWNEMOCOUWRS
    USE YOWFRED, ONLY: FR, COSTH, SINTH, RHOWG_DFIM
    USE YOWICE, ONLY: LICERUN, LWAMRSETCI, CITHRSH, CIBLOCK, ZALPWRS, LCIWA1, LCIWA2, LCIWA3
    USE YOWPARAM, ONLY: NANG, NFRE
    USE YOWPCONS, ONLY: TAUOCMIN, TAUOCMAX, PHIEPSMIN, PHIEPSMAX, EPSUS, EPSU10, G, ZPI, ROWATER, EPSMIN

    USE YOMHOOK, ONLY: LHOOK, JPHOOK

    ! ----------------------------------------------------------------------

    IMPLICIT NONE

    INTEGER(KIND=JWIM), INTENT(IN) :: KIJS, KIJL

    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL, NFRE) :: RHOWGDFTH
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL, NFRE) :: CINV
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL, NANG, NFRE) :: SSURF, SLICE
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL) :: CICOVER
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL) :: PHIWA
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL) :: EM, F1, WSWAVE, WDWAVE
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL) :: USTRA, VSTRA
    REAL(KIND=JWRB), INTENT(IN), DIMENSION(KIJL) :: UFRIC, AIRD
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL) :: TAUXD, TAUYD, TAUOCXD, TAUOCYD, TAUOC
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL) :: TAUICX, TAUICY
    REAL(KIND=JWRB), INTENT(INOUT), DIMENSION(KIJL) :: PHIOCD, PHIEPS, PHIAW
    REAL(KIND=JWRO), INTENT(INOUT), DIMENSION(KIJL) :: NPHIEPS, NTAUOC, NSWH, NMWP, NEMOTAUX
    REAL(KIND=JWRO), INTENT(INOUT), DIMENSION(KIJL) :: NEMOTAUY, NEMOWSWAVE, NEMOPHIF
    REAL(KIND=JWRO), INTENT(INOUT), DIMENSION(KIJL) :: NEMOTAUICX, NEMOTAUICY
    LOGICAL, INTENT(IN) :: LNUPD


    INTEGER(KIND=JWIM) :: WNFLUXES_K, WNFLUXES_M
    INTEGER(KIND=JWIM), INTENT(IN) :: IJ

    !     FICTITIOUS VALUE OF THE NORMALISED WAVE ENERGY FLUX UNDER THE SEA ICE
    !     (negative because it is defined as leaving the waves)
    REAL(KIND=JWRB), PARAMETER :: PHIOC_ICE = -3.75_JWRB
    REAL(KIND=JWRB), PARAMETER :: PHIAW_ICE = 3.75_JWRB

    !     USE HERSBACH 2011 FOR CD(U10) (SEE ALSO EDSON et al. 2013)
    REAL(KIND=JWRB), PARAMETER :: WNFLUXES_C1 = 1.03E-3_JWRB
    REAL(KIND=JWRB), PARAMETER :: WNFLUXES_C2 = 0.04E-3_JWRB
    REAL(KIND=JWRB), PARAMETER :: WNFLUXES_P1 = 1.48_JWRB
    REAL(KIND=JWRB), PARAMETER :: WNFLUXES_P2 = -0.21_JWRB
    REAL(KIND=JWRB), PARAMETER :: CDMAX_LOC = 0.003_JWRB

    REAL(KIND=JWRB), PARAMETER :: EFD_MIN = 0.0625_JWRB    ! corresponds to min Hs=1m under sea ice
    REAL(KIND=JWRB), PARAMETER :: EFD_MAX = 6.25_JWRB    ! corresponds to max Hs=10m under sea ice

    REAL(KIND=JWRB) :: TAU, XN, TAUO
    REAL(KIND=JWRB) :: U10P, CD_BULK, CD_WAVE, CD_ICE
    REAL(KIND=JWRB) :: CNST
    REAL(KIND=JWRB) :: EPSUS3
    REAL(KIND=JWRB) :: EPSMIN1000
    REAL(KIND=JWRB) :: ZCITHRS, CITHRSH_INV, ZMAXEXP
    REAL(KIND=JWRB) :: EFD, FFD, EFD_FAC, FFD_FAC
    REAL(KIND=JPHOOK) :: WNFLUXES_ZHOOK_HANDLE

    REAL(KIND=JWRB) :: WNFLUXES_XSTRESS, WNFLUXES_YSTRESS
    REAL(KIND=JWRB) :: XSTRESSICE, YSTRESSICE
    REAL(KIND=JWRB) :: USTAR
    REAL(KIND=JWRB) :: PHILF
    REAL(KIND=JWRB) :: OOVAL
    REAL(KIND=JWRB) :: EM_OC, F1_OC
    REAL(KIND=JWRB) :: WNFLUXES_CMRHOWGDFTH
    REAL(KIND=JWRB) :: WNFLUXES_SUMT, WNFLUXES_SUMX, WNFLUXES_SUMY
    REAL(KIND=JWRB) :: SUMXICE, SUMYICE
!$acc routine seq
!$acc data present( RHOWGDFTH, CINV, SSURF, SLICE, CICOVER, PHIWA, EM, F1, WSWAVE, WDWAVE, USTRA, VSTRA, UFRIC, AIRD, NPHIEPS,  &
!$acc & NTAUOC, NSWH, NMWP, NEMOTAUX, NEMOTAUY, NEMOTAUICX, NEMOTAUICY, NEMOWSWAVE, NEMOPHIF, TAUXD, TAUYD, TAUOCXD, TAUOCYD,  &
!$acc & TAUOC, TAUICX, TAUICY, PHIOCD, PHIEPS, PHIAW )

    ! ----------------------------------------------------------------------


    EPSUS3 = EPSUS*SQRT(EPSUS)
    EPSMIN1000 = EPSMIN*1000.0_JWRB

    IF (LCIWA1 .or. LCIWA2 .or. LCIWA3) THEN
      ZCITHRS = 0._JWRB
      CITHRSH_INV = 50._JWRB
      ZMAXEXP = 20._JWRB
    ELSE
      ZCITHRS = CIBLOCK
      CITHRSH_INV = 1._JWRB / MAX(CITHRSH, 0.01_JWRB)
      ZMAXEXP = 10._JWRB
    END IF

    EFD_FAC = 4.0_JWRB*EGRCRV / G**2
    FFD_FAC = (EGRCRV / AFCRV)**(1.0_JWRB / BFCRV)*G

    !*    DETERMINE NORMALIZED FLUXES FROM AIR TO WAVE AND FROM WAVE TO OCEAN.
    !     -------------------------------------------------------------------

    !     ENERGY FLUX from SSURF
    !     MOMENTUM FLUX FROM SSURF and SLICE
    PHILF = 0.0_JWRB
    WNFLUXES_XSTRESS = 0.0_JWRB
    WNFLUXES_YSTRESS = 0.0_JWRB
    XSTRESSICE = 0.0_JWRB
    YSTRESSICE = 0.0_JWRB
    SUMXICE = 0.0_JWRB
    SUMYICE = 0.0_JWRB

    IF (LWNEMOCOUWRS) THEN
      !     THE INTEGRATION UP TO FR(NFRE)
!$acc loop seq
      DO WNFLUXES_M=1,NFRE
        WNFLUXES_K = 1
        !         NOTE THAT EVERYTHING HERE IS ALWAYS NEGATIVE DUE TO SLICE BEING NEGATIVE
        SUMXICE = SINTH(WNFLUXES_K)*MIN(SLICE(IJ, WNFLUXES_K, WNFLUXES_M), -EPSMIN1000)
        SUMYICE = COSTH(WNFLUXES_K)*MIN(SLICE(IJ, WNFLUXES_K, WNFLUXES_M), -EPSMIN1000)
!$acc loop seq
        DO WNFLUXES_K=2,NANG
          SUMXICE = SUMXICE + SINTH(WNFLUXES_K)*MIN(SLICE(IJ, WNFLUXES_K, WNFLUXES_M), -EPSMIN1000)
          SUMYICE = SUMYICE + COSTH(WNFLUXES_K)*MIN(SLICE(IJ, WNFLUXES_K, WNFLUXES_M), -EPSMIN1000)
        END DO
        XSTRESSICE = XSTRESSICE + ZALPWRS*SUMXICE*CINV(IJ, WNFLUXES_M)*RHOWG_DFIM(WNFLUXES_M)
        YSTRESSICE = YSTRESSICE + ZALPWRS*SUMYICE*CINV(IJ, WNFLUXES_M)*RHOWG_DFIM(WNFLUXES_M)
      END DO
    END IF

!$acc loop seq
    DO WNFLUXES_M=1,NFRE
      WNFLUXES_K = 1
      WNFLUXES_SUMT = SSURF(IJ, WNFLUXES_K, WNFLUXES_M)
      WNFLUXES_SUMX = SINTH(WNFLUXES_K)*SSURF(IJ, WNFLUXES_K, WNFLUXES_M)
      WNFLUXES_SUMY = COSTH(WNFLUXES_K)*SSURF(IJ, WNFLUXES_K, WNFLUXES_M)
!$acc loop seq
      DO WNFLUXES_K=2,NANG
        WNFLUXES_SUMT = WNFLUXES_SUMT + SSURF(IJ, WNFLUXES_K, WNFLUXES_M)
        WNFLUXES_SUMX = WNFLUXES_SUMX + SINTH(WNFLUXES_K)*SSURF(IJ, WNFLUXES_K, WNFLUXES_M)
        WNFLUXES_SUMY = WNFLUXES_SUMY + COSTH(WNFLUXES_K)*SSURF(IJ, WNFLUXES_K, WNFLUXES_M)
      END DO
      PHILF = PHILF + WNFLUXES_SUMT*RHOWGDFTH(IJ, WNFLUXES_M)
      WNFLUXES_CMRHOWGDFTH = CINV(IJ, WNFLUXES_M)*RHOWGDFTH(IJ, WNFLUXES_M)
      WNFLUXES_XSTRESS = WNFLUXES_XSTRESS + WNFLUXES_SUMX*WNFLUXES_CMRHOWGDFTH
      WNFLUXES_YSTRESS = WNFLUXES_YSTRESS + WNFLUXES_SUMY*WNFLUXES_CMRHOWGDFTH
    END DO

    IF (LICERUN .and. LWAMRSETCI) THEN
      IF (CICOVER(IJ) > ZCITHRS) THEN
        OOVAL = EXP(-MIN((CICOVER(IJ)*CITHRSH_INV)**4, ZMAXEXP))

        !           ADJUST USTAR FOR THE PRESENCE OF SEA ICE
        U10P = MAX(WSWAVE(IJ), EPSU10)
        CD_BULK = MIN((WNFLUXES_C1 + WNFLUXES_C2*U10P**WNFLUXES_P1)*U10P**WNFLUXES_P2, CDMAX_LOC)
        CD_WAVE = (UFRIC(IJ) / U10P)**2
        CD_ICE = OOVAL*CD_WAVE + (1.0_JWRB - OOVAL)*CD_BULK
        USTAR = MAX(SQRT(CD_ICE)*U10P, EPSUS)

        ! EM_OC and F1_OC with fully developed model ENERGY
        ! The significant wave height derived from EM_OC will be used
        ! by NEMO as a scaling factor as if it was open ocean
        EFD = MIN(EFD_FAC*USTAR**4, EFD_MAX)
        EM_OC = MAX(OOVAL*EM(IJ) + (1.0_JWRB - OOVAL)*EFD, EFD_MIN)
        FFD = FFD_FAC / USTAR
        F1_OC = OOVAL*F1(IJ) + (1.0_JWRB - OOVAL)*FFD
        F1_OC = MIN(MAX(F1_OC, FR(2)), FR(NFRE))
      ELSE
        OOVAL = 1.0_JWRB
        USTAR = UFRIC(IJ)
        EM_OC = EM(IJ)
        F1_OC = F1(IJ)
      END IF
    ELSE
      OOVAL = 1.0_JWRB
      USTAR = UFRIC(IJ)
      EM_OC = EM(IJ)
      F1_OC = F1(IJ)
    END IF

    TAU = AIRD(IJ)*MAX(USTAR**2, EPSUS)
    TAUXD(IJ) = TAU*SIN(WDWAVE(IJ))
    TAUYD(IJ) = TAU*COS(WDWAVE(IJ))

    TAUOCXD(IJ) = TAUXD(IJ) - OOVAL*WNFLUXES_XSTRESS
    TAUOCYD(IJ) = TAUYD(IJ) - OOVAL*WNFLUXES_YSTRESS
    TAUO = SQRT(TAUOCXD(IJ)**2 + TAUOCYD(IJ)**2)
    TAUOC(IJ) = MIN(MAX(TAUO / TAU, TAUOCMIN), TAUOCMAX)

    IF (LWNEMOCOUWRS) THEN
      ! FLIP COMPONENTS TO APPLY POSITIVE STRESS TO SEA ICE
      TAUICX(IJ) = -XSTRESSICE
      TAUICY(IJ) = -YSTRESSICE
    ELSE IF (.not.LWNEMOCOUWRS) THEN
      TAUICX(IJ) = 0.0_JWRB
      TAUICY(IJ) = 0.0_JWRB
    END IF

    IF (LWCOUAST) THEN
      !       USE THE SURFACE STRESSES AS PROVIDED BY THE ATMOSPHERE AND
      !       ONLY RESCALE THEM WITH TAUOC
      IF (USTRA(IJ) /= 0.0_JWRB .or. VSTRA(IJ) /= 0.0_JWRB) THEN
        TAUXD(IJ) = USTRA(IJ)
        TAUOCXD(IJ) = USTRA(IJ)*TAUOC(IJ)
        TAUYD(IJ) = VSTRA(IJ)
        TAUOCYD(IJ) = VSTRA(IJ)*TAUOC(IJ)
      END IF
    END IF


    XN = AIRD(IJ)*MAX(USTAR**3, EPSUS3)
    PHIOCD(IJ) = OOVAL*(PHILF - PHIWA(IJ)) + (1.0_JWRB - OOVAL)*PHIOC_ICE*XN

    PHIEPS(IJ) = PHIOCD(IJ) / XN
    PHIEPS(IJ) = MIN(MAX(PHIEPS(IJ), PHIEPSMIN), PHIEPSMAX)

    PHIOCD(IJ) = PHIEPS(IJ)*XN

    PHIAW(IJ) = PHIWA(IJ) / XN
    PHIAW(IJ) = OOVAL*PHIWA(IJ) / XN + (1.0_JWRB - OOVAL)*PHIAW_ICE

    IF (LWNEMOCOU .and. LNUPD) THEN
      NPHIEPS(IJ) = PHIEPS(IJ)
      NTAUOC(IJ) = TAUOC(IJ)
      IF (EM_OC /= 0.0_JWRB) THEN
        NSWH(IJ) = 4.0_JWRO*SQRT(EM_OC)
      ELSE
        NSWH(IJ) = 0.0_JWRO
      END IF
      IF (F1_OC /= 0.0_JWRB) THEN
        NMWP(IJ) = 1.0_JWRO / F1_OC
      ELSE
        NMWP(IJ) = 0.0_JWRO
      END IF

      IF (LWNEMOTAUOC) THEN
        NEMOTAUX(IJ) = NEMOTAUX(IJ) + TAUOCXD(IJ)
        NEMOTAUY(IJ) = NEMOTAUY(IJ) + TAUOCYD(IJ)
      ELSE
        NEMOTAUX(IJ) = NEMOTAUX(IJ) + TAUXD(IJ)
        NEMOTAUY(IJ) = NEMOTAUY(IJ) + TAUYD(IJ)
      END IF
      NEMOWSWAVE(IJ) = NEMOWSWAVE(IJ) + WSWAVE(IJ)
      NEMOPHIF(IJ) = NEMOPHIF(IJ) + PHIOCD(IJ)
      NEMOTAUICX(IJ) = NEMOTAUICX(IJ) + TAUICX(IJ)
      NEMOTAUICY(IJ) = NEMOTAUICY(IJ) + TAUICY(IJ)
    END IF

    ! ----------------------------------------------------------------------


!$acc end data
  END SUBROUTINE WNFLUXES_LOKI
END MODULE WNFLUXES_LOKI_MOD
