!$loki & SWELLF4, RNLCOEF, SSDSC5, NICT, Z0RAT, X0TAUHF, RNUM, K2W, LWNEMOCOUSEND, CHNKMIN_U, Z0TUBMAX, K21W, LWFLUXOUT,  &
!$loki & ZALPWRS, OM3GMKM_GC, C2OSQRTVG_GC, ZPIFR, FLMAX, LWAMRSETCI, DFIMFR2, ALPHA, SINTH )
    IF (LHOOK) CALL DR_HOOK('DATA_OFFLOAD', 1, ZHOOK_HANDLE_DATA_OFFLOAD)
  END IF

  IF (LHOOK) CALL DR_HOOK('DATA_OFFLOAD', 0, ZHOOK_HANDLE_DATA_OFFLOAD)
!$loki stack-insert
  CALL WAIT_FOR_ASYNC_QUEUE(QUEUE=1)
  CALL GET_DEVICE_DATA_RDWR(VARS_4D, FL1=.true.)
  CALL GET_DEVICE_DATA_RDONLY(WVPRPT)
  CALL GET_DEVICE_DATA_RDONLY(WVENVI, DEPTH=.true., DELLAM1=.true., COSPHM1=.true., UCUR=.true., VCUR=.true., EMAXDPT=.true.,  &
  & IOBND=.true., IODP=.true., IBRMEM=.true.)
  CALL GET_DEVICE_DATA_RDONLY(BLK2GLO)
  IF (LHOOK) CALL DR_HOOK('DATA_OFFLOAD', 1, ZHOOK_HANDLE_DATA_OFFLOAD)




!$acc data present( VARS_4D, WVPRPT, WVENVI, BLK2GLO )


  IF (CDATE == CDTPRA) THEN
    CALL START_TIMER(REGION_TIMER)
    TIME0 = -WAM_USER_CLOCK()
    CALL PROPAG_WAM(BLK2GLO, WVPRPT%WAVNUM, WVPRPT%CGROUP, WVPRPT%OMOSNH2KD, VARS_4D%FL1, WVENVI%DEPTH, WVENVI%DELLAM1,  &
    & WVENVI%COSPHM1, WVENVI%UCUR, WVENVI%VCUR)
    TIME_PROPAG = TIME_PROPAG + (TIME0 + WAM_USER_CLOCK())*1.E-06
    CALL ADD_ELAPSED(ORIGINAL_TIMERS, REGION_PROPAGATION, REGION_TIMER)
    CDATE = CDTPRO
  END IF



!$acc end data


  !* RETRIEVING NEW FORCING FIELDS IF NEEDED.
  !  ----------------------------------------
  IF (LHOOK) CALL DR_HOOK('DATA_OFFLOAD', 0, ZHOOK_HANDLE_DATA_OFFLOAD)
  CALL WAIT_FOR_ASYNC_QUEUE(QUEUE=2)
  CALL GET_DEVICE_DATA_RDWR(FF_NOW, AIRD=.true., WDWAVE=.true., CICOVER=.true., WSWAVE=.true., WSTAR=.true., UFRIC=.true.,  &
  & TAUW=.true., TAUWDIR=.true., Z0M=.true., Z0B=.true., CHRNCK=.true., CITHICK=.true., USTRA=.true., VSTRA=.true.)
  CALL GET_DEVICE_DATA_RDONLY(FF_NEXT, AIRD=.true., WDWAVE=.true., CICOVER=.true., WSWAVE=.true., WSTAR=.true., UFRIC=.true.,  &
  & TAUW=.true., TAUWDIR=.true., Z0M=.true., Z0B=.true., CHRNCK=.true., CITHICK=.true., USTRA=.true., VSTRA=.true.)
  IF (LHOOK) CALL DR_HOOK('DATA_OFFLOAD', 1, ZHOOK_HANDLE_DATA_OFFLOAD)
  FORCING_DUE = CDTIMP >= CDATEWH
  IF (FORCING_DUE) CALL START_TIMER(REGION_TIMER)
  CALL NEWWIND(CDTIMP, CDATEWH, LLNEWFILE, WVPRPT, FF_NOW, FF_NEXT)
  IF (FORCING_DUE) CALL ADD_ELAPSED(ORIGINAL_TIMERS, REGION_FORCING, REGION_TIMER)


  ! IT IS TIME TO INTEGRATE THE SOURCE TERMS
  ! ----------------------------------------
  IF (CDATE >= CDTIMPNEXT) THEN
    ! COMPUTE UPDATE DUE TO SOURCE TERMS
    CALL GSTATS(1431, 0)
    IF (LLSOURCE) THEN

      IF (LHOOK) CALL DR_HOOK('DATA_OFFLOAD', 0, ZHOOK_HANDLE_DATA_OFFLOAD)
      IF (LWNEMOCOU .and. .not.LWCOU) THEN
        CALL WAIT_FOR_ASYNC_QUEUE(QUEUE=3)
        CALL GET_DEVICE_DATA_RDWR(WAM2NEMO, NEMOTAUICX=.true., NEMOTAUICY=.true., NEMOWSWAVE=.true., NEMOPHIF=.true.,  &
        & NPHIEPS=.true., NTAUOC=.true., NSWH=.true., NMWP=.true., NEMOTAUX=.true., NEMOTAUY=.true.)
      ELSE
        CALL GET_DEVICE_DATA_WRONLY(WAM2NEMO, NEMOTAUICX=.true., NEMOTAUICY=.true., NEMOWSWAVE=.true., NEMOPHIF=.true.,  &
        & NPHIEPS=.true., NTAUOC=.true., NSWH=.true., NMWP=.true., NEMOTAUX=.true., NEMOTAUY=.true.)
      END IF
      CALL GET_DEVICE_DATA_WRONLY(WAM2NEMO, NEMOUSTOKES=.true., NEMOVSTOKES=.true., NEMOSTRN=.true.)
      CALL GET_DEVICE_DATA_WRONLY(INTFLDS, WSEMEAN=.true., WSFMEAN=.true., USTOKES=.true., VSTOKES=.true., STRNMS=.true.,  &
      & TAUXD=.true., TAUYD=.true., TAUOCXD=.true., TAUOCYD=.true., TAUOC=.true., PHIOCD=.true., PHIEPS=.true., PHIAW=.true.,  &
      & TAUICX=.true., TAUICY=.true.)
      CALL GET_DEVICE_DATA_WRONLY(VARS_4D, XLLWS=.true.)
      CALL GET_DEVICE_DATA_WRONLY(MIJ)
      IF (LHOOK) CALL DR_HOOK('DATA_OFFLOAD', 1, ZHOOK_HANDLE_DATA_OFFLOAD)

      IF (LHOOK) CALL DR_HOOK('IMPLSCH', 0, ZHOOK_HANDLE_IMPLSCH)
      CALL START_TIMER(REGION_TIMER)
      TIME0 = -WAM_USER_CLOCK()

!$acc data present( VARS_4D,WVPRPT,WVENVI,FF_NOW,WAM2NEMO,INTFLDS,MIJ )

!$acc parallel loop gang vector_length( 64 ) default( present ) minctapersm( 20 ) async(1)
      DO ICHNK=1,NCHNK

!$acc loop vector
        DO IJ=1,NPROMA_WAM
          ! [Loki] inlined child subroutine: IMPLSCH_LOKI
          ! =========================================

          ! ----------------------------------------------------------------------



          !*    1. INITIALISATION.
          !        ---------------

          DELT = IDELT
          DELTM = 1.0_JWRB / DELT
          DELT5 = XIMP*DELT

          LCFLX = LWFLUX .or. (LWFLUXOUT .and. .not.LHEIGHT_ONLY) .or. LWNEMOCOU


          RAORW = MAX(FF_NOW%AIRD(IJ, ICHNK), 1.0_JWRB)*ROWATERM1

          IMPLSCH_ALPFAC(IJ, ICHNK) = ZALPFACX            ! <1=some reduction, 1=no reduction to attenuation

!$acc loop seq
          DO IMPLSCH_LOKI_K=1,NANG
            IMPLSCH_COSWDIF(IJ, IMPLSCH_LOKI_K, ICHNK) = COS(TH(IMPLSCH_LOKI_K) - FF_NOW%WDWAVE(IJ, ICHNK))
            IMPLSCH_SINWDIF2(IJ, IMPLSCH_LOKI_K, ICHNK) = SIN(TH(IMPLSCH_LOKI_K) - FF_NOW%WDWAVE(IJ, ICHNK))**2
          END DO

          IF (LWNEMOCOUWRS .and. .not.(LCIWA1 .or. LCIWA2 .or. LCIWA3)) THEN
!$acc loop seq
            DO IMPLSCH_LOKI_M=1,NFRE
!$acc loop seq
              DO IMPLSCH_LOKI_K=1,NANG
                IMPLSCH_SLICE(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) = 0.0_JWRB
              END DO
            END DO
          END IF

          ! ----------------------------------------------------------------------

          !*    2. COMPUTATION OF IMPLICIT INTEGRATION.
          !        ------------------------------------

          !         INTEGRATION IS DONE FROM CDATE UNTIL CDTPRO FOR A BLOCK
          !         OF LATITUDES BETWEEN PROPAGATION CALLS.


          !     REDUCE WAVE ENERGY IF LARGER THAN DEPTH LIMITED WAVE HEIGHT
          IF (LBIWBK) THEN
            ! [Loki] inlined child subroutine: SDEPTHLIM
            ! =========================================

            ! ----------------------------------------------------------------------


            LLEPSMIN = .true.
            ! [Loki] inlined child subroutine: SEMEAN
            ! =========================================

            ! ----------------------------------------------------------------------


            !*    1. INITIALISE ENERGY ARRAY.
            !        ------------------------

            IF (LLEPSMIN) THEN
              EM = EPSMIN
            ELSE
              EM = 0.0_JWRB
            END IF

            ! ----------------------------------------------------------------------

            !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTION.
            !        -----------------------------------------

!$acc loop seq
            DO SEMEAN_M=1,NFRE
              SEMEAN_K = 1
              SDEPTHLIM_TEMP = VARS_4D%FL1(IJ, SEMEAN_K, SEMEAN_M, ICHNK)
!$acc loop seq
              DO SEMEAN_K=2,NANG
                SDEPTHLIM_TEMP = SDEPTHLIM_TEMP + VARS_4D%FL1(IJ, SEMEAN_K, SEMEAN_M, ICHNK)
              END DO
              EM = EM + DFIM(SEMEAN_M)*SDEPTHLIM_TEMP
            END DO

            ! ----------------------------------------------------------------------

            !*    3. ADD TAIL ENERGY.
            !        ----------------

            DELT25 = WETAIL*FR(NFRE)*DELTH
            EM = EM + DELT25*SDEPTHLIM_TEMP


            ! =========================================

            EM = MIN(WVENVI%EMAXDPT(IJ, ICHNK) / EM, 1.0_JWRB)

!$acc loop seq
            DO SDEPTHLIM_M=1,NFRE
!$acc loop seq
              DO SDEPTHLIM_K=1,NANG
                VARS_4D%FL1(IJ, SDEPTHLIM_K, SDEPTHLIM_M, ICHNK) =  &
                & MAX(VARS_4D%FL1(IJ, SDEPTHLIM_K, SDEPTHLIM_M, ICHNK)*EM, EPSMIN)
              END DO
            END DO


            ! =========================================
          END IF

          !*    2.2 COMPUTE MEAN PARAMETERS.
          !        ------------------------

          ! [Loki] inlined child subroutine: FKMEAN
          ! =========================================

          ! ----------------------------------------------------------------------



          !*    1. INITIALISE MEAN FREQUENCY ARRAY AND TAIL FACTOR.
          !        ------------------------------------------------

          IMPLSCH_EMEAN(IJ, ICHNK) = EPSMIN
          IMPLSCH_FMEAN(IJ, ICHNK) = EPSMIN
          IMPLSCH_F1MEAN(IJ, ICHNK) = EPSMIN
          IMPLSCH_AKMEAN(IJ, ICHNK) = EPSMIN
          IMPLSCH_XKMEAN(IJ, ICHNK) = EPSMIN

          FKMEAN_DELT25 = WETAIL*FR(NFRE)*DELTH
          COEFM1 = FRTAIL*DELTH
          COEF1 = WP1TAIL*DELTH*FR(NFRE)**2
          COEFA = COEFM1*SQRT(G) / ZPI
          COEFX = COEF1*(ZPI / SQRT(G))

          !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTIONS.
          !        ------------------------------------------

          !*    2.2 SHALLOW WATER INTEGRATION.
          !         --------------------------

!$acc loop seq
          DO FKMEAN_M=1,NFRE
            SQRTK = SQRT(WVPRPT%WAVNUM(IJ, FKMEAN_M, ICHNK))
            IMPLSCH_TEMPA(IJ, ICHNK) = DFIM(FKMEAN_M) / SQRTK
            IMPLSCH_TEMPX(IJ, ICHNK) = SQRTK*DFIM(FKMEAN_M)
            FKMEAN_K = 1
            IMPLSCH_TEMP2(IJ, ICHNK) = VARS_4D%FL1(IJ, FKMEAN_K, FKMEAN_M, ICHNK)
!$acc loop seq
            DO FKMEAN_K=2,NANG
              IMPLSCH_TEMP2(IJ, ICHNK) = IMPLSCH_TEMP2(IJ, ICHNK) + VARS_4D%FL1(IJ, FKMEAN_K, FKMEAN_M, ICHNK)
            END DO
            IMPLSCH_EMEAN(IJ, ICHNK) = IMPLSCH_EMEAN(IJ, ICHNK) + DFIM(FKMEAN_M)*IMPLSCH_TEMP2(IJ, ICHNK)
            IMPLSCH_FMEAN(IJ, ICHNK) = IMPLSCH_FMEAN(IJ, ICHNK) + DFIMOFR(FKMEAN_M)*IMPLSCH_TEMP2(IJ, ICHNK)
            IMPLSCH_F1MEAN(IJ, ICHNK) = IMPLSCH_F1MEAN(IJ, ICHNK) + DFIMFR(FKMEAN_M)*IMPLSCH_TEMP2(IJ, ICHNK)
            IMPLSCH_AKMEAN(IJ, ICHNK) = IMPLSCH_AKMEAN(IJ, ICHNK) + IMPLSCH_TEMPA(IJ, ICHNK)*IMPLSCH_TEMP2(IJ, ICHNK)
            IMPLSCH_XKMEAN(IJ, ICHNK) = IMPLSCH_XKMEAN(IJ, ICHNK) + IMPLSCH_TEMPX(IJ, ICHNK)*IMPLSCH_TEMP2(IJ, ICHNK)
          END DO

          !*      ADD TAIL CORRECTION TO MEAN FREQUENCY AND
          !*      NORMALIZE WITH TOTAL ENERGY.
          IMPLSCH_EMEAN(IJ, ICHNK) = IMPLSCH_EMEAN(IJ, ICHNK) + FKMEAN_DELT25*IMPLSCH_TEMP2(IJ, ICHNK)
          IMPLSCH_FMEAN(IJ, ICHNK) = IMPLSCH_FMEAN(IJ, ICHNK) + COEFM1*IMPLSCH_TEMP2(IJ, ICHNK)
          IMPLSCH_FMEAN(IJ, ICHNK) = IMPLSCH_EMEAN(IJ, ICHNK) / IMPLSCH_FMEAN(IJ, ICHNK)
          IMPLSCH_F1MEAN(IJ, ICHNK) = IMPLSCH_F1MEAN(IJ, ICHNK) + COEF1*IMPLSCH_TEMP2(IJ, ICHNK)
          IMPLSCH_F1MEAN(IJ, ICHNK) = IMPLSCH_F1MEAN(IJ, ICHNK) / IMPLSCH_EMEAN(IJ, ICHNK)
          IMPLSCH_AKMEAN(IJ, ICHNK) = IMPLSCH_AKMEAN(IJ, ICHNK) + COEFA*IMPLSCH_TEMP2(IJ, ICHNK)
          IMPLSCH_AKMEAN(IJ, ICHNK) = (IMPLSCH_EMEAN(IJ, ICHNK) / IMPLSCH_AKMEAN(IJ, ICHNK))**2
          IMPLSCH_XKMEAN(IJ, ICHNK) = IMPLSCH_XKMEAN(IJ, ICHNK) + COEFX*IMPLSCH_TEMP2(IJ, ICHNK)
          IMPLSCH_XKMEAN(IJ, ICHNK) = (IMPLSCH_XKMEAN(IJ, ICHNK) / IMPLSCH_EMEAN(IJ, ICHNK))**2


          ! =========================================

!$acc loop seq
          DO IMPLSCH_LOKI_K=1,NANG
            ! still allow noise in full sea ice cover, but only ten percent
            IMPLSCH_FLM(IJ, IMPLSCH_LOKI_K, ICHNK) = (1._JWRB - 0.9_JWRB*MIN(FF_NOW%CICOVER(IJ, ICHNK), 0.99_JWRB)) &
            & *FLMIN*MAX(0.0_JWRB, IMPLSCH_COSWDIF(IJ, IMPLSCH_LOKI_K, ICHNK))**2
          END DO

          ! ----------------------------------------------------------------------

        END DO
      END DO
!$acc end parallel loop

      ! Spectrum means and initialization are complete. The iterative wind
      ! solver has its own launch and per-point gust work arrays.
#ifdef WAM_HAVE_SINGLE_PRECISION
!$acc parallel loop gang vector_length( 128 ) default( present ) minctapersm( 6 ) private( SUMFSIN2, SUMF ) async(1)
#else
!$acc parallel loop gang vector_length( 64 ) default( present ) minctapersm( 20 ) private( SUMFSIN2, SUMF ) async(1)
#endif
      DO ICHNK=1,NCHNK
!$acc loop vector private( XSTRESS, YSTRESS, TAUX, TAUY, USTP, USTPM1, USDIRP, UCN, UCNZALPD, GAMNORMA )
        DO IJ=1,NPROMA_WAM
          DELT = IDELT
          DELTM = 1.0_JWRB / DELT
          DELT5 = XIMP*DELT
          LCFLX = LWFLUX .or. (LWFLUXOUT .and. .not.LHEIGHT_ONLY) .or. LWNEMOCOU
          RAORW = MAX(FF_NOW%AIRD(IJ, ICHNK), 1.0_JWRB)*ROWATERM1

          !*    2.3 COMPUTATION OF SOURCE FUNCTIONS.
          !         --------------------------------

          !*    2.3.1 ITERATIVELY UPDATE STRESS AND COMPUTE WIND INPUT TERMS.
          !           -------------------------------------------------------

          LUPDTUS = .true.
          NCALL = 2
!$acc loop seq
          DO ICALL=1,NCALL
            ! [Loki] inlined child subroutine: SINFLX
            ! =========================================

            ! ----------------------------------------------------------------------


            ! UPDATE UFRIC AND Z0M
            IF (ICALL == 1) THEN
              IUSFG = 0
              IF (LWCOU) THEN
                ICODE_WND = ICODE_CPL
              ELSE
                ICODE_WND = ICODE
              END IF
            ELSE
              IUSFG = 1
              ICODE_WND = 3
            END IF

            IF (LLNORMAGAM .and. LLCAPCHNK) THEN
              RNFAC = 1.0_JWRB + DTHRN_A*(1.0_JWRB + TANH(FF_NOW%WSWAVE(IJ, ICHNK) - DTHRN_U))
            ELSE
              RNFAC = 1.0_JWRB
            END IF


            IF (LUPDTUS) THEN
              ! increase noise level in the tail
              IF (ICALL == 1) THEN
!$acc loop seq
                DO SINFLX_K=1,NANG
                  VARS_4D%FL1(IJ, SINFLX_K, NFRE, ICHNK) =  &
                  & MAX(VARS_4D%FL1(IJ, SINFLX_K, NFRE, ICHNK), IMPLSCH_FLM(IJ, SINFLX_K, ICHNK))
                END DO

                IF (LLGCBZ0) THEN
                  ! [Loki] inlined child subroutine: HALPHAP
                  ! =========================================

                  ! ----------------------------------------------------------------------


                  ZLNFRNFRE = LOG(FR(NFRE))

                  ! Find spectrum in wind direction

                  ! [Loki] inlined child subroutine: MEANSQS_LF
                  ! =========================================

                  ! ----------------------------------------------------------------------

                  !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTIONS.
                  !        ------------------------------------------

                  XMSS = 0.0_JWRB

                  ! Mean-square slope and mean frequency share the same
                  ! wind-direction spectrum traversal, but retain separate
                  ! unfloored and EPSMIN-floored direction sums.
                  SINFLX_EM = 0.0_JWRB
                  FM = 0.0_JWRB

                  SINFLX_DELT25 = WETAIL*FR(NFRE)*DELTH
                  DELT2 = FRTAIL*DELTH

                  !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTIONS.
                  !        ------------------------------------------

!$acc loop seq
                  DO FEMEAN_M=1,NFRE
                    TEMP1 = DFIM(FEMEAN_M)*WVPRPT%WAVNUM(IJ, FEMEAN_M, ICHNK)**2
                    SINFLX_TEMP2 = 0.0_JWRB
                    FEMEAN_K = 1
                    wind_direction_mask = 0.5_JWRB + 0.5_JWRB* &
                      SIGN(1.0_JWRB, IMPLSCH_COSWDIF(IJ, FEMEAN_K, ICHNK))
                    SINFLX_TEMP2 = SINFLX_TEMP2 + VARS_4D%FL1(IJ, FEMEAN_K, FEMEAN_M, ICHNK)* &
                      wind_direction_mask
                    FEMEAN_TEMP2 = MAX(VARS_4D%FL1(IJ, FEMEAN_K, FEMEAN_M, ICHNK)*wind_direction_mask, EPSMIN)
!$acc loop seq
                    DO FEMEAN_K=2,NANG
                      wind_direction_mask = 0.5_JWRB + 0.5_JWRB* &
                        SIGN(1.0_JWRB, IMPLSCH_COSWDIF(IJ, FEMEAN_K, ICHNK))
                      SINFLX_TEMP2 = SINFLX_TEMP2 + VARS_4D%FL1(IJ, FEMEAN_K, FEMEAN_M, ICHNK)* &
                        wind_direction_mask
                      FEMEAN_TEMP2 = FEMEAN_TEMP2 + &
                        MAX(VARS_4D%FL1(IJ, FEMEAN_K, FEMEAN_M, ICHNK)*wind_direction_mask, EPSMIN)
                    END DO
                    XMSS = XMSS + TEMP1*SINFLX_TEMP2
                    SINFLX_EM = SINFLX_EM + FEMEAN_TEMP2*DFIM(FEMEAN_M)
                    FM = FM + DFIMOFR(FEMEAN_M)*FEMEAN_TEMP2
                  END DO


                  !*    3. ADD TAIL CORRECTION TO MEAN FREQUENCY AND
                  !*       NORMALIZE WITH TOTAL ENERGY.
                  !        ------------------------------------------

                  SINFLX_EM = SINFLX_EM + SINFLX_DELT25*FEMEAN_TEMP2
                  FM = FM + DELT2*FEMEAN_TEMP2
                  FM = SINFLX_EM / FM
                  FM = MAX(FM, FR(1))


                  ! =========================================

                  IF (SINFLX_EM > 0.0_JWRB .and. FM < FR(-2 + NFRE)) THEN
                    ALPHAP = XMSS / (ZLNFRNFRE - LOG(FM))
                    IF (ALPHAP > ALPHAPMAX) THEN
                      ! some odd cases, revert to tail value
                      F1D = 0.0_JWRB
!$acc loop seq
                      DO HALPHAP_K=1,NANG
                        wind_direction_mask = 0.5_JWRB + 0.5_JWRB* &
                          SIGN(1.0_JWRB, IMPLSCH_COSWDIF(IJ, HALPHAP_K, ICHNK))
                        F1D = F1D + VARS_4D%FL1(IJ, HALPHAP_K, NFRE, ICHNK)*wind_direction_mask*DELTH
                      END DO
                      ALPHAP = ZPI4GM2*FR5(NFRE)*F1D
                    END IF
                  ELSE
                    F1D = 0.0_JWRB
!$acc loop seq
                    DO HALPHAP_K=1,NANG
                      wind_direction_mask = 0.5_JWRB + 0.5_JWRB* &
                        SIGN(1.0_JWRB, IMPLSCH_COSWDIF(IJ, HALPHAP_K, ICHNK))
                      F1D = F1D + VARS_4D%FL1(IJ, HALPHAP_K, NFRE, ICHNK)*wind_direction_mask*DELTH
                    END DO
                    ALPHAP = ZPI4GM2*FR5(NFRE)*F1D
                  END IF

                  !     1/2 ALPHAP:
                  HALP = 0.5_JWRB*MIN(ALPHAP, ALPHAPMAX)


                  ! =========================================
                ELSE
                  HALP = 0.0_JWRB
                END IF

              END IF

              ! [Loki] inlined child subroutine: AIRSEA
              ! =========================================

              ! ----------------------------------------------------------------------

              !*    2. DETERMINE TOTAL STRESS (if needed)
              !        ----------------------------------

              IF (ICODE_WND == 3) THEN

                ! [Loki] inlined child subroutine: TAUT_Z0
                ! =========================================

                ! ----------------------------------------------------------------------


                XLOGXL = LOG(XNLEV)
                US2TOTAUW = 1.0_JWRB + EPS1

                RNUEFF = 0.04_JWRB*RNU
                RNUKAPPAM1 = RNUEFF / XKAPPA

                PCE_GC = 0.001_JWRB*IUSFG + (1 - IUSFG)*0.005_JWRB

                !     ONLY take the contribution of TAUW that is in the wind direction
                COSDIFF = COS(FF_NOW%WDWAVE(IJ, ICHNK) - FF_NOW%TAUWDIR(IJ, ICHNK))
                TAUWACT = MAX(FF_NOW%TAUW(IJ, ICHNK)*COSDIFF, EPSMIN)
                LLCOSDIFF = COSDIFF > 0.9_JWRB

                !  USING THE CG MODEL:
                IF (LLGCBZ0) THEN

                  IF (LLCAPCHNK) THEN
                    ! [Loki] inlined child subroutine: CHNKMIN_LOKI
                    ! =========================================

                    ! ----------------------------------------------------------------------


                    result_chnkmin =  &
                    & ALPHAMIN + (ALPHA - ALPHAMIN)*0.5_JWRB*(1.0_JWRB - TANH(FF_NOW%WSWAVE(IJ, ICHNK) - CHNKMIN_U))


                    ! =========================================
                    CHARNOCK_MIN = result_chnkmin
                    ALPHAOG = CHARNOCK_MIN*GM1
                  ELSE
                    ALPHAOG = 0.0_JWRB
                  END IF

                  USMAX = MAX(-0.21339_JWRB + 0.093698_JWRB*FF_NOW%WSWAVE(IJ, ICHNK) - 0.0020944_JWRB*FF_NOW%WSWAVE(IJ, ICHNK)**2 &
                  &  + 5.5091E-5_JWRB*FF_NOW%WSWAVE(IJ, ICHNK)**3, 0.03_JWRB)
                  TAUWEFF = MIN(TAUWACT*US2TOTAUW, USMAX**2)


                  IF (IUSFG == 0) THEN
                    ALPHAGM1 = ALPHA*GM1
                    IF (FF_NOW%WSWAVE(IJ, ICHNK) < 1.0_JWRB) THEN
                      CDFG = 0.002_JWRB
                    ELSE IF (LLCOSDIFF) THEN
                      X = MIN(TAUWACT / MAX(FF_NOW%UFRIC(IJ, ICHNK), EPSUS)**2, PMAX)
                      ZCHAR = MIN(ALPHAGM1*FF_NOW%UFRIC(IJ, ICHNK)**2 / SQRT(1.0_JWRB - X),  &
                      & 0.05_JWRB*EXP(-0.05_JWRB*(FF_NOW%WSWAVE(IJ, ICHNK) - 35._JWRB)))
                      ZCHAR = MIN(ZCHAR, ALPHAMAX)
                      CDFG = ACDLIN + BCDLIN*SQRT(ZCHAR)*FF_NOW%WSWAVE(IJ, ICHNK)
                    ELSE
                      CDFG = CDM(FF_NOW%WSWAVE(IJ, ICHNK))
                    END IF
                    FF_NOW%UFRIC(IJ, ICHNK) = FF_NOW%WSWAVE(IJ, ICHNK)*SQRT(CDFG)
                  END IF

                  W1 = 0.85_JWRB - 0.05_JWRB*(TANH(10.0_JWRB*(FF_NOW%WSWAVE(IJ, ICHNK) - 5.0_JWRB)) + 1.0_JWRB)

                  XKUTOP = XKAPPA*FF_NOW%WSWAVE(IJ, ICHNK)

                  USTOLD = FF_NOW%UFRIC(IJ, ICHNK)
                  TAUOLD = USTOLD**2

!$acc loop seq
                  DO ITER=1,NITER
                    !         Z0 IS DERIVED FROM THE NEUTRAL LOG PROFILE: UTOP = (USTAR/XKAPPA)*LOG((XNLEV+Z0)/Z0)
                    FF_NOW%Z0M(IJ, ICHNK) = MAX(XNLEV / (EXP(MIN(XKUTOP / USTOLD, 50.0_JWRB)) - 1.0_JWRB), Z0MIN)
                    ! Viscous kinematic stress nu_air * dU/dz at z=0 of the neutral log profile reduced by factor 25 (0.04)
                    TAUV = RNUKAPPAM1*USTOLD / FF_NOW%Z0M(IJ, ICHNK)

                    ANG_GC = ANG_GC_A + ANG_GC_B*TANH(ANG_GC_C*TAUOLD)

                    ! [Loki] inlined child subroutine: STRESS_GC_LOKI
                    ! =========================================
                    ! ----------------------------------------------------------------------


                    !*    1.0  DETERMINE GRAV_CAP SPECTRUM, TAUWHF.
                    !          ------------------------------------

                    !     FIND NS:
                    ! [Loki] inlined child subroutine: NS_GC_LOKI
                    ! =========================================

                    ! ----------------------------------------------------------------------


                    !!!Y = 1.0_JWRB/(1.48_JWRB+2.05_JWRB*UST)
                    !!!Y = (1.0_JWRB + UST**2)/(1.0_JWRB+10.0_JWRB*UST**2)

                    NS_GC_XKS = SQRTGOSURFT / (1.48_JWRB + 2.05_JWRB*FF_NOW%UFRIC(IJ, ICHNK))

                    result_ns_gc = MIN(INT(LOG(MAX(NS_GC_XKS*XKM_GC(1), 1.0_JWRB))*XLOGKRATIOM1_GC) + 1, NWAV_GC - 1)


                    ! =========================================
                    STRESS_GC_NS = result_ns_gc

                    STRESS_GC_TAUWCG_MIN = (FF_NOW%UFRIC(IJ, ICHNK)*(Z0MIN / FF_NOW%Z0M(IJ, ICHNK)))**2

                    STRESS_GC_XLAMBDA = 1.0_JWRB + STRESS_GC_XLAMA*TANH(STRESS_GC_XLAMB*FF_NOW%UFRIC(IJ, ICHNK)**STRESS_GC_NLAM)

                    STRESS_GC_ZABHRC = ANG_GC*BETAMAXOXKAPPA2*HALP*C2OSQRTVG_GC(STRESS_GC_NS)
                    IF (LLNORMAGAM) THEN
                      STRESS_GC_CONST = RNFAC*BMAXOKAP*HALP*C2OSQRTVG_GC(STRESS_GC_NS) / MAX(FF_NOW%UFRIC(IJ, ICHNK), EPSUS)
                    ELSE
                      STRESS_GC_CONST = 0.0_JWRB
                    END IF

                    !     GAM_W GROWTHRATE BY WIND WITHOUT the multiplicative factor representing the ratio of air density to water density (eps)
                    !     and BETAMAXOXKAPPA2
                    STRESS_GC_X = FF_NOW%UFRIC(IJ, ICHNK)*CM_GC(STRESS_GC_NS)
                    STRESS_GC_XLOG = LOG(XK_GC(STRESS_GC_NS)*FF_NOW%Z0M(IJ, ICHNK)) + XKAPPA / (STRESS_GC_X + ZALP)
                    STRESS_GC_ZLOG = STRESS_GC_XLOG - LOG(STRESS_GC_XLAMBDA)
                    STRESS_GC_ZLOG = MIN(STRESS_GC_ZLOG, 0.0_JWRB)
                    STRESS_GC_ZLOG2X = STRESS_GC_ZLOG*STRESS_GC_ZLOG*STRESS_GC_X
                    STRESS_GC_GAM_W = STRESS_GC_ZLOG2X*STRESS_GC_ZLOG2X*EXP(STRESS_GC_XLOG)*OM3GMKM_GC(STRESS_GC_NS)

                    STRESS_GC_ZN = STRESS_GC_CONST*XKMSQRTVGOC2_GC(STRESS_GC_NS)*STRESS_GC_GAM_W
                    STRESS_GC_GAMNORMA = (1.0_JWRB + RN1_RN*STRESS_GC_ZN) / (1.0_JWRB + STRESS_GC_ZN)

                    STRESS_GC_TAUWCG = STRESS_GC_GAM_W*DELKCC_GC_NS(STRESS_GC_NS)*OMXKM3_GC(STRESS_GC_NS)*STRESS_GC_GAMNORMA

!$acc loop seq
                    DO STRESS_GC_I=STRESS_GC_NS + 1,NWAV_GC
                      !       ANALYTICAL FORM INERTIAL SUB RANGE F(k) = k**(-4)*BB
                      !       BB = HALP * C2OSQRTVG_GC(NS)*SQRT(VG_GC(I))/C_GC(I)**2
                      !       Tauwcg : (rhow * g /rhoa) * integral of (1/c) * gammma * F(k)  k dk
                      !       with omega=g*k and omega=k*c,  then
                      !       Tauwcg : (rhow /rhoa) * integral of omega * gammma * F(k)  k dk
                      !       but gamma is computed wihtout the rhoa/rhow factor so
                      !       Tauwcg : integral of omega * gammma_wam * F(k)  k dk
                      !       It should be done in vector form with actual directional spreading information
                      !       It simplified here by using the ANG_GC factor.

                      STRESS_GC_X = FF_NOW%UFRIC(IJ, ICHNK)*CM_GC(STRESS_GC_I)
                      STRESS_GC_XLOG = LOG(XK_GC(STRESS_GC_I)*FF_NOW%Z0M(IJ, ICHNK)) + XKAPPA / (STRESS_GC_X + ZALP)
                      STRESS_GC_ZLOG = STRESS_GC_XLOG - LOG(STRESS_GC_XLAMBDA)
                      STRESS_GC_ZLOG = MIN(STRESS_GC_ZLOG, 0.0_JWRB)
                      STRESS_GC_ZLOG2X = STRESS_GC_ZLOG*STRESS_GC_ZLOG*STRESS_GC_X
                      STRESS_GC_GAM_W = STRESS_GC_ZLOG2X*STRESS_GC_ZLOG2X*EXP(STRESS_GC_XLOG)*OM3GMKM_GC(STRESS_GC_I)

                      STRESS_GC_ZN = STRESS_GC_CONST*XKMSQRTVGOC2_GC(STRESS_GC_I)*STRESS_GC_GAM_W
                      STRESS_GC_GAMNORMA = (1.0_JWRB + RN1_RN*STRESS_GC_ZN) / (1.0_JWRB + STRESS_GC_ZN)

                      STRESS_GC_TAUWCG = STRESS_GC_TAUWCG + STRESS_GC_GAM_W*DELKCC_OMXKM3_GC(STRESS_GC_I)*STRESS_GC_GAMNORMA
                    END DO
                    result_stress_gc_res = MAX(STRESS_GC_ZABHRC*STRESS_GC_TAUWCG, STRESS_GC_TAUWCG_MIN)


                    ! =========================================
                    TAUUNR = result_stress_gc_res

                    !         TOTAL kinematic STRESS:
                    TAUNEW = TAUWEFF + TAUV + TAUUNR
                    USTNEW = SQRT(TAUNEW)
                    FF_NOW%UFRIC(IJ, ICHNK) = W1*USTOLD + (1.0_JWRB - W1)*USTNEW

                    !         CONVERGENCE ?
                    DEL = FF_NOW%UFRIC(IJ, ICHNK) - USTOLD
                    IF (ABS(DEL) < PCE_GC*FF_NOW%UFRIC(IJ, ICHNK)) EXIT
                    TAUOLD = FF_NOW%UFRIC(IJ, ICHNK)**2
                    USTOLD = FF_NOW%UFRIC(IJ, ICHNK)
                  END DO

                  X = TAUWEFF / TAUOLD

                  ! protection just in case there is no convergence
                  IF (ITER > NITER .and. X >= PMAX) THEN
                    CDFG = CDM(FF_NOW%WSWAVE(IJ, ICHNK))
                    FF_NOW%UFRIC(IJ, ICHNK) = FF_NOW%WSWAVE(IJ, ICHNK)*SQRT(CDFG)
                    Z0MINRST = FF_NOW%UFRIC(IJ, ICHNK)**2*ALPHA*GM1
                    FF_NOW%Z0M(IJ, ICHNK) = MAX(XNLEV / (EXP(XKUTOP / FF_NOW%UFRIC(IJ, ICHNK)) - 1.0_JWRB), Z0MINRST)
                    FF_NOW%Z0B(IJ, ICHNK) = Z0MINRST
                  ELSE
                    FF_NOW%Z0M(IJ, ICHNK) = MAX(XNLEV / (EXP(XKUTOP / FF_NOW%UFRIC(IJ, ICHNK)) - 1.0_JWRB), Z0MIN)
                    FF_NOW%Z0B(IJ, ICHNK) = FF_NOW%Z0M(IJ, ICHNK)*SQRT(TAUUNR / TAUOLD)
                  END IF

                  !       Refine solution

                  IF (X < PMAX) THEN

                    USNRF = FF_NOW%UFRIC(IJ, ICHNK)
                    Z0NRF = FF_NOW%Z0M(IJ, ICHNK)
                    Z0BNRF = FF_NOW%Z0B(IJ, ICHNK)

                    USTOLD = FF_NOW%UFRIC(IJ, ICHNK)
                    TAUOLD = MAX(USTOLD**2, TAUWEFF)

                    ALPOG = MAX(MIN(FF_NOW%Z0B(IJ, ICHNK) / TAUOLD, ALPHAMAX), ALPHAOG)

!$acc loop seq
                    DO ITER=1,NITER
                      X = MIN(TAUWEFF / TAUOLD, PMAX)
                      USTM1 = 1.0_JWRB / MAX(USTOLD, EPSUS)
                      Z0VIS = RNUM*USTM1
                      HZ0VISO1MX = 0.5_JWRB*Z0VIS / (1.0_JWRB - X)
                      FF_NOW%Z0B(IJ, ICHNK) = ALPOG*TAUOLD
                      FF_NOW%Z0M(IJ, ICHNK) = HZ0VISO1MX + SQRT(HZ0VISO1MX**2 + FF_NOW%Z0B(IJ, ICHNK)**2 / (1.0_JWRB - X))

                      XOLOGZ0 = 1.0_JWRB / LOG(XNLEV / FF_NOW%Z0M(IJ, ICHNK) + 1.0_JWRB)
                      F = USTOLD - XKUTOP*XOLOGZ0
                      ZZ = 2.0_JWRB*USTM1*(3.0_JWRB*FF_NOW%Z0B(IJ, ICHNK)**2 + 0.5_JWRB*Z0VIS*FF_NOW%Z0M(IJ, ICHNK) -  &
                      & FF_NOW%Z0M(IJ, ICHNK)**2) / (2.0_JWRB*FF_NOW%Z0M(IJ, ICHNK)**2*(1.0_JWRB - X) - Z0VIS*FF_NOW%Z0M(IJ,  &
                      & ICHNK))

                      DELF = 1.0_JWRB - XKUTOP*XOLOGZ0**2*ZZ

                      IF (DELF /= 0.0_JWRB) FF_NOW%UFRIC(IJ, ICHNK) = USTOLD - F / DELF
                      !           CONVERGENCE ?
                      TAUNEW = MAX(FF_NOW%UFRIC(IJ, ICHNK)**2, TAUWEFF)
                      FF_NOW%UFRIC(IJ, ICHNK) = SQRT(TAUNEW)
                      DEL = TAUNEW - TAUOLD
                      IF (ABS(DEL) < PCE_GC*TAUOLD) EXIT
                      TAUOLD = TAUNEW
                      USTOLD = FF_NOW%UFRIC(IJ, ICHNK)

                    END DO
                    ! protection just in case there is no convergence
                    IF (ITER > NITER) THEN
                      FF_NOW%UFRIC(IJ, ICHNK) = USNRF
                      FF_NOW%Z0M(IJ, ICHNK) = Z0NRF
                      FF_NOW%Z0B(IJ, ICHNK) = Z0BNRF
                      USTM1 = 1.0_JWRB / MAX(FF_NOW%UFRIC(IJ, ICHNK), EPSUS)
                      Z0VIS = RNUM*USTM1
                      FF_NOW%CHRNCK(IJ, ICHNK) = MAX(G*(FF_NOW%Z0M(IJ, ICHNK) - Z0VIS)*USTM1**2, ALPHAMIN)

                    ELSE
                      FF_NOW%CHRNCK(IJ, ICHNK) =  &
                      & MAX(G*(FF_NOW%Z0B(IJ, ICHNK) / SQRT(1.0_JWRB - X)) / MAX(FF_NOW%UFRIC(IJ, ICHNK), EPSUS)**2, ALPHAMIN)
                    END IF

                  ELSE
                    USTM1 = 1.0_JWRB / MAX(FF_NOW%UFRIC(IJ, ICHNK), EPSUS)
                    Z0VIS = RNUM*USTM1
                    FF_NOW%CHRNCK(IJ, ICHNK) = MAX(G*(FF_NOW%Z0M(IJ, ICHNK) - Z0VIS)*USTM1**2, ALPHAMIN)
                  END IF



                ELSE

                  TAUWEFF = TAUWACT*US2TOTAUW

                  IF (LLCAPCHNK) THEN
                    ! [Loki] inlined child subroutine: CHNKMIN_LOKI
                    ! =========================================

                    ! ----------------------------------------------------------------------


                    result_chnkmin =  &
                    & ALPHAMIN + (ALPHA - ALPHAMIN)*0.5_JWRB*(1.0_JWRB - TANH(FF_NOW%WSWAVE(IJ, ICHNK) - CHNKMIN_U))


                    ! =========================================
                    CHARNOCK_MIN = result_chnkmin
                    XMIN = 0.15_JWRB*(ALPHA - CHARNOCK_MIN)
                    ALPHAOG = CHARNOCK_MIN*GM1
                  ELSE
                    XMIN = 0.0_JWRB
                    ALPHAOG = ALPHA*GM1
                  END IF

                  XKUTOP = XKAPPA*FF_NOW%WSWAVE(IJ, ICHNK)

                  USTOLD = (1 - IUSFG)*FF_NOW%WSWAVE(IJ, ICHNK)*SQRT(MIN(ACD + BCD*FF_NOW%WSWAVE(IJ, ICHNK), CDMAX)) +  &
                  & IUSFG*FF_NOW%UFRIC(IJ, ICHNK)
                  TAUOLD = MAX(USTOLD**2, TAUWEFF)
                  FF_NOW%UFRIC(IJ, ICHNK) = SQRT(TAUOLD)
                  USTM1 = 1.0_JWRB / MAX(FF_NOW%UFRIC(IJ, ICHNK), EPSUS)

!$acc loop seq
                  DO ITER=1,NITER
                    X = MAX(TAUWACT / TAUOLD, XMIN)
                    Z0CH = ALPHAOG*TAUOLD / SQRT(1.0_JWRB - X)
                    Z0VIS = RNUM*USTM1
                    Z0TOT = Z0CH + Z0VIS

                    XOLOGZ0 = 1.0_JWRB / (XLOGXL - LOG(Z0TOT))
                    F = FF_NOW%UFRIC(IJ, ICHNK) - XKUTOP*XOLOGZ0
                    ZZ = USTM1*(Z0CH*(2.0_JWRB - TWOXMP1*X) / (1.0_JWRB - X) - Z0VIS) / Z0TOT
                    DELF = 1.0_JWRB - XKUTOP*XOLOGZ0**2*ZZ

                    IF (DELF /= 0.0_JWRB) FF_NOW%UFRIC(IJ, ICHNK) = FF_NOW%UFRIC(IJ, ICHNK) - F / DELF
                    TAUNEW = MAX(FF_NOW%UFRIC(IJ, ICHNK)**2, TAUWEFF)
                    FF_NOW%UFRIC(IJ, ICHNK) = SQRT(TAUNEW)
                    IF (TAUNEW == TAUOLD) EXIT
                    USTM1 = 1.0_JWRB / MAX(FF_NOW%UFRIC(IJ, ICHNK), EPSUS)
                    TAUOLD = TAUNEW
                  END DO

                  FF_NOW%Z0M(IJ, ICHNK) = Z0CH
                  FF_NOW%Z0B(IJ, ICHNK) = ALPHAOG*TAUOLD
                  FF_NOW%CHRNCK(IJ, ICHNK) = MAX(G*FF_NOW%Z0M(IJ, ICHNK)*USTM1**2, ALPHAMIN)


                END IF


                ! =========================================

              ELSE IF (ICODE_WND == 1 .or. ICODE_WND == 2) THEN

                ! [Loki] Removed content of pragma-marked region!
              END IF


              ! =========================================

            END IF

            ! COMPUTE WIND INPUT
            !!  FLD AND SL ARE INITIALISED IN SINPUT
            IF (ICALL < NCALL) THEN
              NGST = 1
              LLPHIWA = .false.
              LLSNEG = .false.
            ELSE
              NGST = 2
              LLPHIWA = LCFLX
              LLSNEG = .true.
            END IF

            ! [Loki] inlined child subroutine: SINPUT
            ! =========================================
            ! ----------------------------------------------------------------------

            EM_LOC = EPSMIN
            IMPLSCH_FMEANWS(IJ, ICHNK) = EPSMIN
            FEMEANWS_DELT25 = WETAIL*FR(NFRE)*DELTH
            FEMEANWS_DELT2 = FRTAIL*DELTH

            SELECT CASE (IPHYS)
            CASE (0)
              ! [Loki] Removed content of pragma-marked region!
            CASE (1)
              ! [Loki] inlined child subroutine: SINPUT_ARD
              ! =========================================
              ! ----------------------------------------------------------------------


              AVG_GST = 1.0_JWRB / NGST
              CONST1 = BETAMAXOXKAPPA2
              CONSTN = DELTH / (XKAPPA*ZPI)

              ABS_TAUWSHELTER = ABS(TAUWSHELTER)
              IF (ABS_TAUWSHELTER == 0.0_JWRB) THEN
                LTAUWSHELTER = .false.
              ELSE
                LTAUWSHELTER = .true.
              END IF


              !     ESTIMATE THE STANDARD DEVIATION OF GUSTINESS.
              IF (NGST > 1) THEN
                ! [Loki] inlined child subroutine: WSIGSTAR
                ! =========================================


                ! ----------------------------------------------------------------------


                IF (LLGCBZ0 .or. LLNORMAGAM) THEN
                  ZN = RNUM

                  U10M1 = 1.0_JWRB / MAX(FF_NOW%WSWAVE(IJ, ICHNK), WSPMIN)
                  ! CHARNOCK:
                  WSIGSTAR_Z0VIS = ZN / MAX(FF_NOW%UFRIC(IJ, ICHNK), EPSUS)
                  SINPUT_ZCHAR = G*(FF_NOW%Z0M(IJ, ICHNK) - WSIGSTAR_Z0VIS) / MAX(FF_NOW%UFRIC(IJ, ICHNK)**2, EPSUS)
                  SINPUT_ZCHAR = MAX(MIN(SINPUT_ZCHAR, ALPHAMAX), ALPHAMIN)

                  BCD_LOC = BCDLIN*SQRT(SINPUT_ZCHAR)
                  C_D = ACDLIN + BCD_LOC*FF_NOW%WSWAVE(IJ, ICHNK)
                  DC_DDU = BCD_LOC
                  SIG_CONV = 1.0_JWRB + 0.5_JWRB*FF_NOW%WSWAVE(IJ, ICHNK) / C_D*DC_DDU
                  SIG_N = MIN(SIG_NMAX, SIG_CONV*U10M1*(BG_GUST*FF_NOW%UFRIC(IJ, ICHNK)**3 + 0.5_JWRB*XKAPPA*FF_NOW%WSTAR(IJ,  &
                  & ICHNK)**3)**ONETHIRD)

                ELSE
                  ZN = 0.0_JWRB


                  !!! for consistency I have kept the old method, even though the new method above could be used,
                  !!! but until LLGCBZ0 or LLNORMAGAM is the default, keep the old scheme whe it is not...
                  !
                  !       IN THE FOLLOWING U10 IS ESTIMATED ASSUMING EVERYTHING IS
                  !       BASED ON U*
                  !
                  SINPUT_XKAPPAD = 1.0_JWRB / XKAPPA
                  U10 = FF_NOW%UFRIC(IJ, ICHNK)*SINPUT_XKAPPAD*(LOG(10.0_JWRB) - LOG(FF_NOW%Z0M(IJ, ICHNK)))
                  U10 = MAX(U10, WSPMIN)
                  U10M1 = 1.0_JWRB / U10
                  C2U10P1 = C2*U10**P1
                  U10P2 = U10**P2
                  C_D = (C1 + C2U10P1)*U10P2
                  DC_DDU = (P2*C1 + (P1 + P2)*C2U10P1)*U10P2*U10M1
                  SIG_CONV = 1.0_JWRB + 0.5_JWRB*U10 / C_D*DC_DDU
                  SIG_N = MIN(SIG_NMAX, SIG_CONV*U10M1*(BG_GUST*FF_NOW%UFRIC(IJ, ICHNK)**3 + 0.5_JWRB*XKAPPA*FF_NOW%WSTAR(IJ,  &
                  & ICHNK)**3)**ONETHIRD)

                END IF


                ! =========================================
              END IF


              IF (LLNORMAGAM) THEN
                CSTRNFAC = CONSTN*RNFAC / RAORW
              END IF
              ! ----------------------------------------------------------------------

              IF (LLSNEG) THEN
                !!!!  only for the negative sinput
                NU_AIR = RNU
                FACM1_NU_AIR = 4.0_JWRB / NU_AIR

                FAC_NU_AIR = RNUM

                FU = ABS(SWELLF3)
                FUD = SWELLF2
                DELABM1 = REAL(IAB) / (ABMAX - ABMIN)


                !       computation of Uorb and Aorb
                UORBT = EPSMIN
                AORB = EPSMIN

!$acc loop seq
                DO SINPUT_M=1,NFRE
                  SIG = ZPIFR(SINPUT_M)
                  SIG2 = SIG**2
                  DFIM_SIG2 = DFIM(SINPUT_M)*SIG2

                  SINPUT_K = 1
                  SINFLX_TEMP = VARS_4D%FL1(IJ, SINPUT_K, SINPUT_M, ICHNK)
!$acc loop seq
                  DO SINPUT_K=2,NANG
                    SINFLX_TEMP = SINFLX_TEMP + VARS_4D%FL1(IJ, SINPUT_K, SINPUT_M, ICHNK)
                  END DO

                  UORBT = UORBT + DFIM_SIG2*SINFLX_TEMP
                  AORB = AORB + DFIM(SINPUT_M)*SINFLX_TEMP
                END DO

                UORBT = 2.0_JWRB*SQRT(UORBT)                  ! this is the significant orbital amplitude
                AORB = 2.0_JWRB*SQRT(AORB)                  ! this 1/2 Hs
                RE = FACM1_NU_AIR*UORBT*AORB                  ! this is the Reynolds number
                SINPUT_Z0VIS = FAC_NU_AIR / MAX(FF_NOW%UFRIC(IJ, ICHNK), 0.0001_JWRB)
                Z0TUB = Z0RAT*MIN(Z0TUBMAX, FF_NOW%Z0M(IJ, ICHNK))
                Z0NOZ = MAX(SINPUT_Z0VIS, Z0TUB)
                ZORB = AORB / Z0NOZ

                !         compute fww
                SINPUT_XI = (LOG10(MAX(ZORB, 3.0_JWRB)) - ABMIN)*DELABM1
                IND = MIN(IAB - 1, INT(SINPUT_XI))
                SINPUT_DELI1 = MIN(1.0_JWRB, SINPUT_XI - REAL(IND, kind=JWRB))
                SINPUT_DELI2 = 1.0_JWRB - SINPUT_DELI1
                FWW = SWELLFT(IND)*SINPUT_DELI2 + SWELLFT(IND + 1)*SINPUT_DELI1
                SINPUT_TEMP2 = FWW*UORBT

                !       Define the critical Reynolds number
                IF (SWELLF6 == 1.0_JWRB) THEN
                  RE_C = SWELLF4
                ELSE
                  HFTSWELLF6 = 1.0_JWRB - SWELLF6
                  RE_C = SWELLF4*(2.0_JWRB / AORB)**HFTSWELLF6
                END IF

                !       Swell damping weight between viscous and turbulent boundary layer
                IF (SWELLF7 > 0.0_JWRB) THEN
                  SMOOTH = 0.5_JWRB*TANH((RE - RE_C)*SWELLF7M1)
                  PTURB = 0.5_JWRB + SMOOTH
                  PVISC = 0.5_JWRB - SMOOTH
                ELSE
                  IF (RE <= RE_C) THEN
                    PTURB = 0.0_JWRB
                    PVISC = 0.5_JWRB
                  ELSE
                    PTURB = 0.5_JWRB
                    PVISC = 0.0_JWRB
                  END IF
                END IF

                AIRD_PVISC = PVISC*RAORW

              END IF



              ! Initialisation

              IF (NGST == 1) THEN
                USTP(1) = FF_NOW%UFRIC(IJ, ICHNK)
              ELSE IF (NGST == 2) THEN
                USTP(1) = FF_NOW%UFRIC(IJ, ICHNK)*(1.0_JWRB + SIG_N)
                USTP(2) = FF_NOW%UFRIC(IJ, ICHNK)*(1.0_JWRB - SIG_N)
              END IF

              !... Expressing the IGST loop in this way enables the compiler to
              !... unroll it whilst still retaining correctness for the case
              !... where NGST == 1. This is an important optimisation for GPUs.
!$acc loop seq
              DO IGST=1,2
                IF (IGST <= NGST) THEN
                  USTPM1(IGST) = 1.0_JWRB / MAX(USTP(IGST), EPSUS)
                END IF
              END DO

              IF (LTAUWSHELTER) THEN
!$acc loop seq
                DO IGST=1,2
                  IF (IGST <= NGST) THEN
                    XSTRESS(IGST) = 0.0_JWRB
                    YSTRESS(IGST) = 0.0_JWRB
                    USG2 = USTP(IGST)**2
                    TAUX(IGST) = USG2*SIN(FF_NOW%WDWAVE(IJ, ICHNK))
                    TAUY(IGST) = USG2*COS(FF_NOW%WDWAVE(IJ, ICHNK))
                  END IF
                END DO

                ROGOROAIR = G / RAORW

              ELSE
!$acc loop seq
                DO SINPUT_K=1,NANG
                  IMPLSCH_COSLP(IJ, SINPUT_K, ICHNK) = IMPLSCH_COSWDIF(IJ, SINPUT_K, ICHNK)
                END DO
              END IF


              !*    2. MAIN LOOP OVER FREQUENCIES.
              !        ---------------------------

              IF (.not.LLNORMAGAM) THEN
                GAMNORMA(1) = 1.0_JWRB
                GAMNORMA(2) = 1.0_JWRB
              END IF

              IF (.not.LLSNEG .and. LTAUWSHELTER) THEN
!$acc loop seq
                DO SINPUT_K=1,NANG
                  IMPLSCH_DSTAB(IJ, SINPUT_K, 1, ICHNK) = 0.0_JWRB
                  IMPLSCH_DSTAB(IJ, SINPUT_K, 2, ICHNK) = 0.0_JWRB
                END DO
              END IF

!$acc loop seq
              DO SINPUT_M=1,NFRE
                FEMEANWS_TEMP2 = 0.0_JWRB
                SIG = ZPIFR(SINPUT_M)
                SIG2 = SIG**2
                SINPUT_CONST = SIG*CONST1

                IF (LLSNEG) THEN
                  COEF = -SWELLF*16._JWRB*SIG2 / G
                  COEF5 = -SWELLF5*2._JWRB*SQRT(2._JWRB*NU_AIR*SIG)
                END IF

                IF (LTAUWSHELTER) THEN
!$acc loop seq
                  DO IGST=1,2
                    IF (IGST <= NGST) THEN
                      TAUPX = TAUX(IGST) - ABS_TAUWSHELTER*XSTRESS(IGST)
                      TAUPY = TAUY(IGST) - ABS_TAUWSHELTER*YSTRESS(IGST)
                      USDIRP(IGST) = ATAN2(TAUPX, TAUPY)
                      USTP(IGST) = (TAUPX**2 + TAUPY**2)**0.25_JWRB
                      USTPM1(IGST) = 1.0_JWRB / MAX(USTP(IGST), EPSUS)
                    END IF
                  END DO

                  CONSTF = ROGOROAIR*WVPRPT%CINV(IJ, SINPUT_M, ICHNK)*DFIM(SINPUT_M)
                END IF


                !*      PRECALCULATE FREQUENCY DEPENDENCE.
                !       ----------------------------------

!$acc loop seq
                DO IGST=1,2
                  IF (IGST <= NGST) THEN
                    UCN(IGST) = USTP(IGST)*WVPRPT%CINV(IJ, SINPUT_M, ICHNK)
                    UCNZALPD(IGST) = XKAPPA / (UCN(IGST) + ZALP)
                  END IF
                END DO
                ZCN = LOG(WVPRPT%WAVNUM(IJ, SINPUT_M, ICHNK)*FF_NOW%Z0M(IJ, ICHNK))
                CNSN = SINPUT_CONST*RAORW

                !*    2.1 LOOP OVER DIRECTIONS.
                !         ---------------------

!$acc loop seq
                DO SINPUT_K=1,NANG
                  VARS_4D%XLLWS(IJ, SINPUT_K, SINPUT_M, ICHNK) = 0.0_JWRB
                END DO

                IF (LLNORMAGAM) THEN
                  XNGAMCONST = CSTRNFAC*WVPRPT%XK2CG(IJ, SINPUT_M, ICHNK)
                END IF

                IF (LLSNEG) THEN
                  !       SWELL DAMPING:
                  DSTAB1 = COEF5*AIRD_PVISC*WVPRPT%WAVNUM(IJ, SINPUT_M, ICHNK)
                  SINPUT_TEMP1 = COEF*RAORW
                END IF

!$acc loop seq
                DO IGST=1,2
                  IF (IGST <= NGST) THEN
!$acc loop seq
                    DO SINPUT_K=1,NANG
                      IF (LTAUWSHELTER) THEN
                        IMPLSCH_COSLP(IJ, SINPUT_K, ICHNK) = COS(TH(SINPUT_K) - USDIRP(IGST))
                      END IF
                      IMPLSCH_GAM0(IJ, SINPUT_K, IGST, ICHNK) = 0.0_JWRB
                      IF (IMPLSCH_COSLP(IJ, SINPUT_K, ICHNK) > 0.01_JWRB) THEN
                        SINPUT_X = IMPLSCH_COSLP(IJ, SINPUT_K, ICHNK)*UCN(IGST)
                        ZLOG = ZCN + UCNZALPD(IGST) / IMPLSCH_COSLP(IJ, SINPUT_K, ICHNK)
                        IF (ZLOG < 0.0_JWRB) THEN
                          ZLOG2X = ZLOG*ZLOG*SINPUT_X
                          IMPLSCH_GAM0(IJ, SINPUT_K, IGST, ICHNK) = EXP(ZLOG)*ZLOG2X*ZLOG2X*CNSN
                          VARS_4D%XLLWS(IJ, SINPUT_K, SINPUT_M, ICHNK) = 1.0_JWRB
                        END IF
                      END IF
                    END DO

                    IF (LLNORMAGAM) THEN

                      SUMF = 0.0_JWRB
                      SUMFSIN2 = 0.0_JWRB
!$acc loop seq
                      DO SINPUT_K=1,NANG
                        SUMF = SUMF + IMPLSCH_GAM0(IJ, SINPUT_K, IGST, ICHNK)*VARS_4D%FL1(IJ, SINPUT_K, SINPUT_M, ICHNK)
                        SUMFSIN2 = SUMFSIN2 + IMPLSCH_GAM0(IJ, SINPUT_K, IGST, ICHNK)*VARS_4D%FL1(IJ, SINPUT_K, SINPUT_M, ICHNK) &
                        & *IMPLSCH_SINWDIF2(IJ, SINPUT_K, ICHNK)
                      END DO

                      ZNZ = XNGAMCONST*USTPM1(IGST)
                      GAMNORMA(IGST) = (1.0_JWRB + ZNZ*SUMFSIN2) / (1.0_JWRB + ZNZ*SUMF)

                    END IF

                    IF (LLSNEG .and. LTAUWSHELTER) THEN
!$acc loop seq
                      DO SINPUT_K=1,NANG
                        DSTAB2 = SINPUT_TEMP1*(SINPUT_TEMP2 + (FU + FUD*IMPLSCH_COSLP(IJ, SINPUT_K, ICHNK))*USTP(IGST))
                        IMPLSCH_DSTAB(IJ, SINPUT_K, IGST, ICHNK) = DSTAB1 + PTURB*DSTAB2
                      END DO
                    END IF
                  END IF
                END DO


                !*    2.2 UPDATE THE SHELTERING STRESS (in any),
                !         AND THEN ADDING INPUT SOURCE TERM TO NET SOURCE FUNCTION.
                !         ---------------------------------------------------------

!$acc loop seq
                DO SINPUT_K=1,NANG
                  FEMEANWS_TEMP2 = FEMEANWS_TEMP2 + VARS_4D%XLLWS(IJ, SINPUT_K, SINPUT_M, ICHNK)* &
                    VARS_4D%FL1(IJ, SINPUT_K, SINPUT_M, ICHNK)

!$acc loop seq
                  DO IGST=1,2
                    IF (IGST <= NGST) THEN
                      ! SLP: only the positive contributions
                      SLP = IMPLSCH_GAM0(IJ, SINPUT_K, IGST, ICHNK)*GAMNORMA(IGST)
                      IF (LTAUWSHELTER) THEN
                        FLP = SLP + IMPLSCH_DSTAB(IJ, SINPUT_K, IGST, ICHNK)
                      ELSE IF (LLSNEG) THEN
                        DSTAB2 = SINPUT_TEMP1*(SINPUT_TEMP2 + (FU + FUD*IMPLSCH_COSLP(IJ, SINPUT_K, ICHNK))*USTP(IGST))
                        FLP = SLP + (DSTAB1 + PTURB*DSTAB2)
                      ELSE
                        FLP = SLP
                      END IF

                      SLP = SLP*VARS_4D%FL1(IJ, SINPUT_K, SINPUT_M, ICHNK)

                      IF (LTAUWSHELTER) THEN
                        CONST11 = CONSTF*SINTH(SINPUT_K)
                        CONST22 = CONSTF*COSTH(SINPUT_K)
                        XSTRESS(IGST) = XSTRESS(IGST) + SLP*CONST11
                        YSTRESS(IGST) = YSTRESS(IGST) + SLP*CONST22
                      END IF

                      IF (IGST == 1) THEN
                        SLP_AVG = SLP
                        FLP_AVG = FLP
                      ELSE
                        SLP_AVG = SLP_AVG + SLP
                        FLP_AVG = FLP_AVG + FLP
                      END IF
                    END IF
                  END DO

                  positive_input = AVG_GST*SLP_AVG
                  IF (LCFLX) THEN
                    IMPLSCH_SPOS(IJ, SINPUT_K, SINPUT_M, ICHNK) = positive_input
                  ELSE IF (SINPUT_K == 1) THEN
                    SUMX = positive_input*SINTH(SINPUT_K)
                    SUMY = positive_input*COSTH(SINPUT_K)
                  ELSE
                    SUMX = SUMX + positive_input*SINTH(SINPUT_K)
                    SUMY = SUMY + positive_input*COSTH(SINPUT_K)
                  END IF

                  IF (ICALL == NCALL) THEN
                  IMPLSCH_FLD(IJ, SINPUT_K, SINPUT_M, ICHNK) = AVG_GST*FLP_AVG
                  IMPLSCH_SL(IJ, SINPUT_K, SINPUT_M, ICHNK) =  &
                  & IMPLSCH_FLD(IJ, SINPUT_K, SINPUT_M, ICHNK)*VARS_4D%FL1(IJ, SINPUT_K, SINPUT_M, ICHNK)
                  END IF

                END DO

                IF (.not.LCFLX) THEN
                  ! Retain only the stress moments when no flux spectrum is read.
                  IMPLSCH_SPOS(IJ, 1, SINPUT_M, ICHNK) = SUMX
                  IMPLSCH_SPOS(IJ, 2, SINPUT_M, ICHNK) = SUMY
                END IF
                EM_LOC = EM_LOC + DFIM(SINPUT_M)*FEMEANWS_TEMP2
                IMPLSCH_FMEANWS(IJ, ICHNK) = IMPLSCH_FMEANWS(IJ, ICHNK) + DFIMOFR(SINPUT_M)*FEMEANWS_TEMP2
              END DO
              ! END LOOP OVER FREQUENCIES


              ! =========================================
            END SELECT


            ! =========================================


            ! MEAN FREQUENCY CHARACTERISTIC FOR WIND SEA
            ! [Loki] inlined child subroutine: FEMEANWS
            ! =========================================

            ! ----------------------------------------------------------------------


            !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTIONS.
            !        ------------------------------------------

            ! Ardhuin wind input accumulated these sums in its existing
            ! direction/frequency traversal. Other physics use this pass.
            IF (IPHYS /= 1) THEN
!$acc loop seq
            DO FEMEANWS_M=1,NFRE
              FEMEANWS_TEMP2 = 0.0_JWRB
!$acc loop seq
              DO FEMEANWS_K=1,NANG
                FEMEANWS_TEMP2 = FEMEANWS_TEMP2 + VARS_4D%XLLWS(IJ, FEMEANWS_K, FEMEANWS_M, ICHNK)*VARS_4D%FL1(IJ, FEMEANWS_K,  &
                & FEMEANWS_M, ICHNK)
              END DO
              EM_LOC = EM_LOC + DFIM(FEMEANWS_M)*FEMEANWS_TEMP2
              IMPLSCH_FMEANWS(IJ, ICHNK) = IMPLSCH_FMEANWS(IJ, ICHNK) + DFIMOFR(FEMEANWS_M)*FEMEANWS_TEMP2
            END DO
            END IF

            !*    3. ADD TAIL CORRECTION TO MEAN FREQUENCY AND
            !*       NORMALIZE WITH TOTAL ENERGY.
            !        ------------------------------------------

            EM_LOC = EM_LOC + FEMEANWS_DELT25*FEMEANWS_TEMP2
            IMPLSCH_FMEANWS(IJ, ICHNK) = IMPLSCH_FMEANWS(IJ, ICHNK) + FEMEANWS_DELT2*FEMEANWS_TEMP2
            IMPLSCH_FMEANWS(IJ, ICHNK) = EM_LOC / IMPLSCH_FMEANWS(IJ, ICHNK)



            ! =========================================

            ! COMPUTE LAST FREQUENCY INDEX OF PROGNOSTIC PART OF SPECTRUM.
            ! [Loki] inlined child subroutine: FRCUTINDEX
            ! =========================================

            ! ----------------------------------------------------------------------


            !*    COMPUTE LAST FREQUENCY INDEX OF PROGNOSTIC PART OF SPECTRUM.
            !*    FREQUENCIES LE MAX(TAILFACTOR*MAX(FMNWS,FM),TAILFACTOR_PM*FPM),
            !*    WHERE FPM IS THE PIERSON-MOSKOWITZ FREQUENCY BASED ON FRICTION
            !*    VELOCITY. (FPM=G/(FRIC*ZPI*USTAR))
            !     ------------------------------------------------------------

            FPMH = TAILFACTOR / FR(1)
            FPPM = TAILFACTOR_PM*G / (FRIC*ZPIFR(1))

            IF (FF_NOW%CICOVER(IJ, ICHNK) <= CITHRSH_TAIL) THEN
              FM2 = MAX(IMPLSCH_FMEANWS(IJ, ICHNK), IMPLSCH_FMEAN(IJ, ICHNK))*FPMH
              FPM = FPPM / MAX(FF_NOW%UFRIC(IJ, ICHNK), EPSMIN)
              FPM4 = MAX(FM2, FPM)
              cutoff_frequency = NINT(LOG10(FPM4)*FLOGSPRDM1) + 1
              cutoff_frequency = MIN(MAX(1, cutoff_frequency), NFRE)
            ELSE
              cutoff_frequency = NFRE
            END IF

            !     SET RHOWGDFTH
!$acc loop seq
            DO FRCUTINDEX_M=1,cutoff_frequency
              IMPLSCH_RHOWGDFTH(IJ, FRCUTINDEX_M, ICHNK) = RHOWG_DFIM(FRCUTINDEX_M)
            END DO
            IF (cutoff_frequency /= NFRE) IMPLSCH_RHOWGDFTH(IJ, cutoff_frequency, ICHNK) = 0.5_JWRB*IMPLSCH_RHOWGDFTH(IJ,  &
            & cutoff_frequency, ICHNK)
!$acc loop seq
            DO FRCUTINDEX_M=cutoff_frequency + 1,NFRE
              IMPLSCH_RHOWGDFTH(IJ, FRCUTINDEX_M, ICHNK) = 0.0_JWRB
            END DO


            ! =========================================

            ! UPDATE TAUW
            ! [Loki] inlined child subroutine: STRESSO
            ! =========================================

            ! ----------------------------------------------------------------------


            IMPLSCH_PHIWA(IJ, ICHNK) = 0.0_JWRB
            STRESSO_XSTRESS = 0.0_JWRB
            STRESSO_YSTRESS = 0.0_JWRB

            !*    CONTRIBUTION TO THE WAVE STRESS FROM THE NEGATIVE PART OF THE WIND INPUT
            !     ------------------------------------------------------------------------

            IF (LLPHIWA) THEN
              !     full energy flux due to negative Sinput (SL-SPOS)
              !     we assume that above NFRE, the contibutions can be neglected
!$acc loop seq
              DO STRESSO_M=1,NFRE
!$acc loop seq
                DO STRESSO_K=1,NANG
                  IMPLSCH_PHIWA(IJ, ICHNK) = IMPLSCH_PHIWA(IJ, ICHNK) + (IMPLSCH_SL(IJ, STRESSO_K, STRESSO_M, ICHNK) -  &
                  & IMPLSCH_SPOS(IJ, STRESSO_K, STRESSO_M, ICHNK))*RHOWG_DFIM(STRESSO_M)
                END DO
              END DO
            END IF

            !*    CALCULATE LOW-FREQUENCY CONTRIBUTION TO STRESS AND ENERGY FLUX (positive sinput).
            !     ---------------------------------------------------------------------------------
!$acc loop seq
            DO STRESSO_M=1,NFRE
              !     THE INTEGRATION ONLY UP TO FR=MIJ SINCE RHOWGDFTH=0 FOR FR>MIJ
              IF (LCFLX) THEN
              STRESSO_K = 1
              SUMX = IMPLSCH_SPOS(IJ, STRESSO_K, STRESSO_M, ICHNK)*SINTH(STRESSO_K)
              SUMY = IMPLSCH_SPOS(IJ, STRESSO_K, STRESSO_M, ICHNK)*COSTH(STRESSO_K)
              SUMT = IMPLSCH_SPOS(IJ, STRESSO_K, STRESSO_M, ICHNK)
!$acc loop seq
              DO STRESSO_K=2,NANG
                SUMX = SUMX + IMPLSCH_SPOS(IJ, STRESSO_K, STRESSO_M, ICHNK)*SINTH(STRESSO_K)
                SUMY = SUMY + IMPLSCH_SPOS(IJ, STRESSO_K, STRESSO_M, ICHNK)*COSTH(STRESSO_K)
                SUMT = SUMT + IMPLSCH_SPOS(IJ, STRESSO_K, STRESSO_M, ICHNK)
              END DO
              ELSE
                SUMX = IMPLSCH_SPOS(IJ, 1, STRESSO_M, ICHNK)
                SUMY = IMPLSCH_SPOS(IJ, 2, STRESSO_M, ICHNK)
              END IF
              CMRHOWGDFTH = IMPLSCH_RHOWGDFTH(IJ, STRESSO_M, ICHNK)*WVPRPT%CINV(IJ, STRESSO_M, ICHNK)
              STRESSO_XSTRESS = STRESSO_XSTRESS + CMRHOWGDFTH*SUMX
              STRESSO_YSTRESS = STRESSO_YSTRESS + CMRHOWGDFTH*SUMY

              IF (LLPHIWA) THEN
                IMPLSCH_PHIWA(IJ, ICHNK) = IMPLSCH_PHIWA(IJ, ICHNK) + IMPLSCH_RHOWGDFTH(IJ, STRESSO_M, ICHNK)*SUMT
              END IF
            END DO

            !     TAUW is the kinematic wave stress !
            STRESSO_XSTRESS = STRESSO_XSTRESS / MAX(FF_NOW%AIRD(IJ, ICHNK), 1.0_JWRB)
            STRESSO_YSTRESS = STRESSO_YSTRESS / MAX(FF_NOW%AIRD(IJ, ICHNK), 1.0_JWRB)


            !*    CALCULATE HIGH-FREQUENCY CONTRIBUTION TO STRESS and energy flux (positive sinput).
            !     ----------------------------------------------------------------------------------

            IF (IPHYS == 0 .or. TAUWSHELTER == 0.0_JWRB) THEN
              STRESSO_LTAUWSHELTER = .false.
              STRESSO_USDIRP = FF_NOW%WDWAVE(IJ, ICHNK)
              UST = FF_NOW%UFRIC(IJ, ICHNK)
            ELSE
              STRESSO_LTAUWSHELTER = .true.
              STRESSO_TAUX = FF_NOW%UFRIC(IJ, ICHNK)**2*SIN(FF_NOW%WDWAVE(IJ, ICHNK))
              STRESSO_TAUY = FF_NOW%UFRIC(IJ, ICHNK)**2*COS(FF_NOW%WDWAVE(IJ, ICHNK))
              STRESSO_TAUPX = STRESSO_TAUX - TAUWSHELTER*STRESSO_XSTRESS
              STRESSO_TAUPY = STRESSO_TAUY - TAUWSHELTER*STRESSO_YSTRESS
              STRESSO_USDIRP = ATAN2(STRESSO_TAUPX, STRESSO_TAUPY)
              UST = (STRESSO_TAUPX**2 + STRESSO_TAUPY**2)**0.25_JWRB
            END IF

            ! [Loki] inlined child subroutine: TAU_PHI_HF
            ! =========================================


            ! ----------------------------------------------------------------------


            IF (LLGCBZ0) THEN
              ! [Loki] inlined child subroutine: OMEGAGC
              ! =========================================
              ! ----------------------------------------------------------------------


              ! [Loki] inlined child subroutine: NS_GC_LOKI
              ! =========================================

              ! ----------------------------------------------------------------------


              !!!Y = 1.0_JWRB/(1.48_JWRB+2.05_JWRB*UST)
              !!!Y = (1.0_JWRB + UST**2)/(1.0_JWRB+10.0_JWRB*UST**2)

              NS_GC_LOKI_NS_GC_XKS = SQRTGOSURFT / (1.48_JWRB + 2.05_JWRB*FF_NOW%UFRIC(IJ, ICHNK))

              result_ns_gc = MIN(INT(LOG(MAX(NS_GC_LOKI_NS_GC_XKS*XKM_GC(1), 1.0_JWRB))*XLOGKRATIOM1_GC) + 1, NWAV_GC - 1)


              ! =========================================
              NS = result_ns_gc
              XKS = XK_GC(NS)
              OMS = OMEGA_GC(NS)


              ! =========================================
            END IF

            !     See INIT_X0TAUHF
            X0G = X0TAUHF*G

            IF (LLPHIWA) USTPH = UST

            !*    COMPUTE THE INTEGRALS
            !     ---------------------

            XLOGGZ0 = LOG(G*FF_NOW%Z0M(IJ, ICHNK))
            OMEGACC = MAX(ZPIFR(cutoff_frequency), X0G / UST)
            SQRTZ0OG = SQRT(FF_NOW%Z0M(IJ, ICHNK)*GM1)
            SQRTGZ0 = 1.0_JWRB / SQRTZ0OG
            YC = OMEGACC*SQRTZ0OG
            ZINF = LOG(YC)

            CONSTTAU = ZPI4GM2*FR5(cutoff_frequency)

            TAU_PHI_HF_K = 1
            TAU_PHI_HF_COSW = MAX(IMPLSCH_COSWDIF(IJ, TAU_PHI_HF_K, ICHNK), 0.0_JWRB)
            TAU_PHI_HF_FCOSW2 = VARS_4D%FL1(IJ, TAU_PHI_HF_K, cutoff_frequency, ICHNK)*TAU_PHI_HF_COSW**2
            F1DCOS3 = TAU_PHI_HF_FCOSW2*TAU_PHI_HF_COSW
            F1DCOS2 = TAU_PHI_HF_FCOSW2
            F1DSIN2 = VARS_4D%FL1(IJ, TAU_PHI_HF_K, cutoff_frequency, ICHNK)*IMPLSCH_SINWDIF2(IJ, TAU_PHI_HF_K, ICHNK)
            STRESSO_F1D = VARS_4D%FL1(IJ, TAU_PHI_HF_K, cutoff_frequency, ICHNK)
!$acc loop seq
            DO TAU_PHI_HF_K=2,NANG
              TAU_PHI_HF_COSW = MAX(IMPLSCH_COSWDIF(IJ, TAU_PHI_HF_K, ICHNK), 0.0_JWRB)
              TAU_PHI_HF_FCOSW2 = VARS_4D%FL1(IJ, TAU_PHI_HF_K, cutoff_frequency, ICHNK)*TAU_PHI_HF_COSW**2
              F1DCOS3 = F1DCOS3 + TAU_PHI_HF_FCOSW2*TAU_PHI_HF_COSW
              F1DCOS2 = F1DCOS2 + TAU_PHI_HF_FCOSW2
              F1DSIN2 =  &
              & F1DSIN2 + VARS_4D%FL1(IJ, TAU_PHI_HF_K, cutoff_frequency, ICHNK)*IMPLSCH_SINWDIF2(IJ, TAU_PHI_HF_K, ICHNK)
              STRESSO_F1D = STRESSO_F1D + VARS_4D%FL1(IJ, TAU_PHI_HF_K, cutoff_frequency, ICHNK)
            END DO
            F1DCOS3 = DELTH*F1DCOS3
            F1DCOS2 = DELTH*F1DCOS2
            F1DSIN2 = DELTH*F1DSIN2
            STRESSO_F1D = DELTH*STRESSO_F1D

            IF (LLNORMAGAM) THEN
              CONFG = GAMNCONST*FR5(cutoff_frequency)*RNFAC*SQRTGZ0
              STRESSO_CONST1 = CONFG*F1DSIN2
              CONST2 = CONFG*STRESSO_F1D
            ELSE
              STRESSO_CONST1 = 0.0_JWRB
              CONST2 = 0.0_JWRB
            END IF


            !     TAUHF :
            IF (LLGCBZ0) THEN
              ZSUP = MIN(LOG(OMS*SQRTZ0OG), ZSUPMAX)
            ELSE
              ZSUP = ZSUPMAX
            END IF

            TAUL = UST**2
            DELZ = MAX((ZSUP - ZINF) / REAL(JTOT_TAUHF - 1, kind=JWRB), 0.0_JWRB)
            TAUHF = 0.0_JWRB

            ! Intergrals are integrated following a change of variable : Z=LOG(Y)
            IF (STRESSO_LTAUWSHELTER) THEN
!$acc loop seq
              DO TAU_PHI_HF_J=1,JTOT_TAUHF
                Y = EXP(ZINF + REAL(TAU_PHI_HF_J - 1, kind=JWRB)*DELZ)
                OMEGA = Y*SQRTGZ0
                CM1 = OMEGA*GM1
                ZX = UST*CM1 + ZALP
                ZARG = XKAPPA / ZX
                STRESSO_ZLOG = XLOGGZ0 + 2.0_JWRB*LOG(CM1) + ZARG
                STRESSO_ZLOG = MIN(STRESSO_ZLOG, 0.0_JWRB)
                ZBETA = STRESSO_ZLOG**4*EXP(STRESSO_ZLOG)
                STRESSO_ZNZ = ZBETA*UST*Y
                STRESSO_GAMNORMA = (1.0_JWRB + STRESSO_CONST1*STRESSO_ZNZ) / (1.0_JWRB + CONST2*STRESSO_ZNZ)
                FNC2 = F1DCOS3*CONSTTAU*ZBETA*TAUL*WTAUHF(TAU_PHI_HF_J)*DELZ*STRESSO_GAMNORMA
                TAUL = MAX(TAUL - TAUWSHELTER*FNC2, 0.0_JWRB)

                UST = SQRT(TAUL)
                TAUHF = TAUHF + FNC2
              END DO
            ELSE
!$acc loop seq
              DO TAU_PHI_HF_J=1,JTOT_TAUHF
                Y = EXP(ZINF + REAL(TAU_PHI_HF_J - 1, kind=JWRB)*DELZ)
                OMEGA = Y*SQRTGZ0
                CM1 = OMEGA*GM1
                ZX = UST*CM1 + ZALP
                ZARG = XKAPPA / ZX
                STRESSO_ZLOG = XLOGGZ0 + 2.0_JWRB*LOG(CM1) + ZARG
                STRESSO_ZLOG = MIN(STRESSO_ZLOG, 0.0_JWRB)
                ZBETA = STRESSO_ZLOG**4*EXP(STRESSO_ZLOG)
                FNC2 = ZBETA*WTAUHF(TAU_PHI_HF_J)
                STRESSO_ZNZ = ZBETA*UST*Y
                STRESSO_GAMNORMA = (1.0_JWRB + STRESSO_CONST1*STRESSO_ZNZ) / (1.0_JWRB + CONST2*STRESSO_ZNZ)
                TAUHF = TAUHF + FNC2*STRESSO_GAMNORMA
              END DO
              TAUHF = F1DCOS3*CONSTTAU*TAUL*TAUHF*DELZ
            END IF


            PHIHF = 0.0_JWRB
            IF (LLPHIWA) THEN
              !       PHIHF:
              !       We are neglecting the gravity-capillary contribution
              !       Recompute DELZ over the full interval
              TAUL = USTPH**2
              ZSUP = ZSUPMAX
              DELZ = MAX((ZSUP - ZINF) / REAL(JTOT_TAUHF - 1, kind=JWRB), 0.0_JWRB)

              CONSTPHI = FF_NOW%AIRD(IJ, ICHNK)*ZPI4GM1*FR5(cutoff_frequency)

              ! Intergrals are integrated following a change of variable : Z=LOG(Y)
              IF (STRESSO_LTAUWSHELTER) THEN
!$acc loop seq
                DO TAU_PHI_HF_J=1,JTOT_TAUHF
                  Y = EXP(ZINF + REAL(TAU_PHI_HF_J - 1, kind=JWRB)*DELZ)
                  OMEGA = Y*SQRTGZ0
                  CM1 = OMEGA*GM1
                  ZX = USTPH*CM1 + ZALP
                  ZARG = XKAPPA / ZX
                  STRESSO_ZLOG = XLOGGZ0 + 2.0_JWRB*LOG(CM1) + ZARG
                  STRESSO_ZLOG = MIN(STRESSO_ZLOG, 0.0_JWRB)
                  ZBETA = STRESSO_ZLOG**4*EXP(STRESSO_ZLOG)
                  STRESSO_ZNZ = ZBETA*UST*Y
                  STRESSO_GAMNORMA = (1.0_JWRB + STRESSO_CONST1*STRESSO_ZNZ) / (1.0_JWRB + CONST2*STRESSO_ZNZ)
                  FNC2 = ZBETA*TAUL*WTAUHF(TAU_PHI_HF_J)*DELZ*STRESSO_GAMNORMA
                  TAUL = MAX(TAUL - TAUWSHELTER*F1DCOS3*CONSTTAU*FNC2, 0.0_JWRB)
                  USTPH = SQRT(TAUL)
                  PHIHF = PHIHF + FNC2 / Y
                END DO
                PHIHF = F1DCOS2*CONSTPHI*SQRTZ0OG*PHIHF
              ELSE
!$acc loop seq
                DO TAU_PHI_HF_J=1,JTOT_TAUHF
                  Y = EXP(ZINF + REAL(TAU_PHI_HF_J - 1, kind=JWRB)*DELZ)
                  OMEGA = Y*SQRTGZ0
                  CM1 = OMEGA*GM1
                  ZX = USTPH*CM1 + ZALP
                  ZARG = XKAPPA / ZX
                  STRESSO_ZLOG = XLOGGZ0 + 2.0_JWRB*LOG(CM1) + ZARG
                  STRESSO_ZLOG = MIN(STRESSO_ZLOG, 0.0_JWRB)
                  ZBETA = STRESSO_ZLOG**4*EXP(STRESSO_ZLOG)
                  STRESSO_ZNZ = ZBETA*UST*Y
                  STRESSO_GAMNORMA = (1.0_JWRB + STRESSO_CONST1*STRESSO_ZNZ) / (1.0_JWRB + CONST2*STRESSO_ZNZ)
                  FNC2 = ZBETA*WTAUHF(TAU_PHI_HF_J)*STRESSO_GAMNORMA
                  PHIHF = PHIHF + FNC2 / Y
                END DO
                PHIHF = F1DCOS2*CONSTPHI*SQRTZ0OG*TAUL*PHIHF*DELZ
              END IF
            END IF


            ! =========================================

            STRESSO_XSTRESS = STRESSO_XSTRESS + TAUHF*SIN(STRESSO_USDIRP)
            STRESSO_YSTRESS = STRESSO_YSTRESS + TAUHF*COS(STRESSO_USDIRP)
            FF_NOW%TAUW(IJ, ICHNK) = SQRT(STRESSO_XSTRESS**2 + STRESSO_YSTRESS**2)
            FF_NOW%TAUW(IJ, ICHNK) = MAX(FF_NOW%TAUW(IJ, ICHNK), 0.0_JWRB)
            FF_NOW%TAUWDIR(IJ, ICHNK) = ATAN2(STRESSO_XSTRESS, STRESSO_YSTRESS)

            IF (.not.LLGCBZ0) THEN
              TAUTOUS2 = 1.0_JWRB / (1.0_JWRB + EPS1)
              FF_NOW%TAUW(IJ, ICHNK) = MIN(FF_NOW%TAUW(IJ, ICHNK), FF_NOW%UFRIC(IJ, ICHNK)**2*TAUTOUS2)
            END IF

            IF (LLPHIWA) THEN
              IMPLSCH_PHIWA(IJ, ICHNK) = IMPLSCH_PHIWA(IJ, ICHNK) + PHIHF
            END IF


            ! =========================================

            ! ----------------------------------------------------------------------


            ! =========================================

          END DO
          MIJ%PTR(IJ, ICHNK) = cutoff_frequency

        END DO
      END DO
!$acc end parallel loop

      ! Whitecap dissipation uses the wind state produced by the preceding
      ! launch, without retaining its gust work arrays or register footprint.
      ! Without cumulative breaking or flux output, frequencies are independent.
      IF (IPHYS == 1 .and. SSDSC3 == 0.0_JWRB .and. SSDSC5 == 0.0_JWRB .and. &
        NSDSNTH == 5 .and. NANG <= SIZE(directional_saturation) .and. &
        .not.(LWFLUX .or. (LWFLUXOUT .and. .not.LHEIGHT_ONLY) .or. LWNEMOCOU)) THEN
#ifdef WAM_HAVE_SINGLE_PRECISION
!$acc parallel loop gang collapse(2) vector_length(128) default(present) minctapersm(10) async(1)
#else
!$acc parallel loop gang collapse(2) vector_length(64) default(present) minctapersm(20) async(1)
#endif
        DO ICHNK=1,NCHNK
          DO SDISSIP_M=1,NFRE
!$acc loop vector private(directional_saturation)
            DO IJ=1,NPROMA_WAM
              TPIINV = 1.0_JWRB / ZPI
              TMP03 = 1.0_JWRB / (SDSBR*MICHE)
              SSDSC6M1 = 1._JWRB - SSDSC6
              saturation_factor = WVPRPT%WAVNUM(IJ, SDISSIP_M, ICHNK)*TPIINV*WVPRPT%XK2CG(IJ, SDISSIP_M, ICHNK)
              maximum_saturation = 0.0_JWRB
!$acc loop seq
              DO SDISSIP_K=1,NANG
                sector_energy = 0.0_JWRB
              sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 1)* &
                VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 1), SDISSIP_M, ICHNK)
              sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 2)* &
                VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 2), SDISSIP_M, ICHNK)
              sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 3)* &
                VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 3), SDISSIP_M, ICHNK)
              sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 4)* &
                VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 4), SDISSIP_M, ICHNK)
              sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 5)* &
                VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 5), SDISSIP_M, ICHNK)
              sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 6)* &
                VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 6), SDISSIP_M, ICHNK)
              sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 7)* &
                VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 7), SDISSIP_M, ICHNK)
              sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 8)* &
                VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 8), SDISSIP_M, ICHNK)
              sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 9)* &
                VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 9), SDISSIP_M, ICHNK)
              sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 10)* &
                VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 10), SDISSIP_M, ICHNK)
              sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 11)* &
                VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 11), SDISSIP_M, ICHNK)
                saturation_value = sector_energy*saturation_factor
                directional_saturation(SDISSIP_K) = saturation_value
                maximum_saturation = MAX(maximum_saturation, saturation_value)
              END DO
              SSDSC2_SIG = SSDSC2*ZPIFR(SDISSIP_M)
              ZCOEF = SSDSC2_SIG*SSDSC6
              ZCOEFM1 = SSDSC2_SIG*SSDSC6M1
!$acc loop seq
              DO SDISSIP_K=1,NANG
                dissipation_rate = ZCOEF*MAX(0._JWRB, maximum_saturation*TMP03 - SSDSC4)**IPSAT + &
                  ZCOEFM1*MAX(0._JWRB, directional_saturation(SDISSIP_K)*TMP03 - SSDSC4)**IPSAT
                IMPLSCH_SL(IJ, SDISSIP_K, SDISSIP_M, ICHNK) = IMPLSCH_SL(IJ, SDISSIP_K, SDISSIP_M, ICHNK) + &
                  dissipation_rate*VARS_4D%FL1(IJ, SDISSIP_K, SDISSIP_M, ICHNK)
                IMPLSCH_FLD(IJ, SDISSIP_K, SDISSIP_M, ICHNK) = IMPLSCH_FLD(IJ, SDISSIP_K, SDISSIP_M, ICHNK) + dissipation_rate
              END DO
            END DO
          END DO
        END DO
!$acc end parallel loop
      ELSE
#ifdef WAM_HAVE_SINGLE_PRECISION
!$acc parallel loop gang vector_length( 128 ) default( present ) minctapersm( 10 ) async(1)
#else
!$acc parallel loop gang vector_length( 64 ) default( present ) minctapersm( 20 ) async(1)
#endif
      DO ICHNK=1,NCHNK
!$acc loop vector private(directional_saturation)
        DO IJ=1,NPROMA_WAM
          LCFLX = LWFLUX .or. (LWFLUXOUT .and. .not.LHEIGHT_ONLY) .or. LWNEMOCOU
          RAORW = MAX(FF_NOW%AIRD(IJ, ICHNK), 1.0_JWRB)*ROWATERM1

          !     2.3.3 ADD THE OTHER SOURCE TERMS.
          !           ---------------------------

          ! [Loki] inlined child subroutine: SDISSIP
          ! =========================================

          ! ----------------------------------------------------------------------


          SELECT CASE (IPHYS)
          CASE (0)
            ! [Loki] Removed content of pragma-marked region!
          CASE (1)
            ! [Loki] inlined child subroutine: SDISSIP_ARD
            ! =========================================

            ! ----------------------------------------------------------------------


            ! INITIALISATION

            EPSR = SQRT(SDSBR)

            TPIINV = 1.0_JWRB / ZPI
            TPIINVH = 0.5_JWRB*TPIINV


            TMP03 = 1.0_JWRB / (SDSBR*MICHE)

            SSDSC6M1 = 1._JWRB - SSDSC6

!$acc loop seq
            DO SDISSIP_M=1,NFRE
              saturation_factor = WVPRPT%WAVNUM(IJ, SDISSIP_M, ICHNK)*TPIINV*WVPRPT%XK2CG(IJ, SDISSIP_M, ICHNK)

              ! Accumulate the directional sector locally, retaining the arrays
              ! needed by the subsequent cumulative dissipation calculation.
              maximum_saturation = 0.0_JWRB
!$acc loop seq
              DO SDISSIP_K=1,NANG
                sector_energy = 0.0_JWRB
                ! integrates in directional sector
                IF (NSDSNTH == 5) THEN
                  ! Expose the common eleven-term sector without reassociation.
                  sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 1)* &
                    VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 1), SDISSIP_M, ICHNK)
                  sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 2)* &
                    VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 2), SDISSIP_M, ICHNK)
                  sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 3)* &
                    VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 3), SDISSIP_M, ICHNK)
                  sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 4)* &
                    VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 4), SDISSIP_M, ICHNK)
                  sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 5)* &
                    VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 5), SDISSIP_M, ICHNK)
                  sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 6)* &
                    VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 6), SDISSIP_M, ICHNK)
                  sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 7)* &
                    VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 7), SDISSIP_M, ICHNK)
                  sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 8)* &
                    VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 8), SDISSIP_M, ICHNK)
                  sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 9)* &
                    VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 9), SDISSIP_M, ICHNK)
                  sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 10)* &
                    VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 10), SDISSIP_M, ICHNK)
                  sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, 11)* &
                    VARS_4D%FL1(IJ, INDICESSAT(SDISSIP_K, 11), SDISSIP_M, ICHNK)
                ELSE
!$acc loop seq
                DO K2=1,NSDSNTH*2 + 1
                  KK = INDICESSAT(SDISSIP_K, K2)
                  sector_energy = sector_energy + SATWEIGHTS(SDISSIP_K, K2)*VARS_4D%FL1(IJ, KK, SDISSIP_M, ICHNK)
                END DO
                END IF
                saturation_value = sector_energy*saturation_factor
                IF (NANG <= SIZE(directional_saturation)) directional_saturation(SDISSIP_K) = saturation_value
                IF (SSDSC3 /= 0.0_JWRB .or. NANG > SIZE(directional_saturation)) &
                  IMPLSCH_BTH(IJ, SDISSIP_K, SDISSIP_M, ICHNK) = saturation_value
                maximum_saturation = MAX(maximum_saturation, saturation_value)
              END DO
              IF (SSDSC3 /= 0.0_JWRB) IMPLSCH_BTH0(IJ, SDISSIP_M, ICHNK) = maximum_saturation

              ! SATURATION TERM
              SSDSC2_SIG = SSDSC2*ZPIFR(SDISSIP_M)
              ZCOEF = SSDSC2_SIG*SSDSC6
              ZCOEFM1 = SSDSC2_SIG*SSDSC6M1
!$acc loop seq
              DO SDISSIP_K=1,NANG
                IF (NANG <= SIZE(directional_saturation)) THEN
                  saturation_value = directional_saturation(SDISSIP_K)
                ELSE
                  saturation_value = IMPLSCH_BTH(IJ, SDISSIP_K, SDISSIP_M, ICHNK)
                END IF
                dissipation_rate = ZCOEF*MAX(0._JWRB, maximum_saturation*TMP03 - SSDSC4)**IPSAT +  &
                & ZCOEFM1*MAX(0._JWRB, saturation_value*TMP03 - SSDSC4)**IPSAT
                IF (SSDSC3 == 0.0_JWRB .and. SSDSC5 == 0.0_JWRB) THEN
                  IMPLSCH_SL(IJ, SDISSIP_K, SDISSIP_M, ICHNK) = IMPLSCH_SL(IJ, SDISSIP_K, SDISSIP_M, ICHNK) + &
                    dissipation_rate*VARS_4D%FL1(IJ, SDISSIP_K, SDISSIP_M, ICHNK)
                  IMPLSCH_FLD(IJ, SDISSIP_K, SDISSIP_M, ICHNK) = IMPLSCH_FLD(IJ, SDISSIP_K, SDISSIP_M, ICHNK) + dissipation_rate
                ELSE
                  IMPLSCH_D(IJ, SDISSIP_K, SDISSIP_M, ICHNK) = dissipation_rate
                END IF
              END DO
            END DO


            ! CUMULATIVE TERM
            IF (SSDSC3 /= 0.0_JWRB) THEN

              NANGD = NANG / 2
              XLOGDFRTH = LOG(FRATIO)*DELTH
              !       l(k,th)=1/(2*pi²)= the breaking crest density
              BRLAMBDA = BRKPBCOEF / (2.0_JWRB*ZPI**2)
              TMP02 = SSDSC3*BRLAMBDA

              !       NDIKCUMUL is the  integer difference in frequency bands
              !       between the "large breakers" and short "wiped-out waves"
              !!! wrong !!???        NDIKCUMUL = NINT(SSDSBRF1/(FRATIO-1.))
              NDIKCUMUL = NINT(-LOG(SSDSBRF1) / LOG(FRATIO))

!$acc loop seq
              DO SDISSIP_M=1,NFRE
                IMPLSCH_C_(IJ, SDISSIP_M, ICHNK) = ZPIFR(SDISSIP_M) / WVPRPT%WAVNUM(IJ, SDISSIP_M, ICHNK)
                IMPLSCH_C_C(IJ, SDISSIP_M, ICHNK) = IMPLSCH_C_(IJ, SDISSIP_M, ICHNK)**2
                IMPLSCH_DSIP(IJ, SDISSIP_M, ICHNK) = TMP02*ZPIFR(SDISSIP_M)*XLOGDFRTH / WVPRPT%CGROUP(IJ, SDISSIP_M, ICHNK)                  !  coef*dtheta*dk = coef*dtheta*dsigma/cg
              END DO

!$acc loop seq
              DO M2=1,NFRE - NDIKCUMUL
                IF (IMPLSCH_BTH0(IJ, M2, ICHNK) > SDSBR) THEN
                  IMPLSCH_SDISSIP_TEMP1(IJ, M2, ICHNK) = 1.0_JWRB
                ELSE
                  IMPLSCH_SDISSIP_TEMP1(IJ, M2, ICHNK) = 0.0_JWRB
                END IF
              END DO
!$acc loop seq
              DO M2=1,NFRE - NDIKCUMUL
!$acc loop seq
                DO K2=1,NANG
                  IMPLSCH_SCUMUL(IJ, K2, M2, ICHNK) =  &
                  & IMPLSCH_SDISSIP_TEMP1(IJ, M2, ICHNK)*MAX(SQRT(IMPLSCH_BTH(IJ, K2, M2, ICHNK)) - EPSR, 0.0_JWRB)**2
                END DO
              END DO

!$acc loop seq
              DO SDISSIP_M=NDIKCUMUL + 1,NFRE
!$acc loop seq
                DO SDISSIP_K=1,NANG
                  IMPLSCH_RENEWALFREQ(IJ, SDISSIP_K, SDISSIP_M, ICHNK) = 0.0_JWRB
                END DO
              END DO


!$acc loop seq
              DO SDISSIP_M=NDIKCUMUL + 1,NFRE

                IF (SDISSIP_M - NDIKCUMUL >= 3) THEN
                  IMPLSCH_TRPZ_DSIP(IJ, 1, ICHNK) = 0.5_JWRB*IMPLSCH_DSIP(IJ, 1, ICHNK)
!$acc loop seq
                  DO M2=2,SDISSIP_M - NDIKCUMUL - 1
                    IMPLSCH_TRPZ_DSIP(IJ, M2, ICHNK) = IMPLSCH_DSIP(IJ, M2, ICHNK)
                  END DO
                  IMPLSCH_TRPZ_DSIP(IJ, SDISSIP_M - NDIKCUMUL, ICHNK) = 0.5_JWRB*IMPLSCH_DSIP(IJ, SDISSIP_M - NDIKCUMUL, ICHNK)
                ELSE
!$acc loop seq
                  DO M2=1,SDISSIP_M - NDIKCUMUL
                    IMPLSCH_TRPZ_DSIP(IJ, M2, ICHNK) = IMPLSCH_DSIP(IJ, M2, ICHNK)
                  END DO
                END IF

!$acc loop seq
                DO M2=1,SDISSIP_M - NDIKCUMUL
!$acc loop seq
                  DO KK=0,NANGD
                    IMPLSCH_WCUMUL(IJ, KK, M2, ICHNK) = SQRT(ABS(IMPLSCH_C_C(IJ, SDISSIP_M, ICHNK) + IMPLSCH_C_C(IJ, M2, ICHNK) - &
                    &  2.0_JWRB*IMPLSCH_C_(IJ, SDISSIP_M, ICHNK)*IMPLSCH_C_(IJ, M2, ICHNK)*COS(KK*DELTH)))*IMPLSCH_TRPZ_DSIP(IJ,  &
                    & M2, ICHNK)
                  END DO
                END DO

!$acc loop seq
                DO SDISSIP_K=1,NANG
                  ! Correction of saturation level for shallow-water kinematics
                  ! Cumulative effect based on lambda   (breaking probability is
                  ! the expected rate of sweeping by larger breaking waves)

!$acc loop seq
                  DO K2=1,NANG
                  END DO

!$acc loop seq
                  DO M2=1,SDISSIP_M - NDIKCUMUL
!$acc loop seq
                    DO K2=1,NANG
                      KK = ABS(K2 - SDISSIP_K)
                      IF (KK > NANGD) KK = KK - NANGD
                      ! Integrates over frequencies M2 and directions K2 to
                      ! Integration is performed from M2=1 to a frequency lower than M: IK-NDIKCUMUL
                      IMPLSCH_RENEWALFREQ(IJ, SDISSIP_K, SDISSIP_M, ICHNK) = IMPLSCH_RENEWALFREQ(IJ, SDISSIP_K, SDISSIP_M, ICHNK) &
                      &  + IMPLSCH_WCUMUL(IJ, KK, M2, ICHNK)*IMPLSCH_SCUMUL(IJ, K2, M2, ICHNK)
                    END DO
                  END DO
                END DO
              END DO

!$acc loop seq
              DO SDISSIP_M=NDIKCUMUL + 1,NFRE
!$acc loop seq
                DO SDISSIP_K=1,NANG
                  IMPLSCH_D(IJ, SDISSIP_K, SDISSIP_M, ICHNK) =  &
                  & IMPLSCH_D(IJ, SDISSIP_K, SDISSIP_M, ICHNK) + IMPLSCH_RENEWALFREQ(IJ, SDISSIP_K, SDISSIP_M, ICHNK)
                END DO
              END DO
            END IF


            !     WAVE-TURBULENCE INTERACTION TERM
            IF (SSDSC5 /= 0.0_JWRB) THEN
              TMP01 = 2._JWRB*SSDSC5 / G
              FACTURB = TMP01*RAORW*FF_NOW%UFRIC(IJ, ICHNK)*FF_NOW%UFRIC(IJ, ICHNK)
!$acc loop seq
              DO SDISSIP_M=1,NFRE
                IMPLSCH_FACWTRB(IJ, SDISSIP_M, ICHNK) = ZPIFR(SDISSIP_M)*WVPRPT%WAVNUM(IJ, SDISSIP_M, ICHNK)*FACTURB
!$acc loop seq
                DO SDISSIP_K=1,NANG
                  IMPLSCH_D(IJ, SDISSIP_K, SDISSIP_M, ICHNK) = IMPLSCH_D(IJ, SDISSIP_K, SDISSIP_M, ICHNK) - IMPLSCH_FACWTRB(IJ,  &
                  & SDISSIP_M, ICHNK)*IMPLSCH_COSWDIF(IJ, SDISSIP_K, ICHNK)
                END DO
              END DO
            END IF


            ! ADD ALL CONTRIBUTIONS TO SOURCE TERM
            IF (SSDSC3 /= 0.0_JWRB .or. SSDSC5 /= 0.0_JWRB) THEN
!$acc loop seq
            DO SDISSIP_M=1,NFRE
!$acc loop seq
              DO SDISSIP_K=1,NANG
                IMPLSCH_SL(IJ, SDISSIP_K, SDISSIP_M, ICHNK) = IMPLSCH_SL(IJ, SDISSIP_K, SDISSIP_M, ICHNK) + IMPLSCH_D(IJ,  &
                & SDISSIP_K, SDISSIP_M, ICHNK)*VARS_4D%FL1(IJ, SDISSIP_K, SDISSIP_M, ICHNK)
                IMPLSCH_FLD(IJ, SDISSIP_K, SDISSIP_M, ICHNK) =  &
                & IMPLSCH_FLD(IJ, SDISSIP_K, SDISSIP_M, ICHNK) + IMPLSCH_D(IJ, SDISSIP_K, SDISSIP_M, ICHNK)
              END DO
            END DO
            END IF


            ! =========================================
          END SELECT


          ! =========================================

          !     Save source term contributions relevant for the calculation of ocean fluxes
          IF (LCFLX .and. .not.LWVFLX_SNL) THEN
!$acc loop seq
            DO IMPLSCH_LOKI_M=1,NFRE
!$acc loop seq
              DO IMPLSCH_LOKI_K=1,NANG
                IMPLSCH_SSOURCE(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) =  &
                & IMPLSCH_SL(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK)
              END DO
            END DO
          END IF

          ! [Loki] inlined child subroutine: SNONLIN_LOKI
          ! =========================================

        END DO
      END DO
!$acc end parallel loop

      END IF
      ! Construct nonlinear depth factors independently from dissipation.
!$acc parallel loop gang vector_length( 64 ) default( present ) minctapersm( 6 ) async(1)
      DO ICHNK=1,NCHNK
!$acc loop vector
        DO IJ=1,NPROMA_WAM

          ! ----------------------------------------------------------------------



          !*    1. SHALLOW WATER SCALING
          !        ---------------------

          SELECT CASE (ISNONLIN)
          CASE (0)
            SNONLIN_ENHFR = MAX(0.75_JWRB*WVENVI%DEPTH(IJ, ICHNK)*IMPLSCH_AKMEAN(IJ, ICHNK), 0.5_JWRB)
            SNONLIN_ENHFR =  &
            & 1.0_JWRB + (5.5_JWRB / SNONLIN_ENHFR)*(1.0_JWRB - .833_JWRB*SNONLIN_ENHFR)*EXP(-1.25_JWRB*SNONLIN_ENHFR)
!$acc loop seq
            DO SNONLIN_MC=1,MLSTHG
              SNONLIN_ENH(IJ, SNONLIN_MC, ICHNK) = SNONLIN_ENHFR
            END DO

          CASE (1)
!$acc loop seq
            DO SNONLIN_MC=1,NFRE
              SNONLIN_ENH(IJ, SNONLIN_MC, ICHNK) = MAX(MIN(SNONLIN_ENH_MAX, TRANSF_LOKI(WVPRPT%WAVNUM(IJ, SNONLIN_MC, ICHNK),  &
              & WVENVI%DEPTH(IJ, ICHNK))), SNONLIN_ENH_MIN)
            END DO
!$acc loop seq
            DO SNONLIN_MC=NFRE + 1,MLSTHG
              SNONLIN_XK = GM1*(ZPIFR(NFRE)*FRATIO**(SNONLIN_MC - NFRE))**2
              SNONLIN_ENH(IJ, SNONLIN_MC, ICHNK) =  &
              & MAX(MIN(SNONLIN_ENH_MAX, TRANSF_LOKI(SNONLIN_XK, WVENVI%DEPTH(IJ, ICHNK))), SNONLIN_ENH_MIN)
            END DO

          CASE (2)
            ! [Loki] inlined child subroutine: PEAK_ANG
            ! =========================================

            ! ----------------------------------------------------------------------

            !***  1. DETERMINE L-H SPECTRAL WIDTH OF THE 2-D SPECTRUM.
            !     ---------------------------------------------------

            SNONLIN_ZEPSILON = 10._JWRB*EPSILON(SNONLIN_ZEPSILON)

            SNONLIN_NSH = 1 + INT(LOG(1.5_JWRB) / LOG(FRATIO))

            SNONLIN_SUM0 = SNONLIN_ZEPSILON
            SNONLIN_SUM1 = 0._JWRB
            SNONLIN_SUM2 = 0._JWRB

!$acc loop seq
            DO SNONLIN_PEAK_ANG_M=1,NFRE
              SNONLIN_PEAK_ANG_K = 1
              SNONLIN_TEMP = VARS_4D%FL1(IJ, SNONLIN_PEAK_ANG_K, SNONLIN_PEAK_ANG_M, ICHNK)
!$acc loop seq
              DO SNONLIN_PEAK_ANG_K=2,NANG
                SNONLIN_TEMP = SNONLIN_TEMP + VARS_4D%FL1(IJ, SNONLIN_PEAK_ANG_K, SNONLIN_PEAK_ANG_M, ICHNK)
              END DO
              SNONLIN_SUM0 = SNONLIN_SUM0 + SNONLIN_TEMP*DFIM(SNONLIN_PEAK_ANG_M)
              SNONLIN_SUM1 = SNONLIN_SUM1 + SNONLIN_TEMP*DFIMFR(SNONLIN_PEAK_ANG_M)
              SNONLIN_SUM2 = SNONLIN_SUM2 + SNONLIN_TEMP*DFIMFR2(SNONLIN_PEAK_ANG_M)
            END DO

            !     ADD TAIL CORRECTIONS
            SNONLIN_DELT25 = WETAIL*FR(NFRE)*DELTH
            SNONLIN_COEF_FR = WP1TAIL*DELTH*FR(NFRE)**2
            SNONLIN_COEF_FR2 = WP2TAIL*DELTH*FR(NFRE)**3
            SNONLIN_SUM0 = SNONLIN_SUM0 + SNONLIN_DELT25*SNONLIN_TEMP
            SNONLIN_SUM1 = SNONLIN_SUM1 + SNONLIN_COEF_FR*SNONLIN_TEMP
            SNONLIN_SUM2 = SNONLIN_SUM2 + SNONLIN_COEF_FR2*SNONLIN_TEMP

            IF (SNONLIN_SUM0 > SNONLIN_ZEPSILON) THEN
