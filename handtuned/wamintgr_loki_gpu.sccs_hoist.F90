                  SNONLIN_K11 = K11W(SNONLIN_K, SNONLIN_KH)
                  SNONLIN_K21 = K21W(SNONLIN_K, SNONLIN_KH)

                  SNONLIN_SAP = SNONLIN_GW1*VARS_4D%FL1(IJ, SNONLIN_K1, SNONLIN_IP, ICHNK) + SNONLIN_GW2*VARS_4D%FL1(IJ,  &
                  & SNONLIN_K11, SNONLIN_IP, ICHNK) + SNONLIN_GW3*VARS_4D%FL1(IJ, SNONLIN_K1, SNONLIN_IP1, ICHNK) +  &
                  & SNONLIN_GW4*VARS_4D%FL1(IJ, SNONLIN_K11, SNONLIN_IP1, ICHNK)
                  SNONLIN_SAM = SNONLIN_GW5*VARS_4D%FL1(IJ, SNONLIN_K2, SNONLIN_IM, ICHNK) + SNONLIN_GW6*VARS_4D%FL1(IJ,  &
                  & SNONLIN_K21, SNONLIN_IM, ICHNK) + SNONLIN_GW7*VARS_4D%FL1(IJ, SNONLIN_K2, SNONLIN_IM1, ICHNK) +  &
                  & SNONLIN_GW8*VARS_4D%FL1(IJ, SNONLIN_K21, SNONLIN_IM1, ICHNK)
                  SNONLIN_FIJ = VARS_4D%FL1(IJ, SNONLIN_K, SNONLIN_IC, ICHNK)*SNONLIN_FTAIL
                  SNONLIN_FAD1 = SNONLIN_FIJ*(SNONLIN_SAP + SNONLIN_SAM)
                  SNONLIN_FAD2 = SNONLIN_FAD1 - 2.0_JWRB*SNONLIN_SAP*SNONLIN_SAM
                  SNONLIN_FAD1 = SNONLIN_FAD1 + SNONLIN_FAD2
                  SNONLIN_FCEN = SNONLIN_FTEMP*SNONLIN_FIJ
                  SNONLIN_AD = SNONLIN_FAD2*SNONLIN_FCEN
                  SNONLIN_DELAD = SNONLIN_FAD1*SNONLIN_FTEMP
                  SNONLIN_DELAP = (SNONLIN_FIJ - 2.0_JWRB*SNONLIN_SAM)*DAL1*SNONLIN_FCEN
                  SNONLIN_DELAM = (SNONLIN_FIJ - 2.0_JWRB*SNONLIN_SAP)*DAL2*SNONLIN_FCEN

!$loki split-read-write
                  IF (SNONLIN_MM1 >= 1) THEN
                    SNONLIN_loki_temp_54 = IMPLSCH_SL(IJ, SNONLIN_K2, SNONLIN_MM1, ICHNK) + SNONLIN_AD*SNONLIN_FKLAMMA
                    SNONLIN_loki_temp_55 = IMPLSCH_FLD(IJ, SNONLIN_K2, SNONLIN_MM1, ICHNK) + SNONLIN_DELAM*SNONLIN_FKLAMA2
                    SNONLIN_loki_temp_56 = IMPLSCH_SL(IJ, SNONLIN_K21, SNONLIN_MM1, ICHNK) + SNONLIN_AD*SNONLIN_FKLAMMB
                    SNONLIN_loki_temp_57 = IMPLSCH_FLD(IJ, SNONLIN_K21, SNONLIN_MM1, ICHNK) + SNONLIN_DELAM*SNONLIN_FKLAMB2
                  END IF

                  SNONLIN_loki_temp_58 = IMPLSCH_SL(IJ, SNONLIN_K, SNONLIN_MC, ICHNK) - 2.0_JWRB*SNONLIN_AD
                  SNONLIN_loki_temp_59 = IMPLSCH_FLD(IJ, SNONLIN_K, SNONLIN_MC, ICHNK) - 2.0_JWRB*SNONLIN_DELAD
                  SNONLIN_loki_temp_60 = IMPLSCH_SL(IJ, SNONLIN_K1, SNONLIN_MP, ICHNK) + SNONLIN_AD*SNONLIN_FKLAMP1
                  SNONLIN_loki_temp_61 = IMPLSCH_FLD(IJ, SNONLIN_K1, SNONLIN_MP, ICHNK) + SNONLIN_DELAP*SNONLIN_FKLAP12
                  SNONLIN_loki_temp_62 = IMPLSCH_SL(IJ, SNONLIN_K11, SNONLIN_MP, ICHNK) + SNONLIN_AD*SNONLIN_FKLAMP2
                  SNONLIN_loki_temp_63 = IMPLSCH_FLD(IJ, SNONLIN_K11, SNONLIN_MP, ICHNK) + SNONLIN_DELAP*SNONLIN_FKLAP22
                  SNONLIN_loki_temp_64 = IMPLSCH_SL(IJ, SNONLIN_K1, SNONLIN_MP1, ICHNK) + SNONLIN_AD*SNONLIN_FKLAMPA
                  SNONLIN_loki_temp_65 = IMPLSCH_FLD(IJ, SNONLIN_K1, SNONLIN_MP1, ICHNK) + SNONLIN_DELAP*SNONLIN_FKLAPA2
                  SNONLIN_loki_temp_66 = IMPLSCH_SL(IJ, SNONLIN_K11, SNONLIN_MP1, ICHNK) + SNONLIN_AD*SNONLIN_FKLAMPB
                  SNONLIN_loki_temp_67 = IMPLSCH_FLD(IJ, SNONLIN_K11, SNONLIN_MP1, ICHNK) + SNONLIN_DELAP*SNONLIN_FKLAPB2
                  IF (SNONLIN_MM1 >= 1) THEN
                    IMPLSCH_SL(IJ, SNONLIN_K2, SNONLIN_MM1, ICHNK) = SNONLIN_loki_temp_54
                    IMPLSCH_FLD(IJ, SNONLIN_K2, SNONLIN_MM1, ICHNK) = SNONLIN_loki_temp_55
                    IMPLSCH_SL(IJ, SNONLIN_K21, SNONLIN_MM1, ICHNK) = SNONLIN_loki_temp_56
                    IMPLSCH_FLD(IJ, SNONLIN_K21, SNONLIN_MM1, ICHNK) = SNONLIN_loki_temp_57
                  END IF
                  IMPLSCH_SL(IJ, SNONLIN_K, SNONLIN_MC, ICHNK) = SNONLIN_loki_temp_58
                  IMPLSCH_FLD(IJ, SNONLIN_K, SNONLIN_MC, ICHNK) = SNONLIN_loki_temp_59
                  IMPLSCH_SL(IJ, SNONLIN_K1, SNONLIN_MP, ICHNK) = SNONLIN_loki_temp_60
                  IMPLSCH_FLD(IJ, SNONLIN_K1, SNONLIN_MP, ICHNK) = SNONLIN_loki_temp_61
                  IMPLSCH_SL(IJ, SNONLIN_K11, SNONLIN_MP, ICHNK) = SNONLIN_loki_temp_62
                  IMPLSCH_FLD(IJ, SNONLIN_K11, SNONLIN_MP, ICHNK) = SNONLIN_loki_temp_63
                  IMPLSCH_SL(IJ, SNONLIN_K1, SNONLIN_MP1, ICHNK) = SNONLIN_loki_temp_64
                  IMPLSCH_FLD(IJ, SNONLIN_K1, SNONLIN_MP1, ICHNK) = SNONLIN_loki_temp_65
                  IMPLSCH_SL(IJ, SNONLIN_K11, SNONLIN_MP1, ICHNK) = SNONLIN_loki_temp_66
                  IMPLSCH_FLD(IJ, SNONLIN_K11, SNONLIN_MP1, ICHNK) = SNONLIN_loki_temp_67
!$loki end split-read-write
                END DO
              END DO

            END IF

            !*    BRANCH BACK TO 2. FOR NEXT FREQUENCY.

          END DO



          ! =========================================

        END DO
      END DO
!$acc end parallel loop

      ! Nonlinear scatter and the remaining implicit update are distinct
      ! launches so their register pressure can be tuned independently.
#ifdef WAM_HAVE_SINGLE_PRECISION
!$acc parallel loop gang vector_length( 128 ) default( present ) minctapersm( 12 ) async(1)
#else
!$acc parallel loop gang vector_length( 64 ) default( present ) minctapersm( 20 ) async(1)
#endif
      DO ICHNK=1,NCHNK
!$acc loop vector
        DO IJ=1,NPROMA_WAM
          DELT = IDELT
          DELTM = 1.0_JWRB / DELT
          DELT5 = XIMP*DELT
          LCFLX = LWFLUX .or. (LWFLUXOUT .and. .not.LHEIGHT_ONLY) .or. LWNEMOCOU

          IF (LCFLX .and. LWVFLX_SNL) THEN
            !     Save source term contributions relevant for the calculation of ocean fluxes
            !!!!!!  SL must only contain contributions contributed to fluxes into the oceans
            !       MODULATE SL BY IMPLICIT FACTOR
!$acc loop seq
            DO IMPLSCH_LOKI_M=1,NFRE
!$acc loop seq
              DO IMPLSCH_LOKI_K=1,NANG
                GTEMP1 = MAX((1.0_JWRB - DELT5*IMPLSCH_FLD(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK)), 1.0_JWRB)
                IMPLSCH_SSOURCE(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) =  &
                & IMPLSCH_SL(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) / GTEMP1
              END DO
            END DO
          END IF


          ! [Loki] inlined child subroutine: SDIWBK
          ! =========================================

          ! ----------------------------------------------------------------------


          !*    1. ADDING DISSIPATION AND ITS FUNCTIONAL DERIVATIVE TO NET SOURCE
          !*       FUNCTION AND NET SOURCE FUNCTION DERIVATIVE.
          !        --------------------------------------------------------------

          IF (LBIWBK .AND. WVENVI%DEPTH(IJ, ICHNK) < DEPTHTRS) THEN
            !       (FOLLOWING BATTJES-JANSSEN AND BEJI)
              ALPH = 2.0_JWRB*WVENVI%EMAXDPT(IJ, ICHNK) / IMPLSCH_EMEAN(IJ, ICHNK)
              SDIWBK_ARG = MIN(ALPH, 50.0_JWRB)
              Q_OLD = EXP(-SDIWBK_ARG)
              !            USE NEWTON-RAPHSON METHOD
!$acc loop seq
              DO IC=1,15
                EXPQ = EXP(-SDIWBK_ARG*(1.0_JWRB - Q_OLD))
                Q = Q_OLD - (EXPQ - Q_OLD) / (SDIWBK_ARG*EXPQ - 1.0_JWRB)
                REL_ERR = ABS(Q - Q_OLD) / Q_OLD
                IF (REL_ERR < 0.00001_JWRB) EXIT
                Q_OLD = Q
              END DO
              Q = MIN(Q, 1.0_JWRB)
              SDS = COEF_B_J*ALPH*Q*IMPLSCH_F1MEAN(IJ, ICHNK)

!$acc loop seq
            DO SDIWBK_M=1,NFRE_RED
!$acc loop seq
              DO SDIWBK_K=1,NANG
                  IMPLSCH_SL(IJ, SDIWBK_K, SDIWBK_M, ICHNK) =  &
                  & IMPLSCH_SL(IJ, SDIWBK_K, SDIWBK_M, ICHNK) - SDS*VARS_4D%FL1(IJ, SDIWBK_K, SDIWBK_M, ICHNK)
                  IMPLSCH_FLD(IJ, SDIWBK_K, SDIWBK_M, ICHNK) = IMPLSCH_FLD(IJ, SDIWBK_K, SDIWBK_M, ICHNK) - SDS
              END DO
            END DO

          END IF


          ! =========================================

          IF (LICERUN) THEN

            !        Use linear scaling of ALL proceeding source terms under sea ice (this is a complete unknown)
            IF (LCISCAL .AND. FF_NOW%CICOVER(IJ, ICHNK) /= 0.0_JWRB) THEN
!$acc loop seq
              DO IMPLSCH_LOKI_M=1,NFRE
!$acc loop seq
                DO IMPLSCH_LOKI_K=1,NANG
                  BETA = 1._JWRB - FF_NOW%CICOVER(IJ, ICHNK)
                  IMPLSCH_SL(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) =  &
                  & BETA*IMPLSCH_SL(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK)
                  IMPLSCH_FLD(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) =  &
                  & BETA*IMPLSCH_FLD(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK)
                END DO
              END DO
            END IF

            !        Coupling of waves and sea ice (type 1): wave-induced sea ice break up + reduced attenuation
            IF (LWNEMOCOUIBR) THEN
              ! [Loki] inlined child subroutine: ICEBREAK_MODIFY_ATTENUATION
              ! =========================================

              ! ----------------------------------------------------------------------


              ZALPFACXINV = 1.0_JWRB / ZALPFACX                ! FACTOR TO DECREASE ATTENUATION BY WHEN ICE IS BROKEN


              ! USE IBRMEM TO CHANGE ATTENUATION FACTOR ALPFAC
              ! OTHERWISE ALPFAC KEEPS VALUE SET IN IMPLSCH

              IF (WVENVI%IBRMEM(IJ, ICHNK) <= ZIBRW_THRSH) THEN
                IMPLSCH_ALPFAC(IJ, ICHNK) = ZALPFACXINV
              END IF



              ! =========================================
            END IF

            !        Attenuation of waves in ice
            IF (LCIWA1 .or. LCIWA2 .or. LCIWA3) THEN
              ! [Loki] inlined child subroutine: SDICE
              ! =========================================


              ! ----------------------------------------------------------------------


              !     Attenuation of waves in ice (type 1): scattering
              IF (LCIWA1) THEN
                ! [Loki] inlined child subroutine: SDICE1
                ! =========================================


                ! ----------------------------------------------------------------------


                SDICE_DELT = IDELT
                SDICE_DELTM = 1.0_JWRB / SDICE_DELT
                SDICE_DELT5 = XIMP*SDICE_DELT

                !     following  Dumont et al. (2011), eqn (13):
                ! sea ice fragility
                CIFRGL = 0.955_JWRB
                ! sea ice foes minimum size (m)
                CIDMIN = 20.0_JWRB
                ! sea ice fragmentation number (>2)
                CIFRGMT = 2.0_JWRB

                A = 200.0_JWRB
                C = 300.0_JWRB
                !     the maximum number of fragmentation step is set
                !     for the limit value for sea ice = 0 (CIDMAX=A)
                !     to insure that CIDMEAN will be increasing with increasing sea ice cover
                MAXICM = INT(LOG(A / CIDMIN) / LOG(CIFRGMT))
                IF (FF_NOW%CITHICK(IJ, ICHNK) > 0.0_JWRB) THEN
                  ! sea ice foes maxmimum size (m)
                  !!!       testing making it function of sea ice cover
                  CIDMAX = A + C*FF_NOW%CICOVER(IJ, ICHNK)
                  ICM = MIN(INT(LOG(CIDMAX / CIDMIN) / LOG(CIFRGMT)), MAXICM)
                  SN = 0.0_JWRB
                  SD = 0.0_JWRB
!$acc loop seq
                  DO SDICE_I=0,ICM
                    SDICE_X = (CIFRGMT**2*CIFRGL)**SDICE_I
                    SN = SN + SDICE_X*CIDMAX / CIFRGMT**SDICE_I
                    SD = SD + SDICE_X
                  END DO
                  CIDMEAN = SN / SD
                  DINV = 1.0_JWRB / CIDMEAN
                ELSE
                  DINV = CIDMIN
                END IF


!$acc loop seq
                DO SDICE_M=1,NFRE
                  TW = 1.0_JWRB / FR(SDICE_M)
                  IT = FLOOR((TW - TICMIN) / DTIC + 1)
                  IT = MAX(1, MIN(IT, NICT))
                  IT1 = IT + 1
                  IT1 = MAX(1, MIN(IT1, NICT))
                  WT1 = MAX(MIN(1.0_JWRB, (TW - (TICMIN + (IT - 1)*DTIC)) / DTIC), 0.0_JWRB)
                  WT = 1.0_JWRB - WT1
                  IF (FF_NOW%CITHICK(IJ, ICHNK) > 0.0_JWRB) THEN
                    IH = FLOOR((FF_NOW%CITHICK(IJ, ICHNK) - HICMIN) / DHIC + 1)
                    IH = MAX(1, MIN(IH, NICH))
                    IH1 = IH + 1
                    IH1 = MAX(1, MIN(IH1, NICH))
                    WH1 = MAX(MIN(1._JWRB, (FF_NOW%CITHICK(IJ, ICHNK) - (HICMIN + (IH - 1)*DHIC)) / DHIC), 0.0_JWRB)
                    WH = 1.0_JWRB - WH1
                    CIDEAC_INT = WT*(WH*CIDEAC(IT, IH) + WH1*CIDEAC(IT, IH1)) + WT1*(WH*CIDEAC(IT1, IH) + WH1*CIDEAC(IT1, IH1))
                    IMPLSCH_ALP(IJ, SDICE_M, ICHNK) = EXP(CIDEAC_INT)*DINV*ZALPFACB                      ! CICV accounted for below

                  ELSE
                    IMPLSCH_ALP(IJ, SDICE_M, ICHNK) = 0.0_JWRB
                  END IF
                END DO

!$acc loop seq
                DO SDICE_M=1,NFRE
!$acc loop seq
                  DO SDICE_K=1,NANG

                    !              apply the source term
                    FLDICE = -IMPLSCH_ALP(IJ, SDICE_M, ICHNK)*WVPRPT%CGROUP(IJ, SDICE_M, ICHNK)
                    IMPLSCH_SLICE(IJ, SDICE_K, SDICE_M, ICHNK) = VARS_4D%FL1(IJ, SDICE_K, SDICE_M, ICHNK)*FLDICE
                    IMPLSCH_SL(IJ, SDICE_K, SDICE_M, ICHNK) = IMPLSCH_SL(IJ, SDICE_K, SDICE_M, ICHNK) + FF_NOW%CICOVER(IJ, ICHNK) &
                    & *IMPLSCH_SLICE(IJ, SDICE_K, SDICE_M, ICHNK)
                    IMPLSCH_FLD(IJ, SDICE_K, SDICE_M, ICHNK) =  &
                    & IMPLSCH_FLD(IJ, SDICE_K, SDICE_M, ICHNK) + FF_NOW%CICOVER(IJ, ICHNK)*FLDICE

                    !              to be used for wave radiative stress calculation
                    SDICE_GTEMP1 = MAX((1.0_JWRB - SDICE_DELT5*FLDICE), 1.0_JWRB)
                    IMPLSCH_SLICE(IJ, SDICE_K, SDICE_M, ICHNK) = IMPLSCH_SLICE(IJ, SDICE_K, SDICE_M, ICHNK) / SDICE_GTEMP1

                  END DO
                END DO


                ! =========================================
              END IF

              !     Attenuation of waves in ice (type 2): bottom friction
              IF (LCIWA2) THEN
                ! [Loki] inlined child subroutine: SDICE2
                ! =========================================


                ! ----------------------------------------------------------------------


                SDICE2_DELT = IDELT
                SDICE2_DELTM = 1.0_JWRB / SDICE2_DELT
                SDICE2_DELT5 = XIMP*SDICE2_DELT

!$acc loop seq
                DO SDICE2_M=1,NFRE
!$acc loop seq
                  DO SDICE2_K=1,NANG

                    EWH = 4.0_JWRB*SQRT(MAX(EPSMIN, VARS_4D%FL1(IJ, SDICE2_K, SDICE2_M, ICHNK)*DFIM(SDICE2_M)))
                    IMPLSCH_XK2(SDICE2_M, ICHNK) = WVPRPT%WAVNUM(IJ, SDICE2_M, ICHNK)**2
                    SDICE2_ALP = CDICWA*IMPLSCH_XK2(SDICE2_M, ICHNK)*EWH*ZALPFACB

                    !              apply the source term
                    SDICE2_FLDICE = -SDICE2_ALP*WVPRPT%CGROUP(IJ, SDICE2_M, ICHNK)
                    IMPLSCH_SLICE(IJ, SDICE2_K, SDICE2_M, ICHNK) = VARS_4D%FL1(IJ, SDICE2_K, SDICE2_M, ICHNK)*SDICE2_FLDICE
                    IMPLSCH_SL(IJ, SDICE2_K, SDICE2_M, ICHNK) = IMPLSCH_SL(IJ, SDICE2_K, SDICE2_M, ICHNK) + FF_NOW%CICOVER(IJ,  &
                    & ICHNK)*IMPLSCH_SLICE(IJ, SDICE2_K, SDICE2_M, ICHNK)
                    IMPLSCH_FLD(IJ, SDICE2_K, SDICE2_M, ICHNK) =  &
                    & IMPLSCH_FLD(IJ, SDICE2_K, SDICE2_M, ICHNK) + FF_NOW%CICOVER(IJ, ICHNK)*SDICE2_FLDICE

                    !              to be used for wave radiative stress calculation
                    SDICE2_GTEMP1 = MAX((1.0_JWRB - SDICE2_DELT5*SDICE2_FLDICE), 1.0_JWRB)
                    IMPLSCH_SLICE(IJ, SDICE2_K, SDICE2_M, ICHNK) = IMPLSCH_SLICE(IJ, SDICE2_K, SDICE2_M, ICHNK) / SDICE2_GTEMP1

                  END DO
                END DO


                ! =========================================
              END IF

              !     Attenuation of waves in ice (type 3): viscous friction
              IF (LCIWA3 .AND. (FF_NOW%CICOVER(IJ, ICHNK) /= 0.0_JWRB .OR. LCFLX)) THEN
                ! [Loki] inlined child subroutine: SDICE3
                ! =========================================


                ! ----------------------------------------------------------------------


                SDICE3_DELT = IDELT
                SDICE3_DELTM = 1.0_JWRB / SDICE3_DELT
                SDICE3_DELT5 = XIMP*SDICE3_DELT

                IMODEL = 2
                HICEMAX = 4.0_JWRB
                HICEMIN = 0.1_JWRB

                SELECT CASE (IMODEL)
                CASE (1)
                  !          Best fit w Tempelfjorde obs from Lotfi Aouf
                  CDICE = 0.0656_JWRB

!$acc loop seq
                  DO SDICE3_M=1,NFRE
                    IMPLSCH_SDICE3_ALP(IJ, SDICE3_M, ICHNK) =  &
                    & (CDICE*FF_NOW%CITHICK(IJ, ICHNK)*WVPRPT%WAVNUM(IJ, SDICE3_M, ICHNK)**2)*IMPLSCH_ALPFAC(IJ, ICHNK)
                  END DO

                CASE (2)
                  !          Jie Yu, W. Erik Rogers, David W. Wang 2022
                  CDICE = 0.1274_JWRB*(ZPI / SQRT(G))**4.5_JWRB

!$acc loop seq
                  DO SDICE3_M=1,NFRE
                    IMPLSCH_SDICE3_ALP(IJ, SDICE3_M, ICHNK) = (2._JWRB*CDICE*(FF_NOW%CITHICK(IJ, ICHNK)**1.25_JWRB)*(FR(SDICE3_M) &
                    & **4.5_JWRB))*IMPLSCH_ALPFAC(IJ, ICHNK)*ZALPFACB
                  END DO

                END SELECT

!$acc loop seq
                DO SDICE3_M=1,NFRE
!$acc loop seq
                  DO SDICE3_K=1,NANG

                    !              calculate source term increments
                    SDICE3_FLDICE = -IMPLSCH_SDICE3_ALP(IJ, SDICE3_M, ICHNK)*WVPRPT%CGROUP(IJ, SDICE3_M, ICHNK)
                    IMPLSCH_SLICE(IJ, SDICE3_K, SDICE3_M, ICHNK) = VARS_4D%FL1(IJ, SDICE3_K, SDICE3_M, ICHNK)*SDICE3_FLDICE

                    !              apply the source term (old way to ensure bit-identicality)
                    SDICE_TEMP =  &
                    & -FF_NOW%CICOVER(IJ, ICHNK)*IMPLSCH_SDICE3_ALP(IJ, SDICE3_M, ICHNK)*WVPRPT%CGROUP(IJ, SDICE3_M, ICHNK)
                    IMPLSCH_SL(IJ, SDICE3_K, SDICE3_M, ICHNK) =  &
                    & IMPLSCH_SL(IJ, SDICE3_K, SDICE3_M, ICHNK) + VARS_4D%FL1(IJ, SDICE3_K, SDICE3_M, ICHNK)*SDICE_TEMP
                    IMPLSCH_FLD(IJ, SDICE3_K, SDICE3_M, ICHNK) = IMPLSCH_FLD(IJ, SDICE3_K, SDICE3_M, ICHNK) + SDICE_TEMP

                    !              apply the source term (new way)
                    !                SL(IJ,K,M)     =  SL(IJ,K,M)  + CICV(IJ)*SLICE(IJ,K,M)
                    !                FLD(IJ,K,M)    =  FLD(IJ,K,M) + CICV(IJ)*FLDICE
                    !
                    !              to be used for wave radiative stress calculation
                    SDICE3_GTEMP1 = MAX((1.0_JWRB - SDICE3_DELT5*SDICE3_FLDICE), 1.0_JWRB)
                    IMPLSCH_SLICE(IJ, SDICE3_K, SDICE3_M, ICHNK) = IMPLSCH_SLICE(IJ, SDICE3_K, SDICE3_M, ICHNK) / SDICE3_GTEMP1

                  END DO
                END DO


                ! =========================================
              END IF


              ! =========================================
            END IF

          END IF

          ! [Loki] inlined child subroutine: SBOTTOM
          ! =========================================

          ! ----------------------------------------------------------------------


          SBOTTOM_CONST = -2.0_JWRB*0.038_JWRB*GM1
          IF (WVENVI%DEPTH(IJ, ICHNK) < BATHYMAX) THEN
!$acc loop seq
          DO SBOTTOM_M=1,NFRE_RED
              SBOTTOM_ARG = 2.0_JWRB*WVENVI%DEPTH(IJ, ICHNK)*WVPRPT%WAVNUM(IJ, SBOTTOM_M, ICHNK)
              SBOTTOM_ARG = MIN(SBOTTOM_ARG, 50.0_JWRB)
              SBO = SBOTTOM_CONST*WVPRPT%WAVNUM(IJ, SBOTTOM_M, ICHNK) / SINH(SBOTTOM_ARG)

!$acc loop seq
            DO SBOTTOM_K=1,NANG
              IMPLSCH_SL(IJ, SBOTTOM_K, SBOTTOM_M, ICHNK) =  &
              & IMPLSCH_SL(IJ, SBOTTOM_K, SBOTTOM_M, ICHNK) + SBO*VARS_4D%FL1(IJ, SBOTTOM_K, SBOTTOM_M, ICHNK)
              IMPLSCH_FLD(IJ, SBOTTOM_K, SBOTTOM_M, ICHNK) = IMPLSCH_FLD(IJ, SBOTTOM_K, SBOTTOM_M, ICHNK) + SBO
            END DO
          END DO
          END IF


          ! =========================================

          ! ----------------------------------------------------------------------

          !*    2.4 COMPUTATION OF NEW SPECTRA.
          !         ---------------------------

          !     INCREASE OF SPECTRUM IN A TIME STEP IS LIMITED TO A FINITE
          !     FRACTION OF A TYPICAL F**(-4) EQUILIBRIUM SPECTRUM.

!$acc loop seq
          DO IMPLSCH_LOKI_M=1,NFRE
            IMPLSCH_DELFL(IMPLSCH_LOKI_M, ICHNK) = COFRM4(IMPLSCH_LOKI_M)*DELT
          END DO
          USFM = FF_NOW%UFRIC(IJ, ICHNK)*MAX(IMPLSCH_FMEANWS(IJ, ICHNK), IMPLSCH_FMEAN(IJ, ICHNK))

          IF (LLUNSTR) THEN
!$acc loop seq
            DO IMPLSCH_LOKI_K=1,NANG
!$acc loop seq
              DO IMPLSCH_LOKI_M=1,NFRE
                GTEMP1 = MAX((1.0_JWRB - DELT5*IMPLSCH_FLD(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK)), 1.0_JWRB)
                GTEMP2 = DELT*IMPLSCH_SL(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) / GTEMP1
                FLHAB = ABS(GTEMP2)
                FLHAB = MIN(FLHAB, USFM*IMPLSCH_DELFL(IMPLSCH_LOKI_M, ICHNK))
                VARS_4D%FL1(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) =  &
                & VARS_4D%FL1(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) + WVENVI%IOBND(IJ, ICHNK)*SIGN(FLHAB, GTEMP2)
                VARS_4D%FL1(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) = MAX(WVENVI%IODP(IJ, ICHNK)*VARS_4D%FL1(IJ,  &
                & IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK), IMPLSCH_FLM(IJ, IMPLSCH_LOKI_K, ICHNK))
                IF (LCFLX) THEN
                IMPLSCH_SSOURCE(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) = IMPLSCH_SSOURCE(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M,  &
                & ICHNK) + DELTM*MIN(FLMAX(IMPLSCH_LOKI_M) - VARS_4D%FL1(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK), 0.0_JWRB)
                END IF
                VARS_4D%FL1(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) =  &
                & MIN(VARS_4D%FL1(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK), FLMAX(IMPLSCH_LOKI_M))
              END DO
            END DO
          ELSE
!$acc loop seq
            DO IMPLSCH_LOKI_K=1,NANG
!$acc loop seq
              DO IMPLSCH_LOKI_M=1,NFRE
                GTEMP1 = MAX((1.0_JWRB - DELT5*IMPLSCH_FLD(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK)), 1.0_JWRB)
                GTEMP2 = DELT*IMPLSCH_SL(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) / GTEMP1
                FLHAB = ABS(GTEMP2)
                FLHAB = MIN(FLHAB, USFM*IMPLSCH_DELFL(IMPLSCH_LOKI_M, ICHNK))
                VARS_4D%FL1(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) =  &
                & VARS_4D%FL1(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) + SIGN(FLHAB, GTEMP2)
                VARS_4D%FL1(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) =  &
                & MAX(VARS_4D%FL1(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK), IMPLSCH_FLM(IJ, IMPLSCH_LOKI_K, ICHNK))
                IF (LCFLX) THEN
                IMPLSCH_SSOURCE(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) = IMPLSCH_SSOURCE(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M,  &
                & ICHNK) + DELTM*MIN(FLMAX(IMPLSCH_LOKI_M) - VARS_4D%FL1(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK), 0.0_JWRB)
                END IF
                VARS_4D%FL1(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK) =  &
                & MIN(VARS_4D%FL1(IJ, IMPLSCH_LOKI_K, IMPLSCH_LOKI_M, ICHNK), FLMAX(IMPLSCH_LOKI_M))
              END DO
            END DO
          END IF

          IF (LCFLX) THEN
            ! [Loki] inlined child subroutine: WNFLUXES
            ! =========================================

            ! ----------------------------------------------------------------------


            EPSUS3 = EPSUS*SQRT(EPSUS)
            EPSMIN1000 = EPSMIN*1000.0_JWRB

            IF (LCIWA1 .or. LCIWA2 .or. LCIWA3) THEN
              ZCITHRS = 0._JWRB
              CITHRSH_INV = 50._JWRB
              ZMAXEXP = 20._JWRB
            ELSE
              ZCITHRS = CIBLOCK
              CITHRSH_INV = 1._JWRB / MAX(CITHRSH, 0.01_JWRB)
              ZMAXEXP = 10._JWRB
            END IF

            EFD_FAC = 4.0_JWRB*EGRCRV / G**2
            FFD_FAC = (EGRCRV / AFCRV)**(1.0_JWRB / BFCRV)*G

            !*    DETERMINE NORMALIZED FLUXES FROM AIR TO WAVE AND FROM WAVE TO OCEAN.
            !     -------------------------------------------------------------------

            !     ENERGY FLUX from SSURF
            !     MOMENTUM FLUX FROM SSURF and SLICE
            PHILF = 0.0_JWRB
            WNFLUXES_XSTRESS = 0.0_JWRB
            WNFLUXES_YSTRESS = 0.0_JWRB
            XSTRESSICE = 0.0_JWRB
            YSTRESSICE = 0.0_JWRB
            SUMXICE = 0.0_JWRB
            SUMYICE = 0.0_JWRB

            IF (LWNEMOCOUWRS) THEN
              !     THE INTEGRATION UP TO FR(NFRE)
!$acc loop seq
              DO WNFLUXES_M=1,NFRE
                WNFLUXES_K = 1
                !         NOTE THAT EVERYTHING HERE IS ALWAYS NEGATIVE DUE TO SLICE BEING NEGATIVE
                SUMXICE = SINTH(WNFLUXES_K)*MIN(IMPLSCH_SLICE(IJ, WNFLUXES_K, WNFLUXES_M, ICHNK), -EPSMIN1000)
                SUMYICE = COSTH(WNFLUXES_K)*MIN(IMPLSCH_SLICE(IJ, WNFLUXES_K, WNFLUXES_M, ICHNK), -EPSMIN1000)
!$acc loop seq
                DO WNFLUXES_K=2,NANG
                  SUMXICE = SUMXICE + SINTH(WNFLUXES_K)*MIN(IMPLSCH_SLICE(IJ, WNFLUXES_K, WNFLUXES_M, ICHNK), -EPSMIN1000)
                  SUMYICE = SUMYICE + COSTH(WNFLUXES_K)*MIN(IMPLSCH_SLICE(IJ, WNFLUXES_K, WNFLUXES_M, ICHNK), -EPSMIN1000)
                END DO
                XSTRESSICE = XSTRESSICE + ZALPWRS*SUMXICE*WVPRPT%CINV(IJ, WNFLUXES_M, ICHNK)*RHOWG_DFIM(WNFLUXES_M)
                YSTRESSICE = YSTRESSICE + ZALPWRS*SUMYICE*WVPRPT%CINV(IJ, WNFLUXES_M, ICHNK)*RHOWG_DFIM(WNFLUXES_M)
              END DO
            END IF

!$acc loop seq
            DO WNFLUXES_M=1,NFRE
              WNFLUXES_K = 1
              WNFLUXES_SUMT = IMPLSCH_SSOURCE(IJ, WNFLUXES_K, WNFLUXES_M, ICHNK)
              WNFLUXES_SUMX = SINTH(WNFLUXES_K)*IMPLSCH_SSOURCE(IJ, WNFLUXES_K, WNFLUXES_M, ICHNK)
              WNFLUXES_SUMY = COSTH(WNFLUXES_K)*IMPLSCH_SSOURCE(IJ, WNFLUXES_K, WNFLUXES_M, ICHNK)
!$acc loop seq
              DO WNFLUXES_K=2,NANG
                WNFLUXES_SUMT = WNFLUXES_SUMT + IMPLSCH_SSOURCE(IJ, WNFLUXES_K, WNFLUXES_M, ICHNK)
                WNFLUXES_SUMX = WNFLUXES_SUMX + SINTH(WNFLUXES_K)*IMPLSCH_SSOURCE(IJ, WNFLUXES_K, WNFLUXES_M, ICHNK)
                WNFLUXES_SUMY = WNFLUXES_SUMY + COSTH(WNFLUXES_K)*IMPLSCH_SSOURCE(IJ, WNFLUXES_K, WNFLUXES_M, ICHNK)
              END DO
              PHILF = PHILF + WNFLUXES_SUMT*IMPLSCH_RHOWGDFTH(IJ, WNFLUXES_M, ICHNK)
              WNFLUXES_CMRHOWGDFTH = WVPRPT%CINV(IJ, WNFLUXES_M, ICHNK)*IMPLSCH_RHOWGDFTH(IJ, WNFLUXES_M, ICHNK)
              WNFLUXES_XSTRESS = WNFLUXES_XSTRESS + WNFLUXES_SUMX*WNFLUXES_CMRHOWGDFTH
              WNFLUXES_YSTRESS = WNFLUXES_YSTRESS + WNFLUXES_SUMY*WNFLUXES_CMRHOWGDFTH
            END DO

            IF (LICERUN .and. LWAMRSETCI) THEN
              IF (FF_NOW%CICOVER(IJ, ICHNK) > ZCITHRS) THEN
                OOVAL = EXP(-MIN((FF_NOW%CICOVER(IJ, ICHNK)*CITHRSH_INV)**4, ZMAXEXP))

                !           ADJUST USTAR FOR THE PRESENCE OF SEA ICE
                U10P = MAX(FF_NOW%WSWAVE(IJ, ICHNK), EPSU10)
                CD_BULK = MIN((WNFLUXES_C1 + WNFLUXES_C2*U10P**WNFLUXES_P1)*U10P**WNFLUXES_P2, CDMAX_LOC)
                CD_WAVE = (FF_NOW%UFRIC(IJ, ICHNK) / U10P)**2
                CD_ICE = OOVAL*CD_WAVE + (1.0_JWRB - OOVAL)*CD_BULK
                USTAR = MAX(SQRT(CD_ICE)*U10P, EPSUS)

                ! EM_OC and F1_OC with fully developed model ENERGY
                ! The significant wave height derived from EM_OC will be used
                ! by NEMO as a scaling factor as if it was open ocean
                EFD = MIN(EFD_FAC*USTAR**4, EFD_MAX)
                EM_OC = MAX(OOVAL*IMPLSCH_EMEAN(IJ, ICHNK) + (1.0_JWRB - OOVAL)*EFD, EFD_MIN)
                FFD = FFD_FAC / USTAR
                F1_OC = OOVAL*IMPLSCH_F1MEAN(IJ, ICHNK) + (1.0_JWRB - OOVAL)*FFD
                F1_OC = MIN(MAX(F1_OC, FR(2)), FR(NFRE))
              ELSE
                OOVAL = 1.0_JWRB
                USTAR = FF_NOW%UFRIC(IJ, ICHNK)
                EM_OC = IMPLSCH_EMEAN(IJ, ICHNK)
                F1_OC = IMPLSCH_F1MEAN(IJ, ICHNK)
              END IF
            ELSE
              OOVAL = 1.0_JWRB
              USTAR = FF_NOW%UFRIC(IJ, ICHNK)
              EM_OC = IMPLSCH_EMEAN(IJ, ICHNK)
              F1_OC = IMPLSCH_F1MEAN(IJ, ICHNK)
            END IF

            TAU = FF_NOW%AIRD(IJ, ICHNK)*MAX(USTAR**2, EPSUS)
            INTFLDS%TAUXD(IJ, ICHNK) = TAU*SIN(FF_NOW%WDWAVE(IJ, ICHNK))
            INTFLDS%TAUYD(IJ, ICHNK) = TAU*COS(FF_NOW%WDWAVE(IJ, ICHNK))

            INTFLDS%TAUOCXD(IJ, ICHNK) = INTFLDS%TAUXD(IJ, ICHNK) - OOVAL*WNFLUXES_XSTRESS
            INTFLDS%TAUOCYD(IJ, ICHNK) = INTFLDS%TAUYD(IJ, ICHNK) - OOVAL*WNFLUXES_YSTRESS
            TAUO = SQRT(INTFLDS%TAUOCXD(IJ, ICHNK)**2 + INTFLDS%TAUOCYD(IJ, ICHNK)**2)
            INTFLDS%TAUOC(IJ, ICHNK) = MIN(MAX(TAUO / TAU, TAUOCMIN), TAUOCMAX)

            IF (LWNEMOCOUWRS) THEN
              ! FLIP COMPONENTS TO APPLY POSITIVE STRESS TO SEA ICE
              INTFLDS%TAUICX(IJ, ICHNK) = -XSTRESSICE
              INTFLDS%TAUICY(IJ, ICHNK) = -YSTRESSICE
            ELSE IF (.not.LWNEMOCOUWRS) THEN
              INTFLDS%TAUICX(IJ, ICHNK) = 0.0_JWRB
              INTFLDS%TAUICY(IJ, ICHNK) = 0.0_JWRB
            END IF

            IF (LWCOUAST) THEN
              !       USE THE SURFACE STRESSES AS PROVIDED BY THE ATMOSPHERE AND
              !       ONLY RESCALE THEM WITH TAUOC
              IF (FF_NOW%USTRA(IJ, ICHNK) /= 0.0_JWRB .or. FF_NOW%VSTRA(IJ, ICHNK) /= 0.0_JWRB) THEN
                INTFLDS%TAUXD(IJ, ICHNK) = FF_NOW%USTRA(IJ, ICHNK)
                INTFLDS%TAUOCXD(IJ, ICHNK) = FF_NOW%USTRA(IJ, ICHNK)*INTFLDS%TAUOC(IJ, ICHNK)
                INTFLDS%TAUYD(IJ, ICHNK) = FF_NOW%VSTRA(IJ, ICHNK)
                INTFLDS%TAUOCYD(IJ, ICHNK) = FF_NOW%VSTRA(IJ, ICHNK)*INTFLDS%TAUOC(IJ, ICHNK)
              END IF
            END IF


            XN = FF_NOW%AIRD(IJ, ICHNK)*MAX(USTAR**3, EPSUS3)
            INTFLDS%PHIOCD(IJ, ICHNK) = OOVAL*(PHILF - IMPLSCH_PHIWA(IJ, ICHNK)) + (1.0_JWRB - OOVAL)*PHIOC_ICE*XN

            INTFLDS%PHIEPS(IJ, ICHNK) = INTFLDS%PHIOCD(IJ, ICHNK) / XN
            INTFLDS%PHIEPS(IJ, ICHNK) = MIN(MAX(INTFLDS%PHIEPS(IJ, ICHNK), PHIEPSMIN), PHIEPSMAX)

            INTFLDS%PHIOCD(IJ, ICHNK) = INTFLDS%PHIEPS(IJ, ICHNK)*XN

            INTFLDS%PHIAW(IJ, ICHNK) = IMPLSCH_PHIWA(IJ, ICHNK) / XN
            INTFLDS%PHIAW(IJ, ICHNK) = OOVAL*IMPLSCH_PHIWA(IJ, ICHNK) / XN + (1.0_JWRB - OOVAL)*PHIAW_ICE

            IF (LWNEMOCOU) THEN
              WAM2NEMO%NPHIEPS(IJ, ICHNK) = INTFLDS%PHIEPS(IJ, ICHNK)
              WAM2NEMO%NTAUOC(IJ, ICHNK) = INTFLDS%TAUOC(IJ, ICHNK)
              IF (EM_OC /= 0.0_JWRB) THEN
                WAM2NEMO%NSWH(IJ, ICHNK) = 4.0_JWRO*SQRT(EM_OC)
              ELSE
                WAM2NEMO%NSWH(IJ, ICHNK) = 0.0_JWRO
              END IF
              IF (F1_OC /= 0.0_JWRB) THEN
                WAM2NEMO%NMWP(IJ, ICHNK) = 1.0_JWRO / F1_OC
              ELSE
                WAM2NEMO%NMWP(IJ, ICHNK) = 0.0_JWRO
              END IF

              IF (LWNEMOTAUOC) THEN
                WAM2NEMO%NEMOTAUX(IJ, ICHNK) = WAM2NEMO%NEMOTAUX(IJ, ICHNK) + INTFLDS%TAUOCXD(IJ, ICHNK)
                WAM2NEMO%NEMOTAUY(IJ, ICHNK) = WAM2NEMO%NEMOTAUY(IJ, ICHNK) + INTFLDS%TAUOCYD(IJ, ICHNK)
              ELSE
                WAM2NEMO%NEMOTAUX(IJ, ICHNK) = WAM2NEMO%NEMOTAUX(IJ, ICHNK) + INTFLDS%TAUXD(IJ, ICHNK)
                WAM2NEMO%NEMOTAUY(IJ, ICHNK) = WAM2NEMO%NEMOTAUY(IJ, ICHNK) + INTFLDS%TAUYD(IJ, ICHNK)
              END IF
              WAM2NEMO%NEMOWSWAVE(IJ, ICHNK) = WAM2NEMO%NEMOWSWAVE(IJ, ICHNK) + FF_NOW%WSWAVE(IJ, ICHNK)
              WAM2NEMO%NEMOPHIF(IJ, ICHNK) = WAM2NEMO%NEMOPHIF(IJ, ICHNK) + INTFLDS%PHIOCD(IJ, ICHNK)
              WAM2NEMO%NEMOTAUICX(IJ, ICHNK) = WAM2NEMO%NEMOTAUICX(IJ, ICHNK) + INTFLDS%TAUICX(IJ, ICHNK)
              WAM2NEMO%NEMOTAUICY(IJ, ICHNK) = WAM2NEMO%NEMOTAUICY(IJ, ICHNK) + INTFLDS%TAUICY(IJ, ICHNK)
            END IF

            ! ----------------------------------------------------------------------

            ! =========================================
          END IF
          ! ----------------------------------------------------------------------

          !*    2.5 REPLACE DIAGNOSTIC PART OF SPECTRA BY A F**(-5) TAIL.
          !         -----------------------------------------------------

          IF (LWFLUX) THEN
          ! [Loki] inlined child subroutine: FKMEAN
          ! =========================================

          ! ----------------------------------------------------------------------



          !*    1. INITIALISE MEAN FREQUENCY ARRAY AND TAIL FACTOR.
          !        ------------------------------------------------

          IMPLSCH_EMEAN(IJ, ICHNK) = EPSMIN
          IMPLSCH_FMEAN(IJ, ICHNK) = EPSMIN
          IMPLSCH_F1MEAN(IJ, ICHNK) = EPSMIN
          IMPLSCH_AKMEAN(IJ, ICHNK) = EPSMIN
          IMPLSCH_XKMEAN(IJ, ICHNK) = EPSMIN

          FKMEAN_DELT25 = WETAIL*FR(NFRE)*DELTH
          COEFM1 = FRTAIL*DELTH
          COEF1 = WP1TAIL*DELTH*FR(NFRE)**2
          COEFA = COEFM1*SQRT(G) / ZPI
          COEFX = COEF1*(ZPI / SQRT(G))

          !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTIONS.
          !        ------------------------------------------

          !*    2.2 SHALLOW WATER INTEGRATION.
          !         --------------------------

!$acc loop seq
          DO FKMEAN_M=1,NFRE
            SQRTK = SQRT(WVPRPT%WAVNUM(IJ, FKMEAN_M, ICHNK))
            IMPLSCH_TEMPA(IJ, ICHNK) = DFIM(FKMEAN_M) / SQRTK
            IMPLSCH_TEMPX(IJ, ICHNK) = SQRTK*DFIM(FKMEAN_M)
            FKMEAN_K = 1
            IMPLSCH_TEMP2(IJ, ICHNK) = VARS_4D%FL1(IJ, FKMEAN_K, FKMEAN_M, ICHNK)
!$acc loop seq
            DO FKMEAN_K=2,NANG
              IMPLSCH_TEMP2(IJ, ICHNK) = IMPLSCH_TEMP2(IJ, ICHNK) + VARS_4D%FL1(IJ, FKMEAN_K, FKMEAN_M, ICHNK)
            END DO
            IMPLSCH_EMEAN(IJ, ICHNK) = IMPLSCH_EMEAN(IJ, ICHNK) + DFIM(FKMEAN_M)*IMPLSCH_TEMP2(IJ, ICHNK)
            IMPLSCH_FMEAN(IJ, ICHNK) = IMPLSCH_FMEAN(IJ, ICHNK) + DFIMOFR(FKMEAN_M)*IMPLSCH_TEMP2(IJ, ICHNK)
            IMPLSCH_F1MEAN(IJ, ICHNK) = IMPLSCH_F1MEAN(IJ, ICHNK) + DFIMFR(FKMEAN_M)*IMPLSCH_TEMP2(IJ, ICHNK)
            IMPLSCH_AKMEAN(IJ, ICHNK) = IMPLSCH_AKMEAN(IJ, ICHNK) + IMPLSCH_TEMPA(IJ, ICHNK)*IMPLSCH_TEMP2(IJ, ICHNK)
            IMPLSCH_XKMEAN(IJ, ICHNK) = IMPLSCH_XKMEAN(IJ, ICHNK) + IMPLSCH_TEMPX(IJ, ICHNK)*IMPLSCH_TEMP2(IJ, ICHNK)
          END DO

          !*      ADD TAIL CORRECTION TO MEAN FREQUENCY AND
          !*      NORMALIZE WITH TOTAL ENERGY.
          IMPLSCH_EMEAN(IJ, ICHNK) = IMPLSCH_EMEAN(IJ, ICHNK) + FKMEAN_DELT25*IMPLSCH_TEMP2(IJ, ICHNK)
          IMPLSCH_FMEAN(IJ, ICHNK) = IMPLSCH_FMEAN(IJ, ICHNK) + COEFM1*IMPLSCH_TEMP2(IJ, ICHNK)
          IMPLSCH_FMEAN(IJ, ICHNK) = IMPLSCH_EMEAN(IJ, ICHNK) / IMPLSCH_FMEAN(IJ, ICHNK)
          IMPLSCH_F1MEAN(IJ, ICHNK) = IMPLSCH_F1MEAN(IJ, ICHNK) + COEF1*IMPLSCH_TEMP2(IJ, ICHNK)
          IMPLSCH_F1MEAN(IJ, ICHNK) = IMPLSCH_F1MEAN(IJ, ICHNK) / IMPLSCH_EMEAN(IJ, ICHNK)
          IMPLSCH_AKMEAN(IJ, ICHNK) = IMPLSCH_AKMEAN(IJ, ICHNK) + COEFA*IMPLSCH_TEMP2(IJ, ICHNK)
          IMPLSCH_AKMEAN(IJ, ICHNK) = (IMPLSCH_EMEAN(IJ, ICHNK) / IMPLSCH_AKMEAN(IJ, ICHNK))**2
          IMPLSCH_XKMEAN(IJ, ICHNK) = IMPLSCH_XKMEAN(IJ, ICHNK) + COEFX*IMPLSCH_TEMP2(IJ, ICHNK)
          IMPLSCH_XKMEAN(IJ, ICHNK) = (IMPLSCH_XKMEAN(IJ, ICHNK) / IMPLSCH_EMEAN(IJ, ICHNK))**2


          ! =========================================

          END IF

          !     MEAN FREQUENCY CHARACTERISTIC FOR WIND SEA
          ! [Loki] inlined child subroutine: FEMEANWS
          ! =========================================

          ! ----------------------------------------------------------------------


          !*    1. INITIALISE MEAN FREQUENCY ARRAY AND TAIL FACTOR.
          !        ------------------------------------------------

          ! Only atmosphere coupling consumes the post-update wind-sea mean.
          IF (LWFLUX) THEN
          FEMEANWS_EM_LOC = EPSMIN
          IMPLSCH_FMEANWS(IJ, ICHNK) = EPSMIN

          FEMEANWS_FEMEANWS_DELT25 = WETAIL*FR(NFRE)*DELTH
          FEMEANWS_FEMEANWS_DELT2 = FRTAIL*DELTH


          !*    2. INTEGRATE OVER FREQUENCIES AND DIRECTIONS.
          !        ------------------------------------------

!$acc loop seq
          DO FEMEANWS_FEMEANWS_M=1,NFRE
            FEMEANWS_FEMEANWS_TEMP2 = 0.0_JWRB
!$acc loop seq
            DO FEMEANWS_FEMEANWS_K=1,NANG
              FEMEANWS_FEMEANWS_TEMP2 = FEMEANWS_FEMEANWS_TEMP2 + VARS_4D%XLLWS(IJ, FEMEANWS_FEMEANWS_K, FEMEANWS_FEMEANWS_M,  &
              & ICHNK)*VARS_4D%FL1(IJ, FEMEANWS_FEMEANWS_K, FEMEANWS_FEMEANWS_M, ICHNK)
            END DO
            FEMEANWS_EM_LOC = FEMEANWS_EM_LOC + DFIM(FEMEANWS_FEMEANWS_M)*FEMEANWS_FEMEANWS_TEMP2
            IMPLSCH_FMEANWS(IJ, ICHNK) = IMPLSCH_FMEANWS(IJ, ICHNK) + DFIMOFR(FEMEANWS_FEMEANWS_M)*FEMEANWS_FEMEANWS_TEMP2
          END DO

          !*    3. ADD TAIL CORRECTION TO MEAN FREQUENCY AND
          !*       NORMALIZE WITH TOTAL ENERGY.
          !        ------------------------------------------

          FEMEANWS_EM_LOC = FEMEANWS_EM_LOC + FEMEANWS_FEMEANWS_DELT25*FEMEANWS_FEMEANWS_TEMP2
          IMPLSCH_FMEANWS(IJ, ICHNK) = IMPLSCH_FMEANWS(IJ, ICHNK) + FEMEANWS_FEMEANWS_DELT2*FEMEANWS_FEMEANWS_TEMP2
          IMPLSCH_FMEANWS(IJ, ICHNK) = FEMEANWS_EM_LOC / IMPLSCH_FMEANWS(IJ, ICHNK)

          EMEANWS = FEMEANWS_EM_LOC
          END IF


          ! =========================================

          ! [Loki] inlined child subroutine: IMPHFTAIL
          ! =========================================

          ! ----------------------------------------------------------------------


          !*    DIAGNOSTIC TAIL.
          !     ----------------

          IMPHFTAIL_TEMP1 = 1.0_JWRB / WVPRPT%XK2CG(IJ, MIJ%PTR(IJ, ICHNK), ICHNK) / WVPRPT%WAVNUM(IJ, MIJ%PTR(IJ, ICHNK), ICHNK)

!$acc loop seq
          DO IMPHFTAIL_M=MIJ%PTR(IJ, ICHNK) + 1,NFRE
            IMPHFTAIL_TEMP2 = 1.0_JWRB / WVPRPT%XK2CG(IJ, IMPHFTAIL_M, ICHNK) / WVPRPT%WAVNUM(IJ, IMPHFTAIL_M, ICHNK)
            IMPHFTAIL_TEMP2 = IMPHFTAIL_TEMP2 / IMPHFTAIL_TEMP1

            !*    MERGE TAIL INTO SPECTRA.
            !     ------------------------
!$acc loop seq
            DO IMPHFTAIL_K=1,NANG
              TFAC = VARS_4D%FL1(IJ, IMPHFTAIL_K, MIJ%PTR(IJ, ICHNK), ICHNK)
              VARS_4D%FL1(IJ, IMPHFTAIL_K, IMPHFTAIL_M, ICHNK) = MAX(IMPHFTAIL_TEMP2*TFAC, IMPLSCH_FLM(IJ, IMPHFTAIL_K, ICHNK))
            END DO
          END DO

          ! ----------------------------------------------------------------------


          ! =========================================


          !     UPDATE WINDSEA VARIANCE AND MEAN FREQUENCY IF PASSED TO ATMOSPHERE
          !     ------------------------------------------------------------------
          IF (LWFLUX) THEN
            IF (EMEANWS < WSEMEAN_MIN) THEN
              INTFLDS%WSEMEAN(IJ, ICHNK) = WSEMEAN_MIN
              INTFLDS%WSFMEAN(IJ, ICHNK) = 2._JWRB*FR(NFRE)
            ELSE
              INTFLDS%WSEMEAN(IJ, ICHNK) = EMEANWS
              INTFLDS%WSFMEAN(IJ, ICHNK) = IMPLSCH_FMEANWS(IJ, ICHNK)
            END IF
          END IF


          !*    2.6 SET FL1 ON ICE POINTS TO ZERO
          !         -----------------------------

          IF (LICERUN .and. LMASKICE) THEN
            ! [Loki] inlined child subroutine: SETICE
            ! =========================================
            ! ----------------------------------------------------------------------


            !*    1. SET SPECTRA TO NOISE LEVEL OVER ICE POINTS.
            !     ----------------------------------------------

            IF (FF_NOW%CICOVER(IJ, ICHNK) > CITHRSH) THEN
              CIREDUC = MAX(EPSMIN, (1.0_JWRB - FF_NOW%CICOVER(IJ, ICHNK)))
              ICEFREE = 0.0_JWRB
            ELSE
              CIREDUC = 0.0_JWRB
              ICEFREE = 1.0_JWRB
            END IF

            SETICE_TEMP = CIREDUC*FLMIN
!$acc loop seq
            DO SETICE_M=1,NFRE
!$acc loop seq
              DO SETICE_K=1,NANG
                VARS_4D%FL1(IJ, SETICE_K, SETICE_M, ICHNK) = VARS_4D%FL1(IJ, SETICE_K, SETICE_M, ICHNK)*ICEFREE +  &
                & SETICE_TEMP*MAX(0.0_JWRB, IMPLSCH_COSWDIF(IJ, SETICE_K, ICHNK))**2
              END DO
            END DO


            ! =========================================
          END IF


          !*    2.7 SURFACE STOKES DRIFT AND STRAIN IN SEA ICE
          !         ------------------------------------------

          ! [Loki] inlined child subroutine: STOKESTRN
          ! =========================================

          ! ----------------------------------------------------------------------


          ! [Loki] inlined child subroutine: STOKESDRIFT
          ! =========================================

          ! ----------------------------------------------------------------------



          !***  1. DETERMINE STOKE DRIFT VECTOR.
          !     --------------------------------

          IF (.not.LHEIGHT_ONLY .or. LWNEMOCOU) THEN
          STOKESTRN_CONST = 2.0_JWRB*DELTH*ZPI**3 / G*FR(NFRE_ODD)**4

          !***  1.1 PERFORM INTEGRATION.
          !     ------------------------

          INTFLDS%USTOKES(IJ, ICHNK) = 0.0_JWRB
          INTFLDS%VSTOKES(IJ, ICHNK) = 0.0_JWRB

!$acc loop seq
          DO STOKESTRN_M=1,NFRE_ODD
            STFAC = WVPRPT%STOKFAC(IJ, STOKESTRN_M, ICHNK)*DFIM_SIM(STOKESTRN_M)
!$acc loop seq
            DO STOKESTRN_K=1,NANG
              FAC3 = STFAC*VARS_4D%FL1(IJ, STOKESTRN_K, STOKESTRN_M, ICHNK)
              INTFLDS%USTOKES(IJ, ICHNK) = INTFLDS%USTOKES(IJ, ICHNK) + FAC3*SINTH(STOKESTRN_K)
              INTFLDS%VSTOKES(IJ, ICHNK) = INTFLDS%VSTOKES(IJ, ICHNK) + FAC3*COSTH(STOKESTRN_K)
            END DO
          END DO

          !***  1.2 ADD CONTRIBUTION OF UNRESOLVED WAVES.
          !     -----------------------------------------

!$acc loop seq
          DO STOKESTRN_K=1,NANG
            FAC1 = STOKESTRN_CONST*SINTH(STOKESTRN_K)
            FAC2 = STOKESTRN_CONST*COSTH(STOKESTRN_K)
            INTFLDS%USTOKES(IJ, ICHNK) = INTFLDS%USTOKES(IJ, ICHNK) + FAC1*VARS_4D%FL1(IJ, STOKESTRN_K, NFRE_ODD, ICHNK)
            INTFLDS%VSTOKES(IJ, ICHNK) = INTFLDS%VSTOKES(IJ, ICHNK) + FAC2*VARS_4D%FL1(IJ, STOKESTRN_K, NFRE_ODD, ICHNK)
          END DO


          !***  1.3 Sea Ice exception
          !     ---------------------
          IF (LICERUN .and. LWAMRSETCI) THEN
            IF (FF_NOW%CICOVER(IJ, ICHNK) > CITHRSH) THEN
              INTFLDS%USTOKES(IJ, ICHNK) =  &
              & 0.016_JWRB*FF_NOW%WSWAVE(IJ, ICHNK)*SIN(FF_NOW%WDWAVE(IJ, ICHNK))*(1.0_JWRB - FF_NOW%CICOVER(IJ, ICHNK))
              INTFLDS%VSTOKES(IJ, ICHNK) =  &
              & 0.016_JWRB*FF_NOW%WSWAVE(IJ, ICHNK)*COS(FF_NOW%WDWAVE(IJ, ICHNK))*(1.0_JWRB - FF_NOW%CICOVER(IJ, ICHNK))
            END IF
          END IF

          !***  1.4 Protection
          !     --------------

          INTFLDS%USTOKES(IJ, ICHNK) = MIN(MAX(INTFLDS%USTOKES(IJ, ICHNK), -STMAX), STMAX)
          INTFLDS%VSTOKES(IJ, ICHNK) = MIN(MAX(INTFLDS%VSTOKES(IJ, ICHNK), -STMAX), STMAX)


          ! =========================================

          ! [Loki] Removed content of pragma-marked region!


          IF (LWNEMOCOU .and. (LWNEMOCOUSEND .and. LWCOU .or. .not.LWCOU)) THEN
            IF (LWNEMOCOUSTK) THEN
              WAM2NEMO%NEMOUSTOKES(IJ, ICHNK) = INTFLDS%USTOKES(IJ, ICHNK)
              WAM2NEMO%NEMOVSTOKES(IJ, ICHNK) = INTFLDS%VSTOKES(IJ, ICHNK)
            ELSE
              WAM2NEMO%NEMOUSTOKES(IJ, ICHNK) = 0.0_JWRO
              WAM2NEMO%NEMOVSTOKES(IJ, ICHNK) = 0.0_JWRO
            END IF

            IF (LWNEMOCOUSTRN) WAM2NEMO%NEMOSTRN(IJ, ICHNK) = INTFLDS%STRNMS(IJ, ICHNK)
          END IF
          END IF


          ! ----------------------------------------------------------------------

          ! =========================================

          ! ----------------------------------------------------------------------



          ! =========================================
        END DO

      END DO
!$acc end parallel loop

! Complete ordered source work before timing and host synchronization.
!$acc wait(1)
!$acc end data

      TIME_PHYS = TIME_PHYS + (TIME0 + WAM_USER_CLOCK())*1.E-06
      CALL ADD_ELAPSED(ORIGINAL_TIMERS, REGION_SOURCE_TERMS, REGION_TIMER)
      IF (LHOOK) CALL DR_HOOK('IMPLSCH', 1, ZHOOK_HANDLE_IMPLSCH)

      IF (LHOOK) CALL DR_HOOK('DATA_OFFLOAD', 0, ZHOOK_HANDLE_DATA_OFFLOAD)
      CALL SYNC_HOST_RDONLY(VARS_4D, FL1=.true., QUEUE=4)
      CALL SYNC_HOST_RDONLY(FF_NOW, QUEUE=4)
      CALL SYNC_HOST_RDONLY(WVENVI, QUEUE=5)
      IF (LWNEMOCOU .and. .not.LWCOU) CALL SYNC_HOST_RDONLY(WAM2NEMO, QUEUE=6)
      IF (LHOOK) CALL DR_HOOK('DATA_OFFLOAD', 1, ZHOOK_HANDLE_DATA_OFFLOAD)

      IF (LWNEMOCOU) NEMONTAU = NEMONTAU + 1

    ELSE
      !   NO SOURCE TERM CONTRIBUTION




!$acc kernels present( MIJ,VARS_4D )




      DO ICHNK=1,NCHNK



        DO IJ=1,NPROMA_WAM
          MIJ%PTR(IJ, ICHNK) = NFRE
        END DO




        DO M=1,NFRE
          DO K=1,NANG
            DO IJ=1,NPROMA_WAM
              VARS_4D%FL1(IJ, K, M, ICHNK) = MAX(VARS_4D%FL1(IJ, K, M, ICHNK), EPSMIN)
              VARS_4D%XLLWS(IJ, K, M, ICHNK) = 0.0_JWRB
            END DO
          END DO
        END DO
      END DO




!$acc end kernels




    END IF
    CALL GSTATS(1431, 1)



    !*       UPDATE FORCING FIELDS TIME COUNTER
    !        ----------------------------------
    IF (LLNEWFILE) THEN
      LLNEWFILE = .false.
      IDELWH = MAX(IDELWI, IDELPRO)
      CALL INCDATE(CDAWIFL, IDELWH)
      CALL INCDATE(CDATEFL, IDELWH)
    END IF

    CDATEWO = CDATEWH
    CDTIMP = CDTIMPNEXT
    CALL INCDATE(CDTIMPNEXT, IDELT)

  END IF

  IF (LHOOK) CALL DR_HOOK('WAMINTGR', 1, ZHOOK_HANDLE)


!$acc exit data delete( IMPLSCH_DELFL, IMPLSCH_EMEAN, IMPLSCH_FMEAN, IMPLSCH_FMEANWS, IMPLSCH_F1MEAN, IMPLSCH_AKMEAN,  &
!$acc & IMPLSCH_XKMEAN, IMPLSCH_PHIWA, IMPLSCH_FLM, IMPLSCH_COSWDIF, IMPLSCH_SINWDIF2, IMPLSCH_RHOWGDFTH,  &
!$acc & IMPLSCH_FLD, IMPLSCH_SL, IMPLSCH_SPOS, IMPLSCH_SSOURCE, IMPLSCH_SLICE, IMPLSCH_ALPFAC, IMPLSCH_TEMPA, IMPLSCH_TEMPX,  &
!$acc & IMPLSCH_TEMP2, IMPLSCH_WD, IMPLSCH_FLWD, IMPLSCH_FD, IMPLSCH_GAM0, IMPLSCH_DSTAB, IMPLSCH_COSLP, IMPLSCH_FACSAT,  &
!$acc & IMPLSCH_FACWTRB, IMPLSCH_SDISSIP_TEMP1, IMPLSCH_BTH0, IMPLSCH_C_, IMPLSCH_C_C, IMPLSCH_DSIP, IMPLSCH_TRPZ_DSIP,  &
!$acc & IMPLSCH_BTH, IMPLSCH_SDISSIP_TEMP2, IMPLSCH_D, IMPLSCH_SCUMUL, IMPLSCH_RENEWALFREQ, IMPLSCH_WCUMUL, IMPLSCH_ALP,  &
!$acc & IMPLSCH_XK2, IMPLSCH_SDICE3_ALP, SNONLIN_ENH )

END SUBROUTINE WAMINTGR_LOKI_GPU
