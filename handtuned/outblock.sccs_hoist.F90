    INTEGER(KIND=JWIM), INTENT(INOUT) :: FNDPRT_KLOC(3*NANG)
    REAL(KIND=JWRB), INTENT(INOUT) :: FNDPRT_W2(NANG, NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: FNDPRT_W1(KIJL, NANG, NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: FNDPRT_SPEC(NANG, NFRE, MERGE(NPMAX, 1, LLPARTITION), KIJL)
    LOGICAL, INTENT(INOUT) :: FNDPRT_LLW3(KIJL, NANG, NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_F1D(NFRE)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_TEMP(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_SI(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_CI(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_EM(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_FM(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: PARMEAN_THQ(NPMAX)
    REAL(KIND=JWRB), INTENT(INOUT) :: WDIRSPREAD_F1D(KIJL, NFRE)
!$acc data present( MIJ, FL1, XLLWS, WAVNUM, CINV, DEPTH, UCUR, VCUR, IODP, WDWAVE, CICOVER, WSWAVE, UFRIC, TAUW, Z0B, CHRNCK,  &
!$acc & BOUT, EM, FM, DP, C3, C4, BF, QP, HMAX, TMAX, ETA_M, R, XNSLC, SIG_TH, EPS, XNU, ESWELL, FSWELL, THSWELL, P1SWELL,  &
!$acc & P2SWELL, SPRDSWELL, ESEA, FSEA, THWISEA, P1SEA, P2SEA, SPRDSEA, CHARNOCK, BETAHQ, CDATM, EMTRAIN, THTRAIN, PMTRAIN,  &
!$acc & COSWDIF, FL2ND, CAL_SECOND_ORDER_SPEC_EMEAN, CAL_SECOND_ORDER_SPEC_FMEAN, CAL_SECOND_ORDER_SPEC_F1MEAN,  &
!$acc & CAL_SECOND_ORDER_SPEC_AKMEAN, CAL_SECOND_ORDER_SPEC_XKMEAN, CAL_SECOND_ORDER_SPEC_F3, CAL_SECOND_ORDER_SPEC_PF1,  &
!$acc & CAL_SECOND_ORDER_SPEC_PF3, SECSPOM_LL, SECSPOM_OMEGA_EXT, SECSPOM_F2, INTPOL_DFTH, KURTOSIS_FAC4, KURTOSIS_HMAXN,  &
!$acc & KURTOSIS_SUM0, KURTOSIS_SUM1, KURTOSIS_XKP, KURTOSIS_SIG_HM, KURTOSIS_F_M, KURTOSIS_AA, KURTOSIS_BB, KURTOSIS_C4_DYN,  &
!$acc & KURTOSIS_C4_B, KURTOSIS_FF, DOMINANT_PERIOD_F1D4, SEPWISW_XINVWVAGE, SEPWISW_DIRCOEF, SEPWISW_SWM, SEPWISW_F1,  &
!$acc & SEP3TR_NPEAK, SEP3TR_FRINVMIJ, SEP3TR_NFRP, SEP3TR_NTHP, SEP3TR_SUMENE, SEP3TR_ETT, SEP3TR_ENMAX, SEP3TR_FLNOISE,  &
!$acc & SEP3TR_EUNASNG, SEP3TR_FUNASNG, SEP3TR_THUNASNG, SEP3TR_SPRD, SEP3TR_DIR, SEP3TR_PER, SEP3TR_ENE, SEP3TR_FL,  &
!$acc & SEP3TR_FLLOW, SEP3TR_SUNASGN, SEP3TR_LLCOSDIFF, FNDPRT_KLOC, FNDPRT_W2, FNDPRT_W1, FNDPRT_SPEC, FNDPRT_LLW3,  &
!$acc & PARMEAN_F1D, PARMEAN_TEMP, PARMEAN_SI, PARMEAN_CI, PARMEAN_EM, PARMEAN_FM, PARMEAN_THQ, WDIRSPREAD_F1D )

    ! ----------------------------------------------------------------------


    !
    !*    1. COMPUTE MEAN PARAMETERS.
    !        ------------------------

    !     PREPARE THE WAVE SPECTRA THAT SHOULD BE USED FOR OUTPUT

    LLPEAKF = .false.

    IRA = 1
    SIG = 1._JWRB
    GOZPI = G / ZPI

    BOUT(IJ, :) = 0._JWRB
    IF (IREFRA == 2 .or. IREFRA == 3) THEN
      CALL INTPOL_LOKI(KIJS, KIJL, FL1, FL2ND, WAVNUM, UCUR, VCUR, IRA, IJ=IJ, DFTH=INTPOL_DFTH)
    ELSE
!$acc loop seq
      DO M=1,NFRE
!$acc loop seq
        DO K=1,NANG
          FL2ND(IJ, K, M) = FL1(IJ, K, M)
        END DO
      END DO
    END IF
    IF (LSECONDORDER) CALL CAL_SECOND_ORDER_SPEC_LOKI(KIJS, KIJL, FL2ND, WAVNUM, DEPTH, SIG, IJ=IJ,  &
    & EMEAN=CAL_SECOND_ORDER_SPEC_EMEAN,   FMEAN=CAL_SECOND_ORDER_SPEC_FMEAN, F1MEAN=CAL_SECOND_ORDER_SPEC_F1MEAN,  &
    & AKMEAN=CAL_SECOND_ORDER_SPEC_AKMEAN,   XKMEAN=CAL_SECOND_ORDER_SPEC_XKMEAN, F3=CAL_SECOND_ORDER_SPEC_F3,  &
    & PF1=CAL_SECOND_ORDER_SPEC_PF1,   PF3=CAL_SECOND_ORDER_SPEC_PF3, SECSPOM_LL=SECSPOM_LL, SECSPOM_OMEGA_EXT=SECSPOM_OMEGA_EXT, &
    &  SECSPOM_F2=SECSPOM_F2)

    ! Adapting the noise level structure to be more consistent in sea ice conditions
    IF (LICERUN .and. .not.LMASKICE) THEN
      ZTHRS = (1._JWRB - 0.9_JWRB*MIN(CICOVER(IJ), 0.99_JWRB))*FLMIN

!$acc loop seq
      DO M=1,NFRE
        ZRDUC = EXP(-10.0_JWRB*FR(M)**2 / SQRT(MAX(WSWAVE(IJ), 1.0_JWRB)))

!$acc loop seq
        DO K=1,NANG
          IF (FL2ND(IJ, K, M) <= ZTHRS) THEN
            FL2ND(IJ, K, M) = MAX(ZRDUC*FL2ND(IJ, K, M), ZTHRS*ZRDUC**2)
          END IF
        END DO
      END DO
    END IF

    !     COMPUTE MEAN PARAMETERS

    IF (NIPRMOUT /= 1 .OR. IPFGTBL(1) == 0) THEN
!$acc loop seq
      DO K=1,NANG
        COSWDIF(IJ, K) = COS(TH(K) - WDWAVE(IJ))
      END DO
    END IF

    CALL FEMEAN_LOKI(KIJS, KIJL, FL2ND, EM, FM, IJ=IJ)

    ! Significant wave height needs the integrated energy above, but not
    ! period, extreme-wave or wind/swell partition diagnostics.
    IF (NIPRMOUT /= 1 .OR. IPFGTBL(1) == 0) THEN
      CALL DOMINANT_PERIOD_LOKI(KIJS, KIJL, FL2ND, DP, IJ=IJ, F1D4=DOMINANT_PERIOD_F1D4)

    CALL KURTOSIS_LOKI(KIJS, KIJL, FL1, DEPTH, C3, C4, BF, QP, HMAX, TMAX, ETA_M, R, XNSLC, SIG_TH, EPS, XNU, IJ=IJ,  &
    & FAC4=KURTOSIS_FAC4, HMAXN=KURTOSIS_HMAXN, SUM0=KURTOSIS_SUM0, SUM1=KURTOSIS_SUM1, XKP=KURTOSIS_XKP,  &
    & SIG_HM=KURTOSIS_SIG_HM, F_M=KURTOSIS_F_M, AA=KURTOSIS_AA, BB=KURTOSIS_BB, C4_DYN=KURTOSIS_C4_DYN, C4_B=KURTOSIS_C4_B,  &
    & FF=KURTOSIS_FF)

    !     WIND/SWELL PARAMETERS
    CALL SEPWISW_LOKI(KIJS, KIJL, MIJ, FL1, XLLWS, CINV, UFRIC, WDWAVE, COSWDIF, ESWELL, FSWELL, THSWELL, P1SWELL, P2SWELL,  &
    & SPRDSWELL, ESEA, FSEA, THWISEA, P1SEA, P2SEA, SPRDSEA, EMTRAIN, THTRAIN, PMTRAIN, IJ=IJ, XINVWVAGE=SEPWISW_XINVWVAGE,  &
    & DIRCOEF=SEPWISW_DIRCOEF, SWM=SEPWISW_SWM, F1=SEPWISW_F1, SEP3TR_NPEAK=SEP3TR_NPEAK, SEP3TR_FRINVMIJ=SEP3TR_FRINVMIJ,  &
    & SEP3TR_NFRP=SEP3TR_NFRP, SEP3TR_NTHP=SEP3TR_NTHP, SEP3TR_SUMENE=SEP3TR_SUMENE, SEP3TR_ETT=SEP3TR_ETT,  &
    & SEP3TR_ENMAX=SEP3TR_ENMAX, SEP3TR_FLNOISE=SEP3TR_FLNOISE, SEP3TR_EUNASNG=SEP3TR_EUNASNG, SEP3TR_FUNASNG=SEP3TR_FUNASNG,  &
    & SEP3TR_THUNASNG=SEP3TR_THUNASNG, SEP3TR_SPRD=SEP3TR_SPRD, SEP3TR_DIR=SEP3TR_DIR, SEP3TR_PER=SEP3TR_PER,  &
    & SEP3TR_ENE=SEP3TR_ENE, SEP3TR_FL=SEP3TR_FL, SEP3TR_FLLOW=SEP3TR_FLLOW, SEP3TR_SUNASGN=SEP3TR_SUNASGN,  &
    & SEP3TR_LLCOSDIFF=SEP3TR_LLCOSDIFF, FNDPRT_KLOC=FNDPRT_KLOC, FNDPRT_W2=FNDPRT_W2, FNDPRT_W1=FNDPRT_W1,  &
    & FNDPRT_SPEC=FNDPRT_SPEC, FNDPRT_LLW3=FNDPRT_LLW3, PARMEAN_F1D=PARMEAN_F1D, PARMEAN_TEMP=PARMEAN_TEMP,  &
    & PARMEAN_SI=PARMEAN_SI, PARMEAN_CI=PARMEAN_CI, PARMEAN_EM=PARMEAN_EM, PARMEAN_FM=PARMEAN_FM, PARMEAN_THQ=PARMEAN_THQ,  &
    & WDIRSPREAD_F1D=WDIRSPREAD_F1D)
    END IF


    !     LOAD THE OUTPUT BUFFER:

    IF (IPFGTBL(1) /= 0) THEN
      !       SIGNIFICANT WAVE HEIGHT CONVERSION
      BOUT(IJ, ITOBOUT(1)) = 4._JWRB*SQRT(MAX(EM(IJ), 0._JWRB))
    END IF

    IF (IPFGTBL(2) /= 0) THEN
      ITG = ITOBOUT(2)
      CALL STHQ_LOKI(KIJS, KIJL, FL2ND, BOUT(KIJS:KIJL, ITG), IJ=IJ)
      !       CONVERT DIRECTIONS TO DEGREES AND METEOROLOGICAL CONVENTION
      BOUT(IJ, ITG) = MOD(DEG*BOUT(IJ, ITG) + 180._JWRB, 360._JWRB)
    END IF

    IF (IPFGTBL(3) /= 0) THEN
      !       CONVERSION TO PERIOD
      IF (FM(IJ) > 0._JWRB) THEN
        BOUT(IJ, ITOBOUT(3)) = 1._JWRB / FM(IJ)
      ELSE
        BOUT(IJ, ITOBOUT(3)) = ZMISS
      END IF
    END IF

    IF (IPFGTBL(4) /= 0) THEN
      BOUT(IJ, ITOBOUT(4)) = UFRIC(IJ)
    END IF

    IF (IPFGTBL(5) /= 0) THEN
      !       CONVERT DIRECTIONS TO DEGREES AND METEOROLOGICAL CONVENTION
      BOUT(IJ, ITOBOUT(5)) = MOD(DEG*WDWAVE(IJ) + 180._JWRB, 360._JWRB)
    END IF

    IF (IPFGTBL(6) /= 0) THEN
      !       CONVERSION TO PERIOD
      IF (DP(IJ) > 0.0_JWRB) THEN
        BOUT(IJ, ITOBOUT(6)) = DP(IJ)
      ELSE
        BOUT(IJ, ITOBOUT(6)) = ZMISS
      END IF
    END IF

    IF (IPFGTBL(7) /= 0) THEN
      !!      if the numerical computation of TAU and CD changes, a similar
      !!      modification has to be put in buildstress where the friction
      !!      velocity is determined from U10 and CD.
      !!      Because of the limited numerical resolution when encoding in grib, the maximum value for Cd is set to 0.01
      !!!!!!!!!!        BOUT(KIJS:KIJL,ITOBOUT(IR))=MIN(MAX(UFRIC(KIJS:KIJL)**2,EPSUS)/MAX(WSWAVE(KIJS:KIJL)**2,EPSU10**2), 0.01_JWRB)
      !!! output the drag coeffient that is consistent with the Charnock parameter that is returned to the atmosphere model:
      CALL OUTBETA_LOKI(KIJS, KIJL, WSWAVE, UFRIC, Z0B, CHRNCK, CHARNOCK, BETAHQ, CD=CDATM, IJ=IJ)

      BOUT(IJ, ITOBOUT(7)) = MIN(CDATM(IJ), 0.01_JWRB)
    END IF

    IF (IPFGTBL(8) /= 0) THEN
      BOUT(IJ, ITOBOUT(8)) = TAUW(IJ) / MAX(UFRIC(IJ)**2, EPSUS)
    END IF

    ! [Loki] Removed content of pragma-marked region!

    IF (IPFGTBL(10) /= 0) THEN
      BOUT(IJ, ITOBOUT(10)) = WSWAVE(IJ)
    END IF

    ! [Loki] Removed content of pragma-marked region!



    !     APPLY SEA ICE MASK AND SEA MASK IF NECESSARY
    CALL OUTSETWMASK_LOKI(KIJS, KIJL, IODP, CICOVER, BOUT, IJ=IJ)



!$acc end data
  END SUBROUTINE OUTBLOCK_LOKI
END MODULE OUTBLOCK_LOKI_MOD
