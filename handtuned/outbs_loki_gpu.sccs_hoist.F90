SUBROUTINE OUTBS_LOKI_GPU (MIJ, FL1, XLLWS, WVPRPT, WVENVI, FF_NOW, INTFLDS, NEMO2WAM, BOUT)
  ! ----------------------------------------------------------------------

  !**** *OUTBS* - MODEL OUTPUT FROM BLOCK TO FILE, PRINTER AND COMMON.

  !*    PURPOSE.
  !     --------

  !       CONTROL OUTPUT OF WAVE AND WIND FIELDS (except spectrum).

  !**   INTERFACE.
  !     ----------
  !      *CALL*OUTBS (MIJ, FL1, XLLWS,
  !                   WVPRPT, WVENVI, FF_NOW, INTFLDS, NEMO2WAM, BOUT)
  !      *MIJ*     - LAST FREQUENCY INDEX OF THE PROGNOSTIC RANGE.
  !      *FL1*     - INPUT SPECTRUM.
  !      *XLLWS*   - WINDSEA MASK FROM INPUT SOURCE TERM
  !      *WVENVI*  - WAVE ENVIRONMENT (depth, currents,...)
  !      *FF_NOW*  - FORCING FIELDS
  !      *INTFLDS* - INTEGRATED/DERIVED PARAMETERS
  !      *NEMO2WAM*- FIELDS FRON OCEAN MODEL to WAM
  !      *BOUT*    - OUTPUT PARAMETERS BUFFER



  !     EXTERNALS.
  !     ----------

  !       *OUTBLOCK*  - GET ALL OUTPUT PARAMETERS
  !
  !     METHOD.
  !     -------

  !       NONE.

  !     REFERENCE.
  !     ----------

  !       NONE.

  ! ----------------------------------------------------------------------
  USE OUTBLOCK_LOKI_MOD, ONLY: OUTBLOCK_LOKI
  USE INTPOL_LOKI_MOD, ONLY: INTPOL_LOKI
  USE FEMEAN_LOKI_MOD, ONLY: FEMEAN_LOKI
  USE OUTSETWMASK_LOKI_MOD, ONLY: OUTSETWMASK_LOKI
  ![Loki::HoistVariablesTransformation] -------- Added hoisted temporary size imports -------------------------------
  USE YOWPCONS, ONLY: NPMAX
  USE YOWCOUT, ONLY: NTRAIN
  ![Loki::HoistVariablesTransformation] ---------------------------------------
  ![Loki::GlobalVarOffloadTransformation] -------- Added global variable imports for offload directives -----------
  USE yowmap, ONLY: LCLDOMAIN
  USE yowcoup, ONLY: LLGCBZ0
  USE yowpcons, ONLY: ZPISQRT, ZPI, G, DEG, GM1, ZMISS, PI
  USE yowparam, ONLY: NFRE_ODD
  USE yowcout, ONLY: IPFGTBL, LSECONDORDER, LLPARTITION, IPRMINFO, ITOBOUT
  USE yowstat, ONLY: LLSOURCE, IREFRA
  USE yowfred, ONLY: TH, DFIMFR_SIM, DFIMOFR, FLOGSPRDM1, DFIMFR, FR5, DFIMFR2_SIM, DFIMFR2, DELTH, DFIM_SIM, COSTH, DFIM, FR,  &
  & SINTH
  USE yowice, ONLY: CITHRSH, LMASKICE, LICERUN
  USE yowtabl, ONLY: IM_P, IM_M, TT_4M, TA, MA, NFREH, TB, NMAX, NANGH, TC_QL, MR, OMEGA, TT_4P
  USE yowshal, ONLY: DEPTHD, DEPTHA, NDEPTH
  USE yowphys, ONLY: ALPHAMIN, ALPHA, RNUM
  ![Loki::GlobalVarOffloadTransformation] ---------------------------------------
  USE PARKIND_WAVE, ONLY: JWIM, JWRB, JWRU
  USE YOWDRVTYPE, ONLY: ENVIRONMENT, FREQUENCY, FORCING_FIELDS, INTGT_PARAM_FIELDS, OCEAN2WAVE

  USE YOWCOUT, ONLY: JPPFLAG, NIPRMOUT
  USE YOWCOUP, ONLY: LLNORMWAMOUT
  USE YOWGRID, ONLY: NPROMA_WAM, NCHNK
  USE YOWPARAM, ONLY: NANG, NFRE
  USE YOWSTAT, ONLY: LUPDATE_GPU_GLOBALS_OUTBS

  USE YOMHOOK, ONLY: LHOOK, DR_HOOK, JPHOOK

  ! ----------------------------------------------------------------------
  IMPLICIT NONE
  INTEGER(KIND=JWIM), INTENT(IN), DIMENSION(NPROMA_WAM, NCHNK) :: MIJ
  REAL(KIND=JWRB), INTENT(IN), DIMENSION(NPROMA_WAM, NANG, NFRE, NCHNK) :: FL1
  REAL(KIND=JWRB), INTENT(IN), DIMENSION(NPROMA_WAM, NANG, NFRE, NCHNK) :: XLLWS
  TYPE(FREQUENCY), INTENT(IN) :: WVPRPT
  TYPE(ENVIRONMENT), INTENT(IN) :: WVENVI
  TYPE(FORCING_FIELDS), INTENT(IN) :: FF_NOW
  TYPE(INTGT_PARAM_FIELDS), INTENT(IN) :: INTFLDS
  TYPE(OCEAN2WAVE), INTENT(IN) :: NEMO2WAM
  REAL(KIND=JWRB), POINTER, CONTIGUOUS, INTENT(INOUT) :: BOUT(:, :, :)


  INTEGER(KIND=JWIM) :: ICHNK

  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE, ZHOOK_HANDLE_DATA_OFFLOAD

  LOGICAL :: LDREPROD
  LOGICAL :: LHEIGHT_ONLY
  INTEGER :: IJ
  REAL(KIND=JWRB) :: OUTBLOCK_EM(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_FM(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_DP(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_C3(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_C4(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_BF(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_QP(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_HMAX(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_TMAX(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_ETA_M(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_R(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_XNSLC(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_SIG_TH(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_EPS(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_XNU(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_ESWELL(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_FSWELL(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_THSWELL(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_P1SWELL(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_P2SWELL(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_SPRDSWELL(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_ESEA(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_FSEA(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_THWISEA(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_P1SEA(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_P2SEA(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_SPRDSEA(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_CHARNOCK(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_BETAHQ(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_CDATM(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_EMTRAIN(NPROMA_WAM, NTRAIN, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_THTRAIN(NPROMA_WAM, NTRAIN, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_PMTRAIN(NPROMA_WAM, NTRAIN, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_COSWDIF(NPROMA_WAM, NANG, NCHNK)
  REAL(KIND=JWRB) :: OUTBLOCK_FL2ND(NPROMA_WAM, NANG, NFRE, NCHNK)
  REAL(KIND=JWRB) :: CAL_SECOND_ORDER_SPEC_EMEAN(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: CAL_SECOND_ORDER_SPEC_FMEAN(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: CAL_SECOND_ORDER_SPEC_F1MEAN(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: CAL_SECOND_ORDER_SPEC_AKMEAN(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: CAL_SECOND_ORDER_SPEC_XKMEAN(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: CAL_SECOND_ORDER_SPEC_F3(NPROMA_WAM, NANG, NFRE, NCHNK)
  REAL(KIND=JWRB) :: CAL_SECOND_ORDER_SPEC_PF1(NPROMA_WAM, NANGH, NFREH, NCHNK)
  REAL(KIND=JWRB) :: CAL_SECOND_ORDER_SPEC_PF3(NPROMA_WAM, NANGH, NFREH, NCHNK)
  INTEGER(KIND=JWIM) :: SECSPOM_LL(NANGH, NANGH, NCHNK)
  REAL(KIND=JWRB) :: SECSPOM_OMEGA_EXT(NMAX, NCHNK)
  REAL(KIND=JWRB) :: SECSPOM_F2(NPROMA_WAM, NANGH, NMAX, NCHNK)
  REAL(KIND=JWRB) :: INTPOL_DFTH(NFRE, NCHNK)
  REAL(KIND=JWRB) :: KURTOSIS_FAC4(NFRE, NCHNK)
  REAL(KIND=JWRB) :: KURTOSIS_HMAXN(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: KURTOSIS_SUM0(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: KURTOSIS_SUM1(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: KURTOSIS_XKP(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: KURTOSIS_SIG_HM(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: KURTOSIS_F_M(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: KURTOSIS_AA(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: KURTOSIS_BB(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: KURTOSIS_C4_DYN(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: KURTOSIS_C4_B(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: KURTOSIS_FF(NPROMA_WAM, NFRE, NCHNK)
  REAL(KIND=JWRB) :: DOMINANT_PERIOD_F1D4(NPROMA_WAM, NFRE, NCHNK)
  REAL(KIND=JWRB) :: SEPWISW_XINVWVAGE(NPROMA_WAM, NFRE, NCHNK)
  REAL(KIND=JWRB) :: SEPWISW_DIRCOEF(NPROMA_WAM, NANG, NCHNK)
  REAL(KIND=JWRB) :: SEPWISW_SWM(NPROMA_WAM, NANG, NFRE, NCHNK)
  REAL(KIND=JWRB) :: SEPWISW_F1(NPROMA_WAM, NANG, NFRE, NCHNK)
  INTEGER(KIND=JWIM) :: SEP3TR_NPEAK(NPROMA_WAM, NCHNK)
  INTEGER(KIND=JWIM) :: SEP3TR_FRINVMIJ(NPROMA_WAM, NCHNK)
  INTEGER(KIND=JWIM) :: SEP3TR_NFRP(NPROMA_WAM, NPMAX, NCHNK)
  INTEGER(KIND=JWIM) :: SEP3TR_NTHP(NPROMA_WAM, NPMAX, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_SUMENE(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_ETT(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_ENMAX(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_FLNOISE(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_EUNASNG(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_FUNASNG(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_THUNASNG(NPROMA_WAM, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_SPRD(NPROMA_WAM, NANG, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_DIR(NPROMA_WAM, 0:NPMAX, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_PER(NPROMA_WAM, 0:NPMAX, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_ENE(NPROMA_WAM, 0:NPMAX, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_FL(NPROMA_WAM, NANG, NFRE, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_FLLOW(NPROMA_WAM, NANG, NFRE, NCHNK)
  REAL(KIND=JWRB) :: SEP3TR_SUNASGN(NPROMA_WAM, NANG, NFRE, NCHNK)
  LOGICAL :: SEP3TR_LLCOSDIFF(NPROMA_WAM, NANG, NCHNK)
  INTEGER(KIND=JWIM) :: FNDPRT_KLOC(3*NANG, NCHNK)
  REAL(KIND=JWRB) :: FNDPRT_W2(NANG, NFRE, NCHNK)
  REAL(KIND=JWRB) :: FNDPRT_W1(NPROMA_WAM, NANG, NFRE, NCHNK)
  REAL(KIND=JWRB) :: FNDPRT_SPEC(NANG, NFRE, MERGE(NPMAX, 1, LLPARTITION), NPROMA_WAM, NCHNK)
  LOGICAL :: FNDPRT_LLW3(NPROMA_WAM, NANG, NFRE, NCHNK)
  REAL(KIND=JWRB) :: PARMEAN_F1D(NFRE, NCHNK)
  REAL(KIND=JWRB) :: PARMEAN_TEMP(NPMAX, NCHNK)
  REAL(KIND=JWRB) :: PARMEAN_SI(NPMAX, NCHNK)
  REAL(KIND=JWRB) :: PARMEAN_CI(NPMAX, NCHNK)
  REAL(KIND=JWRB) :: PARMEAN_EM(NPMAX, NCHNK)
  REAL(KIND=JWRB) :: PARMEAN_FM(NPMAX, NCHNK)
  REAL(KIND=JWRB) :: PARMEAN_THQ(NPMAX, NCHNK)
  REAL(KIND=JWRB) :: WDIRSPREAD_F1D(NPROMA_WAM, NFRE, NCHNK)

  LHEIGHT_ONLY = NIPRMOUT == 1 .AND. IPFGTBL(1) /= 0 .AND. .NOT.LSECONDORDER .AND. (.NOT.LICERUN .OR. LMASKICE)
  IF (LHEIGHT_ONLY) THEN
!$acc enter data create( OUTBLOCK_EM, OUTBLOCK_FM, OUTBLOCK_FL2ND, INTPOL_DFTH )
  ELSE
!$acc enter data create( OUTBLOCK_EM, OUTBLOCK_FM, OUTBLOCK_DP, OUTBLOCK_C3, OUTBLOCK_C4, OUTBLOCK_BF, OUTBLOCK_QP,  &
!$acc & OUTBLOCK_HMAX, OUTBLOCK_TMAX, OUTBLOCK_ETA_M, OUTBLOCK_R, OUTBLOCK_XNSLC, OUTBLOCK_SIG_TH, OUTBLOCK_EPS, OUTBLOCK_XNU,  &
!$acc & OUTBLOCK_ESWELL, OUTBLOCK_FSWELL, OUTBLOCK_THSWELL, OUTBLOCK_P1SWELL, OUTBLOCK_P2SWELL, OUTBLOCK_SPRDSWELL,  &
!$acc & OUTBLOCK_ESEA, OUTBLOCK_FSEA, OUTBLOCK_THWISEA, OUTBLOCK_P1SEA, OUTBLOCK_P2SEA, OUTBLOCK_SPRDSEA, OUTBLOCK_CHARNOCK,  &
!$acc & OUTBLOCK_BETAHQ, OUTBLOCK_CDATM, OUTBLOCK_EMTRAIN, OUTBLOCK_THTRAIN, OUTBLOCK_PMTRAIN, OUTBLOCK_COSWDIF, OUTBLOCK_FL2ND,  &
!$acc & CAL_SECOND_ORDER_SPEC_EMEAN, CAL_SECOND_ORDER_SPEC_FMEAN, CAL_SECOND_ORDER_SPEC_F1MEAN, CAL_SECOND_ORDER_SPEC_AKMEAN,  &
!$acc & CAL_SECOND_ORDER_SPEC_XKMEAN, CAL_SECOND_ORDER_SPEC_F3, CAL_SECOND_ORDER_SPEC_PF1, CAL_SECOND_ORDER_SPEC_PF3,  &
!$acc & SECSPOM_LL, SECSPOM_OMEGA_EXT, SECSPOM_F2, INTPOL_DFTH, KURTOSIS_FAC4, KURTOSIS_HMAXN, KURTOSIS_SUM0, KURTOSIS_SUM1,  &
!$acc & KURTOSIS_XKP, KURTOSIS_SIG_HM, KURTOSIS_F_M, KURTOSIS_AA, KURTOSIS_BB, KURTOSIS_C4_DYN, KURTOSIS_C4_B, KURTOSIS_FF,  &
!$acc & DOMINANT_PERIOD_F1D4, SEPWISW_XINVWVAGE, SEPWISW_DIRCOEF, SEPWISW_SWM, SEPWISW_F1, SEP3TR_NPEAK, SEP3TR_FRINVMIJ,  &
!$acc & SEP3TR_NFRP, SEP3TR_NTHP, SEP3TR_SUMENE, SEP3TR_ETT, SEP3TR_ENMAX, SEP3TR_FLNOISE, SEP3TR_EUNASNG, SEP3TR_FUNASNG,  &
!$acc & SEP3TR_THUNASNG, SEP3TR_SPRD, SEP3TR_DIR, SEP3TR_PER, SEP3TR_ENE, SEP3TR_FL, SEP3TR_FLLOW, SEP3TR_SUNASGN,  &
!$acc & SEP3TR_LLCOSDIFF, FNDPRT_KLOC, FNDPRT_W2, FNDPRT_W1, FNDPRT_SPEC, FNDPRT_LLW3, PARMEAN_F1D, PARMEAN_TEMP, PARMEAN_SI,  &
!$acc & PARMEAN_CI, PARMEAN_EM, PARMEAN_FM, PARMEAN_THQ, WDIRSPREAD_F1D )
  END IF


  ! ----------------------------------------------------------------------


  !*    1. COMPUTE MEAN PARAMETERS.
  !        ------------------------

  IF (LHOOK) CALL DR_HOOK('DATA_OFFLOAD', 0, ZHOOK_HANDLE_DATA_OFFLOAD)
!$loki stack-insert
  !     COMPUTE MEAN PARAMETERS
  IF (LUPDATE_GPU_GLOBALS_OUTBS) THEN
!$acc update device( ALPHAMIN, CITHRSH, ZPI, LSECONDORDER, TH, TA, LICERUN, NFREH, NFRE_ODD, DEPTHA, DFIM_SIM, LMASKICE, COSTH,  &
!$acc & TC_QL, DEG, FR, LLSOURCE, PI, TT_4P, NIPRMOUT, ITOBOUT, IM_P, IM_M, NANG, TT_4M, LCLDOMAIN, DFIMFR_SIM, ZMISS,  &
!$acc & FLOGSPRDM1, DEPTHD, TB, DFIMFR2_SIM, NANGH, NFRE, IPRMINFO, OMEGA, IREFRA, RNUM, ZPISQRT, LLPARTITION, DFIMOFR, DFIMFR,  &
!$acc & G, MR, GM1, MA, NDEPTH, LLGCBZ0, FR5, NMAX, IPFGTBL, DELTH, DFIMFR2, DFIM, ALPHA, SINTH )
!$loki omp-update-global-vars in( ALPHAMIN, CITHRSH, ZPI, LSECONDORDER, TH, TA, LICERUN, NFREH, NFRE_ODD, DEPTHA, DFIM_SIM,  &
!$loki & LMASKICE, COSTH, TC_QL, DEG, FR, LLSOURCE, PI, TT_4P, NIPRMOUT, ITOBOUT, IM_P, IM_M, NANG, TT_4M, LCLDOMAIN,  &
!$loki & DFIMFR_SIM, ZMISS, FLOGSPRDM1, DEPTHD, TB, DFIMFR2_SIM, NANGH, NFRE, IPRMINFO, OMEGA, IREFRA, RNUM, ZPISQRT,  &
!$loki & LLPARTITION, DFIMOFR, DFIMFR, G, MR, GM1, MA, NDEPTH, LLGCBZ0, FR5, NMAX, IPFGTBL, DELTH, DFIMFR2, DFIM, ALPHA, SINTH )
  END IF
  IF (LHOOK) CALL DR_HOOK('DATA_OFFLOAD', 1, ZHOOK_HANDLE_DATA_OFFLOAD)

  IF (LHOOK) CALL DR_HOOK('OUTBS', 0, ZHOOK_HANDLE)
  CALL GSTATS(1502, 0)
!$acc data present( MIJ,WVPRPT,WVENVI,INTFLDS,FF_NOW,BOUT )

  ! The height-only path needs interpolation, energy integration and the
  ! output mask. Second-order and ice-noise adjustments use full OUTBLOCK.
  IF (LHEIGHT_ONLY) THEN
!$acc parallel loop gang vector_length( NPROMA_WAM )
    DO ICHNK=1,NCHNK
!$acc loop vector
      DO IJ=1,NPROMA_WAM
        BOUT(IJ, 1, ICHNK) = 0.0_JWRB
        ! At zero current the moving and absolute frequency grids coincide.
        IF ((IREFRA == 2 .OR. IREFRA == 3) .AND. &
            (WVENVI%UCUR(IJ, ICHNK) /= 0.0_JWRB .OR. WVENVI%VCUR(IJ, ICHNK) /= 0.0_JWRB)) THEN
          CALL INTPOL_LOKI(1, NPROMA_WAM, FL1(:, :, :, ICHNK), OUTBLOCK_FL2ND(:, :, :, ICHNK), &
            WVPRPT%WAVNUM(:, :, ICHNK), WVENVI%UCUR(:, ICHNK), WVENVI%VCUR(:, ICHNK), 1, IJ=IJ, &
            DFTH=INTPOL_DFTH(:, ICHNK))
          CALL FEMEAN_LOKI(1, NPROMA_WAM, OUTBLOCK_FL2ND(:, :, :, ICHNK), OUTBLOCK_EM(:, ICHNK), &
            OUTBLOCK_FM(:, ICHNK), IJ=IJ)
        ELSE
          CALL FEMEAN_LOKI(1, NPROMA_WAM, FL1(:, :, :, ICHNK), OUTBLOCK_EM(:, ICHNK), &
            OUTBLOCK_FM(:, ICHNK), IJ=IJ)
        END IF
        BOUT(IJ, ITOBOUT(1), ICHNK) = 4._JWRB*SQRT(MAX(OUTBLOCK_EM(IJ, ICHNK), 0._JWRB))
        CALL OUTSETWMASK_LOKI(1, NPROMA_WAM, WVENVI%IODP(:, ICHNK), FF_NOW%CICOVER(:, ICHNK), &
          BOUT(:, :, ICHNK), IJ=IJ)
      END DO
    END DO
!$acc end parallel loop
  ELSE
!$acc parallel loop gang vector_length( NPROMA_WAM )
  DO ICHNK=1,NCHNK

!$acc loop vector
    DO IJ=1,NPROMA_WAM
      CALL OUTBLOCK_LOKI(1, NPROMA_WAM, MIJ(:, ICHNK), FL1(:, :, :, ICHNK), XLLWS(:, :, :, ICHNK), WVPRPT%WAVNUM(:, :, ICHNK),  &
      & WVPRPT%CINV(:, :, ICHNK), WVENVI%DEPTH(:, ICHNK), WVENVI%UCUR(:, ICHNK), WVENVI%VCUR(:, ICHNK), WVENVI%IODP(:, ICHNK),  &
      & FF_NOW%WDWAVE(:, ICHNK), FF_NOW%CICOVER(:, ICHNK), FF_NOW%WSWAVE(:, ICHNK), FF_NOW%UFRIC(:, ICHNK),  &
      & FF_NOW%TAUW(:, ICHNK), FF_NOW%Z0B(:, ICHNK), FF_NOW%CHRNCK(:, ICHNK), BOUT(:, :, ICHNK), IJ=IJ,  &
      & EM=OUTBLOCK_EM(:, ICHNK), FM=OUTBLOCK_FM(:, ICHNK), DP=OUTBLOCK_DP(:, ICHNK), C3=OUTBLOCK_C3(:, ICHNK),  &
      & C4=OUTBLOCK_C4(:, ICHNK), BF=OUTBLOCK_BF(:, ICHNK), QP=OUTBLOCK_QP(:, ICHNK), HMAX=OUTBLOCK_HMAX(:, ICHNK),  &
      & TMAX=OUTBLOCK_TMAX(:, ICHNK), ETA_M=OUTBLOCK_ETA_M(:, ICHNK), R=OUTBLOCK_R(:, ICHNK), XNSLC=OUTBLOCK_XNSLC(:, ICHNK),  &
      & SIG_TH=OUTBLOCK_SIG_TH(:, ICHNK), EPS=OUTBLOCK_EPS(:, ICHNK), XNU=OUTBLOCK_XNU(:, ICHNK),  &
      & ESWELL=OUTBLOCK_ESWELL(:, ICHNK), FSWELL=OUTBLOCK_FSWELL(:, ICHNK), THSWELL=OUTBLOCK_THSWELL(:, ICHNK),  &
      & P1SWELL=OUTBLOCK_P1SWELL(:, ICHNK), P2SWELL=OUTBLOCK_P2SWELL(:, ICHNK), SPRDSWELL=OUTBLOCK_SPRDSWELL(:, ICHNK),  &
      & ESEA=OUTBLOCK_ESEA(:, ICHNK), FSEA=OUTBLOCK_FSEA(:, ICHNK), THWISEA=OUTBLOCK_THWISEA(:, ICHNK),  &
      & P1SEA=OUTBLOCK_P1SEA(:, ICHNK), P2SEA=OUTBLOCK_P2SEA(:, ICHNK), SPRDSEA=OUTBLOCK_SPRDSEA(:, ICHNK),  &
