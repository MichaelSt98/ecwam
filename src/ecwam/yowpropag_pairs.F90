! Internal CPU paired storage. Expanded arrays are authoritative through CFL checks.
MODULE YOWPROPAG_PAIRS
  USE PARKIND_WAVE, ONLY: JWIM,JWRB
  USE YOMHOOK, ONLY: LHOOK,DR_HOOK,JPHOOK
  IMPLICIT NONE
  PRIVATE
  PUBLIC :: P2_FACTORED,P2_LAT_BASE,P2_COR_BASE,P2_PREPARE_PAIRS,P2_RELEASE_PAIRS
  LOGICAL :: P2_FACTORED=.FALSE.
  REAL(KIND=JWRB), ALLOCATABLE :: P2_LAT_BASE(:,:,:,:),P2_COR_BASE(:,:,:,:)
CONTAINS
  SUBROUTINE P2_RELEASE_PAIRS()
    REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
    IF (LHOOK) CALL DR_HOOK('P2_RELEASE_PAIRS',0,ZHOOK_HANDLE)
    IF (ALLOCATED(P2_LAT_BASE)) DEALLOCATE(P2_LAT_BASE)
    IF (ALLOCATED(P2_COR_BASE)) DEALLOCATE(P2_COR_BASE)
    P2_FACTORED=.FALSE.
    IF (LHOOK) CALL DR_HOOK('P2_RELEASE_PAIRS',1,ZHOOK_HANDLE)
  END SUBROUTINE P2_RELEASE_PAIRS

  SUBROUTINE P2_PREPARE_PAIRS()
    USE YOWUBUF, ONLY: WLATN,WCORN
    USE OML_MOD, ONLY: OML_GET_MAX_THREADS
    INTEGER(KIND=JWIM) :: FIRST,LAST,NA,NF,BLOCK,IB,IJS,IJL,IJ,K,M,C
    REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
    IF (LHOOK) CALL DR_HOOK('P2_PREPARE_PAIRS',0,ZHOOK_HANDLE)
    CALL P2_RELEASE_PAIRS()
    FIRST=LBOUND(WLATN,1); LAST=UBOUND(WLATN,1)
    NA=SIZE(WLATN,2); NF=SIZE(WLATN,3)
    ALLOCATE(P2_LAT_BASE(FIRST:LAST,NA,NF,2),P2_COR_BASE(FIRST:LAST,NA,NF,4))
    BLOCK=(LAST-FIRST+1)/OML_GET_MAX_THREADS()+1
! Each sum is the original attenuated pair's total incoming coefficient.
! Reconstructing its interpolation legs changes rounding; SUMWN is untouched.
!$OMP PARALLEL DO SCHEDULE(STATIC,1) PRIVATE(IB,IJS,IJL,IJ,K,M,C)
    DO IB=FIRST,LAST,BLOCK
      IJS=IB; IJL=MIN(IB+BLOCK-1,LAST)
      DO M=1,NF
        DO K=1,NA
          DO C=1,2
            DO IJ=IJS,IJL
              P2_LAT_BASE(IJ,K,M,C)=WLATN(IJ,K,M,C,1)+WLATN(IJ,K,M,C,2)
            ENDDO
          ENDDO
          DO C=1,4
            DO IJ=IJS,IJL
              P2_COR_BASE(IJ,K,M,C)=WCORN(IJ,K,M,C,1)+WCORN(IJ,K,M,C,2)
            ENDDO
          ENDDO
        ENDDO
      ENDDO
    ENDDO
!$OMP END PARALLEL DO
    DEALLOCATE(WLATN,WCORN)
    P2_FACTORED=.TRUE.
    IF (LHOOK) CALL DR_HOOK('P2_PREPARE_PAIRS',1,ZHOOK_HANDLE)
  END SUBROUTINE P2_PREPARE_PAIRS
END MODULE YOWPROPAG_PAIRS
