! Full-output compact-pair comparison against the expanded reference.
! Synthetic maps exercise cross-tile reads; this is not a performance benchmark.
PROGRAM PROPAG_PAIRS_CHECK
  USE PARKIND_WAVE, ONLY: JWIM, JWRB
  USE, INTRINSIC :: ISO_FORTRAN_ENV, ONLY: NULOUT => OUTPUT_UNIT
  USE YOWABORT, ONLY: WAM_ABORT
  USE YOWUBUF, ONLY: SUMWN,WLONN,WLATN,WCORN,WKPMN,WMPMN,KLON,KLAT,KCOR, &
    KPM,MPM,KCR,JXO,JYO,LLWLONN,LLWLATN,LLWCORN,LLWKPMN,LLWMPMN,WLAT,WCOR
  USE YOWSTAT, ONLY: ICASE, IREFRA
  USE YOWTEST, ONLY: IU06
  USE YOMHOOK, ONLY: LHOOK,DR_HOOK,JPHOOK
  USE YOWPROPAG_PAIRS, ONLY: P2_FACTORED,P2_PREPARE_PAIRS,P2_RELEASE_PAIRS
  IMPLICIT NONE
#include "propags2.intfb.h"
  INTEGER(KIND=JWIM), PARAMETER :: NP=9231, NA=5, NM=3
  REAL(KIND=JWRB), ALLOCATABLE :: F1(:,:,:), F3(:,:,:)
  REAL(KIND=JWRB), ALLOCATABLE :: FINIT(:,:,:),FN1(:,:,:)
  REAL(KIND=JWRB), ALLOCATABLE :: LATREF(:,:,:,:,:),CORREF(:,:,:,:,:),FACTUAL(:,:,:),SUMREF(:,:,:)
  REAL(KIND=JWRB) :: A,B,OBS
  REAL(KIND=JWRB) :: PAIR_MAX_ERROR=0.0_JWRB
  INTEGER(KIND=JWIM) :: PAIR_VALUES=0
  INTEGER(KIND=JWIM) :: SUBSTEP
  INTEGER(KIND=JWIM) :: IJ, K, M, IC, ICL, ICR, CASE_ID, FIRST, LAST, UNIT
  INTEGER(KIND=JWIM), PARAMETER :: STARTS(8)=[7,7,257,1,7,5,7,7]
  INTEGER(KIND=JWIM), PARAMETER :: ENDS(8)=[9219,262,257,256,9219,4,9219,9219]
  CHARACTER(LEN=1024) :: OUTPUT
  CHARACTER(LEN=16) :: MODE
  CALL GET_COMMAND_ARGUMENT(1, OUTPUT)
  MODE='fact'
  IF (COMMAND_ARGUMENT_COUNT()>=2) CALL GET_COMMAND_ARGUMENT(2, MODE)
  IF (LEN_TRIM(OUTPUT)==0) OUTPUT='propag-pairs-reference.bin'
  LHOOK=.FALSE.
  IU06=6
  ICASE=1
  ALLOCATE(F1(0:NP+1,NA,0:NM+1), F3(0:NP+1,NA,1:NM))
  ALLOCATE(SUMWN(0:NP+1,NA,NM), WLONN(0:NP+1,NA,NM,2), &
    WLATN(0:NP+1,NA,NM,2,2), WCORN(0:NP+1,NA,NM,4,2), &
    WKPMN(0:NP+1,NA,NM,-1:1), WMPMN(0:NP+1,NA,NM,-1:1))
  ALLOCATE(KLON(0:NP+1,2), KLAT(0:NP+1,2,2), KCOR(0:NP+1,4,2), &
    KPM(NA,-1:1), MPM(NM,-1:1), KCR(NA,4), JXO(NA,1), JYO(NA,1))
  ALLOCATE(LLWLONN(NA,NM,2), LLWLATN(NA,NM,2,2), LLWCORN(NA,NM,4,2), &
    LLWKPMN(NA,NM,-1:1), LLWMPMN(NA,NM,-1:1))
  DO M=0,NM+1
    DO K=1,NA
      DO IJ=0,NP+1
        F1(IJ,K,M)=REAL(MODULO(17*IJ+31*K+13*M,997),JWRB)/997.0_JWRB
      ENDDO
    ENDDO
  ENDDO
  F1(NP+1,:,:)=0.0_JWRB
  IF (INDEX(MODE,'fact')==1) THEN
    ALLOCATE(WLAT(0:NP+1,2),WCOR(0:NP+1,4))
    DO IJ=0,NP+1
      DO IC=1,2
        WLAT(IJ,IC)=REAL(MOD(IJ+IC,18),JWRB)/17.0_JWRB
        IF (MOD(IJ,19)==0) WLAT(IJ,IC)=0.5_JWRB
      ENDDO
      DO ICR=1,4
        WCOR(IJ,ICR)=REAL(MOD(IJ+ICR,18),JWRB)/17.0_JWRB
        IF (MOD(IJ,19)==0) WCOR(IJ,ICR)=0.5_JWRB
      ENDDO
    ENDDO
    ALLOCATE(FINIT(0:NP+1,NA,0:NM+1),FN1(0:NP+1,NA,0:NM+1),FACTUAL(0:NP+1,NA,NM))
    FINIT(:,:,:)=F1(:,:,:)
  ENDIF
  DO IC=1,2
    DO IJ=0,NP+1
      KLON(IJ,IC)=MODULO(IJ+(-1)**IC*263,NP)
      DO ICL=1,2
        KLAT(IJ,IC,ICL)=MODULO(97*IJ+IC*ICL,NP)
        DO ICR=1,4
          KCOR(IJ,ICR,ICL)=MODULO(IJ+ICR*509-ICL*1021,NP)
        ENDDO
      ENDDO
    ENDDO
  ENDDO
  KLON(256,:)=NP+1
  DO K=1,NA
    JXO(K,1)=1+MOD(K,2)
    JYO(K,1)=1+MOD(K+1,2)
    DO ICR=1,4
      KCR(K,ICR)=1+MOD(K+ICR,4)
    ENDDO
    DO IC=-1,1
      KPM(K,IC)=1+MODULO(K-1+IC,NA)
    ENDDO
  ENDDO
  DO M=1,NM
    DO IC=-1,1
      MPM(M,IC)=M+IC
    ENDDO
    DO K=1,NA
      DO IJ=0,NP+1
        SUMWN(IJ,K,M)=0.1_JWRB+REAL(MOD(IJ+K+M,13),JWRB)/100.0_JWRB
        DO IC=1,2
          WLONN(IJ,K,M,IC)=REAL(MOD(IJ+IC,7)-3,JWRB)/71.0_JWRB
          DO ICL=1,2
            WLATN(IJ,K,M,IC,ICL)=REAL(MOD(IJ+IC+ICL,11)-5,JWRB)/113.0_JWRB
          ENDDO
        ENDDO
        DO ICR=1,4
          DO ICL=1,2
            WCORN(IJ,K,M,ICR,ICL)=REAL(MOD(IJ+ICR+ICL,17)-8,JWRB)/173.0_JWRB
          ENDDO
        ENDDO
        DO IC=-1,1
          WKPMN(IJ,K,M,IC)=REAL(MOD(IJ+K+IC,19)-9,JWRB)/191.0_JWRB
          WMPMN(IJ,K,M,IC)=REAL(MOD(IJ+M+IC,23)-11,JWRB)/233.0_JWRB
        ENDDO
      ENDDO
    ENDDO
  ENDDO
  IF (INDEX(MODE,'fact')==1) THEN
! Follow the real producer's two rounded products, including common obstruction.
    DO M=1,NM
      DO K=1,NA
        DO IJ=0,NP+1
          DO IC=1,2
            A=WLAT(IJ,IC)
            B=REAL(MOD(IJ+K+M+IC,13),JWRB)/113.0_JWRB
            OBS=REAL(MOD(IJ+M+IC,11),JWRB)/10.0_JWRB
            WLATN(IJ,K,M,IC,1)=(A*B)*OBS
            WLATN(IJ,K,M,IC,2)=((1.0_JWRB-A)*B)*OBS
          ENDDO
          DO ICR=1,4
            A=WCOR(IJ,KCR(K,ICR))
            B=REAL(MOD(IJ+K+M+ICR,19),JWRB)/191.0_JWRB
            OBS=REAL(MOD(IJ+M+ICR,11),JWRB)/10.0_JWRB
            WCORN(IJ,K,M,ICR,1)=(A*B)*OBS
            WCORN(IJ,K,M,ICR,2)=((1.0_JWRB-A)*B)*OBS
          ENDDO
        ENDDO
      ENDDO
    ENDDO
    ALLOCATE(LATREF(0:NP+1,NA,NM,2,2),CORREF(0:NP+1,NA,NM,4,2),SUMREF(0:NP+1,NA,NM))
    LATREF(:,:,:,:,:)=WLATN(:,:,:,:,:); CORREF(:,:,:,:,:)=WCORN(:,:,:,:,:); SUMREF(:,:,:)=SUMWN(:,:,:)
  ENDIF
  OPEN(NEWUNIT=UNIT,FILE=TRIM(OUTPUT),ACCESS='STREAM',FORM='UNFORMATTED', &
    STATUS='REPLACE',CONVERT='LITTLE_ENDIAN')
  DO CASE_ID=1,SIZE(STARTS)
    FIRST=STARTS(CASE_ID)
    LAST=ENDS(CASE_ID)
    IF (INDEX(MODE,'fact')==1) CALL RESTORE_EXPANDED
    IREFRA=2
    LLWLONN=.TRUE.
    LLWLATN=.TRUE.
    LLWCORN=.TRUE.
    LLWKPMN=.TRUE.
    LLWMPMN=.TRUE.
    IF (CASE_ID==5) THEN
      IREFRA=3
      DO M=1,NM
        DO K=1,NA
          LLWLONN(K,M,:)=MOD(K+M,2)==0
          LLWLATN(K,M,:,:)=MOD(K+M,3)==0
          LLWCORN(K,M,:,:)=MOD(K+M,4)==0
          LLWKPMN(K,M,-1)=MOD(K+M,2)==0
          LLWMPMN(K,M,1)=MOD(K+M,3)==0
        ENDDO
      ENDDO
    ELSEIF (CASE_ID==7) THEN
      LLWLONN=.FALSE.
      LLWLATN=.FALSE.
      LLWCORN=.FALSE.
      LLWKPMN=.FALSE.
      LLWMPMN=.FALSE.
    ELSEIF (CASE_ID==8) THEN
      IREFRA=0
    ENDIF
    F3=-999.0_JWRB
    CALL PROPAGS2(F1,F3,0,NP,FIRST,LAST,NA,0,NM+1,1,NM)
    IF (ANY(F3(0:FIRST-1,:,:)/=-999.0_JWRB)) CALL WAM_ABORT('PROPAG_PAIRS_CHECK failure 2',__FILE__,__LINE__)
    IF (ANY(F3(MAX(FIRST,LAST+1):NP+1,:,:)/=-999.0_JWRB)) CALL WAM_ABORT('PROPAG_PAIRS_CHECK failure 3',__FILE__,__LINE__)
    WRITE(UNIT) F3
    IF (TRIM(MODE)=='fact') THEN
      FN1(:,:,:)=FINIT(:,:,:)
      FACTUAL=-999.0_JWRB
      SUBSTEP=0
      IF (IREFRA==2 .OR. IREFRA==3) CALL P2_PREPARE_PAIRS()
      IF (ANY(SUMWN/=SUMREF)) CALL WAM_ABORT('PROPAG_PAIRS_CHECK failure 8',__FILE__,__LINE__)
      CALL PROPAGS2(FN1,FACTUAL,0,NP,FIRST,LAST,NA,0,NM+1,1,NM)
      CALL CHECK_PAIRS
      DO SUBSTEP=1,3
        F1(FIRST:LAST,:,1)=F3(FIRST:LAST,:,1)
        FN1(FIRST:LAST,:,1)=FACTUAL(FIRST:LAST,:,1)
        CALL RESTORE_EXPANDED
        CALL PROPAGS2(F1(:,:,0:2),F3(:,:,1:1),0,NP,FIRST,LAST,NA,0,2,1,1)
        IF (IREFRA==2 .OR. IREFRA==3) THEN
          DEALLOCATE(WLATN,WCORN)
          P2_FACTORED=.TRUE.
        ENDIF
        CALL PROPAGS2(FN1(:,:,0:2),FACTUAL(:,:,1:1),0,NP,FIRST,LAST,NA,0,2,1,1)
        CALL CHECK_PAIRS
        IF (ANY(FN1(:,:,2)/=FINIT(:,:,2))) CALL WAM_ABORT('PROPAG_PAIRS_CHECK failure 9',__FILE__,__LINE__)
      ENDDO
      CALL P2_RELEASE_PAIRS()
      F1(:,:,:)=FINIT(:,:,:)
    ENDIF
  ENDDO
  CLOSE(UNIT)
  WRITE(NULOUT,*) 'Wrote eight full-output cases: ', TRIM(OUTPUT)
  IF (TRIM(MODE)=='fact') WRITE(NULOUT,*) 'Paired values checked / maximum error:',PAIR_VALUES,PAIR_MAX_ERROR
CONTAINS
  SUBROUTINE RESTORE_EXPANDED
    REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
    IF (LHOOK) CALL DR_HOOK('PROPAG_PAIRS_CHECK%RESTORE_EXPANDED',0,ZHOOK_HANDLE)
    P2_FACTORED=.FALSE.
    IF (.NOT.ALLOCATED(WLATN)) ALLOCATE(WLATN(0:NP+1,NA,NM,2,2))
    IF (.NOT.ALLOCATED(WCORN)) ALLOCATE(WCORN(0:NP+1,NA,NM,4,2))
    WLATN(:,:,:,:,:)=LATREF(:,:,:,:,:); WCORN(:,:,:,:,:)=CORREF(:,:,:,:,:)
    IF (LHOOK) CALL DR_HOOK('PROPAG_PAIRS_CHECK%RESTORE_EXPANDED',1,ZHOOK_HANDLE)
  END SUBROUTINE RESTORE_EXPANDED

  SUBROUTINE CHECK_PAIRS
    INTEGER(KIND=JWIM) :: I,K1,M1
    REAL(KIND=JWRB) :: ERROR
    REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
    IF (LHOOK) CALL DR_HOOK('PROPAG_PAIRS_CHECK%CHECK_PAIRS',0,ZHOOK_HANDLE)
    DO M1=1,NM
      DO K1=1,NA
        DO I=0,NP+1
          ERROR=ABS(FACTUAL(I,K1,M1)-F3(I,K1,M1))
          PAIR_MAX_ERROR=MAX(PAIR_MAX_ERROR,ERROR)
          PAIR_VALUES=PAIR_VALUES+1
          IF (.NOT.(ERROR<=1.e-6_JWRB+1.e-6_JWRB*ABS(F3(I,K1,M1)))) THEN
            WRITE(NULOUT,*) 'Paired mismatch:',CASE_ID,SUBSTEP,I,K1,M1,F3(I,K1,M1),FACTUAL(I,K1,M1)
            CALL WAM_ABORT('PROPAG_PAIRS_CHECK failure 10',__FILE__,__LINE__)
          ENDIF
        ENDDO
      ENDDO
    ENDDO
    IF (ANY(FACTUAL(0:FIRST-1,:,:)/=-999.0_JWRB)) CALL WAM_ABORT('PROPAG_PAIRS_CHECK failure 11',__FILE__,__LINE__)
    IF (ANY(FACTUAL(MAX(FIRST,LAST+1):NP+1,:,:)/=-999.0_JWRB)) &
      & CALL WAM_ABORT('PROPAG_PAIRS_CHECK failure 12',__FILE__,__LINE__)
    IF (LHOOK) CALL DR_HOOK('PROPAG_PAIRS_CHECK%CHECK_PAIRS',1,ZHOOK_HANDLE)
  END SUBROUTINE CHECK_PAIRS

END PROGRAM PROPAG_PAIRS_CHECK
